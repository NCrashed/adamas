/// Чем исполнение может кончиться помимо значения.
#[derive(Debug, thiserror::Error)]
pub enum RunError {
    /// Операция дошла до верха, не встретив своего хендлера.
    ///
    /// Проверка типов такого не пропускает - погашение требует, чтобы row
    /// определения была пуста, - так что случай этот означает расхождение
    /// машины с правилом, а не ошибку автора.
    #[error("операция `{operation}` метки `{effect}` осталась без хендлера")]
    Unhandled {
        /// Метка операции.
        effect: String,
        /// Сама операция.
        operation: String,
    },

    /// Единицы в сигнатуре нет либо конструктор у неё не один.
    ///
    /// Приостановленное вычисление `{ε} A` есть функция от единицы, и запустить
    /// его без неё нечем. Проверка типов до этого места не доходит: без единицы
    /// не объявляется ни эффект, ни вставка закрытия.
    #[error(
        "единица не объявлена одним конструктором: приостановленное вычисление запускать нечем"
    )]
    NoUnit,

    /// Питомник спрошен о файбере, которого нет.
    ///
    /// Случается на значении задачи, собранном не питомником: невыразимое имя
    /// файбера автор написать не может, но конструктор задачи публичен (§3.3),
    /// и `MkTask Zero` собирается руками. Отказ здесь честнее догадки.
    #[error("значение задачи не называет живого файбера: собрано не питомником")]
    NoFiber,

    /// Ожидание задачи **чужого** питомника.
    ///
    /// Круг у задачи один - тот, что её породил, - и очередь с ждущими лежат
    /// там же. Дождаться её отсюда нечем, а ответа её уже нет: питомник, закрыв
    /// круг, освобождает готовые. Отказ говорит это прямо: прежде сюда попадал
    /// `NoFiber` с сообщением «собрано не питомником», а оно **ложно** -
    /// собрано питомником, просто другим (ревью 2026-09-08).
    #[error("задача принадлежит другому питомнику: дождаться её можно только в нём")]
    ForeignTask,

    /// Результат `spawn` не годится под значение задачи.
    ///
    /// Тип задачи машина берёт из **написанного** результата операции, а не из
    /// вшитого имени, и требует от него двух вещей: один конструктор и одно
    /// поле под номер файбера. Не сошлось - отказ на месте, а не значение, про
    /// которое неизвестно, чем оно окажется.
    ///
    /// Параметры семейства законны: значение собирается спайном из одного
    /// применения, и стёртый параметр встаёт в него маркером - как его ставит
    /// обычное применение конструктора. Пока маркеров не было, `data Task
    /// (a : Type)` отвергалось целиком: без них разбор задачи выпускал наружу
    /// лямбду (ревью 2026-09-07).
    #[error(
        "результат `{operation}` обязан быть типом с одним конструктором и одним полем: в нём стоит номер файбера"
    )]
    TaskShape {
        /// Операция, чей результат не подошёл.
        operation: String,
    },

    /// Все живые файберы ждут друг друга.
    ///
    /// Очередь пуста, а ждущие есть: чужого ответа им не дождаться никогда.
    /// Видно это по построению - ждущий стоит вне круга, - а не по зависанию.
    #[error("взаимная блокировка: все живые задачи ждут друг друга")]
    Deadlock,

    /// Разделяемая библиотека не загрузилась (§5.3).
    ///
    /// Отказ, а не паника: имя библиотеки приходит из пользовательского текста,
    /// и отсутствующая библиотека - обычная ошибка автора. Текст `dlopen`
    /// пересказывается дословно, потому что он и называет причину (нет файла,
    /// не та архитектура, не разрешился её собственный сосед).
    #[error("библиотека `{library}` не загрузилась: {why}")]
    NoLibrary {
        /// Имя, как его написал автор.
        library: String,
        /// Что сказал `dlopen`.
        why: String,
    },

    /// Символа в загруженной библиотеке нет (§5.3).
    ///
    /// Отдельно от [`RunError::NoLibrary`] намеренно: «нет файла» и «файл есть,
    /// имени в нём нет» чинятся по-разному, и одно слово на оба случая послало
    /// бы автора искать не там.
    #[error("в библиотеке `{library}` нет символа `{symbol}`: {why}")]
    NoSymbol {
        /// Где искали.
        library: String,
        /// Что искали.
        symbol: String,
        /// Что сказал `dlsym`.
        why: String,
    },

    /// Сигнатура чужой функции вне таблицы вызова (§5.3, уровень 1).
    ///
    /// Не «не умеем» вообще, а «этой формы в таблице нет»: звать по
    /// нетипизированному адресу можно только точной сигнатурой, и таблица их
    /// конечна по построению (`foreign.rs`, шапка).
    #[error("сигнатура `{symbol} : {signature}` вне таблицы вызова: звать её нечем")]
    ForeignShape {
        /// Какой символ.
        symbol: String,
        /// Какой сигнатурой его объявили.
        signature: String,
    },

    /// Литерал не того типа, каким объявлен аргумент чужой функции.
    ///
    /// Догадка здесь была бы хуже отказа: расширить `Int32` до слова можно
    /// двумя способами, и выбор между ними принадлежит объявлению, а не машине.
    #[error("аргумент {at} функции `{symbol}` объявлен `{want}`, а пришёл `{got}`")]
    ForeignArgument {
        /// Какой символ.
        symbol: String,
        /// Номер аргумента, считая с нуля.
        at: usize,
        /// Что объявлено.
        want: &'static str,
        /// Что пришло.
        got: &'static str,
    },
}

/// Исполняет замкнутый терм и читает результат обратно в терм.
///
/// # Errors
///
/// [`RunError`] - операция без хендлера либо отсутствующая единица.
pub fn run(signature: &Signature, term: &Term) -> Result<Term, RunError> {
    run_linked(signature, term, Linkage::default())
}

/// Он же с библиотеками, с которыми связана программа (§5.3, §7.1).
///
/// Список приходит из `[link]` манифеста и есть тот же, который уезжает в
/// `cc`. Стандартная библиотека C ([`foreign::C_LIBRARY`]) дописывается сама:
/// её и `cc` подключает без единого ключа.
///
/// # Errors
///
/// [`RunError`] - операция без хендлера, отсутствующая единица либо отказ
/// чужого вызова.
pub fn run_linked(signature: &Signature, term: &Term, linkage: Linkage) -> Result<Term, RunError> {
    let machine = Machine::linked(signature, linkage);
    let value = machine.evaluate(&Env::default(), term)?;
    machine.read(value)
}
