//! Backend IR: шов между ядром и эмиттером.
//!
//! Представление одно на все бэкенды, и существует оно ради **фактов**, а не
//! ради узлов. Узлов здесь ровно столько, сколько требует чистый фрагмент;
//! факты - те, что знает тайпчекер и не восстановит алиас-анализ.
//!
//! # Зачем шов
//!
//! `docs/phase7-plan.md`: LLVM-бэкенд переносит факты QTT в `noalias`, scoped
//! `!alias.scope`/`!noalias`, `dereferenceable`. Устрой понижение как «ядро →
//! текст C», и факты гаснут на границе: из C-подобного представления
//! уникальность не восстанавливается - это ровно та задача, которую алиас-анализ
//! решает консервативно. Поэтому кратность и уникальность лежат **здесь**, а
//! эмиттер теряет их последним шагом.
//!
//! Сегодня C-эмиттер их игнорирует целиком: сверх `restrict` в C выразить
//! `noalias` нечем, а ставить его наугад незачем. Существенно, что он их
//! игнорирует, а не что их нет.
//!
//! # Что лежит на связывании
//!
//! [`Fact`] - четыре поля, каждое со своим свидетелем в дизайне.
//!
//! *Кратность* (§3.2) есть у ядра дословно, и терять её нельзя: `noalias` в
//! Фазе 7 берётся из неё.
//!
//! *Уникальность* (§5.1): «линейные значения обходятся без RC вообще:
//! компилятор знает уникальность статически». Известна она статически ровно при
//! кратности `1`; `resource`-вход §5.1 называет вторым источником, и отдельного
//! поля он не требует - правило владения §3.3 даёт связыванию типа `File`
//! кратность `1`, то есть в ядре оба источника - одно и то же.
//!
//! *Регион* (§3.6) - место под непересечение `Ref r a`. Регионов сейчас нет, и
//! поле пусто у всех; заведено оно затем, чтобы Фаза 7 добавляла эмиттер, а не
//! меняла форму IR.
//!
//! *Наличие в рантайме* - не то же, что ненулевая кратность, и это измерено
//! машиной: решение дырки терма есть цепочка лямбд при `0`, а значения в них
//! настоящие - словарь класса приезжает в тело ровно таким спайном
//! (`adamas-interp/src/machine.rs`, `erases`). Поэтому кратность остаётся
//! фактом тайпчекера, а решение «эмитить или нет» стоит отдельным полем.

use adamas_core::mult::Mult;

/// Номер функции в программе.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct FuncId(pub usize);

/// Номер конструктора. Он же тег в заголовке объекта рантайма.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct CtorId(pub u16);

/// Номер локального связывания внутри одной функции.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct LocalId(pub u32);

/// Номер региона (§3.6). Пока не заводится никем.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct RegionId(pub u32);

/// Известна ли уникальность статически.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Unique {
    /// Известна: значение не алиасировано, и RC-протокол ему не нужен (§5.1).
    Certain,
    /// Неизвестна: значение вправе быть разделено, и уникальность придётся
    /// спрашивать у счётчика.
    Unknown,
}

/// Что тайпчекер знает о связывании.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Fact {
    /// Кратность из ядра.
    pub mult: Mult,
    /// Уникальность, если она известна статически.
    pub unique: Unique,
    /// Регион, которому принадлежит значение (§3.6). Всегда `None`.
    pub region: Option<RegionId>,
    /// Есть ли у связывания значение в рантайме.
    ///
    /// Стёртое (`0`) в C не эмитится вовсе, но в IR присутствует: это факт, и
    /// он нужен LLVM-эмиттеру наравне с прочими.
    pub present: bool,
}

impl Fact {
    /// Факт о связывании объявленной кратности.
    ///
    /// Наличие берётся из неё же - так решает и машина, когда стирает аргумент
    /// глобального имени, - а уникальность приходит от `1` (§5.1).
    #[must_use]
    pub fn declared(mult: Mult) -> Self {
        Self {
            mult,
            unique: if mult == Mult::One {
                Unique::Certain
            } else {
                Unique::Unknown
            },
            region: None,
            present: mult != Mult::Zero,
        }
    }

    /// Факт о связывании, значение которого в рантайме есть при любой кратности.
    ///
    /// Таковы связывания лямбды и `let`: машина их вычисляет, не спрашивая
    /// кратности, и кратность здесь - факт о **использовании**, а не о наличии.
    #[must_use]
    pub fn present(mult: Mult) -> Self {
        Self {
            present: true,
            ..Self::declared(mult)
        }
    }
}

/// Связывание: имя для читаемости, номер для ссылок, факты для бэкенда.
#[derive(Clone, Debug)]
pub struct Binding {
    /// Имя из исходника. На семантику не влияет, идёт в комментарий.
    pub name: String,
    /// Номер, которым на связывание ссылается [`Expr::Local`].
    pub local: LocalId,
    /// Что о нём известно.
    pub fact: Fact,
}

/// Конструктор индуктивного типа.
#[derive(Clone, Debug)]
pub struct Constructor {
    /// Тег в заголовке объекта.
    pub tag: CtorId,
    /// Имя: его печатает ответ программы.
    pub name: String,
    /// Семейство, которому конструктор принадлежит.
    pub data: String,
    /// Факты о **всех** связываниях: сперва параметры семейства, потом поля.
    ///
    /// Стёртые здесь есть, и это то самое место, где IR богаче C: в объекте
    /// рантайма их нет, а в IR они лежат со своей кратностью.
    pub binders: Vec<Fact>,
    /// Сколько первых связываний - параметры семейства. Ветвь их не связывает.
    pub params: u32,
}

impl Constructor {
    /// Слот в объекте рантайма, если связывание до него доживает.
    #[must_use]
    pub fn slot(&self, binder: usize) -> Option<u32> {
        if !self.binders.get(binder)?.present {
            return None;
        }
        let live = self.binders[..binder]
            .iter()
            .filter(|fact| fact.present)
            .count();
        u32::try_from(live).ok()
    }

    /// Сколько полей у объекта рантайма.
    #[must_use]
    pub fn slots(&self) -> usize {
        self.binders.iter().filter(|fact| fact.present).count()
    }
}

/// Форма понижения (§13, записи 2026-09-08 про ABI).
///
/// Различает их трёхзначный вердикт §3.4 - тот же, у которого §5.1 насчитал
/// трёх потребителей и которого пока нет: `crates/adamas-core/src/alloc.rs`
/// называет его отсутствие прямо и потому считает всякий элиминатор хендлера
/// аллоцирующим. Понижение четвёртый потребитель, и спрашивать оно обязано
/// **вердикт**, а не грубую замену ему; отсюда форма лежит на функции, а не
/// угадывается эмиттером.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Form {
    /// Первая: обычная C-функция, кадр на C-стеке.
    ///
    /// Скрытый аргумент один - вектор evidence.
    Stack,
    /// Вторая: кадр отчуждается в кучу.
    ///
    /// Скрытых аргумента два - вектор evidence и ручка стека продолжения рядом
    /// с ним. Нужна только под общим или мультишотным хендлером; понижение её
    /// пока не производит, и эмиттер отказывает на ней названной причиной,
    /// вместо того чтобы досочинить.
    Detached,
}

/// Функция программы.
#[derive(Clone, Debug)]
pub struct Function {
    /// Собственный номер.
    pub id: FuncId,
    /// Имя из исходника либо описание происхождения.
    pub name: String,
    /// Как понижается (§3.4, трёхзначный вердикт).
    pub form: Form,
    /// Захваченная среда. Пусто у определения верхнего уровня.
    pub captured: Vec<Binding>,
    /// Параметры.
    pub parameters: Vec<Binding>,
    /// Тело.
    pub body: Expr,
}

impl Function {
    /// Параметры, доживающие до рантайма.
    pub fn live_parameters(&self) -> impl Iterator<Item = &Binding> {
        self.parameters.iter().filter(|it| it.fact.present)
    }

    /// Захваченное, доживающее до рантайма.
    pub fn live_captured(&self) -> impl Iterator<Item = &Binding> {
        self.captured.iter().filter(|it| it.fact.present)
    }
}

/// Ветвь разбора.
#[derive(Clone, Debug)]
pub struct Arm {
    /// Конструктор, который она разбирает.
    pub constructor: CtorId,
    /// Связывания полей - по одному на связывание конструктора после
    /// параметров, включая стёртые.
    pub fields: Vec<Binding>,
    /// Тело ветви.
    pub body: Expr,
}

/// Выражение IR.
///
/// Дерево, а не последовательность: `Bind` и `Match` задают порядок сами, а
/// линеаризация - работа эмиттера. Узлов ровно столько, сколько требует чистый
/// фрагмент; эффектов, хендлеров и резумпций здесь нет.
#[derive(Clone, Debug)]
pub enum Expr {
    /// Значение локального связывания.
    Local(LocalId),
    /// Значения нет: позиция стёрта (§3.3).
    Erased,
    /// Конструктор со всеми аргументами: по одному на связывание, стёртые
    /// [`Expr::Erased`].
    Construct {
        /// Какой.
        constructor: CtorId,
        /// Аргументы по связываниям.
        arguments: Vec<Expr>,
    },
    /// Конструктор как значение: замыкание, собирающее его по аргументам.
    ConstructClosure {
        /// Какой.
        constructor: CtorId,
    },
    /// Прямой вызов функции: аргументов ровно столько, сколько параметров.
    Call {
        /// Кого.
        function: FuncId,
        /// Аргументы по параметрам, стёртые [`Expr::Erased`].
        arguments: Vec<Expr>,
    },
    /// Функция как значение: код плюс захваченная среда.
    Closure {
        /// Чей код.
        function: FuncId,
        /// Захваченное - по одному на связывание в [`Function::captured`].
        captured: Vec<Expr>,
    },
    /// Применение значения-функции к одному аргументу.
    ///
    /// Стирания здесь не бывает: машина стирает аргумент по типу **глобального
    /// имени**, а к этому месту имени уже нет.
    Apply {
        /// Что применяется.
        callee: Box<Expr>,
        /// К чему.
        argument: Box<Expr>,
    },
    /// Связывание значения.
    Bind {
        /// Кого связывает.
        binding: Binding,
        /// Чем.
        value: Box<Expr>,
        /// Что под ним.
        body: Box<Expr>,
    },
    /// Разбор по конструктору. Пустой список ветвей - разбор пустого типа.
    Match {
        /// Что разбирается.
        scrutinee: Box<Expr>,
        /// Кратность, с которой разбор потребляет разбираемое (§3.3).
        consumed: Mult,
        /// Ветви.
        arms: Vec<Arm>,
    },
}

/// Программа целиком.
#[derive(Clone, Debug)]
pub struct Program {
    /// Конструкторы по тегу: индекс совпадает с [`CtorId`].
    pub constructors: Vec<Constructor>,
    /// Функции по номеру: индекс совпадает с [`FuncId`].
    pub functions: Vec<Function>,
    /// Точка входа: функция без параметров, чьё значение печатается.
    pub entry: FuncId,
}
