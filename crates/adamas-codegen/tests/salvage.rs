//! Свидетель схлопывания пары «`dup` поля - дроп разобранного» (§5.1).
//!
//! Разбор берёт ссылку на каждое поле, которое называет ветвь, а дроп
//! разобранного на последней ссылке обходит поля и возвращает эти же ссылки
//! обратно. На **уникальном** родителе пара сокращается целиком: поля переходят
//! ветви даром, блок освобождается, счётчиков никто не трогает. На разделённом
//! не сокращается ничего - поля живут дальше в родителе.
//!
//! Уникальность спрашивается в рантайме (`adamas_is_unique`, `rc == 0`) - тем
//! же, чем её спрашивает reuse, и по той же причине: из кратности она не
//! следует (§10 вопрос 149, `tests/perceus.rs`).
//!
//! # Чем это свидетельствуется
//!
//! Тремя вещами, и ни одна не заменяет двух других.
//!
//! **Текстом** - потому что утверждение «пара схлопнута» есть утверждение об
//! **отсутствии** `dup` на быстром пути, а отсутствия в ответе не видно. Ответ
//! у схлопнутой пары тот же по построению: `dup` и `drop` взаимно сокращаются,
//! и программа, где сокращение сделано неверно, отвечает то же самое, пока не
//! упадёт.
//!
//! **Счётом ячеек на уникальном пути** - невзятое поле дропает сам дроп, минуя
//! release, и забудь он это, блок останется живым. Ответ этого не заметит:
//! утёкшее поле ветвь не называет.
//!
//! **Прогоном на разделённом пути** - там пара обязана остаться на месте.
//! Схлопни её и здесь, и поле лишится ссылки, которую держит переживший
//! родитель; ответ при этом сохранится до первого дропа, а рантайм оборвётся на
//! освобождении блока, которого он не выдавал.

mod harness;

/// Общая часть: пара с двумя указательными полями и ветвь, берущая одно.
///
/// Поля **оба объекты**: `Zero` был бы непосредственным, счётчика у него нет, и
/// ни взятым, ни невзятым он в схлопывании не участвовал бы вовсе.
///
/// `second` не строит ничего, поэтому ячейка родителя не придерживается, и
/// схлопывание идёт по дропу, а не по [`Reclaim`](adamas_codegen::ir::Expr).
const COMMON: &str = "\
data Nat where
  Zero : Nat
  Succ : Nat -> Nat

data Pair where
  MkPair : Nat -> Nat -> Pair

second : Pair -> Nat
second (MkPair a b) = b

hold : Nat -> Pair -> Nat
hold n p = n

made : Pair
made = MkPair (Succ Zero) (Succ (Succ Zero))
";

/// Уникальный родитель: пару называют один раз.
fn sole() -> String {
    format!("{COMMON}\nmain : Nat\nmain = second made\n")
}

/// Разделённый родитель: пару называют дважды, и `hold` отдаёт её сам.
///
/// Ответ **тот же**, что у [`sole`]: разошлись программы только владением.
fn shared() -> String {
    format!("{COMMON}\nmain : Nat\nmain =\n  let p : Pair = made\n  hold (second p) p\n")
}

/// Тело функции по имени из комментария, который эмиттер ставит перед ней.
///
/// Текст C читается кусками, а не целиком: `adamas_is_unique` в другой функции
/// сказал бы о схлопывании ровно ничего. Имя ищется вместе с началом
/// определения - тем же комментарием эмиттер метит и **место вызова**.
fn body(text: &str, name: &str) -> String {
    let marked = format!("/* {name} */\nstatic ");
    let at = text
        .find(&marked)
        .unwrap_or_else(|| panic!("в тексте C нет функции `{name}`"));
    let rest = &text[at + marked.len()..];
    let end = rest
        .find("\n}\n")
        .unwrap_or_else(|| panic!("тело `{name}` не кончается"));
    rest[..=end].to_owned()
}

/// Пара схлопнута: `dup` полей стоит только на разделённом пути.
///
/// Свидетель сперва требует, чтобы `dup` в ветви вообще был, - иначе он зелен и
/// пуст на любой программе, где счёта нет вовсе.
#[test]
fn a_unique_parent_hands_its_fields_over_uncounted() {
    let text = harness::text(&sole()).expect("исходник обязан понижаться");
    let second = body(&text, "second");
    let (fast, slow) = second
        .split_once("} else {")
        .expect("схлопывания в ветви нет: развилки по уникальности не эмитировано");

    assert!(
        fast.contains("if (adamas_is_unique("),
        "уникальность спрошена не рантаймом:\n{second}"
    );
    assert!(
        !fast.contains("adamas_dup("),
        "уникальный путь берёт ссылку на поле - пара не схлопнута:\n{second}"
    );
    assert!(
        fast.contains("adamas_free("),
        "уникальный путь не освобождает блок сам, значит идёт через release, \
         а тот вернёт полям их ссылки:\n{second}"
    );
    assert!(
        fast.contains("adamas_drop_value("),
        "невзятое поле не дропнуто на уникальном пути - release его дропнул бы, \
         а здесь release не зовётся:\n{second}"
    );
    assert!(
        slow.contains("adamas_dup("),
        "разделённый путь не берёт ссылок на поля: родитель переживёт ветвь, \
         и поля обязаны принадлежать обоим:\n{second}"
    );
}

/// Сколько блоков выдал прогон. Ответ по дороге сверяется с машиной.
fn allocated(name: &str, source: &str) -> usize {
    let stderr = harness::agreed(name, source).unwrap_or_else(|error| panic!("{name}: {error}"));
    let (allocated, live) = harness::blocks(name, &stderr);
    assert_eq!(live, 0, "{name}: прогон оставил блоки живыми");
    allocated
}

/// Обе стороны развилки считают то же и не оставляют ячеек.
///
/// Числа выданных блоков обязаны совпасть: схлопывание трогает счётчики, а не
/// аллокации, и разойдись они - изменилось бы то, что оптимизация менять не
/// вправе. Программы при этом идут **разными** путями развилки, и ответ у них
/// один и тот же (`hold` отбрасывает второй аргумент).
#[test]
fn both_paths_keep_the_contract() {
    let sole = allocated("уникальный", &sole());
    let shared = allocated("разделённый", &shared());
    // Пара плюс два поля: свидетель сперва обязан быть непустым.
    assert_eq!(sole, 4, "программа выдала не те блоки, что написана");
    assert_eq!(
        sole, shared,
        "пути развилки разошлись числом ячеек: уникальный {sole}, разделённый {shared}"
    );
}
