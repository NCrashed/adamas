/// Чем назвать порождённую задачу (§5.2).
///
/// Тип её называет **написанный** результат `spawn`, вшитого имени у него нет:
/// то же требование, что у машины, - один конструктор и одно поле, куда встанет
/// невыразимое имя файбера.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Task {
    /// Конструктор типа задачи.
    pub constructor: CtorId,
    /// Сколько у него живых слотов.
    pub slots: u32,
    /// Который из них несёт имя файбера.
    pub at: u32,
}

/// Что делает операция питомника (§5.2).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FiberOp {
    /// `suspend`: файбер уходит в хвост очереди.
    Suspend,
    /// `spawnDetached`: ответа звавшему не нужно, значением идёт единица.
    Detached,
    /// `spawn`: ответом идёт задача. `None` - написанный результат под задачу
    /// не подходит, и обслужить операцию питомник не сможет.
    Spawn(Option<Task>),
    /// `await`: ждущий уходит из круга до чужого ответа. Число - слот, в
    /// котором у значения задачи стоит имя файбера.
    Await(Option<u32>),
}

/// Чем занято поле плоского агрегата.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SlotTy {
    /// Примитив своей ширины.
    Prim(PrimTy),
    /// Вложенный агрегат: байты его укладки целиком (§4.11, §10 вопрос 157).
    ///
    /// Проекция сквозь него - композиция двух чтений по смещению, а не путь:
    /// внешнее чтение отдаёт плотное значение вложенной укладки, внутреннее -
    /// его поле.
    Pack(PackId),
}

impl SlotTy {
    /// Представление значения такого поля.
    #[must_use]
    pub const fn repr(self) -> Repr {
        match self {
            Self::Prim(ty) => Repr::Flat(ty),
            Self::Pack(pack) => Repr::Packed(pack),
        }
    }

    /// Ширина поля в байтах.
    #[must_use]
    pub fn width(self, packings: &[Packing]) -> u32 {
        match self {
            Self::Prim(ty) => ty.size(),
            Self::Pack(pack) => packings[pack.0 as usize].size,
        }
    }

    /// Граница поля в байтах.
    #[must_use]
    pub fn align(self, packings: &[Packing]) -> u32 {
        match self {
            Self::Prim(ty) => ty.size(),
            Self::Pack(pack) => packings[pack.0 as usize].align,
        }
    }
}

/// Поле плоского агрегата: где лежит и чем является.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Slot {
    /// Смещение от начала агрегата в байтах.
    pub offset: u32,
    /// Тип поля.
    pub ty: SlotTy,
}

/// Поля одного конструктора внутри плотной укладки (§4.11).
///
/// У записи вариант один и без имени конструктора; у семейства - по варианту
/// на конструктор, в порядке объявления, и порядок этот же - значение тега.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Variant {
    /// Тег конструктора в общей таблице: им говорят печать и объект кучи.
    /// `None` - вариант записи: форма заводится лишь при боксировании.
    pub ctor: Option<CtorId>,
    /// Метки полей в написанном порядке - им же идёт проекция.
    pub labels: Vec<String>,
    /// Поля в том же порядке. Стёртые сюда не входят: у них нет байтов.
    pub slots: Vec<Slot>,
}

/// Плоская укладка агрегата (§4.11).
///
/// «Запись, все поля которой `Flat`: укладка последовательная, выравнивание по
/// максимальному `align` полей» - здесь она посчитана числами, и числа эти те
/// же, что выводит типовая сторона (`adamas-elab/src/flat.rs`): `Vec3` из трёх
/// `Float32` - 12 байт при выравнивании 4. Совпадение двух записей одного
/// числа проверяется тестом, а не обещанием: у понижения нет доступа к
/// элаборации, и вторая запись - цена шва.
///
/// Семейство с `Flat`-полями укладывается ею же (§10 вопрос 157): «тег плюс
/// payload размера максимума». Тег стоит первым, payload начинается по своей
/// границе, и `Option Int64` занимает 16 байт, а не 8, - названная §4.11 цена.
/// Один конструктор тега не требует - различать нечего - и укладывается как
/// запись; значение тега - **номер варианта**, а не общий [`CtorId`]:
/// последний нумерует таблицу всей программы, а тег различает конструкторы
/// одного семейства.
///
/// **Поле адресуется смещением, а не слотом**, и это названная цена варианта
/// (а) вопроса 154: раскладка «слово на слот» принадлежит объекту кучи Perceus,
/// а здесь байты лежат плотно.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Packing {
    /// Ширина тега в байтах. Ноль - запись либо единственный конструктор.
    pub tag: u32,
    /// Варианты по значению тега; у записи он один.
    pub variants: Vec<Variant>,
    /// Сколько байт занимает агрегат.
    pub size: u32,
    /// По какой границе стоит.
    pub align: u32,
}

impl Packing {
    /// Единственный вариант укладки без тега: запись либо один конструктор.
    ///
    /// `None` - укладка теговая, и полей «самой укладки» у неё нет: они у
    /// варианта, а вариант выбирает тег в рантайме.
    #[must_use]
    pub fn sole(&self) -> Option<&Variant> {
        match &self.variants[..] {
            [variant] if self.tag == 0 => Some(variant),
            _ => None,
        }
    }

    /// Вариант с таким конструктором и его номер - он же значение тега.
    #[must_use]
    pub fn variant_of(&self, ctor: CtorId) -> Option<(u32, &Variant)> {
        self.variants
            .iter()
            .position(|variant| variant.ctor == Some(ctor))
            .and_then(|at| Some((u32::try_from(at).ok()?, &self.variants[at])))
    }
}

/// Свойство «не разделён» - уникальность из **производства** (§10 вопрос 149).
///
/// Из кратности не выводится: `both : (1 x : Two) -> (1 y : Two) -> Two`,
/// позванная как `both shared shared`, принимается и считается - кратность
/// ограничивает, сколько раз связывание употребит **вызываемый**, а не то,
/// указывают ли два связывания на один объект. `noalias` по кратности - UB,
/// безусловный без-RC-путь по ней же - лишняя ячейка (`tests/perceus.rs`).
///
/// Законных источников `Certain` два, и оба производственные (§3.3, Entente
/// Cordiale: линейность про потребление, уникальность про производство).
/// Тип, уникальный по построению, - `unique data`/`resource`: ω-значений не
/// существует, и разделённым значение такого типа не бывает. И локально
/// видимый свежий источник - конструктор на месте, результат `reuse`.
///
/// Заполняет поле [`crate::unique`] - проходом по IR после вставки RC, и
/// **вторым** источником: маркер `unique data` живёт в элаборации и до шва не
/// доезжает, а на корпусе он достался бы тем же местам (почему - в доке того
/// модуля). Пишется только у параметров: свежесть переносится через вызов,
/// потому что локально свежий объект на корпусе не разбирается там же, где
/// построен (замер трека B, `tests/alias.rs`). Читает его
/// [`crate::emit_llvm`]: `Certain` снимает вопрос `adamas_is_unique` и печатает
/// одну ветвь дропа вместо двух. C-эмиттер игнорирует, как и прочие факты.
///
/// Чего `Certain` **не** меняет - числа выданных блоков: решение «переписать
/// или выдать» рантайм и без него принимает верно, а счётчик считает решения.
/// Ложное `Certain` его тоже не двигает - оно роняет прогон, забирая чужую
/// ячейку (`tests/alias.rs`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Unique {
    /// Производство уникально: unique-тип либо локально свежий объект.
    Certain,
    /// Про производство ничего не известно.
    Unknown,
}

/// Как уложены элементы массива (§4.11).
///
/// Раздваивается **представление, а не тип**: в исходном тексте `Array` один,
/// и различает эти два случая наличие `Flat` у элемента.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Elems {
    /// `n × size` байт подряд: ни заголовков у элементов, ни RC на запись.
    Flat,
    /// `n` указателей на объекты Perceus: запись есть `dup` нового плюс `drop`
    /// старого.
    Boxed,
}

