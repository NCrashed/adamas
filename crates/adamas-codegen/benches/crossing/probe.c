/* Чужая сторона стенда пересечения (трек D волны 1 Фазы 8, §5.3, §6).
 *
 * Собирается **отдельной единицей трансляции и без `-flto`**: настоящая чужая
 * библиотека лежит отдельным объектом, и прозрачное тело свернулось бы в тело
 * цикла - стенд померил бы инлайнинг вместо границы. Тот же довод и тот же
 * выбор, что у `boundary/probe.c` трека A.
 *
 * Число витков приходит **из окружения**, а не литералом в программе на
 * Adamas. Литерал дал бы компилятору право посчитать точку разложения целиком
 * на сборке: у неё внутри чистая арифметика, и свернуть её он вправе. Через
 * границу число приходит непрозрачным, и обе стороны замера считают одинаково
 * честно. Цена - одно лишнее пересечение на прогон. */

#include <stdint.h>
#include <stdlib.h>

/* Сколько витков крутить: `ADAMAS_BENCH_CALLS` окружения, ноль без неё. */
uint64_t adamas_bench_calls(void) {
    const char *written = getenv("ADAMAS_BENCH_CALLS");
    return written == NULL ? 0u : (uint64_t)strtoull(written, NULL, 10);
}

/* Виток тяжёлой пары: умножение и сложение, то же, что в точке разложения.
 * Константы - множитель и приращение из PCG; выбраны они за то, что результат
 * зависит от каждого витка, поэтому потерянный виток меняет ответ.
 *
 * Цепочка зависимости по данным у умножения - три такта, и вызов прячется в её
 * тени. Это не изъян стенда, а измеряемая величина: на теле такого веса
 * граница не стоит ничего. */
uint64_t adamas_bench_step(uint64_t accumulator) {
    return accumulator * 6364136223846793005u + 1442695040888963407u;
}

/* Виток лёгкой пары: поворот на бит, однотактная цепочка. Прятать вызов ей
 * нечем, и потому цена его здесь видна. Результат так же зависит от каждого
 * витка - поворот обратим. */
uint64_t adamas_bench_turn(uint64_t accumulator) {
    return (accumulator << 1) | (accumulator >> 63);
}

/* Виток пары займа: **тот же поворот**, и первый аргумент нарочно не читается.
 *
 * Не читается потому, что мерится цена **займа**, а не цена чтения по нему:
 * обе программы пары зовут ровно этот символ с ровно этой сигнатурой, и
 * разнятся только тем, откуда берётся первое слово - из адреса нагрузки нашего
 * массива либо из константы. Прочти он буфер - в разность вошла бы ещё и
 * загрузка из памяти, которой у словесной стороны нет. */
uint64_t adamas_bench_stir(uint64_t buffer, uint64_t accumulator) {
    (void)buffer;
    return (accumulator << 1) | (accumulator >> 63);
}

/* Цикл индиректных вызовов: чужая сторона зовёт колбэк на каждом витке.
 *
 * `noinline` стоит **ради симметрии замера**, а не ради строгости. Без него
 * компилятор вправе развернуть этот цикл внутрь `adamas_bench_native`, увидеть
 * там указатель константой, девиртуализовать вызов и встроить тело - и стенд
 * померил бы инлайнинг, а не цену колбэка. С ним обе половины пары ходят одним
 * и тем же индиректным вызовом, и разность есть ровно разница вызываемых. */
__attribute__((noinline)) uint64_t adamas_bench_through(uint64_t turns,
                                                        uint64_t (*step)(uint64_t)) {
    uint64_t accumulator = 1u;
    for (uint64_t at = 0; at < turns; at++) {
        accumulator = step(accumulator);
    }
    return accumulator;
}

/* Тот же поворот, что у `adamas_bench_turn`, но своей стороны границы. */
static uint64_t adamas_bench_local(uint64_t accumulator) {
    return (accumulator << 1) | (accumulator >> 63);
}

/* Тот же цикл со **своим** вызываемым: точка сравнения для колбэка. */
uint64_t adamas_bench_native(uint64_t turns) {
    return adamas_bench_through(turns, adamas_bench_local);
}
