/** Метка кадра - тег в его заголовке. Первые четыре те же, что у машины. */
typedef enum adamas_mark {
    /** Обычная отложенная работа. */
    ADAMAS_MARK_PLAIN = 0,
    /** Хендлер: на нём режется сегмент. */
    ADAMAS_MARK_HANDLER = 1,
    /**
     * Маска: пропускает один подходящий хендлер. Ставит её вектор
     * (`adamas_evidence_mask`), кадра у неё в этом рантайме нет.
     */
    ADAMAS_MARK_MASKING = 2,
    /**
     * Раскручиваемый хендлер. Подавление ставит **вектор** деструктора, а не
     * этот кадр: см. раздел «Подавление» в шапке. Метка оставлена ради
     * симметрии с машиной и обходом раскрутки не читается.
     */
    ADAMAS_MARK_SUPPRESSING = 3,
    /**
     * Питомник файберов (§5.2): под ним идёт файбер, ему же он отдаёт значение.
     *
     * Кадр свой у **каждого** файбера, а запись в таблице одна на круг: разрез
     * уступки идёт по этому кадру, и возобновление ставит файбер обратно под
     * свой питомник, а не под чужой. Сам питомник лежит в нулевом слоте среды
     * и слотом **не считается** - счётчика у него нет (см. `adamas_nursery`).
     */
    ADAMAS_MARK_NURSERY = 4,
    /** Scope, держащий ресурс: деструктор в слоте 0 (§3.3). */
    ADAMAS_MARK_CLOSING = 5,
    /**
     * Ответ scope, пережидающий деструктор: слот 0 - значение тела. Ответ
     * самого деструктора (`()`) дропается, значение идёт дальше. Аналог
     * `Frame::Closed` машины.
     */
    ADAMAS_MARK_CLOSED = 6,
    /**
     * Шаг раскрутки: слот 0 - значение, которым раскрутка кончится, слот 1 -
     * остаток цепочки сегментом. За шаг обрабатывается одно звено; кадр
     * перекладывается заново, поэтому вершина между шагами открыта тому, что
     * положили деструкторы и их release. Аналог `Frame::Unwinding` машины
     * (§10 вопрос 144). Мультишот его не копирует: ресурсы под `handleMulti`
     * запрещены статически (§10 вопрос 15), и копия падала бы на владении
     * цепочкой.
     */
    ADAMAS_MARK_UNWINDING = 7
} adamas_mark;

typedef struct adamas_segment adamas_segment;

/**
 * Чем занять место, когда придёт значение. Кадр заимствуется.
 *
 * Ручка стека идёт аргументом, потому что код кадра **вправе положить новые
 * кадры**: дроблёное тело второй формы есть цепочка таких кодов, и каждый из
 * них продолжает ровно там, где прошлый приостановился. Без ручки положить их
 * было бы некуда, а «кадр и есть часть стека» даёт кадр, но не вершину.
 */
typedef adamas_value (*adamas_frame_code)(adamas_frame *frame, adamas_kont *kont,
                                          adamas_value incoming);

/**
 * Ветки хендлера одной функцией: их выбирает номер операции (§3.4, решение 5
 * волны 4).
 *
 * Стоит отдельно от [`adamas_frame_code`], и причина не в удобстве: операция
 * приходит к своему хендлеру **через вектор evidence**, то есть с кадром на
 * руках и без единого статического знания о том, чьи это ветки. Ей нужны три
 * вещи, которых у кода кадра нет вовсе, - ручка стека (ветка вправе
 * производить), номер операции и её аргументы. Замыкание дало бы то же ценой
 * ячейки кучи на ветку, а формы веток известны месту `handle`.
 *
 * `arguments` - аргументы операции **владением**, `count` их число; лишние
 * (синтезированный триггер приостановленного вычисления) ветка дропает сама.
 * Окружающую ветки брать неоткуда, кроме кадра: она есть вектор на месте
 * `handle`, то есть [`adamas_frame_evidence`].
 *
 * Ответ - то, чем кончается ветка. У хвостово-резумптивной это **аргумент
 * `resume`**, то есть значение самой операции: возобновление на месте, без
 * снятия сегмента.
 */
typedef adamas_value (*adamas_handler_code)(adamas_frame *handler, adamas_kont *kont,
                                            uint32_t operation, adamas_value *arguments,
                                            size_t count);

/** Номер ветки `return`: она не операция, и своего номера у неё нет. */
#define ADAMAS_HANDLER_RETURN 0xFFFFFFFFu

/**
 * Дроп среды кадра; блок не освобождает. Ручка стека - для резумпций в среде:
 * их дроп кладёт раскрутку кадром, и класть её больше некуда.
 */
typedef void (*adamas_frame_release)(adamas_frame *frame, adamas_kont *kont);

/**
 * Стек продолжения второй формы понижения - её второй скрытый аргумент.
 *
 * Поле одно, и длины среди них нет: разрез сегмента обязан идти за постоянное
 * время, иначе операция под рекурсией стоит глубины, а прогон - квадрата
 * (§10 вопрос 94). Длину спрашивают диагностика и свидетели, и она считается
 * обходом - [`adamas_kont_depth`].
 */
struct adamas_kont {
    /** Вершина: ближайшая работа. `NULL` - стек пуст. */
    adamas_frame *top;
};

/** Пустой стек. */
void adamas_kont_init(adamas_kont *kont);

/** Кадров в стеке. Считается обходом; диагностика. */
size_t adamas_kont_depth(const adamas_kont *kont);

/**
 * Кладёт кадр на вершину и отдаёт его: среду заполняет вызывающий, а указатель
 * идёт в вектор evidence, если кадр - хендлер. Вектор заимствуется, кадр берёт
 * на него свою ссылку.
 *
 * `counted` - сколько первых слотов среды **считаются**: копия сегмента дупает
 * ровно их. Плоское значение лежит в слоте битами (§4.11), заголовка у него
 * нет, и `adamas_dup` по нему писал бы счётчик по чужому адресу; порядок слотов
 * поэтому - соглашение порождённого кода, счётные первыми.
 */
adamas_frame *adamas_kont_push(adamas_kont *kont, uint16_t mark, uint32_t label,
                               adamas_frame_code code, adamas_frame_release release,
                               size_t fields, size_t counted, const adamas_evidence *evidence);

/**
 * То же кадром `HANDLER`: вместо кода отложенной работы он несёт ветки.
 *
 * Отдельная точка входа, а не флаг: обычному кадру ветки не нужны, а кадру
 * хендлера не нужен код - работы у него нет, его дело быть найденным.
 */
adamas_frame *adamas_kont_handler(adamas_kont *kont, uint32_t label, adamas_handler_code branches,
                                  adamas_frame_release release, size_t fields,
                                  const adamas_evidence *evidence);

/**
 * Зовёт ветку операции у найденного кадра хендлера.
 *
 * Кадр приходит от [`adamas_evidence_lookup`] с вердиктом `HANDLER`;
 * `SUPPRESSED` сюда не идёт - у него свой путь через [`adamas_kont_abort`].
 * Аргументы передаются **владением**.
 */
adamas_value adamas_frame_perform(adamas_frame *handler, adamas_kont *kont, uint32_t operation,
                                  adamas_value *arguments, size_t count);

/**
 * Кадр `CLOSING` вокруг scope, держащего ресурс (§3.3): деструктор в слоте 0.
 *
 * Отдельная точка входа, а не [`adamas_kont_push`], по той же причине, что и у
 * хендлера: вектор здесь приходит `const` - у порождённого кода он такой, - а
 * работы у кадра нет, его дело быть найденным раскруткой. Деструктор берётся
 * **владением**; отдаёт его `release` кадра.
 */
adamas_frame *adamas_kont_closing(adamas_kont *kont, const adamas_evidence *evidence,
                                  adamas_frame_release release, adamas_value closer);

/** Среда кадра: массив на `adamas_frame_fields` слотов. */
adamas_value *adamas_frame_env(adamas_frame *frame);

/** Слотов в среде кадра. */
size_t adamas_frame_fields(const adamas_frame *frame);

/** Сколько первых слотов среды считаются RC. Остальные - плоские биты. */
size_t adamas_frame_counted(const adamas_frame *frame);

/** Метка кадра. */
uint16_t adamas_frame_mark(const adamas_frame *frame);

/** Метка эффекта у меченого кадра. */
uint32_t adamas_frame_label(const adamas_frame *frame);

/** Вектор evidence, действовавший на месте кадра. Заимствуется. */
adamas_evidence *adamas_frame_evidence(adamas_frame *frame);

/**
 * Режет стек от вершины до `handler` включительно **за постоянное время**.
 *
 * Кадр хендлера приходит из вектора evidence: поиска по стеку рантайм не ведёт,
 * и проверки принадлежности - тоже. Проверка была бы обходом сегмента, а
 * сегмент общей ветки растёт с глубиной рекурсии под хендлером: обход на каждой
 * операции даёт квадрат. Мерено на ряде 3200/6400/12800/25600 операций.
 */
adamas_segment *adamas_kont_cut(adamas_kont *kont, adamas_frame *handler);

/** Ставит сегмент обратно на вершину. Ручка сегмента потребляется. */
void adamas_kont_restore(adamas_kont *kont, adamas_segment *segment);

/**
 * Возобновление резумпции-значения: сегмент встаёт обратно, ручка **тратится**.
 *
 * От [`adamas_kont_restore`] отличается судьбой ручки: там она потреблена и
 * блок отдан, здесь блок остаётся жить, потому что на него могут указывать ещё
 * ссылки - резумпция есть обычное значение языка (§3.4), и счётчик у неё
 * обычный. Потраченная ручка пуста: дроп её просто освобождает, а второе
 * возобновление обрывает процесс - аффинность резумпции проверена типами
 * (§3.3), и нарушить её может только дефект понижения.
 *
 * **Мультишотная ручка** (`ADAMAS_FLAG_MULTI`) не тратится, пока на неё есть
 * лишние ссылки: возобновление ставит **копию** сегмента, и это цена §3.4 -
 * O(глубины) на каждый `resume`. Последняя ссылка (`rc == 0`) копии не делает:
 * второго возобновления взяться неоткуда, и сегмент отдаётся сам - тот же
 * договор об уникальности, что у reuse (§5.1, §10 вопрос 149). N возобновлений
 * стоят поэтому N-1 копий.
 */
void adamas_kont_resume(adamas_kont *kont, adamas_value resumption);

/**
 * Крутит стек, пока он не опустеет: вершина получает значение, отдаёт своё
 * следующей. Код кадра вправе положить новые кадры - они и станут вершиной.
 * Отработавший кадр освобождается сразу, поэтому среду код заимствует, и
 * пережившее кадр значение обязано пройти через `adamas_dup`.
 *
 * Три метки трамплин обрабатывает сам, кода у них нет вовсе. `CLOSING` -
 * деструктор срабатывает, а значение пережидает его кадром `CLOSED` и идёт
 * дальше: оно и есть ответ scope'а (§3.3). `HANDLER` - кадр снимается, а
 * значение уходит ветке `return`: нормальный выход из хендлера есть приход
 * значения вычисления к его кадру, и другого пути у дроблёного тела нет.
 * `UNWINDING` - шаг раскрутки.
 */
adamas_value adamas_kont_run(adamas_kont *kont, adamas_value value);

/**
 * То же, но с полом: крутит, пока вершиной не станет `floor`.
 *
 * Нужно направленному стилю. Раскрутка брошенного сегмента обязана кончиться
 * там, где стоял хендлер: ниже неё - живой C-кадр, который её и запустил, и
 * его работа не отложена кадром. `adamas_kont_run` есть частный случай с полом
 * `NULL`; цикл и модель у них одни, второй копии не заводится.
 */
adamas_value adamas_kont_run_to(adamas_kont *kont, adamas_frame *floor, adamas_value value);

/**
 * Обрыв: снимает всё до ближайшего кадра `UNWINDING` - кадры оборванного
 * деструктора, - кладёт их раскрутку кадром и отдаёт `()`. Вне раскрутки
 * такого кадра нет, и снимается весь стек - прежнее правило как частный
 * случай.
 *
 * Зовётся операцией, чей `adamas_evidence_lookup` ответил `SUPPRESSED`: ответа
 * хендлеру не даётся - первый уже дан веткой, - а scope'ы, открытые оборванным
 * кодом, закрываются, как требует §3.3. Отданное значение понижение обязано
 * вернуть немедленно: кадры, ради которых оно бы продолжалось, уже сняты, а
 * деструкторы их выполнит `adamas_kont_run` по дороге вниз.
 */
adamas_value adamas_kont_abort(adamas_kont *kont);

/** Кадров в сегменте. Считается обходом; диагностика. */
size_t adamas_segment_depth(const adamas_segment *segment);

/** Нижний кадр сегмента - им стоит хендлер. */
adamas_frame *adamas_segment_base(adamas_segment *segment);

/**
 * Копия сегмента: звенья свои, счётные поля общие через `dup`. Цена мультишота.
 *
 * Векторы evidence у копии тоже свои - по одному на различный вектор сегмента:
 * записи, называющие скопированные хендлеры, переписываются на их копии. Без
 * этого операция под возобновлённым сегментом резала бы стек по кадру
 * оригинала. Подробности - в шапке, «Копия сегмента переписывает вектор».
 */
adamas_segment *adamas_segment_copy(const adamas_segment *segment);

/**
 * Помечает ручку мультишотной: возобновление будет копировать (§3.4).
 *
 * Ставит это место `handleMulti` при разрезе; отдаёт ту же ручку значением,
 * чтобы порождённый код писал её одним выражением.
 */
adamas_value adamas_segment_multi(adamas_value resumption);

/**
 * Раскрутка: от вершины к основанию, деструкторы `CLOSING` в порядке LIFO.
 * Сегмент потребляется. Кладётся кадром `UNWINDING` на `kont` и возвращается:
 * деструкторы выполнит `adamas_kont_run` - см. «дроп резумпции - точка
 * приостановки» в шапке.
 */
void adamas_segment_unwind(adamas_kont *kont, adamas_segment *segment);

/**
 * Она же с готовым ответом: раскрутка кончится **этим** значением.
 *
 * Нужно отмене задачи (§5.2): разбор её значения ждёт того же значения обратно,
 * и второго пути отдать его нет - кадр раскрутки стоит между. Обычная
 * `adamas_segment_unwind` держит здесь `()`, потому что ответа её никто не
 * читает.
 */
void adamas_segment_unwind_holding(adamas_kont *kont, adamas_segment *segment, adamas_value held);

/** Сегмент как значение: резумпция - обычное значение языка (§3.4). */
adamas_value adamas_segment_value(adamas_segment *segment);

/** Обратное преобразование. */
adamas_segment *adamas_segment_of(adamas_value value);

/**
 * Дроп резумпции: последняя ссылка кладёт размотку приостановленного сегмента
 * кадром `UNWINDING` на `kont` - точка приостановки, см. шапку.
 *
 * Потраченная (возобновлённая) резумпция раскручивать нечего: её звенья уже
 * стоят на стеке, и последняя ссылка просто отдаёт блок ручки.
 *
 * Мультишотная, возобновлённая копией, потраченной **не** становится, и её
 * последняя ссылка раскручивает нетронутый оригинал. Деструкторов там нет ни
 * одного: ресурсы в scope `handleMulti` запрещены статически (§3.4), поэтому
 * раскрутка здесь есть чистое освобождение памяти.
 */
void adamas_resumption_drop(adamas_kont *kont, adamas_value value);

/**
 * Он же там, где ручки стека нет вовсе: слот замыкания, поле объекта.
 *
 * Раскрутка идёт **немедленно и на своём корне**, потому что взять чужой
 * неоткуда: `adamas_release` о стеке не знает по своей сигнатуре, а знать
 * обязан - резумпция есть обычное значение и в замыкание попадает наравне с
 * прочими (`\s -> resume v s` параметризованного хендлера, §3.4). Блок ручки
 * здесь **не** освобождается: его отдаёт тот, кто дропал, - таков договор
 * `adamas_release`.
 */
void adamas_segment_abandon(adamas_value value);

/**
 * Промоушен **захваченной резумпции** (§5.2): значения в средах её кадров.
 *
 * Резумпция есть обычное значение и уезжает в чужой поток наравне с прочими -
 * `\s -> resume v s` держит её в слоте замыкания, а замыкание бывает телом
 * `spawn`. Значения внутри её кадров при этом считались бы неатомарно.
 *
 * Разделение труда то же, что у [`adamas_share`]: обход **сегмента** знает
 * рантайм (сколько слотов среды счётные, говорит сам кадр), обход **данных**
 * приходит параметром. Близнеца `promote` у кадра поэтому не понадобилось.
 *
 * Саму цепочку кадров не метит: кадр уникален по построению, счётчик его
 * неизменно нуль.
 */
void adamas_segment_promote(adamas_value resumption, adamas_promote children);

/**
 * Снимает с нижнего кадра сегмента метку питомника: раскрутке он обычный.
 *
 * Нужно отмене одной задачи (§5.2). Сегмент уступившего файбера включает **его
 * собственный** кадр питомника - им возобновление ставит файбер обратно под
 * свой круг, - а раскрутке тот же кадр означает «питомник брошен» и вычерпывает
 * круг целиком: отмена одной задачи сносила остальные (ревью 2026-09-08 у
 * машины, `Segment::without_base`).
 *
 * Кадр **остаётся на месте**, а не снимается: вектор деструктора внутри
 * сегмента его называет, и снятый оставил бы висячий указатель. Раскрутка
 * пройдёт его звеном обычной работы и освободит в свой черёд - тогда же
 * отпустится и ссылка на питомник.
 */
void adamas_segment_disown_base(adamas_segment *segment);

/* ------------------------------------------------------------------ */
/* Питомник и файберы (§5.2)                                           */
/* ------------------------------------------------------------------ */

/**
 * Круг файберов: очередь готовых, ждущие чужого ответа и ответы договоривших.
 *
 * Модель повторяет машину (`adamas-interp/src/fiber.rs`) и не изобретается
 * заново. Файбер есть **сегмент того же стека**: уступка снимает его от кадра
 * питомника до вершины, пробуждение возвращает на место, копий не делается ни
 * одной. Резумпция файбера аффинна по построению - он либо в очереди, либо
 * бежит, - поэтому ресурс внутри задачи законен.
 *
 * Питомник **дожидается** порождённых (structured concurrency в смысле Trio) и
 * отвечает значением корневого файбера.
 *
 * Записью в вектор evidence питомник назван невыразимой меткой
 * [`ADAMAS_LABEL_NURSERY`], и «ближайший выигрывает» читается позициями
 * записей: вектор строится копией родителя плюс запись, значит порядок записей
 * и есть порядок вложенности. Ровно это у машины делает сравнение звеньев
 * (`Kont::nested` против `Kont::catching`).
 */
typedef struct adamas_nursery adamas_nursery;

/**
 * Невыразимая метка питомника: имени в языке у неё нет, и совпасть с меткой
 * эффекта она не может - номера меток понижение раздаёт снизу.
 */
#define ADAMAS_LABEL_NURSERY 0xFFFFFFFFu

/** Порождение без ответа (`spawnDetached`): тега у значения задачи нет. */
#define ADAMAS_NO_TASK 0xFFFFFFFFu

/**
 * Обслуживает ли операцию метки `label` питомник, а не написанный хендлер.
 *
 * Ближайший выигрывает - то же правило, по которому выбирается хендлер:
 * написанный `handle` над той же меткой значит написанное. Подавленная запись
 * питомника не считается вовсе (деструктор брошенного файбера бежит на чужом
 * стеке, и его кадра там нет), а подавленная запись хендлера считается наравне
 * с живой - у машины маску гасят и `Handler`, и `Suppressing`.
 */
int adamas_nursery_serves(const adamas_evidence *evidence, uint32_t label);

/**
 * `withNursery`: круг заводится, корневой файбер идёт под свежим кадром.
 *
 * Тело берётся **владением**. Вектор заимствуется и запоминается кругом: под
 * ним пойдёт всякий порождённый файбер, потому что стек его - это стек места
 * `withNursery` плюс собственный кадр питомника, и хендлеры, стоящие внутри
 * круга, файберу не видны (§5.2, dynamic scoping по своему сегменту).
 *
 * `release` порождает понижение по типу: круг держит чужие значения - ответы
 * договоривших, тела ещё не начатых, - а какие у них дети, знает тип.
 * `promote` - его близнец для [`adamas_share`], и нужен он только
 * многопоточному кругу: тело `spawn` и ответ договорившего пересекают поток, и
 * с этой минуты считаются атомарно (§5.1). Однопоточный круг его не зовёт
 * вовсе - промоушен там был бы чистым налогом в 4.2 раза на паре `dup`/`drop`.
 *
 * Ответ - значение вершине стека, как у всякой точки приостановки: круг
 * кончится, когда кадру питомника придёт значение последнего файбера.
 *
 * # Сколько потоков
 *
 * Читается это из окружения: `ADAMAS_THREADS` - целое не меньше единицы,
 * единица либо пусто значит «круг как был, однопоточный». Переменная, а не
 * умолчание: под настоящими потоками порядок файберов не определён, и всякая
 * программа со следом отвечала бы иначе, чем машина.
 *
 * Многопоточный круг **не выражает обрыва наружу себя** из мигрировавшего
 * файбера: под кадром питомника у воркера пусто. Рантайм говорит об этом
 * вслух.
 */
adamas_value adamas_nursery_begin(adamas_kont *kont, const adamas_evidence *evidence,
                                  adamas_value body, adamas_release release,
                                  adamas_promote promote);

/** `suspend`: текущий файбер уходит в хвост очереди, бежит следующий. */
adamas_value adamas_nursery_suspend(adamas_kont *kont, const adamas_evidence *evidence);

/**
 * `spawn` и `spawnDetached`: вычисление встаёт в очередь, звавший бежит дальше.
 *
 * Тело берётся владением. `tag` - конструктор типа задачи, `slots` его живых
 * полей, `at` - то из них, куда встаёт невыразимое имя файбера; тип этот
 * называет **написанный** результат `spawn`, вшитого имени у него нет.
 * [`ADAMAS_NO_TASK`] в `tag` значит `spawnDetached`: ответ - единица.
 */
adamas_value adamas_nursery_spawn(adamas_kont *kont, const adamas_evidence *evidence,
                                  adamas_value body, uint32_t tag, uint32_t slots, uint32_t at);

/**
 * `await`: ждущий уходит из круга, пока ожидаемый не договорит.
 *
 * Готовый ответ отдаётся сразу - тогда ждущий и не останавливается. Задача
 * берётся владением и потребляется здесь: разбора её значения не происходит,
 * поэтому и отмены нет (§5.2).
 */
adamas_value adamas_nursery_await(adamas_kont *kont, const adamas_evidence *evidence,
                                  adamas_value task, uint32_t at);

/**
 * Отмена: разбор значения задачи потребил её мимо `await` (§5.2).
 *
 * Зовётся **перед** разбором значения типа задачи и отдаёт то же значение:
 * файбера в круге нет - сразу, иначе - когда договорит раскрутка его сегмента.
 * Ещё не начатый отбрасывается молча, уступивший обрывается в suspend-точке:
 * деструкторы, набранные телом задачи, отрабатывают, а само тело не
 * досчитывается.
 *
 * Точка приостановки: раскрутка кладётся кадром и бежит трамплином.
 */
adamas_value adamas_nursery_cancel(adamas_kont *kont, adamas_value task, uint32_t at);

/**
 * Файбер отдал значение своему кадру: он договорил. Зовёт [`adamas_kont_run`].
 *
 * Значение берётся владением. Ответ - значение следующего шага круга: файбер
 * из очереди либо ответ самого питомника, если дожидаться больше некого.
 */
adamas_value adamas_nursery_finished(adamas_kont *kont, adamas_frame *frame, adamas_value value);

/**
 * Один брошенный файбер питомника: его сегмент надо раскрутить. Зовёт раскрутка.
 *
 * По одному, потому что раскрутка одного сегмента - один шаг; снятый обратно не
 * кладётся, поэтому обход конечен. `NULL` - брошенных больше нет, и круг на
 * этом закрывается.
 */
adamas_segment *adamas_nursery_abandoned(adamas_frame *frame);

/** Невыразимое имя файбера отпускает свой круг. Зовёт порождённый release. */
void adamas_fiber_name_release(adamas_value value);

#endif /* ADAMAS_H */
