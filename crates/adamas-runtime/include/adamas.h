int adamas_is_imm(adamas_value value);

/** Машинное целое как значение. Помещается 63 бита. */
adamas_value adamas_imm(intptr_t number);

/** Число из непосредственного значения. */
intptr_t adamas_imm_get(adamas_value value);

/** Нульарный конструктор: то же непосредственное, номером конструктора. */
adamas_value adamas_con0(uint16_t tag);

/** Значение `()` - нульарный конструктор с номером 0. */
adamas_value adamas_unit(void);

