//! Восстановление после отказа: граница определения (§10 вопрос 177).
//!
//! # Где проведена граница и почему не там, где предполагалось
//!
//! Постановка вопроса 177 называла стартовой гипотезой восстановление **в
//! разборе**: пропускать до следующего определения верхнего уровня, отдавая по
//! диагностике на каждое сломанное. Гипотеза измерена и отвергнута числом:
//! из 125 фикстур `tests/golden/errors` разбор роняет **одну**
//! (`variadic-off-the-boundary`), остальные 124 разбираются и падают в
//! элаборации. Восстановление в разборе покрыло бы меньше процента корпуса и
//! ни одного случая, которым вопрос был заведён: «три неизвестных имени в
//! файле» - отказ элаборации, а не синтаксиса.
//!
//! Граница поэтому взята та же (**определение верхнего уровня**), но проведена
//! в элаборации: отказ одного члена не роняет проход, а снимает с этого члена
//! всё остальное. Отравленного типа-поглотителя (вариант (б) вопроса 177) при
//! этом не заводится нигде: член, который не элаборировался, не даёт термов
//! вовсе, и работать с ним следующим проходам не приходится.
//!
//! # Выдуманная вторая ошибка
//!
//! Опасность здесь одна, и она названа в вопросе: после отказа состояние
//! прохода испорчено, и наивное продолжение выдаёт каскад следствий. Читателю
//! такой каскад хуже молчания - он правит то, чего не ломал.
//!
//! Правило против него одно: **отказ, ссылающийся на имя, которое объявить не
//! удалось, не печатается**. Имя того, кто такой отказ получил, при этом само
//! становится отсутствующим - следствие следствия молчит по той же причине, - и
//! цепочка `data Foo` → `x : Foo` → `y = x` даёт ровно один отказ, у корня.
//!
//! Подавление узкое нарочно: глотаются два вида отказа, «имя не найдено» и
//! «клаузы без сигнатуры», и только когда названное имя - то самое, которое не
//! объявилось. Широкое подавление хуже узкого: оно съедает настоящие ошибки
//! ниже по файлу, то есть возвращает ровно то молчание, ради устранения
//! которого восстановление и заводилось. Свидетели в
//! `adamas-elab/tests/recovery.rs` стоят поэтому парами: за каждым «здесь
//! молчит» - «а здесь говорит».
//!
//! # Чего здесь нет: постулат вместо отсутствия
//!
//! Напрашивается лечение сильнее. Сигнатура и клаузы в этом языке - разные
//! объявления (§4.8), поэтому у определения, чьё **тело** не собралось,
//! написанный тип уже проверен: объяви его постулатом, и всё, что зовёт это имя
//! ниже, читалось бы по написанному типу, а не молчало.
//!
//! Написано пробной правкой и отвергнуто прогоном: хранилище дырок отпускает их
//! на границе объявления, и написанный тип, переживший `define`, ссылается на
//! дырки, которых уже нет. Семнадцать фикстур корпуса роняли процесс паникой
//! «дырка ?N вне живого диапазона». Цена этого хода - порядок жизни
//! метапеременных, а не десять строк, и покупать его незачем: отсутствие имени
//! даёт тот же один отказ у корня, что видно по свидетелю следствия.

use std::collections::HashSet;
use std::rc::Rc;

use adamas_parser::ast::{self, DeclKind, Symbol};

use crate::error::ElabError;

/// Отказы файла и имена, которых после них в нём нет.
#[derive(Debug, Default)]
pub struct Refusals {
    /// Отказы в порядке появления, следствия уже отброшены.
    found: Vec<ElabError>,
    /// Написанные имена, объявить которые не удалось.
    absent: HashSet<Symbol>,
}

impl Refusals {
    /// Пусто.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Отказ определения вместе с именами, которые оно должно было объявить.
    ///
    /// Имена уходят в отсутствующие **в любом случае**, печатается ли отказ:
    /// объявления не случилось независимо от того, был ли сам отказ следствием.
    pub(crate) fn refused(&mut self, error: ElabError, declares: Vec<Symbol>) {
        if !self.induced(&error) {
            self.found.push(error);
        }
        self.absent.extend(declares);
    }

    /// Отказ - следствие уже записанного?
    ///
    /// Спрашивается по имени, а не по позиции: следствием тут называется ровно
    /// обращение к тому, чьё объявление не состоялось, и другого рода следствий
    /// эта граница не порождает - член, не прошедший элаборацию, не оставляет
    /// за собой ни термов, ни половины сигнатуры.
    fn induced(&self, error: &ElabError) -> bool {
        match error {
            // Два вида отказа на одно имя. «Имя не найдено» - у того, кто звал
            // необъявившееся. «Клаузы без сигнатуры» - у определения, чья
            // сигнатура отказала строкой выше: писать «нет сигнатуры» там, где
            // она написана, и значит выдумать вторую ошибку.
            ElabError::UnknownName { name, .. } | ElabError::MissingSignature { name, .. } => {
                self.absent(name)
            }
            // «Модуль не проходит проверку» - не сообщение, а способ поднять
            // отказ через границу файла: сами отказы уже разложены по своим
            // единицам ([`crate::program`]), каждый со своим текстом и своей
            // позицией. Печатать сверх них ещё и это значило бы сказать
            // читателю о чужом файле то, что в чужом файле уже сказано.
            ElabError::InModule { .. } => true,
            _ => false,
        }
    }

    /// Имя не объявлено - само либо своим префиксом.
    ///
    /// Префикс нужен члену модуля и подключённого файла: не объявился `M`, а
    /// написано `M.f`, и отсутствует по существу одно имя.
    fn absent(&self, name: &str) -> bool {
        self.absent.contains(name)
            || self.absent.iter().any(|it| {
                name.strip_prefix(&**it)
                    .is_some_and(|it| it.starts_with('.'))
            })
    }

    /// Был ли отказ.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.found.is_empty()
    }

    /// Отказы в порядке появления.
    pub fn iter(&self) -> impl Iterator<Item = &ElabError> {
        self.found.iter()
    }

    /// Первый отказ - тем, кто отвечает одним.
    pub(crate) fn first(self) -> Option<ElabError> {
        self.found.into_iter().next()
    }
}

/// Имена, которые объявление вводит, как они написаны.
///
/// Написанные, а не квалифицированные: сравниваются они с тем, что стоит в
/// отказе «имя не найдено», а туда попадает написанное.
///
/// Члены модуля и группы перечисляются рекурсивно. У модуля это мало что
/// меняет: его члены квалифицированы его именем, и префикс их и так покрывает.
/// У `mutual` перечисление единственное, что работает: члены группы стоят на
/// верхнем уровне под своими именами.
pub(crate) fn declares(decl: &ast::Decl) -> Vec<Symbol> {
    let mut out = Vec::new();
    match &decl.kind {
        DeclKind::Signature { name, .. }
        | DeclKind::Clauses { name, .. }
        | DeclKind::Alias { name, .. }
        | DeclKind::Module(ast::ModuleDecl { name, .. }) => out.push(Rc::clone(&name.text)),
        DeclKind::Extern(written) => out.push(Rc::clone(&written.name.text)),
        DeclKind::Data(data) => {
            out.push(Rc::clone(&data.name.text));
            out.extend(data.constructors.iter().map(|it| Rc::clone(&it.name.text)));
        }
        DeclKind::Effect(effect) => {
            out.push(Rc::clone(&effect.name.text));
            out.extend(effect.operations.iter().map(|it| Rc::clone(&it.name.text)));
        }
        DeclKind::Resource(resource) => {
            out.push(Rc::clone(&resource.name.text));
            out.extend(resource.members.iter().flat_map(declares));
        }
        // Методы класса - имена программы, а не члены класса (§4.4): класс, не
        // объявившийся, уносит их с собой. Имя самого инстанса необязательно.
        DeclKind::Class(class) => {
            out.extend(class.name.iter().map(|it| Rc::clone(&it.text)));
            out.extend(class.members.iter().flat_map(declares));
        }
        DeclKind::Mutual(members) => out.extend(members.iter().flat_map(declares)),
        // Не подключившийся файл уносит и свой префикс, и всё, что написано в
        // его `open`: под этими именами его члены и зовутся.
        DeclKind::Import(import) => {
            out.push(Rc::from(import.written().as_str()));
            out.push(Rc::from(import.prefix().as_str()));
            out.extend(import.open.iter().map(|it| Rc::clone(&it.text)));
        }
        // Фикситет и экспорт имён не вводят.
        DeclKind::Fixity(_) | DeclKind::Export(_) => {}
    }
    out
}
