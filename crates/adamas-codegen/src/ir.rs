//! Backend IR: шов между ядром и эмиттером.
//!
//! Представление одно на все бэкенды, и существует оно ради **фактов**, а не
//! ради узлов. Узлов здесь ровно столько, сколько требует чистый фрагмент;
//! факты - те, что знает тайпчекер и не восстановит алиас-анализ.
//!
//! # Зачем шов
//!
//! `docs/phase7-plan.md`: LLVM-бэкенд переносит факты QTT в `noalias`, scoped
//! `!alias.scope`/`!noalias`, `dereferenceable`. Устрой понижение как «ядро →
//! текст C», и факты гаснут на границе: из C-подобного представления
//! уникальность не восстанавливается - это ровно та задача, которую алиас-анализ
//! решает консервативно. Поэтому кратность и уникальность лежат **здесь**, а
//! эмиттер теряет их последним шагом.
//!
//! C-эмиттер их игнорирует целиком: сверх `restrict` в C выразить `noalias`
//! нечем, а ставить его наугад незачем. Существенно, что он их игнорирует, а не
//! что их нет.
//!
//! LLVM-эмиттер `noalias` не ставит **тоже**, и это измерено, а не забыто:
//! `noalias` на параметрах, `align 8` на слоте и `inbounds` у `getelementptr`
//! дают ноль инструкций разницы на трёх нагрузках (`tests/alias.rs`, трек B).
//! Уникальность он читает не ради атрибута, а ради ветвления.
//!
//! # Что лежит на связывании
//!
//! [`Fact`] - четыре поля, каждое со своим свидетелем в дизайне.
//!
//! *Кратность* (§3.2) есть у ядра дословно, и терять её нельзя. Чего из неё
//! **не** следует - алиасинг: см. [`Unique`] и §10 вопрос 149.
//!
//! *Уникальность* - «не разделён», и берётся она у **производства**, а не у
//! кратности (§10 вопрос 149). Заполняет [`crate::unique`], читает
//! [`crate::emit_llvm`]; что именно она даёт и чего не даёт - в доке
//! [`Unique`].
//!
//! *Регион* (§3.6) - место под непересечение `Ref r a`. Регионов сейчас нет, и
//! поле пусто у всех; заведено оно затем, чтобы Фаза 7 добавляла эмиттер, а не
//! меняла форму IR.
//!
//! # Почему RC живёт здесь, а не в эмиттере
//!
//! [`Expr::Dup`], [`Expr::Drop`], [`Expr::Reclaim`] и поле
//! [`reuse`](Expr::Construct::reuse) - узлы представления, а не приём печати.
//! Причина та же, по которой существует сам шов: LLVM-бэкенд Фазы 7 обязан
//! получить вставленный RC готовым. Устрой вставку эмиттером - и второй эмиттер
//! пришлось бы писать вместе со вторым Perceus'ом.
//!
//! *Наличие в рантайме* - не то же, что ненулевая кратность, и это измерено
//! машиной: решение дырки терма есть цепочка лямбд при `0`, а значения в них
//! настоящие - словарь класса приезжает в тело ровно таким спайном
//! (`adamas-interp/src/machine.rs`, `erases`). Поэтому кратность остаётся
//! фактом тайпчекера, а решение «эмитить или нет» стоит отдельным полем.
//!
//! *Представление* ([`Repr`]) - плоское значение против указательного (§4.11).
//! Это ABI, а не оптимизация, и читают его все трое: эмиттер выбирает C-тип,
//! [`perceus`](crate::perceus) не считает ссылок по плоскому, печать и дроп
//! объекта узнают по нему, какие слоты - числа, а какие - указатели.

