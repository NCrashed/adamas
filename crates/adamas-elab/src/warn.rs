//! Предупреждение - третий исход рядом с принятой программой и отказом.
//!
//! До этого модуля компилятор отвечал двумя: либо сигнатура, либо `ElabError`.
//! Дизайном же обещаны и предупреждения - умолчание литерала (§4.3), подъём
//! замкнутой row (§3.4), discoverability FBIP (§5.1), - и §10 вопрос 81 велел
//! заводить канал вместе с первым, кому он понадобится всерьёз.
//!
//! Первым оказалась цена вопроса 79: `{ x : Nat }` в домене читается
//! связыванием, а написана могла быть записью. Оба прочтения дают корректный
//! тип, поэтому отказом такое не поймать - различает их только то, что имя из
//! группы больше нигде не встречается.
//!
//! # Приёмник внутри, список наружу
//!
//! Предупреждения копятся в [`Warnings`] по ходу прогона и отдаются вместе с
//! сигнатурой. Ядро при этом не трогается вовсе: всё, что обещано сегодня,
//! живёт в элаборации.
//!
//! Уровень у диагностики здесь так и не завёлся, хотя ждали его от LSP (§7.2).
//! Сервер пришёл в волне 1 Фазы 9 и попросил другого: различать **отказ и
//! оговорку**, а не градации внутри оговорок. Это различие живёт в
//! [`crate::Severity`] снаружи списка, поэтому сам список остаётся однородным.

use adamas_core::source::Span;
use adamas_parser::ast::Symbol;

/// О чём компилятор предупреждает, приняв программу.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum Warning {
    /// Имя из implicit-группы не встречается в остатке типа (§10 вопросы 79, 81).
    #[error(
        "имя `{name}` из implicit-группы нигде не используется: в этой позиции \
         `{{ {name} : … }}` читается связыванием, а записью пишется как \
         `{{ {name} : … | r }}` (§4.2)"
    )]
    UnusedImplicit {
        /// Имя связывания.
        name: Symbol,
        /// Где написана группа.
        span: Span,
    },
    /// Литерал без типа из контекста взял умолчание по имени (§4.3).
    #[error("использую default {name}; для явного типа добавьте аннотацию (§4.3)")]
    DefaultedLiteral {
        /// Имя умолчания: `Int` либо `Float`.
        name: Symbol,
        /// Где стоит литерал.
        span: Span,
    },
    /// Связывание, которое никто не читает (§10 вопрос 218).
    #[error(
        "`{name}` - {what} - нигде не читается; если так и задумано, назовите \
         его `_{name}`"
    )]
    UnusedBinding {
        /// Что это за связывание - подлежащим: «связывание `let`».
        what: &'static str,
        /// Имя.
        name: Symbol,
        /// Где оно связано.
        span: Span,
    },
    /// Результат, отброшенный строкой, хотя он что-то несёт (§10 вопрос 207).
    ///
    /// Молчит у семейства с единственным конструктором без полей - `Unit` и
    /// всякий его двойник: отбрасывать там нечего. Явное «прочёл и выбросил»
    /// пишется `let _ = …`.
    #[error("результат типа `{ty}` отбрасывается; если так и задумано, напишите `let _ = …`")]
    DiscardedResult {
        /// Голова типа результата.
        ty: Symbol,
        /// Где стоит строка.
        span: Span,
    },
    /// Имя из списка импорта, которое файл не употребляет (§10 вопрос 218).
    #[error("`{name}` импортировано из `{module}`, но нигде не употребляется")]
    UnusedImport {
        /// Откуда.
        module: Symbol,
        /// Имя.
        name: Symbol,
        /// Где оно в списке импорта.
        span: Span,
    },
}

impl Warning {
    /// Где предупреждение показывать.
    #[must_use]
    pub fn span(&self) -> Span {
        match self {
            Self::UnusedImplicit { span, .. }
            | Self::DefaultedLiteral { span, .. }
            | Self::UnusedBinding { span, .. }
            | Self::UnusedImport { span, .. }
            | Self::DiscardedResult { span, .. } => *span,
        }
    }
}

/// Собранное за прогон. Пусто - программа принята без оговорок.
pub type Warnings = Vec<Warning>;
