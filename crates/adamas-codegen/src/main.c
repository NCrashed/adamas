/* Точка входа: печать ответа и счётчики блоков.
 *
 * Форм у ответа две, и различает их представление (§4.11). Боксированный
 * приходит владением, как всё в этом понижении, и дропается здесь же. Плоский
 * лежит в регистре: заголовка у него нет, счётчика нет, отдавать нечего -
 * печатается он по сорту, который назвало понижение.
 */

static void adamas_answer(void) {
#ifdef ADAMAS_ANSWER_FLAT
    ADAMAS_ANSWER_TYPE answer = ADAMAS_ENTRY();
    adamas_print_flat(ADAMAS_ANSWER_KIND, ADAMAS_ANSWER_FLAT(answer), 0);
    printf("\n");
#else
    adamas_value answer = ADAMAS_ENTRY();
    adamas_print(answer, 0);
    printf("\n");
    /* Не отдай его здесь - живым остался бы ровно он, и счётчик показал бы это
     * числом. */
    adamas_drop_value(answer);
#endif
}

int main(void) {
    /* Первой строкой: границы стека считаются от кадра `main`, и всё, что
     * ниже, обязано быть под правилом. Горячему пути это не стоит ничего -
     * см. шапку `c/stack.c`. */
    adamas_stack_guard();
    adamas_answer();
    /* Выдано против живого. Второе - критерий «течи нет»; первое - свидетель
     * reuse и плоского значения разом: переписанная ячейка выдачей не
     * считается, а под арифметику ячейка не выдаётся вовсе.
     *
     * Сумма **по всем потокам**, а не ряд этого: круг питомника вправе идти на
     * нескольких (§5.2, `ADAMAS_THREADS`), и блок, выданный воркером, в ряд
     * главного не попадает вовсе. У однопоточной программы ряд один, и число
     * от этого не меняется ни на единицу. */
    fprintf(stderr, "блоков выдано %zu, живо %zu\n", adamas_stat_allocated_everywhere(),
            adamas_stat_live_everywhere());
    /* Строка эта появляется **только** у многопоточного прогона, и порядок тут
     * обратный обычному: она и есть наблюдаемое, а не диагностика. Без неё
     * прогон с `ADAMAS_THREADS=4` неотличим от однопоточного - ответ у
     * программы тот же, - и свидетель проверял бы, что она просто не сломалась.
     * Однопоточный вывод от этого не меняется ни на символ: рядов у него один. */
    if (adamas_stat_threads() > 1) {
        fprintf(stderr, "потоков выдавало %zu\n", adamas_stat_threads());
    }
    return 0;
}
