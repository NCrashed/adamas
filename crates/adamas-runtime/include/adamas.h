/* Вектор evidence                                                     */
/* ------------------------------------------------------------------ */

typedef struct adamas_evidence adamas_evidence;
typedef struct adamas_frame adamas_frame;
typedef struct adamas_kont adamas_kont;

/**
 * Первая форма понижения: чистый и хвостово-резумптивный код. Скрытых
 * аргументов нет **вовсе** - написанное и есть всё (§13, 2026-09-08).
 */
typedef adamas_value (*adamas_lowered_first)(adamas_value argument);

/**
 * Вторая форма: функция, способная оказаться под общим или мультишотным
 * хендлером. Несёт два скрытых аргумента - вектор evidence и ручку стека
 * продолжения, рядом.
 *
 * Стек ей нужен, чтобы отчуждать кадр, резать сегмент и обрываться; вектор -
 * чтобы находить хендлер. Первая форма не делает ни того, ни другого и не
 * платит ни за что.
 */
typedef adamas_value (*adamas_lowered_second)(const adamas_evidence *evidence, adamas_kont *kont,
                                              adamas_value argument);

/** Запись подавлена: её хендлер ответ уже дал (§3.3, раскрутка). */
#define ADAMAS_EV_SUPPRESSED 0x0001u

/** Чем кончился поиск метки в векторе. Ответов три, и это существенно. */
typedef enum adamas_lookup {
    /** Хендлера нет вовсе - операция без хендлера. */
    ADAMAS_LOOKUP_MISSING = 0,
    /** Нашёлся живой: `handler` есть его кадр. */
    ADAMAS_LOOKUP_HANDLER = 1,
    /** Нашёлся подавленный: операция обрывает свой деструктор. */
    ADAMAS_LOOKUP_SUPPRESSED = 2
} adamas_lookup;

/** Пустой вектор. */
adamas_evidence *adamas_evidence_empty(void);

/**
 * Вектор родителя плюс запись о хендлере метки. Копирует: вектор неизменяем.
 * Запись хендлером не владеет - им владеет цепочка кадров.
 */
adamas_evidence *adamas_evidence_extend(const adamas_evidence *parent, uint32_t label,
                                        adamas_frame *handler);

/** Записей в векторе. */
size_t adamas_evidence_count(const adamas_evidence *evidence);

/** Кадр хендлера по статической позиции - тот самый доступ без смещения. */
adamas_frame *adamas_evidence_at(const adamas_evidence *evidence, size_t index);

/** Метка записи по позиции. */
uint32_t adamas_evidence_label_at(const adamas_evidence *evidence, size_t index);

/**
 * Ближайшая запись метки, пропустив `skip` подходящих: так считаются маски
 * (§3.4, §10 вопрос 72). Подавленная запись подходящей считается наравне с
 * живой - маску гасит и она.
 *
 * Ответ трёхзначный, и **сводить его к двум нельзя**: подавленная запись не то
 * же, что отсутствующая. Приняв её за отсутствие, поиск ушёл бы к одноимённому
 * хендлеру снаружи, а тому ответ деструктора деть некуда - это ровно дефект,
 * найденный ревью 2026-09-05 в интерпретаторе.
 *
 * `handler` (может быть `NULL`) получает кадр найденной записи.
 */
int adamas_evidence_lookup(const adamas_evidence *evidence, uint32_t label, size_t skip,
                           adamas_frame **handler);

/** Копия вектора: та же длина, те же записи, свой счётчик. */
adamas_evidence *adamas_evidence_copy(const adamas_evidence *evidence);

/**
 * Помечает подавленной запись **этого кадра**-хендлера; чужие не трогает.
 * Правит на месте, поэтому вектор обязан быть свежей копией.
 *
 * По кадру, а не по метке: двух одноимённых хендлеров в цепочке ничто не
 * запрещает, и подавить надо тот, чей ответ уже дан.
 */
void adamas_evidence_suppress(adamas_evidence *evidence, const adamas_frame *handler);

/** Берёт лишнюю ссылку на вектор. */
adamas_evidence *adamas_evidence_dup(adamas_evidence *evidence);

/** Отдаёт ссылку; на последней освобождает. */
void adamas_evidence_drop(adamas_evidence *evidence);

