//! Аллоцирует ли определение в куче Perceus - вердикт для `@noalloc` (§5.1).
//!
//! Жанр тот же, что у [`crate::total`]: считает ядро по телу и графу вызовов,
//! а атрибут поверхностного языка требует, чтобы ответ был «нет». Хранится
//! вердикт не булевым, а первым найденным источником
//! ([`Definition::allocates`]): §5.1 требует от диагностики назвать, что именно
//! аллоцирует, иначе атрибут превращается в загадку.
//!
//! # Где проходит линия
//!
//! По видимости в сигнатуре, а не по цене. Запрещена аллокация, не названная в
//! типе, - куча Perceus. Аллокация в регионе (`{Alloc r}`, §3.6) нарушением не
//! считается: она объявлена в row и видна автору. Стек не в счёт вовсе - о
//! глубине рекурсии атрибут не говорит ничего, поэтому рекурсивное определение
//! под ним законно.
//!
//! # Что проверка видит
//!
//! - применение конструктора **с рантайм-полем** и построение записи: значение
//!   уходит в кучу;
//! - замыкание - лямбда сверх параметров определения либо частичное применение;
//! - вызов определения с отрицательным вердиктом: это и есть вывод по графу
//!   вызовов внутри пакета (§5.1);
//! - вызов определения без тела, на котором `@noalloc` не написан: обязательство
//!   через границу объявляется, а не выводится из чужого кода (§5.1);
//! - вызов операции эффекта;
//! - площадка `handle`, чья ветка зовёт `resume` вне хвостовой позиции, и
//!   всякая площадка `handleMulti`: продолжение снимается в сегмент кучи.
//!   Вердикт считает [`crate::resume`], и берётся из него **одно** из трёх
//!   значений - общий случай. Хвостовая ветка продолжения не трогает,
//!   абортивная его отбрасывает, и обе под `@noalloc` законны.
//!
//! Стёртое не считается: определение кратности `0`, аргумент на связывании `0`,
//! `let 0`, мотив разбора, всякий тип. Иначе индекс `Succ n` в аргументе
//! отвергал бы любую функцию над индексированным семейством.
//!
//! # Конструктор без рантайм-полей - не объект
//!
//! `Zero`, `Leaf`, `MkRef` при стёртом `r`: указатель с младшим битом 1 есть
//! непосредственное значение - номер конструктора, - и `dup` с `drop` по нему
//! суть проверка бита (ABI, лог 2026-09-08). Аллокации нет, и такой конструктор
//! под `@noalloc` законен. Граница считается по телескопу: аллоцирует тот, у
//! кого есть хотя бы одно связывание кратности не `0`. Параметры семейства
//! стоят в типе конструктора стёртыми и в счёт не идут - иначе `Leaf` у
//! `Tree (a : Type)` отличался бы от `Zero` у `Nat` без всякой причины.
//!
//! # Что не покрыто
//!
//! **Reuse.** §5.1 разрешает конструктор с полями там, где reuse гарантирован, -
//! на линейном или unique входе. Perceus'а нет, уникальность в точке разбора
//! никто не считает, поэтому такой конструктор аллоцирует здесь всегда.
//! Направление консервативно: отвергается часть законных определений, но не
//! принимается ни одно аллоцирующее.
//!
//! **Операция без своей площадки.** Анализ хвостовой резумптивности
//! ([`crate::resume`]) отвечает по **площадке** `handle`: её ветки стоят тут же,
//! аргументами спайна, и вердикт по ним точен. Вызов операции площадки не
//! называет: какой хендлер её перехватит, решает место применения, а у
//! эффектно-полиморфной функции - и вовсе её вызывающий. Ответ «все площадки
//! этой метки в программе хвостовые» выражается ([`crate::resume::labels`]) и
//! здесь **не** спрашивается: вердикт считается при объявлении группы, а
//! площадка, написанная ниже, в него ещё не вошла бы - тот же порядковый капкан,
//! который §3.4 у ресурсов под `handleMulti` закрывает предпроходом. Поэтому
//! всякая операция по-прежнему считается аллоцирующей: отвергается лишнее, не
//! принимается аллоцирующее.
//!
//! **Боксирование** в указательную позицию (§4.11) требует класса `Flat`, а
//! `Lazy` в языке ещё нет вовсе. Оба источника §5.1 перечисляет, и оба здесь
//! отсутствуют не по решению, а по отсутствию предмета.
//!
//! **Release-lowering.** §5.1 говорит, что проверка идёт по нему: мономорфизация
//! обязательна в release, а debug вправе боксировать. Понижения нет, и считается
//! вердикт по терму ядра; появится - проверке переезжать туда.
//!
//! **Граница пакета.** Пакетов нет, но форма обязательства есть: постулат. Он
//! и служит границей - `@noalloc` на нём **принимается** и объявляет
//! обязательство, а вызов постулата без атрибута аллоцирует. Проверить обещание
//! при этом нечем, и это ровно то же, чем `@total` обходится с постулатом:
//! тела нет, разворачивать нечего.

use std::fmt;
use std::rc::Rc;

use crate::error::Frame;
use crate::meta::{Metas, zonk_term};
use crate::mult::Mult;
use crate::sig::{Definition, DefinitionKind, Signature};
use crate::term::{Case, Name, Term, spine};

/// Чем определение аллоцирует.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Source {
    /// Применение конструктора с рантайм-полем: значение строится в куче.
    Construct(Name),
    /// Литерал записи или её обновление.
    Record,
    /// Лямбда сверх параметров: окружение уходит в кучу.
    Closure,
    /// Частичное применение: недостающие аргументы ждут в замыкании.
    Partial(Name),
    /// Вызов операции эффекта.
    Operation(Name),
    /// Площадка `handle`, чья ветка снимает продолжение в сегмент кучи.
    ///
    /// Вердикт считает [`crate::resume`]; сюда попадает только
    /// [`crate::resume::Verdict::General`]. Хвостовая ветка продолжения не
    /// трогает, абортивная его отбрасывает - «раскрутка до метки плюс
    /// отложенные деструкторы, ноль аллокаций» (§5.1), - и обе здесь законны.
    Resumption {
        /// Метка, которую площадка снимает.
        effect: Name,
        /// Операция, чья ветка виновата. `None` - платит сама форма:
        /// `handleMulti` копирует сегмент на каждое возобновление, и ветки тут
        /// ни при чём (§3.4).
        operation: Option<Name>,
    },
    /// Применение значения-функции: аргумент уходит слотом замыкания.
    ///
    /// Слот говорит указателем, и плоский аргумент на этой границе
    /// **боксируется** (§4.11, §10 вопрос 158) - объект под него и есть
    /// аллокация. Типов у вердикта нет - считается по терму, - поэтому
    /// аллоцирующим признаётся всякое такое применение: консервативно в ту же
    /// сторону, что прочие пробелы, - отвергается лишнее, не принимается
    /// аллоцирующее.
    Boxing,
    /// Вызов определения без тела, на котором обязательство не объявлено.
    Opaque(Name),
    /// Вызов определения, чей вердикт отрицателен.
    Call(Name),
}

/// Цепочка от определения к тому, что аллоцирует на самом деле.
///
/// «`f` зовёт аллоцирующее `g`» без продолжения не говорит, что чинить, поэтому
/// цепочка идёт по графу вызовов до первого не-вызова.
///
/// # Чем адресуется звено и чем - конец
///
/// Звенья - **имена**, и место каждого берётся у того же определения, что его
/// зовёт: у всякого члена цепочки есть свой источник аллокации со своим местом
/// в **его собственном** теле ([`Signature::allocated_at`]). `f` зовёт `g` -
/// место у `f`; `g` строит `MkPair` - место у `g`. Конец пути поэтому
/// адресуется так же, как звенья, а не отдельно.
///
/// Объявление звена - другое место и берётся другой таблицей
/// ([`Signature::origin`]): туда ведёт переход, а не подсказка. Звенья
/// [`Blame::through`] в ней есть все по построению - в цепочку попадает только
/// [`Source::Call`], а его записывают определению **с телом**, то есть с
/// клаузами.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Blame {
    /// Кого зовут по пути. Само определение сюда не входит.
    through: Vec<Name>,
    /// Что аллоцирует в конце пути.
    source: Source,
}

impl Blame {
    /// Кого зовут по пути, снаружи внутрь. Само определение сюда не входит.
    #[must_use]
    pub fn through(&self) -> &[Name] {
        &self.through
    }

    /// Что аллоцирует в конце пути.
    #[must_use]
    pub const fn source(&self) -> &Source {
        &self.source
    }

    /// Кому принадлежит место аллокации - последнему звену либо самому
    /// определению, если звеньев нет.
    ///
    /// Именно это имя спрашивают у [`Signature::allocated_at`]: источник стоит
    /// в теле того, кто его написал, а не того, кто до него дозвался.
    #[must_use]
    pub fn owner<'a>(&'a self, name: &'a Name) -> &'a Name {
        self.through.last().unwrap_or(name)
    }
}

/// Чем определение нарушает `@noalloc`. `None` - не нарушает.
///
/// Читает сохранённые вердикты и тел не трогает: зовут её после границы
/// объявления, где дырки уже освобождены, а зонканье там падает.
#[must_use]
pub fn blame(signature: &Signature, name: &Name) -> Option<Blame> {
    let mut source = signature.lookup(name)?.allocates.clone()?;
    let mut through: Vec<Name> = Vec::new();
    while let Source::Call(callee) = &source {
        let callee = Rc::clone(callee);
        // Цикл взаимной рекурсии обрывает цепочку: по нему идут те же имена.
        if callee == *name || through.contains(&callee) {
            break;
        }
        let Some(next) = signature
            .lookup(&callee)
            .and_then(|it| it.allocates.clone())
        else {
            break;
        };
        through.push(callee);
        source = next;
    }
    Some(Blame { through, source })
}

impl fmt::Display for Blame {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for callee in &self.through {
            write!(f, "зовёт `{callee}`, а та ")?;
        }
        match &self.source {
            Source::Construct(name) => write!(
                f,
                "строит значение конструктором `{name}` - это куча Perceus. Выходов три (§5.1): \
                 линейный или unique вход, где reuse гарантирован; регион `{{Alloc r}}`; отказ от \
                 конструирования. Первых двух в компиляторе пока нет, так что остаётся третий"
            ),
            Source::Record => write!(
                f,
                "строит запись - это куча Perceus. Выходов три (§5.1): линейный или unique вход, \
                 где reuse гарантирован; регион `{{Alloc r}}`; отказ от конструирования. Первых \
                 двух в компиляторе пока нет, так что остаётся третий"
            ),
            Source::Closure => write!(
                f,
                "создаёт замыкание: лямбда стоит сверх параметров, и окружение её уходит в кучу"
            ),
            Source::Partial(name) => write!(
                f,
                "применяет `{name}` частично, а недостающие аргументы ждут в замыкании"
            ),
            Source::Operation(name) => write!(
                f,
                "зовёт операцию `{name}`: аллоцирует ли она, решает ветка того хендлера, который \
                 её перехватит, а в точке вызова он неизвестен. Вердикт хвостовой резумптивности \
                 (§3.4) считается по площадке `handle`, и площадка эта здесь не написана"
            ),
            Source::Resumption {
                effect,
                operation: Some(operation),
            } => write!(
                f,
                "ставит хендлер `{effect}`, чья ветка `{operation}` зовёт `resume` вне хвостовой \
                 позиции: продолжение приходится снять в сегмент кучи (§3.4, §5.1). Хвостовая \
                 ветка продолжения не трогает, абортивная его отбрасывает - обе законны"
            ),
            Source::Resumption {
                effect,
                operation: None,
            } => write!(
                f,
                "ставит `handleMulti` над `{effect}`: ω-резумпция не обещает «не более одного \
                 раза», и сегмент копируется в кучу на каждое возобновление (§3.4, «Стоимость \
                 multi-shot»)"
            ),
            Source::Opaque(name) => write!(
                f,
                "зовёт `{name}`, у которой нет тела и не написан `@noalloc`: через границу \
                 обязательство объявляется, а не выводится из чужого кода (§5.1)"
            ),
            Source::Boxing => write!(
                f,
                "применяет значение-функцию: аргумент уходит слотом замыкания, а слот говорит \
                 указателем, и плоский аргумент на этой границе боксируется (§4.11). Типов у \
                 вердикта нет, поэтому аллоцирующим считается всякое такое применение"
            ),
            Source::Call(name) => write!(f, "зовёт `{name}`, а та аллоцирует"),
        }
    }
}

/// Аллоцирует ли применение конструктора. `None` - нет.
///
/// Аллоцирует тот, у кого есть хотя бы одно **рантайм-поле**: связывание
/// кратности не `0`. Конструктор без таких полей объектом не становится вовсе -
/// указатель с младшим битом 1 несёт его номер непосредственно (ABI, лог
/// 2026-09-08), - и `Zero`, `Leaf`, `Nil` под `@noalloc` законны.
///
/// Параметры семейства стоят в типе конструктора стёртыми и в счёт не идут:
/// иначе `Leaf` у `Tree (a : Type)` отличался бы от `Zero` у `Nat` без всякой
/// причины, а хранят они одно и то же - ничего.
#[must_use]
pub fn constructed(name: &Name, ty: &Term) -> Option<Source> {
    let mut current = ty;
    while let Term::Pi(binder, _, _, _, codomain) = current {
        if binder.mult != Mult::Zero {
            return Some(Source::Construct(Rc::clone(name)));
        }
        current = codomain;
    }
    None
}

/// Источник аллокации вместе с маршрутом до него.
///
/// Маршрут - тот же, каким ядро называет место отказа (§10 вопрос 49б,
/// [`crate::error::Frame`]): спанов на узлах терма нет и не будет, а кадрами
/// место проходится второй раз по дереву поверхностного языка. Переводит его в
/// спан элаборация - единственная, у кого дерево есть, - и кладёт ответ в
/// [`Signature::allocated_at`].
///
/// Тот же механизм уже носит `@fbip` ([`crate::fbip::Incompatible`]), и кадры
/// здесь складываются **теми же правилами**: разойдись они, один и тот же
/// подтерм получал бы у двух проверок разные места.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Found {
    /// Что аллоцирует.
    pub source: Source,
    /// Маршрут до места **снаружи внутрь**, от корня тела.
    pub route: Vec<Frame>,
}

/// Первый источник аллокации определения вместе с местом. `None` - не
/// аллоцирует.
///
/// Зовётся на границе объявления, где дырки ещё живы: тело зонкается, потому что
/// словарь метода инстанса стоит в нём дыркой (§10 вопрос 134), а за ней прячутся
/// и вызовы, и конструкторы.
///
/// Вердикт вызываемых берётся из сигнатуры. Внутри объявляемой группы он там
/// оптимистичный - «не аллоцирует», - и понижает его неподвижная точка
/// вызывающего: цикл не аллоцирующих функций не аллоцирует, поэтому старт сверху
/// верен.
///
/// У определения **без тела** маршрут пуст: источник там не написан внутри, а
/// выведен из вида объявления, и указывать в нём не на что.
#[must_use]
pub fn source(
    signature: &Signature,
    metas: &Metas,
    name: &Name,
    definition: &Definition,
) -> Option<Found> {
    let Some(body) = &definition.body else {
        let source = match &definition.kind {
            // Формер - тип: значений в рантайме у него нет.
            DefinitionKind::Data { .. } | DefinitionKind::Effect { .. } => None,
            DefinitionKind::Constructor { .. } => constructed(name, &definition.ty),
            DefinitionKind::Operation { .. } => Some(Source::Operation(Rc::clone(name))),
            // Постулат: тела нет, и вывести вердикт не из чего. Снимает этот
            // ответ написанный `@noalloc` - [`Signature::promise_noalloc`], -
            // потому что через границу обязательство объявляется (§5.1).
            DefinitionKind::Regular => Some(Source::Opaque(Rc::clone(name))),
        };
        return source.map(|source| Found {
            source,
            route: Vec::new(),
        });
    };
    let body = zonk_term(metas, body);
    let mut walk = Walk {
        signature,
        found: None,
        route: Vec::new(),
    };
    walk.parameters(&body);
    walk.found
}

/// Обход тела до первого источника.
struct Walk<'a> {
    signature: &'a Signature,
    /// Найденное. Дальше первого не ищется: диагностика называет одно место.
    found: Option<Found>,
    /// Где обход стоит сейчас - снаружи внутрь.
    route: Vec<Frame>,
}

impl Walk<'_> {
    /// Снимает лямбды-параметры и обходит остаток.
    ///
    /// Снимаются **все** ведущие. `mk n = \m -> plus n m` и `mk n m = plus n m`
    /// дают один и тот же терм ядра, и отличить возвращённое замыкание от лишнего
    /// параметра здесь нечем; понижение с известной арностью поступает так же.
    fn parameters(&mut self, term: &Term) {
        let mut current = term;
        while let Term::Lam(_, _, body) = current {
            // Кадр дописывает тот, кто узел строит (`pattern::Tree`): обернул
            // лямбдой - дописал `Body`. Не дописать его здесь значило бы
            // разойтись с маршрутами клауз, по которым место и ищется.
            self.route.push(Frame::Body);
            current = body;
        }
        self.term(current);
    }

    fn record(&mut self, source: Source) {
        if self.found.is_none() {
            self.found = Some(Found {
                source,
                route: self.route.clone(),
            });
        }
    }

    /// Спускается в подтерм, дописав кадры пути до него.
    fn under(&mut self, path: &[Frame], term: &Term) {
        let before = self.route.len();
        self.route.extend_from_slice(path);
        self.term(term);
        self.route.truncate(before);
    }

    fn term(&mut self, term: &Term) {
        if self.found.is_some() {
            return;
        }
        match term {
            // Переменная берёт готовое, а универсум, сорт ряда, `Effect`, тип
            // записи, ряд и стрелка - типы: в рантайме их нет вовсе. Дырка
            // здесь же: тело зонкано, и пережившая зонканье дырка - это
            // нерешённое, которое объявление отвергнет своим чередом.
            // Примитив тут же: плоское значение заголовка не имеет и в куче
            // Perceus не лежит вовсе (§4.11, запись ABI 2026-09-08), поэтому
            // `@noalloc` он не нарушает - ни тип, ни литерал, ни операция.
            Term::Var(_)
            | Term::Universe(_)
            | Term::RowKind(_)
            | Term::EffectKind
            | Term::Meta(_)
            | Term::Record(_)
            | Term::Row(_)
            | Term::Prim(_)
            | Term::Pi(..) => {}

            // У полей записи кадра нет: маршрут обрывается здесь, и спан
            // получится тот, до которого он дошёл (§10 вопрос 49б). То же
            // правило, что у [`crate::fbip`].
            Term::Object(fields) => {
                self.record(Source::Record);
                for (_, value) in fields.iter() {
                    self.term(value);
                }
            }
            Term::With(base, fields) => {
                self.record(Source::Record);
                self.term(base);
                for (_, value) in fields.iter() {
                    self.term(value);
                }
            }
            Term::Project(record, _) => self.term(record),

            Term::Lam(..) => self.record(Source::Closure),

            Term::Const(name, _, _) => self.constant(name, 0),

            Term::App(..) => {
                let (head, arguments) = spine(term);
                match head {
                    // Элиминатор спрашивается до вида: тела у него нет, и без
                    // вердикта он ушёл бы в `Opaque` - ровно то, чем «анализа
                    // нет» и оборачивалось.
                    Term::Const(name, _, _)
                        if crate::resume::eliminated(name).is_some()
                            && self.handling(name, &arguments) => {}
                    Term::Const(name, _, _) => {
                        // Место у источника - **всё применение**, а не его
                        // голова: читателю подчёркивают `MkPair x y`, а не
                        // одно имя конструктора. Кадров поэтому не
                        // дописывается.
                        self.constant(name, arguments.len());
                        self.applied(name, &arguments);
                    }
                    // Convoy: разбор применён к соседним аргументам, и ветви
                    // связывают их лямбдами сверх полей.
                    Term::Case(case) => {
                        let head = vec![Frame::Callee; arguments.len()];
                        let before = self.route.len();
                        self.route.extend_from_slice(&head);
                        self.case(case, arguments.len());
                        self.route.truncate(before);
                        self.spine(&arguments, |_| false);
                    }
                    other => {
                        // Голова - значение: вызов идёт через `adamas_apply`,
                        // аргумент уходит слотом замыкания, и плоский на этой
                        // границе боксируется (§10 вопрос 158).
                        self.record(Source::Boxing);
                        self.under(&vec![Frame::Callee; arguments.len()], other);
                        self.spine(&arguments, |_| false);
                    }
                }
            }

            Term::Let(mult, _, _, value, body) => {
                // Тип связывания - тип. Стёртое значение в рантайме не
                // возникает вовсе (§3.2), и аллоцировать ему нечем.
                if *mult != Mult::Zero {
                    self.under(&[Frame::BindingValue], value);
                }
                self.under(&[Frame::BindingBody], body);
            }

            Term::Case(case) => self.case(case, 0),
        }
    }

    /// Обходит аргументы спайна, пропуская те позиции, что названы стёртыми.
    ///
    /// Кадры складываются так же, как у [`crate::fbip`]: до `at`-го аргумента
    /// спайна из `n` идёт `n - 1 - at` кадров `Callee`, и последним - один
    /// `Argument`. Применение левоассоциативно, и это ровно спуск по нему.
    fn spine(&mut self, arguments: &[&Term], erased: impl Fn(usize) -> bool) {
        for (at, argument) in arguments.iter().enumerate() {
            if erased(at) {
                continue;
            }
            let mut path = vec![Frame::Callee; arguments.len() - 1 - at];
            path.push(Frame::Argument);
            self.under(&path, argument);
        }
    }

    /// Площадка `handle`, `handleMulti`, `handleState` либо `mask`.
    ///
    /// Отдаёт `false`, когда разобрать спайн нечем - имя элиминатора есть, а
    /// метка, тип или насыщение не те, - и тогда вызывающий идёт прежним путём:
    /// элиминатор без тела аллоцирует как всякий постулат. Направление то же,
    /// что у прочих пробелов проверки: отвергается лишнее, не принимается
    /// аллоцирующее.
    ///
    /// Аргументы приходят **со снятыми связываниями**, как ветви разбора: они
    /// не замыкания, а аргументы операции и резумпция, которые раздаёт сама
    /// площадка. Вычисление под хендлером - нульместная функция сахара `{ε} A`
    /// (§3.4), и понижение снимает её связывание тем же ходом.
    ///
    /// # Маршрут здесь замирает
    ///
    /// Терм, который отдаёт [`crate::resume::site`], - не подтерм спайна, а
    /// снятая с него форма: ветка `ask -> resume 2` приезжает как `2`. Кадры
    /// до неё поэтому не выразимы, и весь хендлер получает **один** маршрут -
    /// до самого применения элиминатора. Читателю подчёркивается площадка
    /// целиком; точность теряется, правдивость - нет, и это то же правило, по
    /// которому обрывается маршрут у полей записи (§10 вопрос 49б). Снять
    /// огрубление можно, приложив к [`crate::resume::Site`] позиции аргументов,
    /// - работа не этого трека.
    fn handling(&mut self, name: &Name, arguments: &[&Term]) -> bool {
        let Some(site) = crate::resume::site(self.signature, name, arguments) else {
            return false;
        };
        if site.verdict.allocates() {
            self.record(Source::Resumption {
                effect: Rc::clone(&site.label),
                operation: site.blamed.clone(),
            });
        }
        if let Some(computation) = &site.computation {
            self.term(computation);
        }
        if let Some(returned) = &site.returned {
            self.term(returned);
        }
        for branched in &site.branches {
            // Тело хвостовой ветки приходит со **снятым** применением
            // резумпции: `ask -> resume 2` есть `2`, и понижение видит ровно
            // это. Не снимай его - голова спайна оказалась бы значением, а
            // применение значения проверка считает боксированием (§4.11), и
            // хвостово-резумптивный хендлер аллоцировал бы по причине, которой
            // в понижении нет.
            self.term(&branched.body);
        }
        for argument in &site.extra {
            self.term(argument);
        }
        true
    }

    /// Что стоит за именем в спайне.
    fn constant(&mut self, name: &Name, arguments: usize) {
        let Some(definition) = self.signature.lookup(name) else {
            return;
        };
        // Определение кратности `0` живёт только на этапе проверки типов: в
        // рантайме его вызова нет, аллоцировать нечему.
        if definition.mult == Mult::Zero {
            return;
        }
        match &definition.kind {
            // Тип-формер и метка эффекта - типы.
            DefinitionKind::Data { .. } | DefinitionKind::Effect { .. } => {}
            // Ответ у конструктора один на все места употребления, и посчитан
            // он при объявлении: конструктор без рантайм-полей не аллоцирует
            // нигде.
            DefinitionKind::Constructor { .. } | DefinitionKind::Operation { .. } => {
                if let Some(source) = definition.allocates.clone() {
                    self.record(source);
                }
            }
            DefinitionKind::Regular => {
                if definition.allocates.is_some() {
                    self.record(if definition.body.is_none() {
                        Source::Opaque(Rc::clone(name))
                    } else {
                        Source::Call(Rc::clone(name))
                    });
                } else if arguments < telescope(&definition.ty) {
                    // Недостающие аргументы ждут в замыкании - и оно в куче.
                    self.record(Source::Partial(Rc::clone(name)));
                }
            }
        }
    }

    /// Обходит аргументы спайна, пропуская стёртые связыванием позиции.
    ///
    /// Позиции читаются по телескопу вызываемого и совпадают с аргументами, пока
    /// спайн насыщается по порядку - то же допущение, на котором стоит
    /// [`crate::carrier`].
    fn applied(&mut self, callee: &Name, arguments: &[&Term]) {
        let mut binders: Vec<Mult> = Vec::new();
        if let Some(definition) = self.signature.lookup(callee) {
            let mut current = &definition.ty;
            while let Term::Pi(binder, _, _, _, codomain) = current {
                binders.push(binder.mult);
                current = codomain;
            }
        }
        self.spine(arguments, |at| binders.get(at) == Some(&Mult::Zero));
    }

    /// Обходит разбор: мотив - тип, ветви связывают поля и соседей convoy.
    fn case(&mut self, case: &Case, applied: usize) {
        self.under(&[Frame::Scrutinee], &case.scrutinee);
        for (at, branch) in case.branches.iter().enumerate() {
            let binders = self.fields(&branch.constructor, case.params) + applied;
            let before = self.route.len();
            self.route
                .push(Frame::Branch(u32::try_from(at).unwrap_or(u32::MAX)));
            self.branch(binders, &branch.body);
            self.route.truncate(before);
        }
    }

    /// Сколько полей связывает ветвь конструктора.
    fn fields(&self, constructor: &Name, params: u32) -> usize {
        let Some(declaration) = self.signature.lookup(constructor) else {
            return 0;
        };
        telescope(&declaration.ty).saturating_sub(params as usize)
    }

    /// Снимает связывания ветви и обходит её тело.
    ///
    /// Связывания ветви - не замыкания: это поля разобранного значения и
    /// соседние аргументы, к которым разбор применён. Записаны лямбдами они не
    /// обязаны (η), и что не снялось, обходится как обычный терм.
    fn branch(&mut self, binders: usize, term: &Term) {
        match (binders, term) {
            (0, other) => self.term(other),
            (_, Term::Lam(_, _, body)) => {
                self.route.push(Frame::Body);
                self.branch(binders - 1, body);
                self.route.pop();
            }
            (_, other) => self.term(other),
        }
    }
}

/// Длина телескопа типа.
fn telescope(ty: &Term) -> usize {
    let mut found = 0;
    let mut current = ty;
    while let Term::Pi(_, _, _, _, codomain) = current {
        found += 1;
        current = codomain;
    }
    found
}
