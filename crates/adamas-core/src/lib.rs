//! Ядро компилятора Adamas: core language, elaborator, type checker.
//!
//! Спецификация - `adamas-design.md` §3.
//!
//! # Состояние (Фаза 1)
//!
//! Готово: термы ([`term`]) с кратностями ([`mult`]) и алгебраическими
//! уровнями ([`level`]), `NbE` ([`eval`]), проверка конвертируемости
//! ([`conv`]) с δ-разворотом, bidirectional-проверка типов с учётом
//! использований QTT ([`check`] поверх [`ctx`]), определения верхнего уровня
//! с universe polymorphism ([`sig`]).
//!
//! Universe polymorphism **неявная с обеих сторон**: аргументы уровня
//! выводятся в местах использования, арность определения выводится обобщением
//! нерешённых дырок ([`meta`], [`sig::Signature::define_inferred`]).
//!
//! Индуктивные типы есть целиком: объявление со строгой позитивностью и
//! проверкой универсумов ([`sig::Signature::declare_data`]) и разбор по
//! конструктору с мотивом ([`term::Case`]). Поэтому **`Type 0` населён**: до
//! data-декларации замкнутых термов в нём не существовало, потому что `Pi`
//! живёт в `max` уровней своих частей и опуститься до нуля было неоткуда.
//! Список конструкторов полон с момента, когда семейство стало видимым:
//! семейство объявляется вместе с ними, одним вызовом, и расти под принятым
//! определением он не вправе - дописать в него нечем.
//!
//! Форму типа - `Pi`, универсум, семейство - читают через
//! [`conv::whnf`]: определение имеет собственную голову, и без разворота
//! тип-синоним не годился бы ни в одном из этих мест.
//!
//! Рекурсия прямая ([`sig::Signature::define`]: тип проверяется без
//! собственного имени, тело - уже с ним), завершаемость держит проверка
//! структурной рекурсии ([`total`]).
//!
//! Клаузы со вложенными паттернами собираются в дерево разбора ([`pattern`]) -
//! и для индексированных семейств тоже: индексы унифицируются (`unify`), а
//! реализует ответ разбор индекса внутри мотива. Оттуда сразу и уточнение
//! соседних аргументов (convoy), и невозможные ветви. Границы фрагмента - §10
//! вопрос 53.
//!
//! Ещё нет: метапеременных на термах, зависимых пар, взаимной рекурсии.
//!
//! Из ревью Фазы 1 незакрытым осталось только архитектурное - §10 вопросы
//! 49 (ошибка ядра не доносит «где»: [`check::TypeError`] несёт готовые
//! строки, а спанов у термов нет), 50 (у [`sig::Signature`] нет атомарной
//! единицы объявления) и 51 (владение [`meta::Metas`] на границе API
//! непоследовательно). Все три - решения про границу с Фазой 2, и вход для
//! них - первый живой элаборатор.

