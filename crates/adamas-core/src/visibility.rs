//! Видимость связывания `Pi` (§4.1).
//!
//! `{a : Type} -> …` против `(a : Type) -> …`: аргумент выводится или пишется.
//!
//! # Почему это знает ядро
//!
//! После элаборации имплисит есть обычный аргумент: вставленный, но обычный,
//! и вычислению видимость не нужна. Нужна она **вызывающему**: элаборация
//! спрашивает у ядра тип (`infer`) и по нему решает, вставлять ли аргумент в
//! месте использования. Тип этот - значение ядра, поэтому видимость обязана
//! доехать до него, иначе решение принимать не по чему.
//!
//! Отсюда же следует, что конвертируемость её **сравнивает**: будь `{a : A} ->
//! B` и `(a : A) -> B` одним типом, значение одного встало бы на место другого,
//! и вставка перестала бы быть определённой. Тот же довод, что у кратности и у
//! row.
//!
//! # Почему её нет на лямбде
//!
//! Кратность на лямбде есть, потому что она ограничивает **тело**: `check`
//! сверяет её с `Pi` и отвергает несовпадение как ошибку автора. Видимость
//! тела не ограничивает ничем - она про то, кто пишет аргумент, - и лямбда,
//! разошедшаяся с `Pi`, была бы багом элаборации, а не программы. Проверять
//! баги компилятора типами его же входа значит заводить правило без
//! пользовательского случая.

/// Пишется аргумент или выводится.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Visibility {
    /// `(x : A) -> …` - аргумент пишется в месте вызова.
    #[default]
    Explicit,
    /// `{x : A} -> …` - аргумент выводится.
    Implicit,
}

impl Visibility {
    /// Выводится ли аргумент.
    #[must_use]
    pub fn is_implicit(self) -> bool {
        self == Self::Implicit
    }

    /// Скобки, в которых связывание пишется.
    #[must_use]
    pub fn brackets(self) -> (char, char) {
        match self {
            Self::Explicit => ('(', ')'),
            Self::Implicit => ('{', '}'),
        }
    }
}
