//! По времени — 1.68 / 1.56 / 1.62 раза. После ступени (2026-09-13) тело не
//! дробится, границы куска нет, reuse листа внутрифункционален и работает:
//! осталось **три блока на программу** — операция на месте (поиск, диспетчер,
//! ветка) плюс вызов `factor` на каждый лист.
//!
//! По времени эта разность мерится [`paired`] так же, как цена хендлера, и с
//! тем же результатом по устойчивости. Пять прогонов 2026-09-13, медиана и
