/// Место под порождённый C и его сборку.
fn scratch() -> PathBuf {
    let dir = Path::new(env!("OUT_DIR")).join("bench-native");
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// Строка сборки release: уровень оптимизации и межмодульная оптимизация.
///
/// `-O2`, а не `-O1` тестового харнесса: замер говорит о том, что получит
/// пользователь release-сборкой, и уровень оптимизации — часть окружения,
/// которое число обязано нести рядом с собой.
///
/// `-flto` здесь по той же причине и ещё по одной. Порождённый C и рантайм —
/// разные единицы трансляции, а горячий путь состоит из вызовов в рантайм:
/// `adamas_tag`, `adamas_field`, `adamas_dup`, `adamas_drop`. Каждый из них —
/// несколько инструкций, и без межмодульной оптимизации вызов дороже тела.
/// `adamas.h` называет это прямо: «Функции не `static inline`: горячий путь
/// ждёт LTO». Сосед на Rust собирается профилем `release` этого репозитория, а
/// он — `lto = "thin"`; без флага здесь сравнивались бы не два понижения, а
/// собранное межмодульно с собранным по отдельности. Измерено 2026-09-13:
/// флаг снимает **99% разрыва** с соседом (пофазно в процессе на глубине 18:
/// 42.3 мс против 17.7 при 17.6 у соседа).
const RELEASE: [&str; 3] = ["-std=c11", "-O2", "-flto"];

/// Объектные файлы рантайма: собираются однажды на весь прогон.
fn runtime() -> &'static [PathBuf] {
    static OBJECTS: OnceLock<Vec<PathBuf>> = OnceLock::new();
    OBJECTS.get_or_init(|| {
        let sources = Path::new(env!("ADAMAS_RUNTIME_SOURCES"));
        let dir = scratch();
        [
            "object.c",
            "array.c",
            "region.c",
            "evidence.c",
            "closure.c",
            "frame.c",
        ]
        .iter()
        .map(|name| {
            let object = dir.join(format!("{name}.o"));
            let status = Command::new(env!("ADAMAS_CC"))
                .args(RELEASE)
                .arg("-c")
                .arg("-I")
                .arg(env!("ADAMAS_RUNTIME_INCLUDE"))
                .arg(sources.join(name))
                .arg("-o")
                .arg(&object)
                .status();
            assert!(
                status.is_ok_and(|status| status.success()),
                "рантайм не собрался: {name}"
            );
            object
        })
        .collect()
    })
}

/// Собирает порождённый C в исполняемый файл.
fn built(name: &str, text: &str) -> PathBuf {
    let dir = scratch();
    let source = dir.join(format!("{name}.c"));
    let binary = dir.join(name);
    std::fs::write(&source, text).unwrap();
    compiled(&source, &binary);
    binary
}

/// Вызов компилятора C — отдельно, потому что он же и мерится.
fn compiled(source: &Path, binary: &Path) {
    let output = Command::new(env!("ADAMAS_CC"))
        .args(RELEASE)
        .args(["-fwrapv", "-w"])
        .arg("-I")
        .arg(env!("ADAMAS_RUNTIME_INCLUDE"))
        .arg(source)
        .args(runtime())
        .arg("-o")
        .arg(binary)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "порождённый C не собрался:\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

/// Прогон собранной программы: ответ на stdout, счётчики блоков на stderr.
fn ran(binary: &Path) -> (String, String) {
    let output = Command::new(binary).output().unwrap();
    assert!(
        output.status.success(),
        "прогон оборвался: {}",
        output.status
    );
    (
        String::from_utf8(output.stdout).unwrap(),
        String::from_utf8(output.stderr).unwrap(),
    )
}

/// Собранная программа, чей ответ уже сверен с машиной.
fn checked(program: &Program, name: &str) -> PathBuf {
    let text = program.lowered().expect("чистая форма обязана понижаться");
    let binary = built(name, &text);
    let (stdout, stderr) = ran(&binary);
    assert_eq!(
        stdout.trim_end_matches('\n'),
        program.answer,
        "{name}: понижение посчитало не то, что машина"
    );
    // Счётчики печатает точка входа безусловно; строку видно в отчёте прогона
    // `--test`, и по ней читается, сработал ли reuse.
    eprintln!("{name}: ответ {}, {}", program.answer, stderr.trim_end());
    binary
}

// --- сосед на Rust ------------------------------------------------------

/// Тот же алгоритм эквивалентным кодом: те же конструкторы, та же владеющая
/// рекурсия, то же заворачивание.
enum Tree {
    Leaf(i64),
    Node(Box<Tree>, Box<Tree>),
}

fn grow(depth: usize, seed: i64) -> Tree {
    if depth == 0 {
        return Tree::Leaf(seed);
    }
    let doubled = seed.wrapping_mul(2);
    Tree::Node(
        Box::new(grow(depth - 1, doubled)),
        Box::new(grow(depth - 1, doubled.wrapping_add(1))),
    )
}

fn scaled(tree: Tree) -> Tree {
    match tree {
        Tree::Leaf(x) => Tree::Leaf(x.wrapping_mul(3)),
        Tree::Node(left, right) => Tree::Node(Box::new(scaled(*left)), Box::new(scaled(*right))),
    }
}

fn total(tree: Tree) -> i64 {
    match tree {
        Tree::Leaf(x) => x,
        Tree::Node(left, right) => total(*left).wrapping_add(total(*right)),
    }
}

fn neighbour(depth: usize) -> i64 {
    total(scaled(grow(depth, 1)))
}

/// Размах адресов дерева, поделённый на число узлов, в байтах.
///
/// Свидетель годности замера, а не замер: считается без единой аллокации,
/// поэтому куче не мешает. На нетронутой куче glibc выдаёт узлы подряд, и
/// величина равна размеру куска — [`NODE_BYTES`]. В процессе, который успел
/// выделить и освободить сотни мегабайт, тот же вызов даёт сотни байт: узлы
/// ложатся вразброс, обход перестаёт попадать в TLB, и время растёт втрое.
/// Порог — [`SPREAD_LIMIT`], обоснование — «Методика» в шапке.
fn spread(tree: &Tree, depth: usize) -> usize {
    fn walk(tree: &Tree, low: &mut usize, high: &mut usize) {
        let address = std::ptr::from_ref(tree) as usize;
        *low = (*low).min(address);
        *high = (*high).max(address);
        if let Tree::Node(left, right) = tree {
            walk(left, low, high);
            walk(right, low, high);
        }
    }
    let (mut low, mut high) = (usize::MAX, 0);
    // Корень лежит на стеке — в размах идут только его дети.
    if let Tree::Node(left, right) = tree {
        walk(left, &mut low, &mut high);
        walk(right, &mut low, &mut high);
    }
    // Узлов в дереве глубины `depth` — 2^(depth+1) − 1, минус корень.
    (high - low) / ((1usize << (depth + 1)) - 2)
}

/// Переменная, которой стенд зовёт сам себя дочерним процессом.
///
/// Значение — глубина; с суффиксом `:witness` дочерний процесс сверх ответа
/// печатает на stderr [`spread`] своего дерева.
const NEIGHBOUR: &str = "ADAMAS_BENCH_NEIGHBOUR";

/// Дочерний прогон соседа, если стенд запущен им.
///
/// Сосед мерится **тем же протоколом**, что и порождённый C: свежий процесс,
/// свежая куча, ответ на stdout. Иначе его цену задаёт не алгоритм, а то,
/// сколько успел выделить и освободить сам стенд — см. «Методика» в шапке.
fn as_child() -> bool {
    let Ok(request) = std::env::var(NEIGHBOUR) else {
        return false;
    };
    let (depth, witness) = match request.strip_suffix(":witness") {
        Some(depth) => (depth, true),
        None => (request.as_str(), false),
    };
    let depth: usize = depth.parse().expect("глубина соседа — число");
    if witness {
        let tree = grow(depth, 1);
        let spread = spread(&tree, depth);
        let answer = total(scaled(tree));
        eprintln!("{spread}");
        println!("{answer}");
    } else {
        println!("{}", neighbour(depth));
    }
    true
}

/// Прогон соседа отдельным процессом: ответ на stdout, свидетель на stderr.
fn ran_neighbour(request: &str) -> (String, String) {
    let executable = std::env::current_exe().expect("стенд знает путь к себе");
    let output = Command::new(executable)
        .env(NEIGHBOUR, request)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "прогон соседа оборвался: {}",
        output.status
    );
    (
        String::from_utf8(output.stdout).unwrap(),
        String::from_utf8(output.stderr).unwrap(),
    )
}

// --- замеры -------------------------------------------------------------

fn symbolic(criterion: &mut Criterion) {
    let mut group = criterion.benchmark_group("symbolic");
    // Точка `native` — запуск процесса, точка `interp` — секунды: сотня
    // выборок по умолчанию превратила бы прогон в часы.
    group.sample_size(10);

    // Цена запуска процесса и печати: та же программа без работы. У соседа
    // свой пол — двоичный файл другой, и его цену вычитать надо свою.
    let floor = Program::new(Shape::Pure, 0);
    let binary = checked(&floor, "floor");
    group.bench_function("floor", |bencher| bencher.iter(|| ran(&binary)));
    group.bench_function("rust/floor", |bencher| {
        bencher.iter(|| ran_neighbour("0"));
    });

    // Сосед на Rust — только у чистой формы: под хендлером сравнивать не с
    // чем, там сравниваются между собой `boxed` и `handled`.
    //
    // Мерится он **процессом**, как и порождённый C. Свидетель [`spread`]
    // берётся у дочернего процесса раз на глубину: он говорит, что куча, на
    // которой сосед считал, — нетронутая, и число, значит, годное.
    let mut answers = [0i64; DEPTHS.len()];
    for (answer, depth) in answers.iter_mut().zip(DEPTHS) {
        let request = depth.to_string();
        let (stdout, stderr) = ran_neighbour(&format!("{request}:witness"));
        let spread: usize = stderr.trim().parse().expect("свидетель — число");
        assert!(
            spread <= SPREAD_LIMIT,
            "rust/{depth}: дерево легло вразброс — {spread} байт/узел при пороге \
             {SPREAD_LIMIT}; куча взболтана, число соседа недействительно"
        );
        eprintln!(
            "rust/{depth}: ответ {}, размах {spread} байт/узел",
            stdout.trim()
        );
        *answer = stdout.trim().parse().expect("ответ соседа — число");
        group.bench_function(format!("rust/{depth}"), |bencher| {
            bencher.iter(|| ran_neighbour(&request));
        });
    }

    same_answer();

    for shape in [
        Shape::Pure,
        Shape::Boxed,
        Shape::TailResumptive,
        Shape::FlatHandled,
    ] {
        let name = shape.name();
        for (index, depth) in DEPTHS.into_iter().enumerate() {
            let program = Program::new(shape, depth);
            if shape == Shape::Pure {
                assert_eq!(
                    program.answer.parse::<i64>().expect("ответ — число"),
                    answers[index],
                    "сосед на Rust считает не тот же алгоритм"
                );
            }
            let text = program
                .lowered()
                .unwrap_or_else(|error| panic!("{name}/{depth}: понижение отвергает: {error}"));
            let binary = built(&format!("{name}{depth}"), &text);
            let (stdout, stderr) = ran(&binary);
            assert_eq!(
                stdout.trim_end_matches('\n'),
                program.answer,
                "{name}/{depth}: понижение посчитало не то, что машина"
            );
            eprintln!(
                "native/{name}/{depth}: ответ {}, {}",
                program.answer,
                stderr.trim_end()
            );
            group.bench_function(format!("native/{name}/{depth}"), |bencher| {
                bencher.iter(|| ran(&binary));
            });
        }
        for depth in DEPTHS {
            let program = Program::new(shape, depth);
            group.bench_function(format!("interp/{name}/{depth}"), |bencher| {
                bencher.iter(|| adamas_interp::run(&program.signature, &program.written).unwrap());
            });
        }
    }

    group.finish();
}

/// Четыре формы обязаны считать одно число.
///
/// Иначе «тот же алгоритм под хендлером» было бы неправдой, и разность точек
/// мерила бы разные программы. Проверяется на мелкой глубине: свойство это
/// формы, а не размера.
fn same_answer() {
    let sample = DEPTHS[0];
    let pure = Program::new(Shape::Pure, sample).answer;
    for shape in [Shape::Boxed, Shape::TailResumptive, Shape::FlatHandled] {
        assert_eq!(
            pure,
            Program::new(shape, sample).answer,
            "форма `{}` считает не то же число",
            shape.name()
        );
    }
}

fn codegen(criterion: &mut Criterion) {
    let program = Program::new(Shape::Pure, CODEGEN_DEPTH);
    let lowered = adamas_codegen::lower::lower(&program.signature, &program.made)
        .expect("чистая форма обязана понижаться");
    let inserted = adamas_codegen::perceus::insert(lowered.clone());
    let text = adamas_codegen::emit_c::emit(&inserted).expect("форма понижения известна эмиттеру");

    let mut group = criterion.benchmark_group("codegen");
    group.bench_function("lower", |bencher| {
        bencher.iter(|| adamas_codegen::lower::lower(&program.signature, &program.made).unwrap());
    });
    group.bench_function("perceus", |bencher| {
        bencher.iter(|| adamas_codegen::perceus::insert(lowered.clone()));
    });
    group.bench_function("emit", |bencher| {
        bencher.iter(|| adamas_codegen::emit_c::emit(&inserted).unwrap());
    });

    // §6 время сборки не ограничивает — точка стоит затем, чтобы доля
    // понижения в общем пути читалась, а не угадывалась.
    let dir = scratch();
    let source = dir.join("codegen.c");
    let binary = dir.join("codegen");
    std::fs::write(&source, &text).unwrap();
    group.sample_size(10);
    group.bench_function("cc", |bencher| bencher.iter(|| compiled(&source, &binary)));
    group.finish();
}

criterion_group!(benches, symbolic, codegen);

/// `main` написан руками, а не взят у `criterion_main!`: дочерний прогон
/// соседа ([`as_child`]) обязан отвечать раньше, чем criterion разберёт
/// аргументы. Остальное — дословно то, во что разворачивается макрос.
fn main() {
    if as_child() {
        return;
    }
    benches();
    Criterion::default().configure_from_args().final_summary();
}
