//! Ядро компилятора Adamas: core language, elaborator, type checker.
//!
//! Спецификация - `adamas-design.md` §3.
//!
//! # Состояние (Фаза 1)
//!
//! Готово: термы ([`term`]) с кратностями ([`mult`]) и алгебраическими
//! уровнями ([`level`]), `NbE` ([`eval`]), проверка конвертируемости
//! ([`conv`]) с δ-разворотом, bidirectional-проверка типов с учётом
//! использований QTT ([`check`] поверх [`ctx`]), определения верхнего уровня
//! с universe polymorphism ([`sig`]).
//!
//! Universe polymorphism **неявная с обеих сторон**: аргументы уровня
//! выводятся в местах использования, арность определения выводится обобщением
//! нерешённых дырок ([`meta`], [`sig::Signature::define_inferred`]).
//!
//! Индуктивные типы есть целиком: объявление со строгой позитивностью и
//! проверкой универсумов ([`sig::Signature::declare_data`],
//! [`sig::Signature::declare_constructor`]) и разбор по конструктору с мотивом
//! ([`term::Case`]). Поэтому **`Type 0` населён**: до data-декларации замкнутых
//! термов в нём не существовало, потому что `Pi` живёт в `max` уровней своих
//! частей и опуститься до нуля было неоткуда.
//!
//! Ещё нет: метапеременных на термах, зависимых пар, рекурсивных определений,
//! элаборации паттернов в дерево разбора, проверки тотальности.

