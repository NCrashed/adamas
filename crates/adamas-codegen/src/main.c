int main(void) {
    /* Скрытых аргументов у первой формы нет вовсе (`adamas_lowered_first`):
     * хендлеров в чистом фрагменте не бывает, отчуждать нечего, искать некого. */
    adamas_value answer = ADAMAS_ENTRY();
    adamas_print(answer, 0);
    printf("\n");
    /* Ответ приходит владением, как всё в этом понижении: не отдай его здесь -
     * живым остался бы ровно он, и счётчик показал бы это числом. */
    adamas_drop_value(answer);
    /* Выдано против живого. Второе - критерий «течи нет»; первое - свидетель
     * reuse: переписанная ячейка выдачей не считается (§5.1). */
    fprintf(stderr, "блоков выдано %zu, живо %zu\n", adamas_stat_allocated(),
            adamas_stat_live());
    return 0;
}
