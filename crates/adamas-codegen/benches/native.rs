///
/// Здесь копия одна, но механизм у неё **не** тот, что у `workloads.rs`. Там
/// стенд читает корпусный файл и переписывает размер; здесь так нельзя:
/// [`source`] строит из одного скелета **четыре** формы, и различаться им
/// положено одной строкой каждой. Прочитай стенд корпусную копию чистой формы
/// — три остальные пришлось бы восстанавливать из неё хирургией по трём
/// местам, то есть менять один риск разъезда на три.
///
/// Поэтому копий текста две, а разъезд **ловится**, а не предотвращается:
/// корпусный файл обязан дословно совпасть с `source(Shape::Pure,
/// SYMBOLIC_DEPTH)`, и проверяет это [`the_corpus_holds_the_symbolic_program`]
/// под `cargo test --all-targets`, то есть в CI. Правка любой из двух сторон
/// роняет прогон.
const SYMBOLIC_FIXTURE: &str = "workload-symbolic";
const SYMBOLIC_DEPTH: usize = 5;

/// Размер кучного куска под узел дерева соседа: `Tree` — тег плюс два
/// указателя, glibc округляет до 32.
const NODE_BYTES: usize = 32;

/// Выше этого размаха адресов на узел ([`spread`]) число соседа
/// недействительно: дерево легло вразброс, и мерится раскладка кучи, а не
/// алгоритм. Двукратный запас к [`NODE_BYTES`]; наблюдавшийся отказ — 784.
const SPREAD_LIMIT: usize = 2 * NODE_BYTES;

// --- исходник -----------------------------------------------------------

/// Форма программы: чистый сосед, он же с указательным множителем, тот же
/// алгоритм под хендлером и он же с плоской арифметикой после операции.
///
/// Все четыре считают одно число. Различие ровно одно на каждом шаге: `Pure` →
/// `Boxed` меняет представление множителя, `Boxed` → `TailResumptive` меняет
/// литерал на операцию `ask`, чья ветка зовёт `resume` в хвосте,
/// `TailResumptive` → `FlatHandled` возвращает арифметику **после** операции,
/// откуда её уносил обход. Порознь, потому что вместе они мерили бы сумму.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Shape {
    /// Чистый сосед: множитель написан литералом.
    Pure,
    /// Множитель — указательное значение, хендлера нет.
    Boxed,
    /// Тот же алгоритм под хвостово резумптивным хендлером.
    TailResumptive,
    /// Он же, но умножение стоит после операции: плоское значение пересекает
    /// границу куска дроблёного тела.
    FlatHandled,
}

impl Shape {
    /// Имя в идентификаторе точки замера.
    const fn name(self) -> &'static str {
        match self {
            Self::Pure => "pure",
            Self::Boxed => "boxed",
            Self::TailResumptive => "handled",
            Self::FlatHandled => "handled-flat",
        }
    }
}

/// Указательный множитель: тип и функция, применяющая его к листу.
///
/// Делится `Boxed` и `TailResumptive` дословно — иначе разность точек мерила
/// бы не операцию.
///
/// Арифметика уехала **внутрь** `scale` намеренно: у `handled` операция дробит
/// тело `scaled`, и разность `handled − boxed` обязана быть операцией и ничем
/// сверх. Плоское значение после операции границу куска пересекает
/// (§10 вопрос 164), и мерится оно отдельной точкой — [`Shape::FlatHandled`].
const MULTIPLIER: &str = "\
data Mult where
  Triple : Mult
  Double : Mult

scale : Mult -> Int64 -> Tree
scale Triple x = Leaf (mulInt64 x 3)
scale Double x = Leaf (mulInt64 x 2)
";

/// Множитель числом: его берёт форма с арифметикой после операции.
///
/// [`MULTIPLIER`] она берёт тоже, хотя `scale` не зовёт: `Mult` объявлен там, а
/// исходники `handled` и `handled-flat` обязаны различаться **одной** строкой —
/// той, что стоит на месте листа. Неупотреблённое определение до понижения не
/// доходит: оно идёт от `main` по достижимости.
const FACTOR: &str = "\
factor : Mult -> Int64
factor Triple = 3
factor Double = 2
";

/// `scaled`, применённая к аргументу [`PASSES`] раз.
fn chained(argument: &str) -> String {
    let mut text = argument.to_owned();
    for _ in 0..PASSES {
        text = format!("scaled ({text})");
    }
    text
}

/// Глубина индуктивным счётчиком: `(Succ (Succ … Zero))`.
fn counter(depth: usize) -> String {
    let mut nat = String::new();
    for _ in 0..depth {
        nat.push_str("(Succ ");
    }
    nat.push_str("Zero");
    for _ in 0..depth {
        nat.push(')');
    }
    nat
}

/// Программа: дерево глубины `depth`, построенное, умноженное и свёрнутое.
fn source(shape: Shape, depth: usize) -> String {
    let nat = counter(depth);

    // Разница форм — объявления, row у `scaled` и то, откуда берётся
    // множитель. Остальное общее дословно.
    let (declarations, row, leaf) = match shape {
        Shape::Pure => (String::new(), "", "Leaf (mulInt64 x 3)"),
        Shape::Boxed => (MULTIPLIER.to_owned(), "", "scale Triple x"),
        // `Unit` объявлением эффекта требуется: нульарная операция пишется
        // через него.
        Shape::TailResumptive => (
            format!(
                "{MULTIPLIER}\n\
                 data Unit where\n  MkUnit : Unit\n\n\
                 effect Ask where\n  ask : Mult\n"
            ),
            "{Ask} ",
            "scale ask x",
        ),
        Shape::FlatHandled => (
            format!(
                "{MULTIPLIER}\n{FACTOR}\n\
                 data Unit where\n  MkUnit : Unit\n\n\
                 effect Ask where\n  ask : Mult\n"
            ),
            "{Ask} ",
            "Leaf (mulInt64 x (factor ask))",
        ),
    };
    // Хвост программы. У `pure` он тот же, каким мерена строка §6, и трогать
    // его нельзя. У прочих трёх свёртка вынесена за `handle`: приостановленное
    // вычисление, как и ответ ветки, обязано быть указательным (§4.11), а
    // `Int64` плоский. Вынесена **у всех**, чтобы разность точек оставалась
    // тем, чем названа, и ничем сверх.
    //
    // `computed` названо связыванием верхнего уровня, а не написано в
    // `handle`: приостановленное вычисление хендлер берёт с написанным типом
    // (§3.4).
    let chain = chained("grow depth 1");
    let tail = match shape {
        Shape::Pure => format!(
            "computed : Int64\n\
             computed = total ({chain})\n\
             \n\
             main : Int64\n\
             main = computed\n"
        ),
        Shape::Boxed => format!(
            "computed : Tree\n\
             computed = {chain}\n\
             \n\
             main : Int64\n\
             main = total computed\n"
        ),
        Shape::TailResumptive | Shape::FlatHandled => format!(
            "computed : {{Ask}} Tree\n\
             computed = {chain}\n\
             \n\
             answered : Tree\n\
             answered = handle computed with\n\
             \x20 return v -> v\n\
             \x20 ask -> resume Triple\n\
             \n\
             main : Int64\n\
             main = total answered\n"
        ),
    };

    format!(
        "\
-- Нагрузка Z: аллокационно-тяжёлый символьный код (§6, строка 2).
--
-- Вторая из четырёх нагрузок трека Z. Двоичное дерево: `grow` строит, `scaled`
-- умножает каждый лист, `total` складывает; проходов `scaled` четыре, потому
-- что §6 просит «цепочками функциональных преобразований», во множественном
-- числе, и потому что цепочку понижение проходит дешевле соседа - проходы
-- сверх первого не стоят ему ни одной ячейки, а соседу стоят по ячейке на
-- узел.
--
-- Листья различны (счётчик по битам пути), поэтому переставленные поддеревья
-- меняют ответ, а не оставляют его тем же.
--
-- **Глубина корпусной копии мельче стендовой, и копия эта порождённая.**
-- Скелет один, форм у него четыре (чистая, с указательным множителем, под
-- хендлером, с плоской арифметикой после операции), и различаться им положено
-- одной строкой; поэтому текст живёт у стенда (`benches/native.rs`, `source`),
-- а здесь лежит его чистая форма на глубине пять. Совпадение дословное и
-- проверяется прогоном - см. `SYMBOLIC_FIXTURE` там же.

data Nat where
  Zero : Nat
  Succ : Nat -> Nat

data Tree where
  Leaf : Int64 -> Tree
  Node : Tree -> Tree -> Tree

{declarations}
-- Лист получает номер пути в двоичной записи: значения различны, и
-- переставленные поддеревья меняют ответ.
grow : Nat -> Int64 -> Tree
grow Zero seed = Leaf seed
grow (Succ k) seed =
  let doubled : Int64 = mulInt64 seed 2
  Node (grow k doubled) (grow k (addInt64 doubled 1))

scaled : Tree -> {row}Tree
scaled (Leaf x) = {leaf}
scaled (Node l r) = Node (scaled l) (scaled r)

total : Tree -> Int64
total (Leaf x) = x
total (Node l r) = addInt64 (total l) (total r)

depth : Nat
depth = {nat}

{tail}"
    )
}

// --- машина -------------------------------------------------------------

/// Программа, готовая к замеру обоими путями.
struct Program {
    signature: Signature,
    /// Терм, как написан: его считает машина.
    written: Term,
    /// Он же после специализации: его понижает бэкенд.
    made: Term,
    /// Ответ по мнению машины.
    answer: String,
}

impl Program {
    fn new(shape: Shape, depth: usize) -> Self {
        let text = source(shape, depth);
        let (mut signature, mut metas, instances) = elaborated(&text);
        let written = entry(&signature);
        let answer = adamas_interp::run(&signature, &written)
            .expect("операция обязана встретить хендлер")
            .printed(Some(PRINT_DEPTH))
            .to_string();
        let made = mono::specialise(&mut signature, &mut metas, &instances, &written)
            .expect("специализация обязана пройти")
            .term;
        Self {
            signature,
            written,
            made,
            answer,
        }
    }

    /// Текст C либо названный отказ понижения.
    fn lowered(&self) -> Result<String, adamas_codegen::CompileError> {
        adamas_codegen::compile(&self.signature, &self.made)
    }

    /// `.ll` со спутником либо названный отказ скалярного фрагмента.
    ///
    /// Из **того же** специализированного терма, что и C: решение волны 0,
    /// вариант (а) — второй эмиттер, а не второй компилятор. Для замера это
    /// условие годности числа: понизь стенд две программы, и отношение мерило
    /// бы расхождение специализаций пополам с расхождением эмиттеров.
    fn llvm(&self) -> Result<Artefacts, adamas_codegen::CompileError> {
        adamas_codegen::compile_llvm(&self.signature, &self.made)
    }
}

// --- порождённый C ------------------------------------------------------

/// Собранная программа, чей ответ уже сверен с машиной.
fn checked(program: &Program, name: &str) -> PathBuf {
    let text = program.lowered().expect("чистая форма обязана понижаться");
    let binary = built(&harness::scratch(STAND), name, &text);
    let (stdout, stderr) = ran(&binary);
    assert_eq!(
        stdout.trim_end_matches('\n'),
        program.answer,
        "{name}: понижение посчитало не то, что машина"
    );
    // Счётчики печатает точка входа безусловно; строку видно в отчёте прогона
    // `--test`, и по ней читается, сработал ли reuse.
    eprintln!("{name}: ответ {}, {}", program.answer, stderr.trim_end());
    binary
}

// --- сосед на Rust ------------------------------------------------------

/// Тот же алгоритм эквивалентным кодом: те же конструкторы, та же владеющая
/// рекурсия, то же заворачивание.
enum Tree {
    Leaf(i64),
    Node(Box<Tree>, Box<Tree>),
}

fn grow(depth: usize, seed: i64) -> Tree {
    if depth == 0 {
        return Tree::Leaf(seed);
    }
    let doubled = seed.wrapping_mul(2);
    Tree::Node(
        Box::new(grow(depth - 1, doubled)),
        Box::new(grow(depth - 1, doubled.wrapping_add(1))),
    )
}

fn scaled(tree: Tree) -> Tree {
    match tree {
        Tree::Leaf(x) => Tree::Leaf(x.wrapping_mul(3)),
        Tree::Node(left, right) => Tree::Node(Box::new(scaled(*left)), Box::new(scaled(*right))),
    }
}

fn total(tree: Tree) -> i64 {
    match tree {
        Tree::Leaf(x) => x,
        Tree::Node(left, right) => total(*left).wrapping_add(total(*right)),
    }
}

fn neighbour(depth: usize) -> i64 {
    total(chain(grow(depth, 1)))
}

/// [`scaled`] столько же раз, сколько её зовёт [`chained`] в исходнике Adamas.
fn chain(mut tree: Tree) -> Tree {
    for _ in 0..PASSES {
        tree = scaled(tree);
    }
    tree
}

/// Размах адресов дерева, поделённый на число узлов, в байтах.
///
/// Свидетель годности замера, а не замер: считается без единой аллокации,
/// поэтому куче не мешает. На нетронутой куче glibc выдаёт узлы подряд, и
/// величина равна размеру куска — [`NODE_BYTES`]. В процессе, который успел
/// выделить и освободить сотни мегабайт, тот же вызов даёт сотни байт: узлы
/// ложатся вразброс, обход перестаёт попадать в TLB, и время растёт втрое.
/// Порог — [`SPREAD_LIMIT`], обоснование — «Методика» в шапке.
fn spread(tree: &Tree, depth: usize) -> usize {
    fn walk(tree: &Tree, low: &mut usize, high: &mut usize) {
        let address = std::ptr::from_ref(tree) as usize;
        *low = (*low).min(address);
        *high = (*high).max(address);
        if let Tree::Node(left, right) = tree {
            walk(left, low, high);
            walk(right, low, high);
        }
    }
    let (mut low, mut high) = (usize::MAX, 0);
    // Корень лежит на стеке — в размах идут только его дети.
    if let Tree::Node(left, right) = tree {
        walk(left, &mut low, &mut high);
        walk(right, &mut low, &mut high);
    }
    // Узлов в дереве глубины `depth` — 2^(depth+1) − 1, минус корень.
    (high - low) / ((1usize << (depth + 1)) - 2)
}

/// Дочерний прогон соседа, если стенд запущен им.
///
/// Сосед мерится **тем же протоколом**, что и порождённый C: свежий процесс,
/// свежая куча, ответ на stdout. Иначе его цену задаёт не алгоритм, а то,
/// сколько успел выделить и освободить сам стенд — см. «Методика» в шапке.
///
/// Запрос в [`NEIGHBOUR`] — глубина; с суффиксом `:witness` дочерний процесс
/// сверх ответа печатает на stderr [`spread`] своего дерева.
fn as_child() -> bool {
    let Ok(request) = std::env::var(NEIGHBOUR) else {
        return false;
    };
    let (depth, witness) = match request.strip_suffix(":witness") {
        Some(depth) => (depth, true),
        None => (request.as_str(), false),
    };
    let depth: usize = depth.parse().expect("глубина соседа — число");
    if witness {
        let tree = grow(depth, 1);
        let spread = spread(&tree, depth);
        let answer = total(chain(tree));
        eprintln!("{spread}");
        println!("{answer}");
    } else {
        println!("{}", neighbour(depth));
    }
    true
}

// --- замеры -------------------------------------------------------------

fn symbolic(criterion: &mut Criterion) {
    the_corpus_holds_the_symbolic_program();
    let mut group = criterion.benchmark_group("symbolic");
    // Точка `native` — запуск процесса, точка `interp` — секунды: сотня
    // выборок по умолчанию превратила бы прогон в часы.
    group.sample_size(10);
    // Выборки одного размера: оценка — пол ([`harness::least`]), а его качество растёт
    // с числом повторов в выборке. При линейной схеме первые выборки коротки,
    // их пол завышен, и регрессия по разнородным полам ничего не значит.
    group.sampling_mode(SamplingMode::Flat);

    // Цена запуска процесса и печати: та же программа без работы. У соседа
    // свой пол — двоичный файл другой, и его цену вычитать надо свою.
    let floor = Program::new(Shape::Pure, 0);
    let binary = checked(&floor, "floor");
    group.bench_function("floor", |bencher| by_floor(bencher, || drop(ran(&binary))));
    group.bench_function("rust/floor", |bencher| {
        by_floor(bencher, || drop(ran_neighbour("0")));
    });

    // Сосед на Rust — только у чистой формы: под хендлером сравнивать не с
    // чем, там сравниваются между собой `boxed` и `handled`.
    //
    // Мерится он **процессом**, как и порождённый C. Свидетель [`spread`]
    // берётся у дочернего процесса раз на глубину: он говорит, что куча, на
    // которой сосед считал, — нетронутая, и число, значит, годное.
    let mut answers = [0i64; DEPTHS.len()];
    for (answer, depth) in answers.iter_mut().zip(DEPTHS) {
        let request = depth.to_string();
        let (stdout, stderr) = ran_neighbour(&format!("{request}:witness"));
        let spread: usize = stderr.trim().parse().expect("свидетель — число");
        assert!(
            spread <= SPREAD_LIMIT,
            "rust/{depth}: дерево легло вразброс — {spread} байт/узел при пороге \
             {SPREAD_LIMIT}; куча взболтана, число соседа недействительно"
        );
        eprintln!(
            "rust/{depth}: ответ {}, размах {spread} байт/узел",
            stdout.trim()
        );
        *answer = stdout.trim().parse().expect("ответ соседа — число");
        group.bench_function(format!("rust/{depth}"), |bencher| {
            by_floor(bencher, || drop(ran_neighbour(&request)));
        });
    }

    same_answer();

    // Двоичные файлы переживают цикл: их берёт парный замер ([`paired`]).
    let mut binaries: Vec<(Shape, usize, PathBuf)> = Vec::new();

    for shape in [
        Shape::Pure,
        Shape::Boxed,
        Shape::TailResumptive,
        Shape::FlatHandled,
    ] {
        let name = shape.name();
        for (index, depth) in DEPTHS.into_iter().enumerate() {
            let program = Program::new(shape, depth);
            if shape == Shape::Pure {
                assert_eq!(
                    program.answer.parse::<i64>().expect("ответ — число"),
                    answers[index],
                    "сосед на Rust считает не тот же алгоритм"
                );
            }
            let text = program
                .lowered()
                .unwrap_or_else(|error| panic!("{name}/{depth}: понижение отвергает: {error}"));
            let binary = built(&harness::scratch(STAND), &format!("{name}{depth}"), &text);
            let (stdout, stderr) = ran(&binary);
            assert_eq!(
                stdout.trim_end_matches('\n'),
                program.answer,
                "{name}/{depth}: понижение посчитало не то, что машина"
            );
            eprintln!(
                "native/{name}/{depth}: ответ {}, {}",
                program.answer,
                stderr.trim_end()
            );
            group.bench_function(format!("native/{name}/{depth}"), |bencher| {
                by_floor(bencher, || drop(ran(&binary)));
            });
            binaries.push((shape, depth, binary));
        }
        for depth in DEPTHS {
            let program = Program::new(shape, depth);
            group.bench_function(format!("interp/{name}/{depth}"), |bencher| {
                bencher.iter(|| adamas_interp::run(&program.signature, &program.written).unwrap());
            });
        }
    }

    group.finish();

    let of = |wanted: Shape, depth: usize| {
        binaries
            .iter()
            .find(|(shape, at, _)| *shape == wanted && *at == depth)
            .map(|(_, _, binary)| binary.clone())
            .expect("двоичный файл собран выше")
    };

    let deepest = DEPTHS[DEPTHS.len() - 1];
    against_the_neighbour(&of(Shape::Pure, deepest), &binary, deepest);
    against_the_c_backend(deepest, &of(Shape::Pure, deepest), &binary);

    for depth in DEPTHS {
        paired(
            "хендлер",
            &of(Shape::Boxed, depth),
            &of(Shape::TailResumptive, depth),
            depth,
        );
        paired(
            "эффект над плоскими",
            &of(Shape::Pure, depth),
            &of(Shape::FlatHandled, depth),
            depth,
        );
    }
}

/// Строка §6 против соседа: число берётся чередованием, а не вычитанием двух
/// строк отчёта.
///
/// Причина — в [`harness::ratio`]; коротко: точки отчёта стоят на расстоянии
/// десятков секунд, и на неспокойной машине отношение из них не читается.
/// Замер 2026-09-15: одиннадцать прогонов отчёта дали 0.75–1.57 при медиане
/// около 0.90, тогда как чередование в том же окне держит размах в сотых.
fn against_the_neighbour(pure: &Path, floor: &Path, depth: usize) {
    let request = depth.to_string();
    harness::ratio(
        &format!("символьная строка §6/{depth}"),
        || drop(ran(pure)),
        || drop(ran(floor)),
        || drop(ran_neighbour(&request)),
        || drop(ran_neighbour("0")),
    );
}

// --- второй столбец таблицы трека Z: LLVM против C ------------------------

/// Символьная строка вторым столбцом: LLVM-путь против C-пути.
///
/// Обе стороны выходят из **одного** специализированного терма и собираются
/// уравненными строками сборки; чем именно уравненными — в заготовке, разделом
/// «LLVM-путь». Свидетели там же, и включает их [`harness::WITNESS`].
fn against_the_c_backend(depth: usize, c: &Path, c_floor: &Path) {
    let Some(backend) = Backend::new(STAND) else {
        return;
    };
    let program = Program::new(Shape::Pure, depth);
    let idle = Program::new(Shape::Pure, 0);
    let (artefacts, idle_artefacts) = match (program.llvm(), idle.llvm()) {
        (Ok(artefacts), Ok(idle_artefacts)) => (artefacts, idle_artefacts),
        (Err(error), _) | (_, Err(error)) => {
            eprintln!("символьная строка/{depth}: LLVM-эмиттер нагрузку не берёт: {error}");
            return;
        }
    };

    let what = format!("символьная строка/{depth}");
    let pipeline = backend.pipeline();
    let build = |stem: &str, pipeline: &Pipeline, support: &str| {
        (
            backend.load(stem, &artefacts, pipeline, support),
            backend.load(&format!("{stem}-floor"), &idle_artefacts, pipeline, support),
        )
    };
    let (llvm, llvm_floor) = build(&format!("symbolic{depth}-llvm"), &pipeline, SUPPORT_LEVEL);
    let c = Load::measured(&format!("symbolic{depth}"), c.to_path_buf());
    let c_floor = Load::measured("symbolic0", c_floor.to_path_buf());
    let column = Column {
        llvm: &llvm,
        llvm_floor: &llvm_floor,
        c: &c,
        c_floor: &c_floor,
        ll: &artefacts.ll,
    };
    llvm_against_c(&what, &column);

    harness::witnesses(&what, &backend, &column, build, |stem| {
        let dir = harness::scratch(STAND);
        let text = |program: &Program| program.lowered().expect("чистая форма обязана понижаться");
        (
            Load::measured(stem, harness::built_apart(&dir, stem, &text(&program))),
            Load::measured(
                &format!("{stem}-floor"),
                harness::built_apart(&dir, &format!("{stem}-floor"), &text(&idle)),
            ),
        )
    });
}

// --- парный замер --------------------------------------------------------

/// Блоков в парном замере, пар в блоке и сколько блоков идёт в число.
///
/// Разброс между блоками — то, против чего сравнивается разность точек, так
/// что блоков нужно не меньше, чем «Методика» требует прогонов. Пар в блоке
/// задают качество пола: при двенадцати запас на глубине 16 гулял между 2.0
/// и 5.0 от прогона к прогону, при шестнадцати держится.
///
/// В число идут не все блоки, а [`PAIRED_QUIET`] **тишайших**, и тишина
/// свидетельствуется полом базовой точки, померенным в том же окне. Помеха,
/// пережившая целый блок, поднимает оба пола разом, и её видно по базовому
/// без всякой отсылки к тому, что мерится. Отбрасывается не неудобное
/// число, а окно, про которое отдельный свидетель говорит, что машина в нём
/// была занята: та же логика, что у [`SPREAD_LIMIT`]. Свидетель работает —
/// прогон 2026-09-13, `эффект над плоскими/18`: блок с полом на 3.6 мс выше
/// прочих дал разность вдвое меньше и уронил прогон.
const PAIRED_BLOCKS: usize = 7;
const PAIRED_QUIET: usize = 4;
const PAIRED_PAIRS: u64 = 16;

/// Разность двух точек, померенная чередованием внутри одного окна.
///
/// Врозь эти две точки не разрешаются, и это измерено: пять прогонов стенда
/// 2026-09-13 дали `boxed/18` 21.41–23.97 при разности точек 0.5 мс, и в
/// одном из пяти `handled` вышел **быстрее** `boxed` — чего не может быть,
/// `handled` есть `boxed` плюс хендлер. Причина в том, что окружение уводит
/// обе точки на единицы процентов за минуты, а точки стоят в прогоне на
/// расстоянии этих минут.
///
/// Чередование ставит их вплотную: в блоке пары идут подряд, и то, что
/// увело блок, увело обе стороны. Свидетель — блоки 6 и 7 замера
/// 2026-09-13: пол обеих точек упал на 3 мс разом, разность не шелохнулась.
///
/// Оценка стороны — пол блока ([`harness::least`]), а не среднее: помеха прибавляет.
fn paired(what: &str, base: &Path, with: &Path, depth: usize) {
    let measuring = measuring();
    let (blocks, pairs) = if measuring {
        (PAIRED_BLOCKS, PAIRED_PAIRS)
    } else {
        (2, 2)
    };
    // Блок: пол базовой точки и разность, померенные чередованием.
    let mut measured: Vec<(f64, f64)> = Vec::with_capacity(blocks);
    for block in 0..blocks {
        let mut low = f64::MAX;
        let mut high = f64::MAX;
        for _ in 0..pairs {
            low = low.min(least(1, || drop(ran(base))).as_secs_f64() * 1e3);
            high = high.min(least(1, || drop(ran(with))).as_secs_f64() * 1e3);
        }
        eprintln!(
            "парно/{what}/{depth}: блок {block}: {low:.3} против {high:.3} мс, \
             разность {:.3}",
            high - low
        );
        measured.push((low, high - low));
    }

    // Тишайшие блоки вперёд, шумные — за черту.
    measured.sort_unstable_by(|left, right| left.0.total_cmp(&right.0));
    let quiet = PAIRED_QUIET.min(measured.len());
    let (kept, dropped) = measured.split_at(quiet);
    let mut differences: Vec<f64> = kept.iter().map(|(_, difference)| *difference).collect();
    let floors: Vec<f64> = kept.iter().map(|(floor, _)| *floor).collect();
    let median = middle(&mut differences);
    let spread = span(&differences);
    // Операций в программе: по одной на лист на каждый проход `scaled`.
    let operations = f64::from(u32::try_from(PASSES << depth).expect("глубина невелика"));
    let beyond = dropped.last().map_or_else(
        || "за чертой никого".to_owned(),
        |(floor, _)| format!("за чертой осталось {} с полом до {floor:.3}", dropped.len()),
    );
    eprintln!(
        "парно/{what}/{depth}: по {quiet} тишайшим блокам разность {median:.3} мс \
         (размах {spread:.3}), запас {:.1}x, на операцию {:.2} нс; пол базовой точки \
         в них гулял на {:.3} мс, {beyond}",
        median / spread,
        median * 1e6 / operations,
        span(&floors),
    );
    if !measuring {
        return;
    }
    // Порядок точек — обязательство, а не наблюдение: точка `with` есть точка
    // `base` плюс операция. Нарушение означает либо помеху шире разности, либо
    // что операции в программе не осталось, — и то и другое делает число
    // недействительным, а свидетеля молчащим.
    assert!(
        differences[0] > 0.0,
        "{what}/{depth}: тишайшие блоки дали разность от {:.3} мс — точка с \
         операцией вышла не медленнее той же программы без неё, чего не может \
         быть по построению",
        differences[0]
    );
    assert!(
        median > spread,
        "{what}/{depth}: разность {median:.3} мс не больше размаха {spread:.3} — \
         стенд эти две точки не различает, и число недействительно"
    );
}

/// Корпусная копия символьной нагрузки совпадает со стендовой дословно.
///
/// Свидетель против разъезда двух текстов одной программы. Правка стенда,
/// правка фикстуры, правка [`SYMBOLIC_DEPTH`] — любая роняет это утверждение,
/// и роняет под `cargo test --all-targets`, то есть в CI, а не только на
/// длинном прогоне бенчмарка.
///
/// Отказ поправляется одной командой, и она названа в тексте отказа: прогон с
/// [`REFRESH`] в окружении перезаливает фикстуру. Руками её править нечего —
/// правится стенд, а фикстура берётся у него.
fn the_corpus_holds_the_symbolic_program() {
    let want = source(Shape::Pure, SYMBOLIC_DEPTH);
    let path = harness::corpus_path(SYMBOLIC_FIXTURE);
    if std::env::var_os(REFRESH).is_some() {
        std::fs::write(&path, &want)
            .unwrap_or_else(|error| panic!("фикстура {} не записалась: {error}", path.display()));
        eprintln!("{SYMBOLIC_FIXTURE}: фикстура перезалита");
        return;
    }
    assert_eq!(
        harness::corpus(SYMBOLIC_FIXTURE),
        want,
        "корпусная копия символьной нагрузки разошлась со стендовой: стенд мерит \
         одно, а договор трёх вычислителей проверяет другое. Перезалить: \
         `{REFRESH}=1 cargo test -p adamas-codegen --bench native`, затем \
         `cargo insta test --accept`"
    );
}

/// Переменная, которой прогон перезаливает корпусную копию символьной
/// нагрузки.
const REFRESH: &str = "ADAMAS_BENCH_REFRESH";

/// Четыре формы обязаны считать одно число.
///
/// Иначе «тот же алгоритм под хендлером» было бы неправдой, и разность точек
/// мерила бы разные программы. Проверяется на мелкой глубине: свойство это
/// формы, а не размера.
fn same_answer() {
    let sample = DEPTHS[0];
    let pure = Program::new(Shape::Pure, sample).answer;
    for shape in [Shape::Boxed, Shape::TailResumptive, Shape::FlatHandled] {
        assert_eq!(
            pure,
            Program::new(shape, sample).answer,
            "форма `{}` считает не то же число",
            shape.name()
        );
    }
}

fn codegen(criterion: &mut Criterion) {
    let program = Program::new(Shape::Pure, CODEGEN_DEPTH);
    let lowered = adamas_codegen::lower::lower(&program.signature, &program.made)
        .expect("чистая форма обязана понижаться");
    let inserted = adamas_codegen::perceus::insert(lowered.clone());
    let text = adamas_codegen::emit_c::emit(&inserted).expect("форма понижения известна эмиттеру");

    let mut group = criterion.benchmark_group("codegen");
    group.bench_function("lower", |bencher| {
        bencher.iter(|| adamas_codegen::lower::lower(&program.signature, &program.made).unwrap());
    });
    group.bench_function("perceus", |bencher| {
        bencher.iter(|| adamas_codegen::perceus::insert(lowered.clone()));
    });
    group.bench_function("emit", |bencher| {
        bencher.iter(|| adamas_codegen::emit_c::emit(&inserted).unwrap());
    });

    // §6 время сборки не ограничивает — точка стоит затем, чтобы доля
    // понижения в общем пути читалась, а не угадывалась.
    let dir = harness::scratch(STAND);
    let source = dir.join("codegen.c");
    let binary = dir.join("codegen");
    std::fs::write(&source, &text).unwrap();
    group.sample_size(10);
    group.bench_function("cc", |bencher| {
        bencher.iter(|| compiled(&dir, &source, &binary));
    });
    group.finish();
}

criterion_group!(benches, symbolic, codegen);

/// `main` написан руками, а не взят у `criterion_main!`: дочерний прогон
/// соседа ([`as_child`]) обязан отвечать раньше, чем criterion разберёт
/// аргументы. Остальное — дословно то, во что разворачивается макрос.
fn main() {
    if as_child() {
        return;
    }
    benches();
    Criterion::default().configure_from_args().final_summary();
}
