//! Предупреждение - третий исход рядом с принятой программой и отказом.
//!
//! До этого модуля компилятор отвечал двумя: либо сигнатура, либо `ElabError`.
//! Дизайном же обещаны и предупреждения - умолчание литерала (§4.3), подъём
//! замкнутой row (§3.4), discoverability FBIP (§5.1), - и §10 вопрос 81 велел
//! заводить канал вместе с первым, кому он понадобится всерьёз.
//!
//! Первым оказалась цена вопроса 79: `{ x : Nat }` в домене читается
//! связыванием, а написана могла быть записью. Оба прочтения дают корректный
//! тип, поэтому отказом такое не поймать - различает их только то, что имя из
//! группы больше нигде не встречается.
//!
//! # Приёмник внутри, список наружу
//!
//! Предупреждения копятся в [`Warnings`] по ходу прогона и отдаются вместе с
//! сигнатурой. Ядро при этом не трогается вовсе: всё, что обещано сегодня,
//! живёт в элаборации. Уровень у диагностики появится, когда её попросит LSP
//! (§7); до тех пор список однороден, и заводить два сорта незачем.

use adamas_core::source::Span;
use adamas_parser::ast::Symbol;

/// О чём компилятор предупреждает, приняв программу.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum Warning {
    /// Имя из implicit-группы не встречается в остатке типа (§10 вопросы 79, 81).
    #[error(
        "имя `{name}` из implicit-группы нигде не используется: в этой позиции \
         `{{ {name} : … }}` читается связыванием, а записью пишется как \
         `{{ {name} : … | r }}` (§4.2)"
    )]
    UnusedImplicit {
        /// Имя связывания.
        name: Symbol,
        /// Где написана группа.
        span: Span,
    },
}

impl Warning {
    /// Где предупреждение показывать.
    #[must_use]
    pub fn span(&self) -> Span {
        match self {
            Self::UnusedImplicit { span, .. } => *span,
        }
    }
}

/// Собранное за прогон. Пусто - программа принята без оговорок.
pub type Warnings = Vec<Warning>;
