/* Чужая библиотека свидетеля одолженного буфера (§5.3, волна 2).
 *
 * Про Adamas она не знает **ничего** - ни заголовка рантайма, ни смещения
 * нагрузки, - и берёт ровно то, что берёт настоящая библиотека: указатель на
 * байты и число байт. Именно поэтому прототипы здесь написаны указателями, а
 * не словами: если бы они были словами, свидетель проверял бы перекладку
 * чисел, а не то, что одолженный адрес есть настоящий адрес нагрузки.
 *
 * Расхождение написаний намеренно и названо. Порождённая единица объявляет
 * символ `uint64_t adamas_foreign_…(uint64_t, …)` с `__asm__`-меткой, а здесь
 * он определён указателем. Сойтись они не могут: уровень 1 переносит слово. Это
 * и есть §10 вопрос 183 - `extern "C"` есть необоснованное утверждение автора,
 * - и здесь оно выполнено по SysV x86-64: указатель и слово идут одним классом
 * регистра.
 *
 * Память не берётся вовсе: чужая сторона пишет **в нашу**. Оттого счётчик
 * живых блоков у прогона и остаётся нулём - никакой чужой аллокации тут нет, а
 * наш массив дропает вставка RC после возврата.
 */

#include <stdint.h>

/* Сколько раз через границу ходили: свёрнут в ответ программы. */
static uint64_t crossings = 0;

/* Заполняет `count` байт возрастающей последовательностью `seed + i`.
 *
 * Пишет **в наш** блок: наблюдаемость этой записи и есть предмет свидетеля. */
void adamas_probe_fill(uint8_t *bytes, uint64_t count, uint64_t seed) {
    uint64_t i;
    crossings += 1;
    for (i = 0; i < count; i += 1) {
        bytes[i] = (uint8_t)(seed + i);
    }
}

/* Читает `count` байт и кладёт сумму в `out[0]`, максимум в `out[1]`.
 *
 * Два одолженных буфера в одном вызове - и оба наши. Out-параметр здесь и
 * есть тот самый `uLongf *destLen` zlib: чужая сторона пишет слово по адресу,
 * который дали мы. */
void adamas_probe_digest(const uint8_t *bytes, uint64_t count, uint64_t *out) {
    uint64_t i;
    uint64_t sum = 0;
    uint64_t top = 0;
    crossings += 1;
    for (i = 0; i < count; i += 1) {
        sum += bytes[i];
        if (bytes[i] > top) {
            top = bytes[i];
        }
    }
    out[0] = sum;
    out[1] = top;
}

/* Адрес одолженного буфера, как его увидела чужая сторона.
 *
 * Нужен одному свидетелю - тому, что спрашивает, одалживается ли **адрес
 * нагрузки нашего блока**, а не копия. Сверяется он с адресом, который чужая
 * сторона запомнила прошлым вызовом. */
static uintptr_t seen = 0;

uint64_t adamas_probe_note(const uint8_t *bytes) {
    crossings += 1;
    seen = (uintptr_t)bytes;
    return (uint64_t)seen;
}

/* Тот же ли адрес одолжили во второй раз: 1 - да, 0 - нет. */
uint64_t adamas_probe_same(const uint8_t *bytes) {
    crossings += 1;
    return (uintptr_t)bytes == seen ? 1u : 0u;
}

uint64_t adamas_probe_crossings(void) {
    crossings += 1;
    return crossings;
}
