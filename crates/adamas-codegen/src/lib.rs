//! Понижение ядра Adamas в C и в LLVM (§9 Фаза 6, трек H; Фаза 7, трек A).
//!
//! Путь: **ядро → backend IR → текст**. Шов посередине не украшение и не слой
//! ради слоя - на нём лежат факты, которые знает тайпчекер и не восстановит
//! алиас-анализ: кратность связывания, уникальность производства, место под
//! непересечение регионов. Устрой понижение как «ядро → текст C», и Фаза 7
//! началась бы с восстановления известного двумя проходами раньше; из
//! C-подобного представления уникальность не восстанавливается.
//!
//! Обещание шва **выполнено**, а не обещано дальше: эмиттеров два, и второй
//! ([`emit_llvm`], Фаза 7) читает то же представление, не трогая ни ядра, ни
//! понижения. Это и есть вариант (а) волны 0 - второй эмиттер, а не второй
//! компилятор.
//!
//! Отсюда раскладка: [`ir`] - представление и факты, [`lower`] - ядро в IR,
//! [`split`] - IR в IR с границами дробления, [`perceus`] - IR в IR со
//! вставленным RC, [`emit_c`] - IR в C, [`emit_llvm`] - IR в текст `.ll`,
//! [`llvm`] - конвейер `llvm-as`/`opt`/`llc` до объектника. Ни один эмиттер
//! термов ядра не читает, и это проверено тестом, а не обещано
//! (`tests/seam.rs`).
//!
//! Срезы у эмиттеров **разные**, и это не временное неудобство: C берёт чистый
//! фрагмент целиком плюс эффекты одношотом, LLVM - скалярный фрагмент и
//! объектный слой над ним (`docs/phase7-plan.md`, треки A и A′). Что берёт
//! второй и где стоит его следующая стена - в его шапке.
//!
//! # Что берётся этим срезом
//!
//! Чистый фрагмент: семейства и конструкторы, функции и применение, разбор,
//! рекурсия, `let`, примитивы и массивы (§4.11), записи и плотная укладка
//! агрегата (§4.2, §4.11), регионы со стандартными стратегиями (§3.6),
//! очистка ресурса на нормальном выходе из scope (§3.3).
//!
//! Плюс **эффекты одношотом целиком** (§3.4, трёхзначный вердикт ветки). Кадр
//! `HANDLER`, вектор evidence копией родителя плюс запись, операция через
//! `adamas_evidence_lookup`. Хвостово-резумптивная ветка зовётся на месте и
//! сегмента не трогает; абортивная режет его и раскручивает - отсюда очистка
//! ресурса на исключительном выходе (§3.3); общая режет его в **значение**, и
//! дальше судьбу резумпции решает владение. Параметризованный хендлер идёт тем
//! же путём, что одношот (§10 вопрос 129). Отсюда и пользовательские стратегии
//! размещения (§10 вопрос 161): политику им задаёт хендлер.
//!
//! **Маска - правка вектора, а не кадр** (§3.4): `#mask.L` строит вектор без
//! ближайшей записи своей метки (`adamas_evidence_mask`) и считает вычисление
//! под ним. Счётчиком пропусков это не выражается - `skip` нужен месту
//! операции, а операции лежат внутри маскируемого вычисления, то есть в чужой
//! функции.
//!
//! **Форм понижения две** (§13, обе записи 2026-09-08), и выбирает между ними
//! row написанного типа: меток нет - первая, обычная C-функция по C-стеку без
//! единого скрытого аргумента; есть - вторая, с вектором evidence и ручкой
//! стека продолжения перед написанным. Сигнатуры обеих канонизированы
//! рантаймом - `adamas_lowered_first` и `adamas_lowered_second`. Лямбда идёт
//! второй формой всегда: написанного типа у её связывания в ядре нет, а
//! граница замыкания несёт оба скрытых аргумента и без того.
//!
//! **Тело второй формы дроблено кадрами** по точкам приостановки ([`split`]):
//! кадр стоит на операции, на возобновлении, на входе в хендлер, на выходе из
//! scope с ресурсом, на применении значения и на вызове функции, внутри
//! которой есть что-то из этого. Отсюда договор возврата: дроблёная функция
//! возвращает не свой ответ, а значение вершине стека, и до кадра его доводит
//! трамплин `adamas_kont_run`. Вторая форма без единой точки приостановки
//! дробления не получает и остаётся обычной C-функцией.
//!
//! **В тихой программе операция - не точка приостановки** (§3.4, вопрос 74,
//! первая ступень): все ветки всех площадок хвостовые, мультишота нет - ветка
//! бежит на месте и отвечает значением операции, а обрыв невозможен по
//! построению. Тело с такими операциями не дробится, кадров продолжения не
//! ставится, переиспользование ячейки не упирается в границу куска. Остаётся
//! evidence-косвенность - поиск хендлера и непрямой вызов ветки на каждой
//! операции; её снимала бы специализация по row, и это следующая ступень того
//! же вопроса. Свидетели - `tests/quiet.rs`.
//!
//! **Питомник и файберы** (§5.2, волна 5): `withNursery` - постулат, чьё тело
//! даёт рантайм; файбер есть сегмент того же стека, уступка режет его по кадру
//! питомника, отмена задачи стоит на **разборе** её значения и раскручивает
//! сегмент отменённого. Кто обслужит операцию - круг или написанный хендлер, -
//! решает рантайм по вектору evidence: ближайший выигрывает, и статически это
//! неразличимо, потому что те же имена пишутся вовсе без питомника
//! (`eval/fibers.adamas`).
//!
//! Что не берётся, отвергается **своим** отказом с именем формы: молча
//! посчитать не то хуже, чем не посчитать ([`LowerError`](lower::LowerError)).
//!
//! # Чем это проверено
//!
//! Договором с интерпретатором: программа корпуса `tests/golden/eval/`
//! компилируется в C, собирается и печатает **то же**, что `adamas eval`. Тот
//! же жанр, каким связаны машина с ядром и специализация с исполнением; третий
//! вычислитель входит в тот же договор.
//!
//! # Что порождённый код делает с памятью
//!
//! Счётчик ссылок вставляет [`perceus`] проходом IR → IR, и он же раздаёт
//! придержанные ячейки под reuse (§5.1). Договор один на всё понижение:
//! аргумент приходит владением, ответ уходит владением. Живых блоков в конце
//! прогона поэтому ноль, и счётчики рантайма печатают это числом на stderr;
//! рядом печатается число **выданных** блоков - по нему видно reuse, потому что
//! переписанная ячейка выдачей не считается.
//!
//! **Прочих оптимизаций нет.** Определение без параметров пересчитывается на
//! каждом упоминании, замыкание аллоцируется на каждое недобранное применение,
//! бета-редекс не сокращается. Предсказуемый выход дороже короткого: milestone
//! фазы про 500-строчную программу, а не про этот срез.
//!
//! # Названные долги
//!
//! **Обходы рекурсивны** - и понижение, и эмиссия. Машина, освобождение и
//! печать терма от рекурсии по кадрам Rust ушли намеренно (§10 вопросы 89, 92,
//! 93), и здесь тот же предел вернулся: глубоко вложенный терм положит стек
//! компилятора. На корпусе чистого фрагмента глубина - единицы, и предела никто
//! не мерил. Мерить его придётся программой, а не рассуждением, - те три
//! вопроса показали ровно это.
//!
//! Печать в порождённом C рекурсивна тоже, но **ограничена**: она режется по
//! глубине там же и так же, как `adamas eval` (§`print.c`), и дальше двухсот
//! уровней не уходит. Ограниченной её сделал срез, а нерекурсивной она не стала.

