/// Собирает `.ll` и спутник на C.
///
/// # Errors
///
/// [`LlvmError`] - форма понижения вне скалярного фрагмента.
pub fn emit(program: &Program) -> Result<Artefacts, LlvmError> {
    let entry = &program.functions[program.entry.0];
    let answer = Answer::of(entry)?;
    // Точка входа зовётся без аргументов, и подать их было бы неоткуда: `main`
    // с параметром есть функция значением, а её ответ печатать нечем и у
    // C-бэкенда (`agreement.rs`, `LANGUAGE`).
    if entry.live_parameters().next().is_some() {
        return Err(LlvmError::Shape {
            function: entry.name.clone(),
            place: "точка входа".to_owned(),
            shape: "функция с параметрами".to_owned(),
        });
    }
    // Вторая форма точкой входа быть не может: скрытых аргументов ей взять
    // неоткуда, а корня стека у неё нет - его заводит `handle`, которого в ней
    // нет по условию. Отказ здесь, а не арность в `.ll`: верификатор промолчал
    // бы, а компоновщик назвал бы не то место.
    if entry.form == Form::Detached {
        return Err(LlvmError::Hidden {
            caller: "точка входа".to_owned(),
            callee: entry.name.clone(),
        });
    }

    let suspending = crate::split::suspending(program);
    boundaries(program, &suspending)?;
    let mut module = Module::default();
    // Отладочная информация появляется **от исходника**, а не от ключа сборки:
    // нет текста - нечего и называть отладчику, и выход тогда байт в байт тот
    // же, что был до трека E.
    if let Some(source) = &program.source {
        module.dwarf = Some(Dwarf::new(&mut module.metadata, source));
    }
    for function in &program.functions {
        module.function(program, function, &suspending)?;
    }
    for at in 0..program.handlers.len() {
        module.branches(program, at);
    }
    for function in taking(program) {
        module.taker(&program.functions[function.0]);
    }
    for function in boxing(program) {
        module.boxer(&program.functions[function.0]);
    }
    // Сборщики - последними: отвергнуть конструктор значением обязано тело
    // ([`Builder::building`]), и до этой строки отказ уже вернулся бы.
    for constructor in builders(program) {
        module.maker(&program.constructors[usize::from(constructor.0)]);
    }
    Ok(Artefacts {
        ll: module.finish(program, answer),
        support: support(program, answer),
    })
}

/// Смещение слота среды кадра от её начала, в байтах.
///
/// Одной записью на всех, потому что читают её пятеро - раздача веток, дроп их
/// среды, постановка кадра, код куска и дроп его среды, - и разъедься любые
/// две, слот читался бы не тот, а сборка молчала бы: тип у всех слотов один.
fn offset(slot: usize) -> u64 {
    u64::try_from(slot).unwrap_or(u64::MAX) * u64::from(SLOT_BYTES)
}

/// Тип регистра, которым функция отдаёт ответ **через границу вызова**.
///
/// Дроблёная отдаёт слово вершине стека, а не свой ответ (`adamas.h`,
/// «дроблёное тело»), и тип у этой границы один. Спрашивается это в трёх
/// местах - у определения, у прямого вызова и у трамплинов, - и запись одна,
/// потому что разъехаться им негде.
fn crossing(program: &Program, suspending: &Suspension, id: FuncId) -> Option<String> {
    if suspending.functions.contains(&id) {
        return Some("ptr".to_owned());
    }
    slot(program.functions[id.0].result)
}

/// Границы, у которых форма функции задана рантаймом, а не понижением.
///
/// Ветка хендлера, ветка `return` и деструктор scope зовутся **через кадр**:
/// сигнатуру им канонизирует `adamas.h` (`adamas_handler_code`, `adamas_code`),
/// и отвечают они словом. Проверяется это здесь, до печати: несовпадение тут не
/// отказ verifier'а, а вызов с другой арностью, который соберётся и упадёт в
/// рантайме. То же утверждение и по тому же поводу делает C-эмиттер
/// (`emit_c::forms_agree`).
fn boundaries(program: &Program, suspending: &Suspension) -> Result<(), LlvmError> {
    let mut named: Vec<(FuncId, &'static str)> = Vec::new();
    for handler in &program.handlers {
        for branch in &handler.branches {
            named.push((branch.function, "ветка хендлера"));
        }
        named.push((handler.returned, "ветка `return`"));
    }
    for closer in taking(program) {
        named.push((closer, "деструктор scope"));
    }
    // Замыкание отвечает словом наравне с ними, но форма у него своя: значением
    // бывает и первая - ей трамплин скрытых аргументов просто не передаёт.
    for boxed in boxing(program) {
        let function = &program.functions[boxed.0];
        if crossing(program, suspending, boxed).as_deref() != Some("ptr") {
            return Err(LlvmError::Shape {
                function: function.name.clone(),
                place: "ответ: замыкание".to_owned(),
                shape: describe(function.result),
            });
        }
    }
    for (id, place) in named {
        let function = &program.functions[id.0];
        if function.form != Form::Detached {
            return Err(LlvmError::Shape {
                function: function.name.clone(),
                place: place.to_owned(),
                shape: "первая форма понижения".to_owned(),
            });
        }
        if crossing(program, suspending, id).as_deref() != Some("ptr") {
            return Err(LlvmError::Shape {
                function: function.name.clone(),
                place: format!("ответ: {place}"),
                shape: describe(function.result),
            });
        }
    }
    Ok(())
}

/// Объявления массива (§4.11): точки входа те же, что зовёт C-бэкенд.
///
/// Условны, как и объявления второй формы, и по той же причине: на программе
/// без массива выход байт в байт тот же, что был до этого трека. Куча за
/// рантаймом целиком - блок выдаёт `adamas_array_alloc`, копию под запись
/// решает `adamas_array_writable`, адрес ячейки с проверкой границы отдаёт
/// `adamas_array_at`; сама ячейка при этом читается и пишется **инструкцией**
/// (см. [`Builder::array_set`]).
fn arrays(out: &mut String, program: &Program) {
    if !arrayed(program) {
        return;
    }
    out.push_str(concat!(
        "; Массив (§4.11): один блок на всю длину, укладка плоская либо слотами.\n",
        "; Ячейку читает и пишет сам IR; адрес её с проверкой границы - рантайм.\n",
        "declare ptr @adamas_array_alloc(i64, i64)\n",
        "declare ptr @adamas_array_at(ptr, i64)\n",
        "declare void @adamas_array_fill_flat(ptr, ptr)\n",
        "declare void @adamas_array_fill(ptr, ptr, ptr)\n",
        "declare void @adamas_array_put(ptr, i64, ptr, ptr)\n",
        "declare ptr @adamas_array_take(ptr, i64, ptr)\n",
        "declare ptr @adamas_array_writable(ptr, ptr)\n",
        "\n",
    ));
}

/// Есть ли в программе массив: постройка, запись либо чтение ячейки.
fn arrayed(program: &Program) -> bool {
    program.functions.iter().any(|function| {
        let mut found = false;
        walk(&function.body, &mut |expr| {
            found |= matches!(
                expr,
                Expr::ArrayNew { .. } | Expr::ArraySet { .. } | Expr::ArrayIndex { .. }
            );
        });
        found
    })
}

/// Функции, стоящие деструктором кадра `CLOSING`: им нужен забирающий трамплин.
///
/// Тот же список, что собирает `emit_c::moving`, и собран он здесь заново по
/// той же причине, по которой у двух эмиттеров два обхода: список этот -
/// свойство печати, а не представления, и C-эмиттер держит свой приватным.
fn taking(program: &Program) -> BTreeSet<FuncId> {
    let mut found = BTreeSet::new();
    for function in &program.functions {
        walk(&function.body, &mut |expr| {
            if let Expr::Closing { closer, .. } = expr {
                found.insert(*closer);
            }
        });
    }
    found
}

/// Есть ли в программе выход из scope кадром: тогда нужен дроп его среды.
fn scoped(program: &Program) -> bool {
    program.functions.iter().any(|function| {
        let mut found = false;
        walk(&function.body, &mut |expr| {
            found |= matches!(expr, Expr::Closing { .. });
        });
        found
    })
}

/// Функции, стоящие значением: им нужен общий трамплин.
///
/// Тот же список, что собирает `emit_c::moving` под `box_`, и собран он здесь
/// заново по той же причине, что и [`taking`].
fn boxing(program: &Program) -> BTreeSet<FuncId> {
    let mut found = BTreeSet::new();
    for function in &program.functions {
        walk(&function.body, &mut |expr| {
            if let Expr::Closure { function: code, .. } = expr {
                found.insert(*code);
            }
        });
    }
    found
}

/// Конструкторы, стоящие значением: им нужен свой сборщик.
///
/// Тот же список, что собирает `emit_c::builders`, и собран он здесь заново по
/// той же причине, что и [`taking`].
fn builders(program: &Program) -> BTreeSet<CtorId> {
    let mut found = BTreeSet::new();
    for function in &program.functions {
        walk(&function.body, &mut |expr| {
            if let Expr::ConstructClosure { constructor } = expr {
                found.insert(*constructor);
            }
        });
    }
    found
}

/// Есть ли в программе питомник: круг, его операция либо отмена (§5.2).
///
/// Спрашивается ради объявлений: точки входа круга объявляются только там, где
/// они зовутся, и выход на программе без питомника байт в байт тот же, что был
/// до этого трека.
fn nursed(program: &Program) -> bool {
    program.functions.iter().any(|function| {
        let mut found = false;
        walk(&function.body, &mut |expr| {
            found |= matches!(
                expr,
                Expr::Nursery { .. } | Expr::Fiber { .. } | Expr::Cancel { .. }
            );
        });
        found
    })
}

/// Обход дерева выражения сверху вниз.
///
/// Шаг берётся у самого представления ([`Expr::children`]): свой обход означал
/// бы, что утверждение об **отсутствии** узла зеленеет молча, стоит
/// представлению вырасти.
fn walk(expr: &Expr, visit: &mut impl FnMut(&Expr)) {
    visit(expr);
    for child in expr.children() {
        walk(child, visit);
    }
}

/// Чем отвечает программа: тем и различаются две печати спутника.
///
/// Форм две, потому что их две у `main.c`, взятого дословно: плоское лежит в
/// регистре и печатается по сорту, объект приходит владением и после печати
/// дропается. Третьей формы нет и у C-бэкенда.
#[derive(Clone, Copy, Debug)]
enum Answer {
    /// Плоское: печатается сортом, дропать нечего.
    Flat(PrimTy),
    /// Объект кучи либо запись: печатается таблицей, дропается спутником.
    Boxed,
}

impl Answer {
    /// Чем отвечает точка входа. Прочее - названный отказ.
    fn of(entry: &Function) -> Result<Self, LlvmError> {
        if let Some(ty) = entry.result.primitive() {
            return Ok(Self::Flat(ty));
        }
        // Запись сюда входит, резумпция - нет: печатать её нечем и у
        // C-бэкенда (`print.c` ответил бы `?tag`), а дроп у неё свой.
        if matches!(entry.result, Repr::Boxed | Repr::Record(_)) {
            return Ok(Self::Boxed);
        }
        Err(LlvmError::Shape {
            function: entry.name.clone(),
            place: "ответ программы".to_owned(),
            shape: describe(entry.result),
        })
    }

    /// Тип регистра, которым ответ уходит из `.ll`.
    const fn machine(self) -> &'static str {
        match self {
            Self::Flat(ty) => machine(ty),
            Self::Boxed => "ptr",
        }
    }
}

/// Как назвать представление в тексте отказа.
fn describe(repr: Repr) -> String {
    match repr {
        Repr::Flat(ty) => format!("плоское {}", ty.name()),
        Repr::Boxed => "объект кучи".to_owned(),
        Repr::Packed(_) => "плотный агрегат".to_owned(),
        Repr::Layout => "дескриптор укладки".to_owned(),
        Repr::Opaque => "плоское неизвестной ширины".to_owned(),
        Repr::Array(_) => "массив".to_owned(),
        Repr::Region => "блок региона".to_owned(),
        Repr::Record(_) => "запись".to_owned(),
        Repr::Resumption => "резумпция".to_owned(),
        Repr::Simd { lanes, lane } => format!("вектор `Simd {lanes} {lane}`"),
    }
}

/// Тип LLVM у плоского значения.
///
/// Знаковость типом не выражается вовсе - её несёт инструкция (`sdiv` против
/// `udiv`, `slt` против `ult`), и это не потеря: §4.11 различает `Int64` и
/// `UInt64` шириной и правилом сравнения, а ширина здесь та же.
const fn machine(ty: PrimTy) -> &'static str {
    match ty {
        PrimTy::Int8 | PrimTy::UInt8 => "i8",
        PrimTy::Int16 | PrimTy::UInt16 => "i16",
        PrimTy::Int32 | PrimTy::UInt32 => "i32",
        PrimTy::Int64 | PrimTy::UInt64 => "i64",
        PrimTy::Float32 => "float",
        PrimTy::Float64 => "double",
    }
}

/// Целое той же ширины: в нём живёт ключ порядка (§4.3).
///
/// У целых типов оно совпадает с [`machine`] - ключ у них и есть само значение
/// с перевёрнутым знаковым разрядом, а переворачивает его предикат `icmp`.
const fn word(ty: PrimTy) -> &'static str {
    match ty {
        PrimTy::Float32 => "i32",
        PrimTy::Float64 => "i64",
        other => machine(other),
    }
}

/// Плоская константа в тексте `.ll`.
///
/// Целое - беззнаковым десятичным: LLVM принимает всё, что укладывается в
/// ширину, а биты в представлении уже обрезаны понижением.
///
/// Плавающее - **шестнадцатеричной** формой, той самой, которую LLVM завёл для
/// точной записи. Десятичная запись поехала бы через разбор строки, а §4.3
/// обещает биты, а не близкое к ним число.
fn constant(ty: PrimTy, bits: u64) -> String {
    match ty {
        PrimTy::Float32 => format!("0x{:016X}", widened(bits)),
        PrimTy::Float64 => format!("0x{bits:016X}"),
        _ => bits.to_string(),
    }
}

/// Биты `Float32`, расширенные до `double`.
///
/// Так устроен разбор `.ll`: константа одинарной точности пишется в нём
/// шестнадцатеричным `double`, и сужение обратно обязано быть точным. Оно
/// точно - младшие 29 бит расширения нулевые по построению, - и `llvm-as`
/// отвергает запись, у которой это не так.
///
/// NaN расширяется **руками**, а не приведением: приведение железом квитирует
/// сигнальный NaN, то есть меняет биты, которые §4.3 обещает сохранить.
#[expect(
    clippy::cast_possible_truncation,
    reason = "биты `Float32` лежат в младшей половине слова по построению"
)]
fn widened(bits: u64) -> u64 {
    let bits = bits as u32;
    let single = f32::from_bits(bits);
    if single.is_nan() {
        let sign = u64::from(bits >> 31) << 63;
        let payload = u64::from(bits & 0x007f_ffff) << 29;
        return sign | (0x7ffu64 << 52) | payload;
    }
    f64::from(single).to_bits()
}

/// Сорт вызова (трек D).
///
/// `musttail` есть свойство **инструкции**, а не ключей пользователя (§3.4,
/// §5.3): оптимизация хвостового вызова, которую `llc` делает сам, идёт только
/// с `-O2` и только там, где кадру вызываемого хватает места вызывающего.
/// Приставка снимает оба условия.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Tail {
    /// Обычный вызов: кадр вызывающего живёт дальше.
    Plain,
    /// Хвостовой: кадр вызывающего замещается кадром вызываемого.
    ///
    /// Требование LLVM к такому вызову одно, и его обязан выполнить эмиттер: за
    /// инструкцией немедленно следует `ret` того же значения. Отсюда разбор без
    /// `phi` в хвостовой позиции ([`Builder::analysis_tail`]).
    Must,
}

impl Tail {
    /// Приставка инструкции вызова.
    const fn prefix(self) -> &'static str {
        match self {
            Self::Plain => "",
            Self::Must => "musttail ",
        }
    }
}

/// Метаданные **одной** инструкции.
///
/// Аргумент [`Builder::instruction`], а не поле билдера, и разница
/// принципиальная: суффикс, лежащий полем, одинаков у всех инструкций подряд, а
/// ни одни из требуемых метаданных таковыми не являются. `!dbg` различается от
/// инструкции к инструкции - у пролога он свой (трек E, [`Builder::prologue`]).
/// Под scoped `!alias.scope`/`!noalias` механизм заводился тоже, и они его не
/// заняли: трек B их не поставил - регионов в IR нет, а на объектах они дают
/// ноль инструкций (`tests/alias.rs`). Довод про аргумент от этого не слабеет,
/// его держит `!dbg`: у пролога локация своя, у тела своя. Но других носителей
/// у механизма нет, и второй ожидался отсюда.
///
/// Собирается цепочкой: [`Notes::none`] плюс [`Notes::and`] на каждый узел.
/// Окружающие метаданные - те, что несёт всякая инструкция тела, - отдаёт
/// [`Builder::here`], и своё дописывается к ним:
/// `self.here().and("alias.scope", "!7")`.
#[derive(Clone, Debug, Default)]
struct Notes {
    /// Узлы в порядке печати.
    items: Vec<String>,
}

impl Notes {
    /// Ни одной.
    const fn none() -> Self {
        Self { items: Vec::new() }
    }

    /// Дописывает узел: `!kind !N`.
    fn and(mut self, kind: &str, node: &str) -> Self {
        self.items.push(format!("!{kind} {node}"));
        self
    }

    /// Хвост инструкции. Пустой список не печатает даже запятой.
    fn suffix(self) -> String {
        if self.items.is_empty() {
            return String::new();
        }
        format!(", {}", self.items.join(", "))
    }
}

/// Атрибуты параметра: пусто, и это результат замера (трек B).
///
/// Здесь стояли бы `noalias`, `dereferenceable` и `align`. Не стоит ни один, и
/// у каждого своя причина.
///
/// *`noalias` ничего не даёт.* Поставленный **щедро** - на каждый указательный
/// параметр - он меняет ноль инструкций на трёх нагрузках (`tests/alias.rs`).
/// Причина видна в выходе: после инлайнинга `noalias` превращается в scoped
/// `!noalias`, но горячий виток FBIP - это самохвостовая рекурсия, свёрнутая в
/// **один** цикл внутри одной области видимости, и разные итерации попадают в
/// одну и ту же scope. Различать им себя нечем.
///
/// *`dereferenceable` и `align` не просто бесполезны - на [`Repr::Boxed`] они
/// неверны.* `adamas.h` говорит прямо: ставить их законно только там, где
/// `adamas_is_imm` уже дал ложь, а `Boxed` покрывает и непосредственное
/// значение - нульарный конструктор приезжает числом `1`. Обещание разрешает
/// поднять чтение тега до проверки, и программа падает: свидетель
/// `dereferenceable_on_a_boxed_parameter_is_a_fault`.
///
/// Уникальность при этом **есть** и читается - [`Fact::unique`], - но не здесь:
/// её место [`Builder::salvaged_unique`], где она снимает вопрос рантайму, а не
/// обещает что-то оптимизатору.
fn parameter_attributes(fact: &Fact) -> String {
    let _ = fact;
    String::new()
}

/// Узлы метаданных модуля, нумерованные порядком заведения.
///
/// Номер выдаётся при записи и возвращается ссылкой `!N`: узлы DWARF ссылаются
/// друг на друга, и держать номер в голове пришлось бы иначе на каждом.
#[derive(Debug, Default)]
struct Metadata {
    /// Узлы по номеру.
    nodes: Vec<String>,
    /// Уже заведённые узлы: текст к ссылке.
    ///
    /// LLVM уникализирует неразличимые узлы сама, поэтому вторая копия
    /// `!DIBasicType(name: "Int64", ...)` не ошибка - она просто занимает место
    /// в тексте. Копий выходит по одной на каждое упоминание типа, и на
    /// программе из сотни функций это сотни строк ни о чём. `distinct` в кеш не
    /// идёт: он затем и написан, чтобы копии различались.
    seen: HashMap<String, String>,
    /// Именованные метаданные: имя и список ссылок.
    named: Vec<(String, Vec<String>)>,
}

impl Metadata {
    /// Заводит узел и отдаёт ссылку на него.
    fn node(&mut self, text: &str) -> String {
        if let Some(known) = self.seen.get(text) {
            return known.clone();
        }
        let at = self.nodes.len();
        self.nodes.push(text.to_owned());
        let reference = format!("!{at}");
        if !text.starts_with("distinct ") {
            self.seen.insert(text.to_owned(), reference.clone());
        }
        reference
    }

    /// Заводит именованный список: `!имя = !{...}`.
    fn name(&mut self, name: &str, refs: Vec<String>) {
        self.named.push((name.to_owned(), refs));
    }

    /// Печатает всё: сперва именованные, потом нумерованные.
    fn print(&self, out: &mut String) {
        for (name, refs) in &self.named {
            let _ = writeln!(out, "!{name} = !{{{}}}", refs.join(", "));
        }
        for (at, node) in self.nodes.iter().enumerate() {
            let _ = writeln!(out, "!{at} = {node}");
        }
    }
}

/// Общие узлы DWARF: файл, единица трансляции, пустой список.
///
/// Заводится ровно тогда, когда у программы назван исходник
/// ([`Program::source`](crate::ir::Program::source)). Нет исходника - нет и
/// отладочной информации, а выход байт в байт тот, что был до трека E.
///
/// `DW_LANG_C99`, а не `DW_LANG_Haskell` или свой код: язык в DWARF выбирает,
/// **каким синтаксисом отладчик разбирает выражения**, и на C-режиме `print x`
/// работает как ожидается. Кода Adamas в DWARF нет, а Haskell-режим включил бы
/// чужие правила печати. Цена названа: имя Adamas, не являющееся идентификатором
/// C (`f'`), отладчику придётся квотировать.
#[derive(Debug)]
struct Dwarf {
    /// Ссылка на `!DIFile`.
    file: String,
    /// Ссылка на `!DICompileUnit`.
    unit: String,
}

impl Dwarf {
    /// Заводит шапку DWARF: флаги модуля, файл, единицу трансляции.
    fn new(metadata: &mut Metadata, source: &Source) -> Self {
        let empty = metadata.node("!{}");
        let file = metadata.node(&format!(
            "!DIFile(filename: \"{}\", directory: \"{}\")",
            source.file, source.directory
        ));
        let unit = metadata.node(&format!(
            "distinct !DICompileUnit(language: DW_LANG_C99, file: {file}, \
             producer: \"adamas\", isOptimized: false, runtimeVersion: 0, \
             emissionKind: FullDebug, enums: {empty})"
        ));
        // Обе версии обязательны, и вторая - не украшение: без «Debug Info
        // Version» verifier выбрасывает метаданные целиком, и `.ll` собирается
        // молча без DWARF. Пятая версия читается и восемнадцатой, и двадцать
        // первой - проверено прогоном, а не таблицей совместимости.
        let dwarf_version = metadata.node("!{i32 7, !\"Dwarf Version\", i32 5}");
        let info_version = metadata.node("!{i32 2, !\"Debug Info Version\", i32 3}");
        metadata.name("llvm.dbg.cu", vec![unit.clone()]);
        metadata.name("llvm.module.flags", vec![dwarf_version, info_version]);
        Self { file, unit }
    }

    /// Тип DWARF под представление слота.
    ///
    /// Имя берётся у **Adamas** (§4.11), а не у машинного типа: `UInt64`, а не
    /// `i64`. Ради этого трек и заведён - отладчик показывает типы языка, а не
    /// типы бэкенда. Знаковость и плавучесть несёт кодировка, ширину - размер.
    ///
    /// `DW_ATE_float` у плавающего - **не** `DW_ATE_signed` с той же шириной:
    /// кодировкой отладчик решает, как читать биты, и спутай её - `1.0`
    /// показалось бы числом `4607182418800017408`.
    fn ty(metadata: &mut Metadata, repr: Repr) -> String {
        match repr.primitive() {
            Some(prim) => {
                let encoding = if prim.floating() {
                    "DW_ATE_float"
                } else if prim.signed() {
                    "DW_ATE_signed"
                } else {
                    "DW_ATE_unsigned"
                };
                metadata.node(&format!(
                    "!DIBasicType(name: \"{}\", size: {}, encoding: {encoding})",
                    prim.name(),
                    prim.size() * 8
                ))
            }
            // Объект кучи: своего имени у него в IR нет - представление знает
            // только, что это указатель. Показать «указатель» честнее, чем
            // выдумать имя типа, которого представление не несёт.
            None => metadata.node(
                "!DIDerivedType(tag: DW_TAG_pointer_type, name: \"объект\", \
                 baseType: null, size: 64)",
            ),
        }
    }

    /// Заводит `!DISubprogram` функции и её локацию тела.
    ///
    /// `linkageName` **не пишется**, и это измерено: с ним gdb показывает в
    /// кадре `fn_3`, без него - имя Adamas. Ради имени трек и существует, а
    /// связь с символом отладчик всё равно берёт по адресам.
    fn subprogram(
        &self,
        metadata: &mut Metadata,
        function: &Function,
        at: Location,
        signature: &[String],
    ) -> Scope {
        let types = metadata.node(&format!("!{{{}}}", signature.join(", ")));
        let subroutine = metadata.node(&format!("!DISubroutineType(types: {types})"));
        let subprogram = metadata.node(&format!(
            "distinct !DISubprogram(name: \"{}\", scope: {}, file: {}, line: {}, \
             type: {subroutine}, scopeLine: {}, \
             spFlags: DISPFlagDefinition | DISPFlagLocalToUnit, unit: {})",
            escaped_name(&function.name),
            self.file,
            self.file,
            at.line,
            at.line,
            self.unit
        ));
        let here = metadata.node(&format!(
            "!DILocation(line: {}, column: {}, scope: {subprogram})",
            at.line, at.column
        ));
        // Строка нуль - «код написан не человеком», и она здесь не заглушка, а
        // требование: `llc` ставит `prologue_end` на первую инструкцию с
        // ненулевой строкой, и без нулевого пролога точка останова вставала бы
        // **до** записи параметра в кадр. Измерено сеансом: параметр печатался
        // нулём вместо своего значения.
        let prologue = metadata.node(&format!("!DILocation(line: 0, scope: {subprogram})"));
        Scope {
            subprogram,
            here,
            prologue,
            at,
        }
    }
}

/// Отладочная подпись одной функции.
#[derive(Clone, Debug)]
struct Scope {
    /// Ссылка на `!DISubprogram`.
    subprogram: String,
    /// Локация тела: строка определения.
    here: String,
    /// Локация пролога: строка нуль.
    prologue: String,
    /// Где определение написано - им же датируются локальные переменные.
    at: Location,
}

/// Имя в кавычках метаданных: обратный слеш и кавычка экранируются.
fn escaped_name(name: &str) -> String {
    name.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Модуль целиком.
#[derive(Debug, Default)]
struct Module {
    /// Тела функций.
    bodies: String,
    /// Узлы метаданных модуля.
    metadata: Metadata,
    /// Шапка DWARF. `None` - исходника у программы нет.
    dwarf: Option<Dwarf>,
}

impl Module {
    /// Эмитит одну функцию.
    fn function(
        &mut self,
        program: &Program,
        function: &Function,
        suspending: &Suspension,
    ) -> Result<(), LlvmError> {
        let split = suspending.functions.contains(&function.id);
        // Дроблёная функция возвращает **не свой ответ**, а значение вершине
        // стека (`adamas.h`, «дроблёное тело»), и значение это - слово. Плоский
        // ответ вернуть им нельзя: обрыв `adamas_kont_abort` отвечает
        // указателем, а вернуть его требуется немедленно. C-эмиттер проверяет то
        // же самое и тем же местом (`emit_c::forms_agree`, `EmitError::Aborting`).
        let result = if split {
            if slot(function.result).as_deref() != Some("ptr") {
                return Err(LlvmError::Shape {
                    function: function.name.clone(),
                    place: "ответ дроблёного тела".to_owned(),
                    shape: describe(function.result),
                });
            }
            "ptr".to_owned()
        } else {
            slot_or(function, "ответ", function.result)?
        };

        let mut parameters = Vec::new();
        // Скрытые аргументы второй формы - вектор evidence и ручка стека, в том
        // же порядке, что у `adamas_lowered_second`. Печатаются они здесь, у
        // прямого вызова ([`Builder::call`]) и у трамплинов; порядок один.
        if function.form == Form::Detached {
            parameters.push("ptr %ev".to_owned());
            parameters.push("ptr %kont".to_owned());
        }
        // Захваченная среда приходит обычными параметрами перед написанным - её
        // раздаёт трамплин либо раздача веток, как и у C-эмиттера.
        for binding in function.live_captured().chain(function.live_parameters()) {
            let ty = slot_or(
                function,
                &format!("параметр `{}`", binding.name),
                binding.fact.repr,
            )?;
            let attributes = parameter_attributes(&binding.fact);
            let spaced = if attributes.is_empty() {
                String::new()
            } else {
                format!("{attributes} ")
            };
            parameters.push(format!("{ty} {spaced}%v{}", binding.local.0));
        }

        // Подпись функции для DWARF собирается **до** тела: `!DISubprogram`
        // обязан существовать раньше, чем на него сошлётся первая локация.
        let scope = match (&self.dwarf, function.position) {
            (Some(dwarf), Some(at)) => {
                let mut signature = vec![Dwarf::ty(&mut self.metadata, function.result)];
                signature.extend(
                    function
                        .live_parameters()
                        .map(|binding| Dwarf::ty(&mut self.metadata, binding.fact.repr)),
                );
                Some(dwarf.subprogram(&mut self.metadata, function, at, &signature))
            }
            _ => None,
        };

        let mut builder = Builder::new(
            program,
            function,
            result.clone(),
            suspending,
            &mut self.metadata,
            self.dwarf.as_ref(),
            scope.clone(),
        );
        builder.parameters_in_frame(function);
        if split {
            // Дроблёное тело возвратом не кончается: всякий его путь отдаёт
            // значение вершине стека, а до кадра его доводит трамплин.
            builder.flowing(&function.body)?;
        } else {
            // Тело стоит в **возвратной** позиции целиком, и обход её разносит:
            // хвостовой вызов печатается `musttail`, всё прочее - `ret`.
            // Печатает `ret` сам обход, потому что у разбора в хвосте их
            // столько, сколько ветвей (трек D).
            builder.tail(&function.body)?;
        }

        let signed = scope.map_or_else(String::new, |scope| format!(" !dbg {}", scope.subprogram));
        for chunk in std::mem::take(&mut builder.chunks) {
            self.bodies.push_str(&chunk);
        }
        let _ = writeln!(self.bodies, "; {}", function.name);
        let _ = writeln!(
            self.bodies,
            "define internal {CONVENTION} {result} @fn_{}({}) {DEFINITION_ATTRIBUTES}{signed} {{",
            function.id.0,
            parameters.join(", ")
        );
        self.bodies.push_str("entry:\n");
        self.bodies.push_str(&builder.head);
        self.bodies.push_str(&builder.body);
        self.bodies.push_str("}\n\n");
        Ok(())
    }

    /// Ветки одной площадки `handle` одной функцией: их выбирает номер операции.
    ///
    /// Одной, а не по функции на ветку, и довод тот же, что у C-эмиттера:
    /// выбирает их **рантайм**, операция приходит с кадром на руках и
    /// статически не знает, чьи это ветки (`adamas.h`, `adamas_handler_code`).
    /// Соглашение о вызове здесь поэтому C, а не [`CONVENTION`]: зовёт её
    /// рантайм по указателю на `adamas_handler_code`.
    ///
    /// Среда кадра принадлежит кадру, а функция берёт аргументы владением -
    /// отсюда `adamas_dup` на каждый слот. Лишние аргументы операции -
    /// синтезированный триггер приостановленного вычисления - дропаются здесь:
    /// сколько ветка связывает, знает площадка, а место операции не знает.
    ///
    /// Вердиктов три, и различает их судьба сегмента: хвостовая его не трогает,
    /// абортивная режет и кладёт раскрутку кадром **до** ветки, общая режет в
    /// значение и отдаёт ветке лишним аргументом. Мультишотная режет как общая и
    /// помечает ручку `adamas_segment_multi`: возобновление будет ставить копию,
    /// пока на ручку есть лишние ссылки (§3.4, «Стоимость multi-shot»).
    fn branches(&mut self, program: &Program, at: usize) {
        let described = &program.handlers[at];
        let label = &program.labels[described.label.0 as usize];
        let env = described
            .captured
            .iter()
            .filter(|it| it.fact.present)
            .count();

        let mut out = String::new();
        let _ = writeln!(out, "; ветки `{}`", label.name);
        let _ = writeln!(
            out,
            "define internal ptr @handler_{at}(ptr %h, ptr %kont, i32 %op, ptr %args, i64 %count) \
             {DEFINITION_ATTRIBUTES} {{"
        );
        out.push_str("entry:\n");
        // Окружающая ветки есть окружающая применения хендлера (§3.4), и взять
        // её неоткуда, кроме кадра: вектор места `handle` лежит в нём.
        let _ = writeln!(out, "  %ev = call ptr @adamas_frame_evidence(ptr %h)");
        if env > 0 {
            let _ = writeln!(out, "  %env = call ptr @adamas_frame_env(ptr %h)");
        }
        let mut cases = Vec::new();
        let mut blocks = String::new();
        for (slot, branch) in described.branches.iter().enumerate() {
            let title = label
                .operations
                .get(slot)
                .map_or_else(|| format!("#{slot}"), Clone::clone);
            cases.push(format!("i32 {slot}, label %op{slot}"));
            dispatch_arm(
                &mut blocks,
                &format!("op{slot}"),
                &title,
                env,
                branch.function,
                branch.written,
                branch.verdict,
                described.multi,
            );
        }
        // Ветка `return` не операция, и номера у неё нет: рантайм зовёт её
        // `ADAMAS_HANDLER_RETURN`. Резумпции у неё не бывает - вычисление
        // договорило, снимать нечего.
        cases.push("i32 -1, label %opret".to_owned());
        dispatch_arm(
            &mut blocks,
            "opret",
            "return",
            env,
            described.returned,
            1,
            Verdict::Tail,
            false,
        );
        let _ = writeln!(
            out,
            "  switch i32 %op, label %missing [ {} ]",
            cases.join(" ")
        );
        out.push_str(&blocks);
        out.push_str("\nmissing:\n");
        let _ = writeln!(out, "  call void @adamas_fail(ptr {BRANCH_MESSAGE})");
        out.push_str("  unreachable\n}\n\n");
        self.bodies.push_str(&out);

        if env == 0 {
            return;
        }
        let _ = writeln!(self.bodies, "; среда веток `{}`", label.name);
        let _ = writeln!(
            self.bodies,
            "define internal void @relh_{at}(ptr %h, ptr %kont) {DEFINITION_ATTRIBUTES} {{"
        );
        self.bodies.push_str("entry:\n");
        let _ = writeln!(self.bodies, "  %env = call ptr @adamas_frame_env(ptr %h)");
        for slot in 0..env {
            let _ = writeln!(
                self.bodies,
                "  %a{slot} = getelementptr i8, ptr %env, i64 {}",
                offset(slot)
            );
            let _ = writeln!(self.bodies, "  %s{slot} = load ptr, ptr %a{slot}");
            let _ = writeln!(
                self.bodies,
                "  call void @adamas_drop(ptr %s{slot}, ptr @{RELEASE_SYMBOL})"
            );
        }
        self.bodies.push_str("  ret void\n}\n\n");
    }

    /// Трамплин деструктора scope'а: слоты **забираются**, а не дублируются.
    ///
    /// Зовут такое замыкание ровно раз и тут же дропают - кадр `CLOSING` его
    /// единственный владелец (`adamas.h`). Дублируй слоты, как общий трамплин, -
    /// и ресурс достался бы деструктору разделённым: FBIP внутри него не
    /// сработал бы никогда, а порядок деструкторов перестал бы быть наблюдаемым
    /// ценой. Слот после взятия зануляется единицей, поэтому дроп замыкания
    /// следом отдаёт уже ничего.
    fn taker(&mut self, function: &Function) {
        let env = function.live_captured().count();
        let _ = writeln!(self.bodies, "; `{}` кадром scope", function.name);
        let _ = writeln!(
            self.bodies,
            "define internal ptr @take_{}(ptr %self, ptr %ev, ptr %kont, ptr %arg) \
             {DEFINITION_ATTRIBUTES} {{",
            function.id.0
        );
        self.bodies.push_str("entry:\n");
        let mut given = match function.form {
            Form::Stack => Vec::new(),
            Form::Detached => vec!["ptr %ev".to_owned(), "ptr %kont".to_owned()],
        };
        for slot in 0..env {
            let _ = writeln!(
                self.bodies,
                "  %s{slot} = call ptr @adamas_closure_get(ptr %self, i64 {slot})"
            );
            let _ = writeln!(self.bodies, "  %u{slot} = call ptr @adamas_unit()");
            let _ = writeln!(
                self.bodies,
                "  call void @adamas_closure_set(ptr %self, i64 {slot}, ptr %u{slot})"
            );
            given.push(format!("ptr %s{slot}"));
        }
        given.push("ptr %arg".to_owned());
        let _ = writeln!(
            self.bodies,
            "  %answer = call {CONVENTION} ptr @fn_{}({})",
            function.id.0,
            given.join(", ")
        );
        self.bodies.push_str("  ret ptr %answer\n}\n\n");
    }

    /// Сборщик конструктора: замыкание копит аргументы, последний собирает
    /// объект.
    ///
    /// Тот же трамплин, что у функции значением ([`Self::boxer`]), и та же
    /// причина `adamas_dup` на слот: слоты принадлежат замыканию, а поле
    /// объекта берёт значение владением. Последний аргумент приходит владением
    /// уже от `adamas_apply` и дублирования не требует.
    ///
    /// Скрытые аргументы трамплин берёт и не смотрит: сборка объекта не
    /// приостанавливается ничем.
    ///
    /// Поля здесь **только указательные**: плоское и стёртое отвергает
    /// [`Builder::building`] до того, как сюда дойдёт.
    fn maker(&mut self, constructor: &Constructor) {
        let arity = constructor.binders.len();
        let slots = constructor.slots();
        let _ = writeln!(
            self.bodies,
            "; `{}` значением: слоты копят аргументы, последний собирает объект",
            constructor.name
        );
        let _ = writeln!(
            self.bodies,
            "define internal ptr @make_{}(ptr %self, ptr %ev, ptr %kont, ptr %arg) \
             {DEFINITION_ATTRIBUTES} {{",
            constructor.tag.0
        );
        self.bodies.push_str("entry:\n");
        if arity == 0 {
            let _ = writeln!(
                self.bodies,
                "  call void @adamas_fail(ptr {ARITYLESS_MESSAGE})"
            );
            self.bodies.push_str("  unreachable\n}\n\n");
            return;
        }
        let _ = writeln!(
            self.bodies,
            "  %value = call ptr @adamas_alloc(i16 {}, i64 {slots})",
            constructor.tag.0
        );
        let mut slot = 0u32;
        for (position, fact) in constructor.binders.iter().enumerate() {
            if !fact.present {
                continue;
            }
            // Номер слота замыкания - номер **связывания** ядра, а не слота
            // объекта: применение позиционно и о стёртых полях не знает.
            let taken = if position + 1 == arity {
                "%arg".to_owned()
            } else {
                let _ = writeln!(
                    self.bodies,
                    "  %s{position} = call ptr @adamas_closure_get(ptr %self, i64 {position})"
                );
                let _ = writeln!(
                    self.bodies,
                    "  %d{position} = call ptr @adamas_dup(ptr %s{position})"
                );
                format!("%d{position}")
            };
            let _ = writeln!(
                self.bodies,
                "  %p{slot} = getelementptr i8, ptr %value, i64 {}",
                HEADER_BYTES + slot * SLOT_BYTES
            );
            let _ = writeln!(self.bodies, "  store ptr {taken}, ptr %p{slot}");
            slot += 1;
        }
        self.bodies.push_str("  ret ptr %value\n}\n\n");
    }

    /// Общий трамплин: замыкание отдаёт слоты позиционно, функция берёт их
    /// аргументами.
    ///
    /// Слоты принадлежат замыканию, а функция берёт аргументы **владением**,
    /// отсюда `adamas_dup` на каждый: своё замыкание дропает применение
    /// ([`crate::perceus`]), и без дублирования оно унесло бы слоты с собой.
    /// Последний аргумент приходит владением уже от `adamas_apply`.
    ///
    /// Скрытые аргументы у самого трамплина есть всегда - граница замыкания
    /// динамическая, - а дальше он передаёт их ровно второй форме. Первой они не
    /// передаются вовсе: у неё их нет в сигнатуре.
    fn boxer(&mut self, function: &Function) {
        let env = function.live_captured().count();
        let arity = function.parameters.len();
        let _ = writeln!(
            self.bodies,
            "; `{}` значением: слоты - среда, затем накопленные аргументы",
            function.name
        );
        let _ = writeln!(
            self.bodies,
            "define internal ptr @box_{}(ptr %self, ptr %ev, ptr %kont, ptr %arg) \
             {DEFINITION_ATTRIBUTES} {{",
            function.id.0
        );
        self.bodies.push_str("entry:\n");
        if arity == 0 {
            let _ = writeln!(
                self.bodies,
                "  call void @adamas_fail(ptr {ARITYLESS_MESSAGE})"
            );
            self.bodies.push_str("  unreachable\n}\n\n");
            return;
        }
        let mut given = match function.form {
            Form::Stack => Vec::new(),
            Form::Detached => vec!["ptr %ev".to_owned(), "ptr %kont".to_owned()],
        };
        // Слотов ровно столько, сколько связываний у ядра, - стёртые в том
        // числе. Стёртый слот в вызов не идёт: понижение кладёт туда
        // `ADAMAS_ERASED`, значение непосредственное, ячейки за ним нет.
        let mut slots: Vec<usize> = (0..env).collect();
        for (position, parameter) in function.parameters.iter().enumerate() {
            if !parameter.fact.present || position + 1 == arity {
                continue;
            }
            slots.push(env + position);
        }
        for slot in &slots {
            let _ = writeln!(
                self.bodies,
                "  %s{slot} = call ptr @adamas_closure_get(ptr %self, i64 {slot})"
            );
            let _ = writeln!(
                self.bodies,
                "  %d{slot} = call ptr @adamas_dup(ptr %s{slot})"
            );
        }
        given.extend(slots.iter().map(|slot| format!("ptr %d{slot}")));
        if function
            .parameters
            .last()
            .is_some_and(|parameter| parameter.fact.present)
        {
            given.push("ptr %arg".to_owned());
        }
        let _ = writeln!(
            self.bodies,
            "  %answer = call {CONVENTION} ptr @fn_{}({})",
            function.id.0,
            given.join(", ")
        );
        self.bodies.push_str("  ret ptr %answer\n}\n\n");
    }

    /// Складывает модуль: шапка, объявления, константы, тела, метаданные.
    fn finish(self, program: &Program, answer: Answer) -> String {
        let mut out = String::new();
        out.push_str(concat!(
            "; Порождено понижением Adamas. Править нечего: правится тот, кто\n",
            "; породил. Договор с рантаймом - `adamas.h`.\n",
            ";\n",
            "; Подмножество IR консервативное (`emit_llvm.rs`): ни `nsw`/`nuw` у\n",
            "; арифметики, ни `inbounds`/`nuw` у `getelementptr`, ни строк цели -\n",
            "; её берёт `llc` у хоста. Проверяется прогоном на минимальной\n",
            "; версии, а не грепом.\n",
            "\n",
            "; Рантайм: те же точки входа, что зовёт C-бэкенд. Куча целиком за\n",
            "; ним; слот объекта читает и пишет сам IR (`emit_llvm.rs`).\n",
            "declare ptr @adamas_con0(i16)\n",
            "declare ptr @adamas_alloc(i16, i64)\n",
            "declare ptr @adamas_reuse(ptr, i16, i64)\n",
            "declare void @adamas_free(ptr)\n",
            "declare i16 @adamas_tag(ptr)\n",
            "declare i32 @adamas_is_unique(ptr)\n",
            "declare ptr @adamas_dup(ptr)\n",
            "declare void @adamas_drop(ptr, ptr)\n",
            "declare ptr @adamas_drop_reuse(ptr, ptr)\n",
            "declare void @adamas_fail(ptr) noreturn\n",
        ));
        // Дроп детей живёт в спутнике: таблица конструкторов, по которой он
        // идёт, - та же, по которой печатается ответ.
        let _ = writeln!(out, "declare void @{RELEASE_SYMBOL}(ptr)\n");

        second_form(&mut out, program);
        arrays(&mut out, program);

        if self.dwarf.is_some() {
            out.push_str(concat!(
                "; Отладочная информация. Вызов интринсика, а не запись\n",
                "; `#dbg_declare`: записи не читает восемнадцатая версия, а\n",
                "; вызов читают обе.\n",
                "declare void @llvm.dbg.declare(metadata, metadata, metadata)\n",
                "\n",
            ));
        }
        for (name, text) in [
            (TAG_MESSAGE, TAG_TEXT),
            (BRANCH_MESSAGE, BRANCH_TEXT),
            (MISSING_MESSAGE, MISSING_TEXT),
            (LANE_MESSAGE, LANE_TEXT),
            (SHAPELESS_MESSAGE, SHAPELESS_TEXT),
            (ARITYLESS_MESSAGE, ARITYLESS_TEXT),
        ] {
            let _ = writeln!(
                out,
                "{name} = private unnamed_addr constant [{} x i8] c\"{}\"",
                terminated(text).len(),
                escaped(&terminated(text))
            );
        }
        out.push('\n');

        out.push_str(&self.bodies);
        entry_point(&mut out, program, answer);

        if !self.metadata.nodes.is_empty() {
            out.push('\n');
            self.metadata.print(&mut out);
        }
        out
    }
}

/// Объявления второй формы понижения и дроп среды кадра scope.
///
/// Отдельно от [`Module::finish`], потому что оба куска условны: точек входа
/// рантайма под кадры не объявляется вовсе там, где второй формы в программе
/// нет, и выход тогда байт в байт тот же, что был до трека G.
///
/// Модель повторена за C-бэкендом дословно - те же точки входа, тот же кадр в
/// куче, тот же сегмент, - и это решение, а не умолчание: см. раздел «Кадр
/// берёт рантайм, а не `llvm.coro.*`» в шапке модуля.
fn second_form(out: &mut String, program: &Program) {
    let nursery = nursed(program);
    let framed = nursery
        || program
            .functions
            .iter()
            .any(|function| function.form == Form::Detached);
    // Замыкание бывает и без второй формы: `module-family` строит значение
    // первой формы и ни одного кадра не отчуждает. Объявления поэтому свои.
    if framed
        || !boxing(program).is_empty()
        || !taking(program).is_empty()
        || !builders(program).is_empty()
    {
        out.push_str(concat!(
            "; Замыкание: объект с кодом и средой, применение через рантайм.\n",
            "declare ptr @adamas_unit()\n",
            "declare ptr @adamas_closure(ptr, ptr, i32, i32)\n",
            "declare void @adamas_closure_set(ptr, i64, ptr)\n",
            "declare ptr @adamas_closure_get(ptr, i64)\n",
            "declare ptr @adamas_apply(ptr, ptr, ptr, ptr)\n",
            "\n",
        ));
        // Применение в чистом отрезке заводит **свой** корень трамплина
        // ([`Builder::applied`]), и обе точки входа под него лежат в блоке
        // второй формы. Нет его - объявить их надо здесь: замыкание бывает и
        // без второй формы, а докрутить трамплин всё равно обязан кто-то.
        if !framed {
            out.push_str(concat!(
                "; Корень трамплина у применения в чистом отрезке.\n",
                "declare void @adamas_kont_init(ptr)\n",
                "declare ptr @adamas_kont_run(ptr, ptr)\n",
                "\n",
            ));
        }
    }
    if framed {
        out.push_str(concat!(
            "; Вторая форма понижения: кадр в куче, вектор evidence, сегмент.\n",
            "declare i32 @adamas_is_imm(ptr)\n",
            "declare ptr @adamas_evidence_empty()\n",
            "declare ptr @adamas_evidence_extend(ptr, i32, ptr)\n",
            "declare ptr @adamas_evidence_mask(ptr, i32)\n",
            "declare i32 @adamas_evidence_lookup(ptr, i32, ptr)\n",
            "declare void @adamas_evidence_drop(ptr)\n",
            "declare void @adamas_kont_init(ptr)\n",
            "declare ptr @adamas_kont_push(ptr, i16, i32, ptr, ptr, i64, i64, ptr)\n",
            "declare ptr @adamas_kont_handler(ptr, i32, ptr, ptr, i64, ptr)\n",
            "declare ptr @adamas_kont_closing(ptr, ptr, ptr, ptr)\n",
            "declare ptr @adamas_kont_run(ptr, ptr)\n",
            "declare ptr @adamas_kont_abort(ptr)\n",
            "declare ptr @adamas_kont_cut(ptr, ptr)\n",
            "declare void @adamas_kont_resume(ptr, ptr)\n",
            "declare ptr @adamas_frame_env(ptr)\n",
            "declare ptr @adamas_frame_evidence(ptr)\n",
            "declare ptr @adamas_frame_perform(ptr, ptr, i32, ptr, i64)\n",
            "declare void @adamas_segment_unwind(ptr, ptr)\n",
            "declare ptr @adamas_segment_value(ptr)\n",
            "declare ptr @adamas_segment_multi(ptr)\n",
            "declare void @adamas_resumption_drop(ptr, ptr)\n",
            "\n",
        ));
    }
    if nursery {
        out.push_str(concat!(
            "; Питомник (§5.2): круг, его операции и отмена. Точки входа те же,\n",
            "; что зовёт C-бэкенд, - новых под LLVM не заведено ни одной.\n",
            "declare i32 @adamas_nursery_serves(ptr, i32)\n",
            "declare ptr @adamas_nursery_begin(ptr, ptr, ptr, ptr)\n",
            "declare ptr @adamas_nursery_suspend(ptr, ptr)\n",
            "declare ptr @adamas_nursery_spawn(ptr, ptr, ptr, i32, i32, i32)\n",
            "declare ptr @adamas_nursery_await(ptr, ptr, ptr, i32)\n",
            "declare ptr @adamas_nursery_cancel(ptr, ptr, i32)\n",
            "\n",
        ));
    }
    if scoped(program) {
        out.push_str(concat!(
            "; Дроп среды кадра scope: деструктор замыканием в слоте 0 (§3.3).\n",
            "define internal void @release_closing(ptr %h, ptr %kont) nounwind {\n",
            "entry:\n",
            "  %env = call ptr @adamas_frame_env(ptr %h)\n",
            "  %closer = load ptr, ptr %env\n",
        ));
        let _ = writeln!(
            out,
            "  call void @adamas_drop(ptr %closer, ptr @{RELEASE_SYMBOL})"
        );
        out.push_str("  ret void\n}\n\n");
    }
}

/// Точка входа для спутника на C.
///
/// Соглашение здесь C - её зовёт спутник; порождённые между собой ходят по
/// [`CONVENTION`] (трек D), и вызов ниже это называет.
fn entry_point(out: &mut String, program: &Program, answer: Answer) {
    let _ = writeln!(out, "; Точка входа для спутника на C.");
    let _ = writeln!(
        out,
        "define {} @{ENTRY_SYMBOL}() {DEFINITION_ATTRIBUTES} {{",
        answer.machine()
    );
    out.push_str("entry:\n");
    let _ = writeln!(
        out,
        "  %answer = call {CONVENTION} {} @fn_{}()",
        answer.machine(),
        program.entry.0
    );
    let _ = writeln!(out, "  ret {} %answer", answer.machine());
    out.push_str("}\n");
}

/// Одна ветвь раздачи веток: аргументы ветке, а у нехвостовой - ещё и сегмент.
///
/// Имена регистров внутри ветви разведены её меткой: блоки лежат в одной
/// функции, и `%d0` двух ветвей были бы переопределением.
#[expect(
    clippy::too_many_arguments,
    reason = "ровно то, чем ветки различаются между собой: меньше не различает"
)]
fn dispatch_arm(
    out: &mut String,
    label: &str,
    title: &str,
    env: usize,
    function: FuncId,
    written: usize,
    verdict: Verdict,
    multi: bool,
) {
    let _ = writeln!(out, "\n{label}: ; {title}");
    // Лишние аргументы операции дропает раздача: сколько ветка связывает, знает
    // площадка, а место операции не знает. Цикл, а не разворот: `count`
    // приходит в рантайме.
    let _ = writeln!(out, "  br label %{label}.spare");
    let _ = writeln!(out, "\n{label}.spare:");
    let _ = writeln!(
        out,
        "  %{label}.at = phi i64 [ {written}, %{label} ], [ %{label}.next, %{label}.free ]"
    );
    let _ = writeln!(out, "  %{label}.more = icmp ult i64 %{label}.at, %count");
    let _ = writeln!(
        out,
        "  br i1 %{label}.more, label %{label}.free, label %{label}.run"
    );
    let _ = writeln!(out, "\n{label}.free:");
    let _ = writeln!(
        out,
        "  %{label}.slot = getelementptr ptr, ptr %args, i64 %{label}.at"
    );
    let _ = writeln!(out, "  %{label}.dead = load ptr, ptr %{label}.slot");
    let _ = writeln!(
        out,
        "  call void @adamas_drop(ptr %{label}.dead, ptr @{RELEASE_SYMBOL})"
    );
    let _ = writeln!(out, "  %{label}.next = add i64 %{label}.at, 1");
    let _ = writeln!(out, "  br label %{label}.spare");
    let _ = writeln!(out, "\n{label}.run:");

    // Скрытые аргументы у ветки есть всегда: зовут её через кадр, и производить
    // она вправе. Форма её - вторая по построению, и это проверено до печати
    // ([`boundaries`]), а не предположено здесь.
    let mut given = vec!["ptr %ev".to_owned(), "ptr %kont".to_owned()];
    for slot in 0..env {
        let _ = writeln!(
            out,
            "  %{label}.e{slot} = getelementptr i8, ptr %env, i64 {}",
            offset(slot)
        );
        let _ = writeln!(out, "  %{label}.v{slot} = load ptr, ptr %{label}.e{slot}");
        let _ = writeln!(
            out,
            "  %{label}.d{slot} = call ptr @adamas_dup(ptr %{label}.v{slot})"
        );
        given.push(format!("ptr %{label}.d{slot}"));
    }
    // Абортивная режет сегмент и кладёт его раскрутку кадром **до** ветки: кадр
    // раскрутки лежит ниже всего, что ветка положит, и деструкторы срабатывают
    // после её ответа. Перестань резать до ветки - и операция ветки нашла бы
    // собственный хендлер живым.
    if verdict == Verdict::Abortive {
        let _ = writeln!(
            out,
            "  %{label}.cut = call ptr @adamas_kont_cut(ptr %kont, ptr %h)"
        );
        let _ = writeln!(
            out,
            "  call void @adamas_segment_unwind(ptr %kont, ptr %{label}.cut)"
        );
    }
    for slot in 0..written {
        let _ = writeln!(
            out,
            "  %{label}.a{slot} = getelementptr ptr, ptr %args, i64 {slot}"
        );
        let _ = writeln!(out, "  %{label}.g{slot} = load ptr, ptr %{label}.a{slot}");
        given.push(format!("ptr %{label}.g{slot}"));
    }
    if verdict == Verdict::General {
        let _ = writeln!(
            out,
            "  %{label}.seg = call ptr @adamas_kont_cut(ptr %kont, ptr %h)"
        );
        let _ = writeln!(
            out,
            "  %{label}.val = call ptr @adamas_segment_value(ptr %{label}.seg)"
        );
        // Мультишотная ручка помечается **здесь**, на разрезе, и только здесь:
        // возобновление читает флаг и ставит копию, пока на ручку есть лишние
        // ссылки. Не пометь - второй ход получил бы потраченный сегмент.
        let seized = if multi {
            let _ = writeln!(
                out,
                "  %{label}.seized = call ptr @adamas_segment_multi(ptr %{label}.val)"
            );
            format!("%{label}.seized")
        } else {
            format!("%{label}.val")
        };
        given.push(format!("ptr {seized}"));
    }
    let _ = writeln!(
        out,
        "  %{label}.answer = call {CONVENTION} ptr @fn_{}({})",
        function.0,
        given.join(", ")
    );
    let _ = writeln!(out, "  ret ptr %{label}.answer");
}

