//! Элаборация: поверхностный язык в термы ядра (§9 Фаза 2).
//!
//! # Почему отдельный крейт
//!
//! §3 говорит прямо: **элаборация не входит в TCB** - она выдаёт обычный терм
//! ядра, и корректность его проверяет `check`. Отдельный крейт делает эту
//! границу структурной: что входит в доверенную базу, видно по `Cargo.toml`, а
//! не по комментарию. Побочно `adamas fmt` и LSP на неполном вводе тянут
//! только синтаксис.
//!
//! Слои: `adamas-core` (без зависимостей) ← `adamas-parser` (за `Span`) ←
//! `adamas-elab` (за обоими) ← `adamas-cli`. Решение записано в decision log
//! 2026-08-25; §8 называл местом элаборации ядро, но это стало невозможным,
//! как только парсер начал зависеть от ядра за позициями в исходнике.
//!
//! # Что элаборируется сегодня
//!
//! Монотипный фрагмент: индуктивные семейства без параметров (индексы можно),
//! определения клаузами, применение, лямбды, стрелки и зависимые функции,
//! `let` с аннотацией. Этого хватает, чтобы программа прошла путь целиком -
//! текст, дерево, термы ядра, проверка типов, - то есть чтобы milestone Фазы 2
//! стал наблюдаемым.
//!
//! Сверх ядра QTT - владение (§3.3): `unique data` и `resource` объявляют тип,
//! связывания которого линейны по построению ([`crate::own`]), а ресурс, о
//! котором тело забыло, закрывается вставленным `drop` ([`crate::live`] -
//! правило и его границы). Ядра это не касается вовсе, и так и задумано:
//! правило назначает связыванию кратность, которую программист мог бы написать
//! сам, и подставляет вызов, который он мог бы написать тоже.
//!
//! # Чего не хватает и почему
//!
//! Полиморфизма: `map : (a -> b) -> Vect n a -> Vect n b` требует подъёма
//! свободных имён в implicit-параметры (§4.1), а у `Pi` в ядре нет видимости и
//! метапеременных на термах - тоже. Это следующий срез **ядра**, не
//! элаборации. Всё остальное, чего недостаёт, перечислено в [`Missing`] вместе
//! с причиной: список - граница архитектуры, а не список недоделок.
//!
//! Элаборация **не типонаправленная**: она собирает терм по синтаксису и
//! отдаёт его `check`. Отсюда и берётся большая часть [`Missing`] - `if`,
//! `case` выражением, дырка `_`, `let` без аннотации нуждаются в ожидаемом
//! типе, которого элаборация не знает.

