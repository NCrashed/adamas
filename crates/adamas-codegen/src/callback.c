/* Таблица трамплинов уровня 3 (§5.3): колбэк, переживающий чужой вызов.
 *
 * Уровень 2 держит регистрацию ровно один чужой вызов: среда строится перед
 * узлом `Expr::Foreign` и дропается после него. `CURLOPT_WRITEFUNCTION`
 * ставится одним вызовом (`curl_easy_setopt`), а зовётся другим
 * (`curl_easy_perform`), и это уже уровень 3.
 *
 * Слот занимается `adamas_callback_register` и освобождается
 * `adamas_callback_release`; обёртка держит его полем `resource`, а деструктор
 * снимает регистрацию (§3.3). Слотов фиксированное число, и это не оговорка:
 * у машины трамплин есть порождённая на этапе сборки функция, породить их по
 * числу колбэков программы нечем, и §5.3 требует, чтобы предел был **виден в
 * API обёртки** - ответом, а не падением.
 *
 * Здесь, на пути понижения, таблица учётна, а не несуща: адрес экспорта есть
 * настоящий сишный символ, и пережил бы он что угодно и без слота. Стоит она
 * тут затем, чтобы предел у трёх вычислителей был **один**: молчаливо взяв
 * пятый колбэк, понижение разошлось бы с машиной на программе, которая её
 * таблицу исчерпала.
 *
 * Число слотов обязано совпадать с `adamas_interp::callback::SLOTS`: расходись
 * они, и пятая регистрация у одного была бы адресом, а у другого нулём.
 */
#define ADAMAS_CALLBACK_SLOTS 4

static uint64_t adamas_callback_table[ADAMAS_CALLBACK_SLOTS];

/* Занимает слот и отдаёт адрес колбэка. Ноль - слотов больше нет.
 *
 * Тот же адрес, зарегистрированный дважды, занимает два слота: считается
 * **регистрация**, а не функция, и снимает её `release` по одной за вызов.
 */
uint64_t adamas_callback_register(uint64_t code) {
    if (code == 0u) {
        return 0u;
    }
    for (int slot = 0; slot < ADAMAS_CALLBACK_SLOTS; slot++) {
        if (adamas_callback_table[slot] == 0u) {
            adamas_callback_table[slot] = code;
            return code;
        }
    }
    return 0u;
}

/* Освобождает слот. Ноль - снято; единица - такой регистрации нет.
 *
 * Ответ едет наружу числом, а не падением: снять незанятое есть ошибка
 * обёртки, и разбирает её обёртка.
 */
int32_t adamas_callback_release(uint64_t code) {
    for (int slot = 0; slot < ADAMAS_CALLBACK_SLOTS; slot++) {
        if (adamas_callback_table[slot] == code && code != 0u) {
            adamas_callback_table[slot] = 0u;
            return 0;
        }
    }
    return 1;
}
