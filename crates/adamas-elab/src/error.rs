//! Ошибка элаборации: что не сошлось и где.
//!
//! Спан здесь есть, в отличие от ошибок ядра: элаборация держит спан того, что
//! элаборирует. Ошибка ядра спана не несёт вовсе - она несёт маршрут, и в спан
//! его переводит [`crate::route`], проходя тот же маршрут по дереву (§10
//! вопрос 49б). Отсюда и правило для [`ElabError::Core`]: спан в нём - место
//! подтерма, а объявление целиком остаётся только там, куда маршрут не дошёл.

use adamas_core::check::TypeError;
use adamas_core::mult::Mult;
use adamas_core::pattern::PatternError;
use adamas_core::source::Span;
use adamas_parser::ast::Symbol;

use crate::own::Ownership;

/// Форма поверхностного языка, для которой в ядре ещё нет механизма.
///
/// Отдельный вариант, а не «неизвестное имя»: программа написана правильно, не
/// хватает ядра. Каждая форма названа вместе с тем, чего именно недостаёт, -
/// иначе сообщение отправляет искать опечатку там, где её нет.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Missing {
    /// Свободная переменная типа там, где подъёма нет: `let x : a = …`.
    FreeTypeVariable,
    /// Литерал: числовая иерархия идёт через классы (§4.3).
    Literal,
    /// `let` без аннотации типа.
    UntypedLet,
    /// Аннотация домена лямбды: `\(0 a : A) -> …`.
    LambdaAnnotation,
    /// Разбор в параметре лямбды: `\(Cons x xs) -> …`.
    LambdaPattern,
    /// Кортеж.
    Tuple,
    /// Единица `()`.
    Unit,
    /// Список `[…]`.
    List,
    /// Цепочка из нескольких операторов подряд.
    Fixities,
    /// Связывание `Pi` без написанного типа.
    TypelessBinder,
    /// Локальные определения `where` или `let` с аргументами.
    LocalDefinitions,
    /// Оператор блока, значение которого отбрасывается.
    Sequencing,
    /// Row без стрелки: `{State Int} Int`.
    Suspended,
    /// Написанный хвост row: `{IO | e}`.
    RowTail,
}

impl Missing {
    /// Что написано и чего для этого не хватает. Одна таблица: разъехаться
    /// описанию и причине негде.
    fn face(self) -> (&'static str, &'static str) {
        match self {
            Self::FreeTypeVariable => (
                "свободная переменная типа",
                "в implicit-параметр (§4.1) поднимается сигнатура объявления; \
                 здесь связать имя нечем",
            ),
            Self::Literal => (
                "числовой или строковый литерал",
                "литерал элаборируется в вызов `FromNat`/`FromInt`/`FromFloat` \
                 (§4.3), а классы появляются в Фазе 3",
            ),
            Self::UntypedLet => (
                "`let` без аннотации типа",
                "тип связывания решает и владение (§3.3): без написанного типа \
                 ресурс не узнаётся, и `drop` молча не вставится - §10 вопрос 76",
            ),
            Self::LambdaAnnotation => (
                "аннотация домена лямбды",
                "лямбда в ядре домена не хранит - его берут из ожидаемого типа, \
                 и сверить с ним аннотацию элаборации нечем",
            ),
            Self::LambdaPattern => (
                "разбор в параметре лямбды",
                "лямбда домена не хранит, а разбору нужен тип разбираемого; \
                 то же пишется через `case` в теле",
            ),
            Self::Tuple => ("кортеж", "зависимых пар в ядре нет"),
            Self::Unit => ("единица `()`", "она появляется вместе с prelude"),
            Self::List => ("список", "`List` появляется вместе с prelude"),
            Self::Fixities => (
                "цепочка из нескольких операторов",
                "скобки расставляются по фикситетам, а `infixl` объявляется в \
                 prelude (§4.4)",
            ),
            Self::TypelessBinder => (
                "связывание без написанного типа",
                "тип связывания `Pi` выводить не из чего: без параметра \
                 семейства слева от `:` такая форма не пишется",
            ),
            Self::LocalDefinitions => (
                "локальное определение",
                "у ядра единица объявления верхнеуровневая, и `where` с \
                 `let f x = …` - отдельная работа",
            ),
            Self::RowTail => (
                "хвост row",
                "переменная хвоста приходит вместе с auto-lift (§3.4): связать \
                 написанное имя сегодня нечем",
            ),
            Self::Suspended => (
                "row без стрелки",
                "`{ε} A` есть нульместная функция `(ω _ : ()) -> ε ▷ A` (§3.4), \
                 а единица приходит вместе с prelude (§4.4)",
            ),
            Self::Sequencing => (
                "оператор, значение которого отбрасывается",
                "последовательность имеет смысл только с эффектами (§3.4), а до \
                 них значение оператора некуда деть",
            ),
        }
    }
}

impl std::fmt::Display for Missing {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let (what, why) = self.face();
        write!(f, "{what} пока не элаборируется: {why}")
    }
}

/// Ошибка элаборации.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum ElabError {
    /// Имя не найдено ни среди связываний, ни в сигнатуре.
    #[error("имя `{name}` не найдено")]
    UnknownName {
        /// Имя.
        name: Symbol,
        /// Где написано.
        span: Span,
    },

    /// Имя с заглавной буквы в позиции паттерна не оказалось конструктором.
    ///
    /// Правило и его цена - у [`crate::is_reference`].
    #[error("`{name}` не конструктор: в паттерне заглавное имя разбирает, строчное связывает")]
    NotAConstructor {
        /// Имя.
        name: Symbol,
        /// Где написано.
        span: Span,
    },

    /// Имя с заглавной буквы в позиции связывания.
    ///
    /// Обратная сторона [`ElabError::NotAConstructor`]: связать заглавным
    /// именем значит заслонить то, на что оно ссылается.
    #[error("`{name}` не связывает: заглавное имя ссылается на объявленное, строчное связывает")]
    UppercaseBinding {
        /// Имя.
        name: Symbol,
        /// Где написано.
        span: Span,
    },

    /// Одно имя связано клаузой дважды.
    #[error("`{name}` в клаузе дважды: равенство аргументов паттерном не выражается")]
    RepeatedBinding {
        /// Имя.
        name: Symbol,
        /// Второе вхождение - то, которое заслоняло первое.
        span: Span,
        /// Первое вхождение.
        first: Span,
    },

    /// Владеемый тип подставлен в параметр, который его не сбережёт.
    ///
    /// §3.3 обещает, что `drop` вызовется на выходе из scope. Под переменной
    /// типа это обещание держать нечем: правило смотрит на голову написанного.
    /// Ядро поэтому считает кратность носителя - как определение обошлось со
    /// значениями своего параметра, - и владеемый тип принимает только `1`:
    /// ровно один раз, то есть ни забыто, ни размножено (§10 вопрос 76).
    #[error(
        "`{owned}` не подставляется в параметр `{parameter}` определения `{callee}`: \
         значение этого типа употребляется там {carrier} раз, а владение требует ровно одного"
    )]
    OwnedCarrier {
        /// Чей параметр инстанцируют.
        callee: Symbol,
        /// Имя параметра.
        parameter: Symbol,
        /// Владеемый тип, которым его инстанцировали.
        owned: Symbol,
        /// Кратность носителя - то, что определение с ним делает.
        carrier: Mult,
        /// Объявление, в котором это написано.
        span: Span,
    },

    /// Семейство без деструктора наполнено владеемым типом.
    ///
    /// §3.3: поле ресурсного типа требует, чтобы держатель сам был `resource`
    /// (вопрос 77). Правило читало объявленный тип поля, а `Cons : a -> …`
    /// головы не имеет; инстанциация `a := File` его и обходила. Проверка
    /// поэтому стоит там, где параметр получает значение.
    #[error("`{family}` не `resource` и не может держать `{owned}`: закрыть его будет некому")]
    OwnedHolder {
        /// Семейство, чей параметр инстанцируют.
        family: Symbol,
        /// Владеемый тип, которым его инстанцировали.
        owned: Symbol,
        /// Объявление, в котором это написано.
        span: Span,
    },

    /// `@`-аргумент, которому нечего заполнять.
    ///
    /// `@` пишет то, что иначе выводилось бы, поэтому связывание, которое он
    /// заполняет, обязано быть выводимым. Написанный `@` при явном связывании -
    /// не «лишний аргумент»: аргумент как раз на месте, ошибка в том, что его
    /// пишут через `@` вместо обычного применения.
    #[error("выводимого параметра здесь нет: `@` пишет то, что иначе вывелось бы")]
    NoImplicitParameter {
        /// Написанный `@`-аргумент.
        span: Span,
    },

    /// `case` без веток.
    ///
    /// Разбор без единой ветви типизировался бы только над пустым типом, а
    /// написать это иначе - `case e of` с пустым блоком - layout не даёт: блок
    /// без операторов не разбирается. Отказ поэтому про форму, а не про тип.
    #[error("`case` без веток: разбирать нечего")]
    EmptyCase {
        /// Где написан разбор.
        span: Span,
    },

    /// Обновляется не запись.
    #[error("обновлять можно только запись")]
    NotUpdatable {
        /// Где написано обновление.
        span: Span,
    },

    /// Атрибут, которого компилятор не проверяет.
    #[error("атрибут `@{name}` не проверяется: {why}")]
    Attribute {
        /// Имя атрибута.
        name: Symbol,
        /// Почему.
        why: &'static str,
        /// Где написан.
        span: Span,
    },

    /// `@total` при отрицательном вердикте.
    ///
    /// Вердикт ядро считает всегда (§4.7, лог 2026-08-24), а атрибут - это
    /// требование «ответ обязан быть да».
    #[error(
        "`{name}` объявлено `@total`, но вердикт отрицательный: рекурсия не структурна \
         либо вызвано нетотальное"
    )]
    NotTotal {
        /// Имя определения.
        name: Symbol,
        /// Где написан атрибут.
        span: Span,
    },

    /// Голова класса или инстанса написана не именем с аргументами.
    #[error("голова класса пишется именем с аргументами: `class Eqv a`, `instance Eqv Nat`")]
    ClassHead {
        /// Где написано.
        span: Span,
    },

    /// Инстанса для написанного типа нет.
    ///
    /// Поиск - управляющий поток (§10 вопрос 52): «не подошёл» там норма. Сюда
    /// приходит окончательный отказ, когда кандидатов не осталось вовсе.
    #[error("инстанс `{written}` не найден")]
    NoInstance {
        /// Класс с головами всех аргументов: `Conv Nat Bool`.
        written: Symbol,
        /// Где написано использование.
        span: Span,
    },

    /// Цепочка контекстов инстансов не кончилась в пределах глубины.
    ///
    /// Разрешение рекурсивно по построению: словарь контекста кандидата
    /// возвращается в ту же очередь (§3.5). Убывания цели никто не обещает -
    /// `instance {Eqv (Box a)} => Eqv (Box a)` законен по форме, - и без
    /// предела такая пара съедает память вместо отказа.
    #[error(
        "разрешение `{written}` не сошлось: предел вложенности контекстов инстансов ({limit}) \
         исчерпан, а цепочка целей не убывает"
    )]
    InstanceDepth {
        /// Класс с головами всех аргументов у цели, на которой предел исчерпан.
        written: Symbol,
        /// Сам предел - чтобы сообщение не требовало заглядывать в исходник.
        limit: u32,
        /// Где написано использование.
        span: Span,
    },

    /// Цель совпала по головам с инстансом, который объявляется прямо сейчас,
    /// но не по самому заголовку.
    ///
    /// Словарь объявляемого инстанса собирается записью из его членов и стоит
    /// ровно на его собственных параметрах: `Eqv (List a)` внутри
    /// `instance {Eqv a} => Eqv (List a)` - это он, а `Eqv (List Nat)` - уже
    /// применение того же инстанса к другому аргументу, и собрать его нечем -
    /// имени у инстанса до конца объявления нет. До этого отказа такая цель
    /// молча получала словарь с непривязанным параметром: ядро на нём даёт
    /// `Mismatch`, а элаборация принимала.
    #[error(
        "инстанс `{written}` объявляется прямо сейчас, и словарь для него собирается только на \
         собственных параметрах: цель другой формы разрядить нечем"
    )]
    DeclaringInstance {
        /// Класс с головами всех аргументов.
        written: Symbol,
        /// Где написано использование.
        span: Span,
    },

    /// Голова аргумента - синоним, отдающий свой параметр.
    ///
    /// Кандидат ищется по паре «класс, головы аргументов», и головы обязаны
    /// быть одни у всех написаний одного типа - иначе на тип объявляются два
    /// инстанса, и какой возьмётся, решает написание цели. У `type Id (a :
    /// Type) = a` головы нет вовсе: `Id Nat` есть `Nat`, а символ `Id` был бы
    /// вторым ключом на тот же тип - `coherent` обещает обратное.
    #[error(
        "голова аргумента `{class}` - синоним, отдающий свой параметр: ключа у неё нет, \
         напишите тип, который он называет"
    )]
    ProjectingHead {
        /// Класс цели.
        class: Symbol,
        /// Где написано.
        span: Span,
    },

    /// Именованных инстансов на пару «класс, голова» несколько.
    #[error(
        "инстансов `{written}` несколько ({}); выберите один через `using`",
        candidates.iter().map(|it| format!("`{it}`")).collect::<Vec<_>>().join(", ")
    )]
    AmbiguousInstance {
        /// Класс с головами всех аргументов: `Conv Nat Bool`.
        written: Symbol,
        /// Имена кандидатов в порядке объявления.
        candidates: Vec<Symbol>,
        /// Где написано использование.
        span: Span,
    },

    /// Умолчание написано не у хвостового параметра (§4.1, правило 2).
    ///
    /// Иначе понадобился бы позиционный пропуск (`Mul _ Int`), то есть вторая
    /// нотация ради редкого случая.
    #[error(
        "у параметра `{name}` умолчания нет, а у предыдущего есть: умолчания бывают только у хвостовых"
    )]
    TrailingDefault {
        /// Параметр без умолчания.
        name: Symbol,
        /// Где написан.
        span: Span,
    },

    /// Метка row не оканчивается сортом `Effect` (§3.4).
    #[error("`{name}` не метка эффекта: метка обязана оканчиваться сортом `Effect`")]
    NotAnEffect {
        /// Написанное имя.
        name: Symbol,
        /// Где написано.
        span: Span,
    },

    /// Констрейнт на параметре запечатанного типа (§3.5).

    ///
    /// Инстанс, участвовавший в построении значения абстрактного типа,
    /// переживает вызов, а тип значения о нём молчит: `Map Int String`,
    /// собранная под одним `Ord Int` и опрошенная под другим, типизируется
    /// обеими сторонами и возвращает `None` на присутствующем ключе.
    #[error(
        "сигнатурой `{signature}` запечатывать нельзя: `{member}` несёт `{class} {param}`, \
         а `{param}` - параметр запечатанного `{sealed}`; вынесите констрейнт в параметр \
         модуля либо объявите `{class}` `coherent`"
    )]
    SealedConstraint {
        /// Имя сигнатуры.
        signature: Symbol,
        /// Член, где написан констрейнт.
        member: Symbol,
        /// Класс констрейнта.
        class: Symbol,
        /// Переменная, на которую он написан.
        param: Symbol,
        /// Запечатываемый тип, чьим аргументом она стоит.
        sealed: Symbol,
        /// Где написано запечатывание.
        span: Span,
    },

    /// Контекст инстанса, констрейнт которого стоит на параметре
    /// запечатанного типа (§3.5).
    ///
    /// Та же форма, что запрещена операции сигнатуры, только написанная в
    /// обход сигнатур: словарь осаждается в значении, чей тип о нём молчит.
    #[error(
        "контекст инстанса несёт `{class} {param}`, а `{param}` - параметр \
         запечатанного `{sealed}`; вынесите констрейнт в параметр модуля либо \
         объявите `{class}` `coherent`"
    )]
    SealedInstance {
        /// Класс констрейнта.
        class: Symbol,
        /// Переменная, на которую он написан.
        param: Symbol,
        /// Запечатанный тип, чьим аргументом она стоит.
        sealed: Symbol,
        /// Где написан инстанс.
        span: Span,
    },

    /// Второй инстанс когерентного класса (§3.5, пункт 3).

    ///
    /// Маркер обещает не более одного инстанса на программу; обещание
    /// проверяется на объявлении второго, потому что первое ни о чём не
    /// говорит.
    #[error("инстанс `{written}` уже объявлен, а `{class}` объявлен `coherent`")]
    CoherentDuplicate {
        /// Имя класса.
        class: Symbol,
        /// Класс с головами аргументов: `Key Nat`.
        written: Symbol,
        /// Где написан второй.
        span: Span,
    },

    /// Контекст инстанса когерентного класса несёт некогерентный (§3.5, пункт 1).
    ///
    /// Инстанс с контекстом - семейство словарей, а не словарь: аргумент
    /// контекста резолвится в точке употребления. Уникальность декларации при
    /// этом ничего не говорит о значении, ради которого маркер и заводился.
    #[error("контекст инстанса `{class}` несёт `{context}`, а он `coherent` не объявлен")]
    CoherentContext {
        /// Имя когерентного класса.
        class: Symbol,
        /// Класс из контекста, которому маркера не поставили.
        context: Symbol,
        /// Где написан инстанс.
        span: Span,
    },

    /// `type T` без уравнения вне сигнатуры модуля.
    ///
    /// Абстрактный типовой член объявляет сигнатура (§4.8); снаружи неё тип
    /// брать неоткуда, а постулировать имя можно обычной сигнатурой.
    #[error(
        "`type {name}` без уравнения объявляет член сигнатуры модуля; здесь тип брать неоткуда"
    )]
    AbstractType {
        /// Имя.
        name: Symbol,
        /// Где написано.
        span: Span,
    },

    /// Объявление, которому не место в теле модуля или его сигнатуры.
    #[error("`{name}` в {what} не объявляется: {why}")]
    ModuleMember {
        /// Имя члена.
        name: Symbol,
        /// Куда написано: «модуле» либо «сигнатуре модуля».
        what: &'static str,
        /// Чего именно не бывает.
        why: &'static str,
        /// Где написано.
        span: Span,
    },

    /// Разбираемое, тип которого не синтезируется.
    #[error("тип разбираемого не выводится: укажите его")]
    NotMatchable {
        /// Где написан разбор.
        span: Span,
    },

    /// Блок кончается связыванием, а не значением.
    #[error("блок кончается связыванием: значения у него нет")]
    BlockWithoutValue {
        /// Последний оператор блока.
        span: Span,
    },

    /// Связывание типа с владением объявлено `ω`.
    ///
    /// Уникальность держится тем, что ω-связывания такого типа не существует
    /// (§3.3): кратность `1` ограничивает потребление, а не производство, и
    /// отсутствие ω-связывания - единственное, что закрывает дыру ω→1. Отказ
    /// поэтому стоит на самом связывании, а не там, куда значение уехало.
    #[error("связывание {owned}-типа не может быть ω: значений такого типа при ω не существует")]
    UnrestrictedOwned {
        /// Чем объявлен тип.
        owned: Ownership,
        /// Написанная кратность.
        span: Span,
    },

    /// Объявление верхнего уровня типа с владением.
    ///
    /// Определение и постулат всегда `ω` - линейность на всю программу не
    /// считается (`sig::LinearDefinition`), - а §3.3 требует владеемому
    /// связыванию `1`. Держать ресурс верхним уровнем поэтому нечем: имя
    /// осталось бы обычным ω-именем, по которому `drop` зовётся сколько
    /// угодно раз.
    #[error(
        "`{name}` объявлен типом с владением ({owned}): держать его может только связывание кратности 1"
    )]
    OwnedTopLevel {
        /// Чем объявлен тип.
        owned: Ownership,
        /// Имя объявления.
        name: Symbol,
        /// Написанный тип.
        span: Span,
    },

    /// В теле `resource` нет определения - то есть нет деструктора.
    #[error("у ресурсного типа `{name}` нет деструктора: определение в теле обязательно (§3.3)")]
    ResourceWithoutDrop {
        /// Имя типа.
        name: Symbol,
        /// Объявление целиком.
        span: Span,
    },

    /// Деструктор не той формы.
    ///
    /// Он берёт свой ресурс и отдаёт что-то, от него не зависящее: вызов
    /// подставляет компилятор, и тип результата пишется рядом с вызовом - там,
    /// где ресурса уже нет.
    #[error(
        "деструктор `{name}` обязан брать один `{data}` кратности 1 и отдавать тип, от него не зависящий и сам не владеемый"
    )]
    DestructorShape {
        /// Имя типа.
        data: Symbol,
        /// Имя деструктора.
        name: Symbol,
        /// Написанный тип деструктора.
        span: Span,
    },

    /// Значение, привязанное к scope, стоит там, откуда оно уедет.
    ///
    /// §3.3: замыкание над владеющим связыванием применяется и передаётся
    /// аргументом, но не возвращается и не кладётся в поле конструктора -
    /// иначе вызывающий получает ω-значение, каждое применение которого
    /// расходует один и тот же ресурс. Свойство распространяется: связывание
    /// от такого замыкания привязано к scope само, и `1`-параметр
    /// функционального типа привязан внутри вызываемой функции. Ядро этого не
    /// видит - одноразовость применения в типе стрелки не записана.
    #[error(
        "`{name}` привязано к своему scope и {face}: захватившее владение замыкание можно применить или передать аргументом, но не вынести наружу"
    )]
    ScopeBound {
        /// Имя, которым значение привязано к scope.
        name: Symbol,
        /// Позиция, в которой оно оказалось.
        face: &'static str,
        /// Написанное выражение.
        span: Span,
    },

    /// Замыкание над владеющим связыванием стоит там, откуда оно уедет.
    ///
    /// Правило §3.3 - scope-bound: захватившая лямбда **может применяться и
    /// передаваться аргументом**, но не может оказаться в позиции
    /// возвращаемого значения. Вернув её, вызывающий получает ω-значение,
    /// каждый вызов которого расходует один и тот же ресурс, - а ядро этого не
    /// поймает, потому что одноразовость применения в типе стрелки не
    /// записана.
    ///
    /// Аргументную позицию ядро закрывает само: замыкание, переданное в
    /// ω-параметр, расходует захваченное ω раз, и `UsageViolation` приходит на
    /// самом связывании. Поэтому здесь остаётся только побег.
    /// Поле с владением у типа, который такого владения не несёт.
    ///
    /// Две половины одного правила. **Владеемое поле у обычного `data`**:
    /// разбор такого значения идёт при `r = ω`, и поле кратности `1` приходит
    /// в ветвь как `ω`, то есть выходит из-под владения и закрывается сколько
    /// угодно раз. **Ресурсное поле у `unique data`**: уничтожение значения
    /// влечёт уничтожение полей (§3.3), а у `unique` деструктора нет, и
    /// забытая обёртка не закрывает ничего.
    #[error(
        "`{constructor}` берёт поле типа `{field}` ({owned}), поэтому `{data}` обязан быть объявлен `{} {data}`",
        needed.keyword()
    )]
    OwnedField {
        /// Имя объявляемого типа.
        data: Symbol,
        /// Конструктор с этим полем.
        constructor: Symbol,
        /// Тип поля.
        field: Symbol,
        /// Чем объявлен тип поля.
        owned: Ownership,
        /// Чем обязан быть объявлен тип, который его держит.
        needed: Ownership,
        /// Написанный тип конструктора.
        span: Span,
    },

    /// Поле записи с владением.
    ///
    /// То же правило, что у конструктора, но у записи оно не имеет исключений:
    /// держателем владеемого поля обязан быть владеемый тип (§3.3, §10 вопрос
    /// 77), а запись владения не несёт и нести не может - объявляется она
    /// `type`, деструктора у неё нет, а связывание её `ω`. Значит поле
    /// проецируется сколько угодно раз, и ресурс закрывается дважды; забытая
    /// же запись не закрывает его ни разу.
    #[error(
        "поле `{field}` записи держит `{ty}` ({owned}), а запись владения не несёт: \
         владеемое поле требует владеемого держателя"
    )]
    OwnedRecordField {
        /// Имя поля.
        field: Symbol,
        /// Тип поля.
        ty: Symbol,
        /// Чем объявлен тип поля.
        owned: Ownership,
        /// Написанный тип поля.
        span: Span,
    },

    /// Деструктор объявлен сигнатурой, но без клауз.
    ///
    /// Жанр члена читается формой записи: голая сигнатура - конструктор, а
    /// конструктор пишется заглавной (§4.1). Строчное имя без клауз - это
    /// деструктор, у которого забыли тело, и сказать надо об этом: иначе отказ
    /// придёт про отсутствующий деструктор, то есть укажет не на ту строку.
    #[error(
        "`{name}` в теле `{data}` объявлен без тела: голая сигнатура - конструктор, а он пишется заглавной"
    )]
    DestructorWithoutBody {
        /// Имя типа.
        data: Symbol,
        /// Имя, оставшееся без клауз.
        name: Symbol,
        /// Сигнатура без клауз.
        span: Span,
    },

    /// Два ресурсных типа с деструкторами под одним именем.
    ///
    /// Имя деструктора свободно, но пространство имён плоское (§4.8, Фаза 3),
    /// поэтому одно имя на два ресурса не делится. Названо здесь, а не в
    /// `DuplicateDefinition` ядра: то говорит о столкновении имён, не называя
    /// причины.
    #[error(
        "`{name}` уже деструктор `{first}`: пространство имён плоское, дайте деструктору `{data}` своё имя"
    )]
    SharedDestructor {
        /// Имя объявляемого типа.
        data: Symbol,
        /// Имя деструктора.
        name: Symbol,
        /// Ресурс, забравший имя первым.
        first: Symbol,
        /// Деструктор, которому имени не досталось.
        span: Span,
    },

    /// В теле `resource` определено что-то помимо `drop`.
    ///
    /// Тело держит конструкторы и деструктор; всё прочее определяется рядом,
    /// на верхнем уровне. Иначе пришлось бы отвечать, видно ли снаружи имя,
    /// определённое внутри, - то есть заводить пространства имён, а они §4.8 и
    /// Фаза 3.
    #[error("в теле `{data}` определяется только `drop`, а не `{name}`")]
    ResourceMember {
        /// Имя типа.
        data: Symbol,
        /// Имя лишнего определения.
        name: Symbol,
        /// Где написано.
        span: Span,
    },

    /// Клаузы без сигнатуры.
    ///
    /// Тип нужен раньше тела: по нему снимается телескоп аргументов, а из него
    /// - арность и типы колонок разбора.
    #[error("у `{name}` есть клаузы, но нет сигнатуры")]
    MissingSignature {
        /// Имя определения.
        name: Symbol,
        /// Первая клауза.
        span: Span,
    },

    /// Клаузы есть, сигнатура написана, но между ними чужое объявление.
    ///
    /// Примыкание - требование реализации, а не §4: сигнатура, за которой сразу
    /// не пошли клаузы, объявляется постулатом, и к их приходу имя уже занято.
    /// Снять его - это `mutual` (§4.8, Фаза 3): пока тела соседей проверяются
    /// по одному, определение обязано идти следом за своим типом.
    #[error("сигнатура `{name}` отделена от клауз: между ними другое объявление")]
    DetachedSignature {
        /// Имя определения.
        name: Symbol,
        /// Где написана сигнатура.
        signature: Span,
        /// Первая клауза.
        span: Span,
    },

    /// Форма, для которой в ядре ещё нет механизма.
    #[error("{what}")]
    Missing {
        /// Какая.
        what: Missing,
        /// Где написана.
        span: Span,
    },

    /// Отказ ядра: терм собран, но проверку не прошёл.
    #[error("{error}")]
    Core {
        /// Что сказало ядро.
        error: Box<TypeError>,
        /// Место подтерма, названного маршрутом; объявление целиком - там,
        /// куда маршрут не дошёл.
        span: Span,
        /// Имена, которых маршрут не несёт.
        names: Names,
    },

    /// Отказ сборки клауз в дерево разбора.
    #[error("{error}")]
    Clauses {
        /// Что сказала сборка.
        error: Box<PatternError>,
        /// Тип - в сигнатуре, где он написан; отказ с номером клаузы - на
        /// самой клаузе; всё прочее - объявление целиком.
        span: Span,
    },
}

/// Имена, которых маршрут ядра не несёт.
///
/// Кадр называет позицию номером - «член группы #0», «конструктор #1», -
/// и иначе не может: для ядра группа это список, а имя в ней - деталь
/// объявления, к проверке отношения не имеющая. Читателю же номер не говорит
/// ничего, тем более что группа сегодня всегда из одного члена (`mutual` -
/// Фаза 3). Имена есть у элаборации, и подставляет их печать
/// ([`crate::report`]).
///
/// Конструкторы лежат при своём члене, а не общим списком: маршрут называет их
/// номером **внутри** члена (`sig.rs`, фаза C), и с приходом `mutual` в группе
/// окажется больше одного семейства.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Names(Vec<(Symbol, Vec<Symbol>)>);

impl Names {
    /// Объявление из одного члена - то, чем сегодня является всякая группа.
    pub(crate) fn of(name: &Symbol, constructors: Vec<Symbol>) -> Self {
        Self(vec![(Symbol::clone(name), constructors)])
    }

    /// Имя члена группы по номеру из маршрута.
    pub(crate) fn member(&self, index: u32) -> Option<&Symbol> {
        self.0.get(index as usize).map(|(name, _)| name)
    }

    /// Имя конструктора по номеру внутри члена.
    pub(crate) fn constructor(&self, member: u32, index: u32) -> Option<&Symbol> {
        self.0.get(member as usize)?.1.get(index as usize)
    }
}

impl ElabError {
    /// Имена объявленного - для маршрута, который несёт только номера.
    pub(crate) fn names(&self) -> Option<&Names> {
        match self {
            Self::Core { names, .. } => Some(names),
            _ => None,
        }
    }

    /// Отказ ядра, если отказало именно оно.
    ///
    /// Нужен рендерингу: телескоп и маршрут ядро отдаёт значениями, а
    /// показывать их - работа снаружи (§10 вопрос 49а).
    #[must_use]
    pub fn core(&self) -> Option<&TypeError> {
        match self {
            Self::Core { error, .. } => Some(error),
            Self::Clauses { error, .. } => match &**error {
                PatternError::IllTypedType { error } => Some(error),
                _ => None,
            },
            _ => None,
        }
    }

    /// Где ошибка.
    #[must_use]
    pub fn span(&self) -> Span {
        match self {
            Self::UnknownName { span, .. }
            | Self::NotAConstructor { span, .. }
            | Self::UppercaseBinding { span, .. }
            | Self::RepeatedBinding { span, .. }
            | Self::OwnedCarrier { span, .. }
            | Self::OwnedHolder { span, .. }
            | Self::EmptyCase { span }
            | Self::NotMatchable { span }
            | Self::AbstractType { span, .. }
            | Self::NoInstance { span, .. }
            | Self::InstanceDepth { span, .. }
            | Self::DeclaringInstance { span, .. }
            | Self::ProjectingHead { span, .. }
            | Self::AmbiguousInstance { span, .. }
            | Self::CoherentDuplicate { span, .. }
            | Self::NotAnEffect { span, .. }
            | Self::TrailingDefault { span, .. }
            | Self::SealedConstraint { span, .. }
            | Self::SealedInstance { span, .. }
            | Self::CoherentContext { span, .. }
            | Self::ClassHead { span }
            | Self::Attribute { span, .. }
            | Self::NotTotal { span, .. }
            | Self::ModuleMember { span, .. }
            | Self::NotUpdatable { span }
            | Self::NoImplicitParameter { span }
            | Self::BlockWithoutValue { span }
            | Self::UnrestrictedOwned { span, .. }
            | Self::OwnedTopLevel { span, .. }
            | Self::ResourceWithoutDrop { span, .. }
            | Self::ScopeBound { span, .. }
            | Self::OwnedField { span, .. }
            | Self::OwnedRecordField { span, .. }
            | Self::DestructorWithoutBody { span, .. }
            | Self::SharedDestructor { span, .. }
            | Self::ResourceMember { span, .. }
            | Self::DestructorShape { span, .. }
            | Self::MissingSignature { span, .. }
            | Self::DetachedSignature { span, .. }
            | Self::Missing { span, .. }
            | Self::Core { span, .. }
            | Self::Clauses { span, .. } => *span,
        }
    }
}
