/// Программы корпуса, которые срез берёт.
///
/// Чистый фрагмент: семейства и конструкторы, функции и применение, разбор,
/// рекурсия, `let`, массивы (§4.11), записи (§4.2), очистка ресурса на
/// нормальном выходе (§3.3). Плюс эффекты, гасимые **без снятия сегмента**
/// (трек B волны 4): хендлер, чьи ветки все до одной зовут резумпцию в хвосте.
/// Плюс абортивная ветка со снятием сегмента и очисткой ресурса на
/// исключительном выходе (трек C волны 4, §3.3, §3.4).
/// Плюс **одношот общего вида и параметризованный хендлер** (трек D волны 4):
/// тела второй формы дроблены кадрами по точкам приостановки, резумпция общей
/// ветки есть значение, и её судьбу решает владение.
/// Плюс **маска** (§3.4): вычисление под ней идёт под вектором без ближайшей
/// записи своей метки, и capstone `interpreter` этим берётся целиком.
/// Плюс **мультишот** (трек E волны 4): возобновление ставит копию сегмента,
/// пока на ручку резумпции есть лишние ссылки, и планировщик файберов
/// `fibers`, написанный на самом языке, этим берётся целиком.
/// Плюс **плоское значение через границу куска** (§10 вопрос 164): арифметика
/// после операции едет из куска в кусок словом, и ширина её наблюдаема.
/// Плюс **сравнения** (§4.3, трек A волны 5): аргументы плоские, ответ -
/// конструктор `Bool`, и знаковость с `totalOrder` считает `flat.c` тем же
/// ключом, каким их считает свёртка ядра.
/// Плюс **цикл по примитиву** (тот же трек): литеральный паттерн есть разбор по
/// `eqT x k`, счётчик остаётся плоским, и ячейки кучи на витке не возникает -
/// это и есть первая из четырёх нагрузок трека Z, до сих пор невыразимая.
/// Плюс **питомник и файберы** (§5.2, трек B волны 5): файбер есть сегмент того
/// же стека, уступка режет его по кадру питомника, отмена задачи раскручивает
/// сегмент отменённого, а «ближайший выигрывает» решает рантайм по вектору
/// evidence - те же имена без питомника остаются обычными операциями (`fibers`).
/// Плюс **тип за синонимом** (трек C волны 5): арность понижения берётся у
/// развёрнутого типа, и вычисление в собственной метке, названное абстрактным
/// именем сигнатуры, перестаёт быть операцией значением.
/// Плюс **словарь `Flat`, собранный вычислением** (тот же трек): дескриптор
/// есть два числа времени компиляции, и написанный через собственный метод он
/// считается, а не отвергается.
/// Плюс **плоский ответ через границу вызова** (тот же трек, §10 вопрос 158):
/// недобранный вызов с плоским ответом едет замыканием над обёрткой, и цена
/// ему - ячейка кучи на пересечение.
/// Плюс **операция значением и форма по спросу** (§10 вопрос 169): row
/// написанного типа меток не имеет, а место вызова кладёт метку в
/// needy-инстанциацию - и функция получает второй экземпляр со скрытыми
/// аргументами, не отнимая первой формы у чистых употреблений; спрос едет по
/// графу вызовов, и `prelude` этим берётся целиком.
/// Плюс **операция под лямбдой** (§10 вопрос 170): эта-разворот не меняет
/// типизируемости - погашение кладёт недостающую метку в хвост-дырку
/// окружающей тем же ходом, что унификация на имени, - и обе формы стоят
/// рядом в `operation-lambda`.
/// Плюс **четыре нагрузки трека Z** (трек E волны 5, `workload-*`): пункт 1
/// милестоуна волны требует, чтобы каждая была программой в корпусе, взятой
/// понижением и сверенной с машиной, а не программой в стенде. Размер у
/// корпусной копии мельче стендового - машине полсотни миллионов витков не по
/// силам, - и разъезд двух копий не допускается механизмом: три из четырёх
/// стенд **читает отсюда**, подставляя одну строку размера, а четвёртая
/// (`workload-symbolic`) сверяется со стендовой дословно.
/// Плюс **разделяемые стратегии** (§3.6, трек B волны 4, `shared-strategies`):
/// `SharedAllocStrategy when AllocStrategy` даёт те же члены, и расходятся
/// стратегии в `new`. Ответ у фикстуры тот же, что у `region-strategies`, и
/// это проверяемое утверждение: разделяемость есть свойство **тождества**, а
/// область машины есть значение - программа, которая их различает, есть ровно
/// программа, на которой машина и рантайм обязаны разойтись. Наблюдают
/// различие поэтому там, где машины нет (`tests/shared.rs`).
/// Плюс **разделяемая область из нескольких воркеров** (тот же трек,
/// `shared-workers`): задача укладывает своё, уступает - то есть вправе
/// доехать до чужого воркера - и читает своё обратно. Ответ от порядка
/// файберов не зависит, потому что задача читает **свою** ячейку; соседскую
/// она прочитать могла бы только у разделяемой области, а область машины есть
/// значение. Захват области замыканием (`spawn (worker r)`) до этой фикстуры
/// отвергался представлением - см. `Repr::pointer`.
/// Плюс **чужой символ** (§5.3, трек D волны 1 Фазы 8): `extern-c` зовёт
/// настоящие функции стандартной библиотеки C, `foreign-resource` заворачивает
/// чужой объект в `resource`, чей деструктор зовёт `free`. Обе стоят здесь
/// наравне со всеми, и это и есть содержание варианта (а) вопроса 182: машина
/// ходит наружу `dlopen`'ом, и договор корпуса цел. Держит согласие двух
/// понижений запрет свёртки - `-fno-builtin` у C и `nobuiltin` у `.ll`; без
/// него `gcc` считает `cbrt(27.0)` сам и отвечает на один ULP иначе, чем
/// библиотека (свидетель - `tests/no_builtin.rs`).
/// Плюс **вариадический чужой символ** (§5.3, трек B волны 5 Фазы 8):
/// `extern-varargs` зовёт `snprintf` и `sscanf` - у первой поимённых параметров
/// три, у второй два, - а `extern-varargs-float` кладёт в вариадическую часть
/// плавающее, то есть единственный случай, где `al` перестаёт быть нулём.
/// Отдельными программами они потому, что имя объявления есть имя символа:
/// двух вариадических форм одного символа в одной программе не написать.
/// Плюс **заём, переживающий вызов** (§5.3, §10 вопрос 185, трек A волны 6):
/// `extern-buffer-outlives` даёт чужой стороне адрес, по которому та читает
/// **после** возврата, и держит блок живым не последним упоминанием, а полем
/// `resource`, чей деструктор стоит на выходе из области. Здесь она не ради
/// полноты: без формы машина и понижение расходятся законным байтом, и ловит
/// это ровно этот тест.
/// Всё, что здесь стоит, обязано собраться и ответить как `adamas eval`; список
