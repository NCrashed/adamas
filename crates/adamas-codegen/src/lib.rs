//! Понижение ядра Adamas в C (§9 Фаза 6, волна 2, трек H).
//!
//! Путь: **ядро → backend IR → текст C**. Шов посередине не украшение и не
//! слой ради слоя - на нём лежат факты, которые знает тайпчекер и не
//! восстановит алиас-анализ: кратность связывания, статически известная
//! уникальность, место под непересечение регионов. LLVM-бэкенд Фазы 7
//! (`docs/phase7-plan.md`) переносит их в `noalias` и scoped alias-метаданные;
//! устрой понижение как «ядро → текст C», и Фаза 7 началась бы с
//! восстановления известного двумя проходами раньше. Из C-подобного
//! представления уникальность не восстанавливается.
//!
//! Отсюда раскладка: [`ir`] - представление и факты, [`lower`] - ядро в IR,
//! [`emit_c`] - IR в C. Эмиттер термов ядра не читает вовсе, и это проверено
//! тестом, а не обещано.
//!
//! # Что берётся этим срезом
//!
//! Чистый фрагмент: семейства и конструкторы, функции и применение, разбор,
//! рекурсия, `let`. По ABI (§13, запись 2026-09-08 «ABI: где живут кадры и как
//! выглядит значение в C») это **первая форма понижения** - обычные C-функции
//! по C-стеку. Вторая форма, где кадр отчуждается в кучу, нужна только под
//! общим или мультишотным хендлером, то есть не здесь.
//!
//! Не берётся: эффекты, хендлеры и резумпции; записи (§4.2); `Flat` (§4.11);
//! регионы (§3.6). Каждое отвергается названной причиной
//! ([`LowerError`](lower::LowerError)) - молча посчитать не то хуже, чем не
//! посчитать.
//!
//! # Чем это проверено
//!
//! Договором с интерпретатором: программа корпуса `tests/golden/eval/`
//! компилируется в C, собирается и печатает **то же**, что `adamas eval`. Тот
//! же жанр, каким связаны машина с ядром и специализация с исполнением; третий
//! вычислитель входит в тот же договор.
//!
//! # Чего в порождённом коде нет
//!
//! **`dup` и `drop` не эмитятся ни одного.** Вставляет их Perceus (волна 3), и
//! разовые `free` до него - работа, которую потом пришлось бы выковыривать.
//! Пока их нет, программа не освобождает ничего; сколько именно - печатают
//! счётчики рантайма на stderr в конце прогона.
//!
//! **Оптимизаций нет тоже.** Определение без параметров пересчитывается на
//! каждом упоминании, замыкание аллоцируется на каждое недобранное применение,
//! бета-редекс не сокращается. Предсказуемый выход дороже короткого: milestone
//! фазы про 500-строчную программу, а не про этот срез.
//!
//! # Названные долги
//!
//! **Обходы рекурсивны** - и понижение, и эмиссия, и печать в порождённом C.
//! Машина, освобождение и печать терма от рекурсии по кадрам Rust ушли
//! намеренно (§10 вопросы 89, 92, 93), и здесь тот же предел вернулся: глубоко
//! вложенный терм положит стек компилятора, глубокое значение - стек
//! скомпилированной программы. На корпусе чистого фрагмента глубина - единицы,
//! и предела никто не мерил.
//!
//! **Печать не режется по глубине.** `adamas eval` обрывает ответ на двухстах
//! уровнях, порождённая программа печатает его целиком. Договор от этого не
//! страдает - тест требует, чтобы срез с полной печатью совпадали, - но на
//! вырожденно глубоком ответе они разойдутся, и разойдутся заметно.

pub mod emit_c;
pub mod ir;
pub mod lower;

use adamas_core::sig::Signature;
use adamas_core::term::Term;

pub use emit_c::EmitError;
pub use lower::LowerError;

/// Почему компиляция отказала.
///
/// Два слоя - два отказа: понижение отвергает форму терма, эмиттер - форму
/// понижения. Разделение не косметическое: первый отказ говорит о программе,
/// второй о бэкенде.
#[derive(Debug, thiserror::Error)]
pub enum CompileError {
    /// Терм не понизился.
    #[error(transparent)]
    Lower(#[from] LowerError),
    /// IR не сэмитился.
    #[error(transparent)]
    Emit(#[from] EmitError),
}

/// Понижает терм в единицу трансляции C.
///
/// `entry` - тело `main` с подставленными аргументами уровня и row, то есть
/// ровно то, что вычисляет `adamas eval`.
///
/// # Errors
///
/// [`CompileError`] - форма вне чистого фрагмента, имя, которого не понизить,
/// либо форма понижения, которой эмиттер не знает.
pub fn compile(signature: &Signature, entry: &Term) -> Result<String, CompileError> {
    Ok(emit_c::emit(&lower::lower(signature, entry)?)?)
}
