/* Массивы (§4.11)                                                     */
/* ------------------------------------------------------------------ */

/** Тег массива в заголовке. */
#define ADAMAS_TAG_ARRAY 0xFFFBu

/**
 * Заголовок массива: длина и шаг перед полезной нагрузкой.
 *
 * `stride` - байт на ячейку у плоского массива и **ноль** у указательного;
 * различает представления только он, потому что различает их одно - есть ли у
 * элемента `Flat` (§4.11). Длина лежит здесь, а не в заголовке объекта,
 * потому что дроп и копирование массива ведёт сам рантайм - в отличие от
 * данных, чей release порождает понижение по типу.
 */
typedef struct adamas_array {
    adamas_header header;
    /** Сколько ячеек. */
    size_t count;
    /** Байт на ячейку; 0 - ячейка есть слот `adamas_value`. */
    size_t stride;
} adamas_array;

_Static_assert(sizeof(adamas_array) == 24, "нагрузка массива идёт со смещения 24");

/** Массив на `count` ячеек по `stride` байт; `stride` 0 - указательный. */
adamas_value adamas_array_alloc(size_t count, size_t stride);

/** Сколько ячеек. */
size_t adamas_array_count(adamas_value array);

/** Байт на ячейку; 0 - массив указательный. */
size_t adamas_array_stride(adamas_value array);

/** Адрес плоской ячейки: `base + index * stride`. Номер вне длины обрывает. */
void *adamas_array_at(adamas_value array, size_t index);

/** Адрес нагрузки целиком: то, что одалживается чужой стороне (§5.3).
 *
 * Отдельно от `adamas_array_at(array, 0)` по двум поводам, и оба - поведение,
 * а не вкус. Нулевая длина законна, а `adamas_array_at` на ней обрывает:
 * пустой буфер чужой стороне отдать нечем, хотя `compress2` с нулевым входом
 * - обычный случай. И проверять тут нечего: одалживается **начало**, а сколько
 * ячеек прочтёт чужая сторона, знает только она (§5.3, уровень 1).
 *
 * Массив обязан быть плоским: у указательного там слоты `adamas_value`, то
 * есть указатели на объекты Perceus с заголовками, и отдавать их наружу
 * значило бы отдать чужой стороне нашу кучу. Указательный обрывает.
 *
 * Счётчика не трогает: заимствование. Держать массив живым на время вызова -
 * дело вызывающего (`perceus::applied_to`).
 */
void *adamas_array_data(adamas_value array);

/** Адрес окна из `lanes` ячеек подряд (§4.9, `simdLoad`/`simdStore`).
 *
 * Отдельно от `adamas_array_at` затем, что проверять надо **хвост** окна:
 * `index < count` пропустил бы чтение семи ячеек за концом блока, и ответ
 * при этом был бы верен. Выход обрывает; выравнивания адресу не обещается -
 * ячейка стоит по шагу массива, и грузить его надо невыровненной формой.
 */
void *adamas_array_window(adamas_value array, size_t index, size_t lanes);

/** Указательная ячейка. Заимствуется. */
adamas_value adamas_array_get(adamas_value array, size_t index);

/** Записывает указательную ячейку, **не** дропая прежнюю: она не заполнена. */
void adamas_array_init(adamas_value array, size_t index, adamas_value value);

/** Переписывает указательную ячейку: прежняя дропается, новая берётся владением. */
void adamas_array_put(adamas_value array, size_t index, adamas_value value,
                      adamas_release release);

/**
 * Заполняет указательный массив одним значением. Значение приходит **владением**.
 *
 * Ссылок нужно `count`, а пришла одна: лишние берёт рантайм, свою отдаёт. Это
 * его дело, а не порождённого кода: длина - величина рантайма, и вставке RC
 * (§5.1) её не видно.
 */
void adamas_array_fill(adamas_value array, adamas_value value, adamas_release release);

/** То же плоским: `stride` байт из `bits` в каждую ячейку. */
void adamas_array_fill_flat(adamas_value array, const void *bits);

/**
 * Читает указательную ячейку и **отдаёт массив**.
 *
 * Ответ приходит владением, массив потреблён - тот же договор, что у всего
 * понижения. Дроп стоит здесь, а не в порождённом коде, по той же причине, что
 * и у [`adamas_array_fill`]: снаружи он был бы решением эмиттера о владении.
 */
adamas_value adamas_array_take(adamas_value array, size_t index, adamas_release release);

/** То же для плоской ячейки: `stride` байт в `out`, массив отдаётся. */
void adamas_array_read(adamas_value array, size_t index, void *out, adamas_release release);

/**
 * Массив, готовый к записи. Приходит **владением**.
 *
 * Уникальный (`rc == 0`) отдаётся собой - запись идёт по месту, и это тот же
 * договор, что у reuse (§5.1): уникальность спрашивается у рантайма, а не у
 * кратности (§10 вопрос 149). Разделённый копируется, прежний отдаётся.
 */
adamas_value adamas_array_writable(adamas_value array, adamas_release release);

/** Дроп ячеек. У плоского не делает ничего: заголовков у ячеек нет (§4.11). */
void adamas_array_release(adamas_value array, adamas_release release);

/**
 * Промоушен ячеек (§5.2): близнец [`adamas_array_release`].
 *
 * Длину знает рантайм, детей ячейки - тип, отсюда и две половины. У плоского
 * не делает ничего по той же причине, по какой ничего не делает дроп.
 */
void adamas_array_promote(adamas_value array, adamas_promote children);

/* ------------------------------------------------------------------ */
/* Регионы (§3.6)                                                      */
/* ------------------------------------------------------------------ */

/** Тег региона в заголовке. */
#define ADAMAS_TAG_REGION 0xFFFAu

/**
 * Ёмкость области в байтах: нагрузка плюс журнал вместе.
 *
 * Фиксирована, и это **названная граница**, а не выбор: рост области - решение
 * стратегии, а `AllocStrategy` §3.6 такого метода не называет вовсе.
 * Переполнение обрывает процесс, а не растит блок молча: молчаливый рост
 * означал бы вторую аллокацию там, где §3.6 обещает одну.
 *
 * Сама проверка ёмкости **свидетеля не имеет**, и это измерено мутантом, а не
 * пропущено: снимается слагаемое журнала - и корпус остаётся зелёным целиком.
 * Различающая программа существует, но кончается она `adamas_fail`, то есть
 * обрывом процесса, а наблюдать обрыв ни один прогон здесь не умеет.
 */
#define ADAMAS_REGION_BYTES 4096u

/**
 * Одна аллокация в журнале области: где лежит, сколько занимает, отдана ли.
 *
 * Журнал нужен **возврату ячейки**: `adamas_region_recycle` размера не
 * получает, а «переиспользование ячеек равного размера» (Pool, §3.6) без
 * размера не выражается. Записать его вторым числом в сигнатуру значило бы
 * завести источник, которым можно соврать; область помнит его сама.
 */
typedef struct adamas_cell {
    /** Смещение нагрузки внутри области. */
    uint32_t at;
    /** Её размер в байтах. */
    uint32_t size;
    /** `1` - ячейка отдана обратно и ждёт равного по размеру. */
    uint32_t free;
} adamas_cell;

/**
 * Заголовок области: курсор, хендл последней аллокации и длина журнала.
 *
 * Нагрузка идёт следом байтами, а не слотами: она плоская по построению
 * (`{Flat a}`, §3.6), заголовков у неё нет, и поэтому **число значений в
 * области не влияет на число блоков** - их всегда один.
 *
 * `last` лежит здесь, потому что `alloc : Block -> Nat -> Ptr` (§3.6) отдаёт
 * хендл вместе с подъёмом курсора, а ядро чисто: подъём возвращает область,
 * хендл спрашивается у неё следом.
 *
 * Журнал живёт в **той же** области, растя от её конца вниз навстречу
 * нагрузке: блок остаётся один, и обещание §3.6 про освобождение одним `free`
 * держится дословно. Ёмкости они делят одну на двоих.
 */
typedef struct adamas_region {
    adamas_header header;
    /** Сколько байт занято нагрузкой. */
    size_t used;
    /** Смещение последней аллокации. */
    size_t last;
    /** Сколько ячеек в журнале. */
    size_t cells;
} adamas_region;

_Static_assert(sizeof(adamas_region) == 32, "нагрузка региона идёт со смещения 32");
_Static_assert((sizeof(adamas_region) + ADAMAS_REGION_BYTES) % _Alignof(adamas_cell) == 0,
               "журнал растёт от конца области, и конец обязан быть его границей");

/** Пустая область. `AllocStrategy.new` (§3.6): один блок кучи. */
adamas_value adamas_region_new(void);

/** Сколько байт области занято нагрузкой. Диагностика. */
size_t adamas_region_used(adamas_value region);

/**
 * Размещает `size` байт по границе `align`. Область приходит **владением**.
 *
 * Правило одно на все стратегии, и политики в нём нет: **свободная ячейка
 * равного размера, иначе подъём курсора**. Свободные ячейки заводит
 * [`adamas_region_recycle`], и у Arena их не бывает вовсе - оттуда «bump» её
 * обещания (§3.6). Из равных берётся самая поздняя по размещению.
 *
 * Уникальная область пишется по месту, разделённая копируется - тот же договор,
 * что у [`adamas_array_writable`] (§5.1, §10 вопрос 149). Ячейки кучи под само
 * значение не выдаётся вовсе.
 */
adamas_value adamas_region_alloc(adamas_value region, const void *bits, size_t size,
                                 size_t align);

/**
 * Ячейка по хендлу свободна: Pool (§3.6). Область приходит владением.
 *
 * Курсор не двигается и занятое не убывает - правится только журнал. Хендл, не
 * называющий занятой ячейки, оставляет область как есть; байты ячейки не
 * трогаются, поэтому чтение отданного отдаёт прежнее - так же, как у машины.
 */
adamas_value adamas_region_recycle(adamas_value region, size_t at);

/**
 * Курсор опускается до хендла: StackAlloc (§3.6). Область приходит владением.
 *
 * Опускается он, только если хендл называет **последнюю** аллокацию, - это и
 * есть LIFO, и этим StackAlloc отличается от Pool наблюдаемо: возврат не с
 * вершины оставляет область как есть.
 */
adamas_value adamas_region_pop(adamas_value region, size_t at);

/** Хендл последней аллокации: смещение внутри области. Область отдаётся. */
size_t adamas_region_last(adamas_value region, adamas_release release);

/** Читает `size` байт по хендлу в `out`. Область приходит владением. */
void adamas_region_read(adamas_value region, size_t at, void *out, size_t size,
                        adamas_release release);

/** Переписывает `size` байт по хендлу. Курсор не двигает; приходит владением. */
adamas_value adamas_region_write(adamas_value region, size_t at, const void *bits,
                                 size_t size);

/** Дроп нагрузки области. Не делает ничего: нагрузка плоская (§3.6). */
void adamas_region_release(adamas_value region);

/* ------------------------------------------------------------------ */
/* Разделяемая область (§3.6 «Thread-safe стратегии», §5.2)            */
/* ------------------------------------------------------------------ */

/** Тег разделяемой области в заголовке. */
#define ADAMAS_TAG_SHARED 0xFFF8u

/**
 * Ёмкость разделяемой области в байтах.
 *
 * Больше обычной (`ADAMAS_REGION_BYTES`), потому что делят её воркеры и
 * раздаётся она кусками: четыре воркера по куску разбирают её вчетверо
 * быстрее одного. Фиксирована по той же причине и с тем же следствием -
 * переполнение обрывает процесс, а не растит блок молча.
 */
#define ADAMAS_SHARED_BYTES 262144u

/**
 * Сколько байт воркер берёт у курсора области разом.
 *
 * Это и есть «per-thread cache» §3.6: укладка внутри куска не делает ни одной
 * атомарной операции, встреча воркеров случается раз в кусок. Число выбрано
 * замером, а не вкусом (`docs/measurements/shared-region/`): оно задаёт, во
 * сколько раз реже воркеры встречаются, и от единицы (встреча на каждой
 * укладке - то, что §3.6 приписывает `SharedArena`) до куска мера расходится.
 *
 * Кратностью ему выровнены начала кусков, поэтому правило границы внутри
 * куска считает абсолютное смещение верно.
 */
#define ADAMAS_SHARED_CHUNK 512u

/** Сколько последних укладок помнит журнал воркера. */
#define ADAMAS_SHARED_CELLS 128

/**
 * Заголовок разделяемой области: один атомарный курсор, и больше ничего.
 *
 * Нагрузка идёт следом байтами - та же раскладка, что у `adamas_region`.
 * Журнала здесь нет: он уехал к воркеру, в `_Thread_local`, потому что общий
 * пришлось бы держать под замком, а его поиск свободной ячейки - линейный.
 *
 * `cursor` - **сколько байт роздано под куски**, а не сколько занято
 * нагрузкой: розданный кусок занят воркером целиком, даже если он уложил в
 * него одно значение. Отсюда и различие с `adamas_region_used`.
 */
typedef struct adamas_shared {
    adamas_header header;
    /**
     * Номер области: им рука воркера отличает новую от старой.
     *
     * Адреса для этого **не хватает**, и это не предосторожность: область
     * есть блок `malloc`, а освобождённый блок той же ширины `malloc` выдаёт
     * снова - тот же указатель у следующей области обычное дело (§3.6,
     * переиспользование блока между регионами). Рука, сверяющая один адрес,
     * приняла бы новую область за свою прежнюю и продолжила бы укладывать в
     * кусок, которого новая никому не раздавала: два воркера получили бы одни
     * байты при верном на вид курсоре.
     *
     * Читается неатомарно: пишется он один раз, до того как область станет
     * видна второму потоку, а ребро happens-before даёт передача - тот же
     * довод, что у `ADAMAS_FLAG_SHARED`.
     */
    size_t birth;
    /** Атомарный: единственное поле, которое воркеры правят вместе. */
    size_t cursor;
} adamas_shared;

_Static_assert(sizeof(adamas_shared) == 24, "нагрузка разделяемой области идёт со смещения 24");

/**
 * Пустая разделяемая область: `SharedAllocStrategy.new` (§3.6).
 *
 * Рождается с `ADAMAS_FLAG_SHARED`: счётчик её атомарен с первой ссылки, а не
 * с промоушена, - разделяемость и есть её назначение. Промоушен на границе
 * `spawn` (§5.2) её увидит и остановится, потому что уже помечена; детей у
 * неё нет вовсе (нагрузка плоская).
 *
 * # Чем она отличается от обычной по договору
 *
 * **Тождеством.** `adamas_region_alloc` над разделённой областью копирует её
 * целиком (`region.c`, `copied`), и ровно этим обычная область
 * потокобезопасна даром: двух воркеров в одной не бывает. Разделяемая копии
 * не делает ни при каком счётчике - `store` правит ту же область и возвращает
 * тот же указатель. Всё прочее следствие: синхронизация нужна потому, что
 * копии больше нет.
 *
 * **Хендл последней укладки - воркерский.** «Последняя» у общей области не
 * определена: между `store` одного воркера и его `here` встаёт `store`
 * другого. `adamas_region_last` над разделяемой областью поэтому отвечает
 * последней укладкой **спрашивающего**.
 *
 * # Что этим не покрыто
 *
 * *Гонка ячейки* (§10 вопрос 40): thread-safety обещана аллокатору, а не
 * нагрузке. Два воркера, пишущие в один хендл, дают гонку данных.
 *
 * *Две области у одного воркера разом:* рука одна, смена области бросает
 * остаток куска и журнал. Ответа это не портит - возврат забытой ячейки
 * оставляет область как есть, ровно как у обычной.
 *
 * *Освобождение под конкурентным использованием* (§10 вопрос 26в): ни hazard
 * pointers, ни эпох здесь нет, и не нужно - тишина даётся структурой.
 * Питомник дожидается порождённых прежде, чем `withNursery` ответит, поэтому
 * к дропу области воркеров, держащих её, не остаётся ни одного.
 */
adamas_value adamas_shared_new(void);

/** Сколько байт области роздано под куски. Диагностика. */
size_t adamas_shared_used(adamas_value area);

/**
 * Укладка в разделяемую область. Область приходит владением и **возвращается
 * собой**: копии нет.
 *
 * Правило одно с обычной областью - свободная ячейка равной ширины, иначе
 * подъём курсора, - и совпадать оно обязано: иначе однопоточная программа над
 * разделяемой областью отвечала бы не то, что над обычной. Разница лишь в
 * том, чьи это ячейка и курсор: воркерские, а не областные. Курсор области
 * поднимается раз в кусок.
 */
adamas_value adamas_shared_alloc(adamas_value area, const void *bits, size_t size, size_t align);

/** Ячейка по хендлу свободна: `SharedPool` (§3.6). Ячейка **воркерская**. */
adamas_value adamas_shared_recycle(adamas_value area, size_t at);

/** Курсор воркера опускается до хендла, и только с его вершины: LIFO. */
adamas_value adamas_shared_pop(adamas_value area, size_t at);

/** Хендл последней укладки **спрашивающего**. Область отдаётся. */
size_t adamas_shared_last(adamas_value area, adamas_release release);

/**
 * Читает `size` байт по хендлу. Область приходит владением.
 *
 * Граница проверяется против **розданного** - то есть против того же курсора,
 * который правят укладчики. Это строка кэша, разделяемая с ними, и чтение её
 * идёт на каждом чтении нагрузки. **Цена не мерена**: замер трека
 * (`docs/measurements/shared-region/`) мерил укладку, а не чтение, и нагрузки,
 * где чтений больше укладок, у корпуса нет. Тому, кто станет писать
 * читающую нагрузку, это первое место, куда смотреть; альтернатива -
 * проверять против ёмкости области, что безопасно ровно так же (байты
 * принадлежат ей), но пропускает хендл в ещё не розданное.
 */
void adamas_shared_read(adamas_value area, size_t at, void *out, size_t size,
                        adamas_release release);

/** Переписывает `size` байт по хендлу. Гонка ячейки не закрыта: вопрос 40. */
adamas_value adamas_shared_write(adamas_value area, size_t at, const void *bits, size_t size);

/** Дроп нагрузки. Не делает ничего: нагрузка плоская. */
void adamas_shared_release(adamas_value area);

