/// Почему компиляция отказала.
///
/// Два слоя - два отказа: понижение отвергает форму терма, эмиттер - форму
/// понижения. Разделение не косметическое: первый отказ говорит о программе,
/// второй о бэкенде.
#[derive(Debug, thiserror::Error)]
pub enum CompileError {
    /// Терм не понизился.
    #[error(transparent)]
    Lower(#[from] LowerError),
    /// IR не сэмитился.
    #[error(transparent)]
    Emit(#[from] EmitError),
    /// IR не сэмитился в LLVM.
    #[error(transparent)]
    Llvm(#[from] LlvmError),
}

/// Понижает терм в единицу трансляции C.
///
/// `entry` - тело `main` с подставленными аргументами уровня и row, то есть
/// ровно то, что вычисляет `adamas eval`.
///
/// # Errors
///
/// [`CompileError`] - форма вне чистого фрагмента, имя, которого не понизить,
/// либо форма понижения, которой эмиттер не знает.
pub fn compile(signature: &Signature, entry: &Term) -> Result<String, CompileError> {
    Ok(emit_c::emit(&prepared(signature, entry)?)?)
}

/// Понижает терм в текст `.ll` и спутник на C (§9 Фаза 7, трек A).
///
/// Тот же путь до того же представления, что у [`compile`], и другой только
/// последний шаг: это и есть содержание варианта (а) волны 0 - **второй
/// эмиттер**, а не второй компилятор.
///
/// # Errors
///
/// [`CompileError`] - форма вне чистого фрагмента либо форма понижения вне
/// скалярного фрагмента LLVM-эмиттера.
pub fn compile_llvm(
    signature: &Signature,
    entry: &Term,
) -> Result<emit_llvm::Artefacts, CompileError> {
    Ok(emit_llvm::emit(&prepared(signature, entry)?)?)
}

/// То же с исходником: `.ll` получает DWARF (§9 Фаза 7, трек E).
///
/// Отладочная информация появляется **от исходника**, а не от ключа: нет
/// текста - нечего и называть отладчику, и выход тогда байт в байт тот же, что
/// у [`compile_llvm`]. Отсюда и отсутствие флага «собрать с `-g`»: флаг
/// пришлось бы сверять с наличием позиций, а сверять нечего.
///
/// # Errors
///
/// [`CompileError`] - то же, что у [`compile_llvm`].
pub fn compile_llvm_located(
    signature: &Signature,
    entry: &Term,
    file: &adamas_core::source::SourceFile,
) -> Result<emit_llvm::Artefacts, CompileError> {
    let lowered = split::prepare(lower::located(signature, entry, file)?);
    Ok(emit_llvm::emit(&unique::infer(perceus::insert(lowered)))?)
}

/// Общая для обоих эмиттеров половина пути: понижение, дробление, вставка RC,
/// вывод уникальности.
///
/// [`unique::infer`] стоит **после** вставки RC и не раньше: судит он по
/// отсутствию узлов [`ir::Expr::Dup`], а ставит их она. Общая половина, а не
/// половина LLVM-пути, потому что уникальность - факт представления, а не приём
/// печати; C-эмиттер её игнорирует наравне с кратностью, и это записано у
/// [`ir::Fact`].
fn prepared(signature: &Signature, entry: &Term) -> Result<ir::Program, CompileError> {
    let lowered = split::prepare(lower::lower(signature, entry)?);
    Ok(unique::infer(perceus::insert(lowered)))
}
