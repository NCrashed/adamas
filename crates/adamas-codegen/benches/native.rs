//! Первый бенчмарк понижения: во что обходится порождённая программа.
//!
//! У понижения замеров не было вовсе (§13, итог 2026-09-11: «native
//! performance не мерил никто»), и §6 оставался непроверенным целиком. Здесь
//! меряется одна его строка — **«символьно-тяжёлый код: паритет с Rust или
//! лучше»**. Взята она потому, что достижима сегодняшним срезом: §6 сам
//! называет символьный workload «цепочками функциональных преобразований над
//! деревьями и списками», а дерево, обход и свёртка — это чистый фрагмент,
//! который понижение берёт.
//!
//! Прочие строки §6 сегодня не меряются, и вот чем:
//!
//! - **Горячие циклы с unboxed numerics** и **zero-alloc циклы с регионами**
//!   требуют цикла, а цикла в языке нет: [`PrimOp`](adamas_core::prim::PrimOp)
//!   знает только `Add`, `Sub`, `Mul`, литеральный паттерн элаборация
//!   отвергает (`Missing::Literal`), и условия выхода из рекурсии по примитиву
//!   не из чего собрать. Счётчик цикла поэтому обязан быть индуктивным, то
//!   есть боксированным, и «unboxed hot loop» не выражается. Мерить нечего до
//!   сравнений и литеральных паттернов.
//! - **`@noalloc`, SIMD, mempool, FFI** — механизмов в понижении нет.
//! - **Плоские контейнеры** есть (§4.11), но хеш-таблицы, против которых
//!   меряется строка, — библиотека, которой нет.
//! - **Бизнес-код с эффектами (1.5–2x Rust)** — мерится здесь же
//!   ([`Shape::TailResumptive`], [`Shape::FlatHandled`]), но не против Rust:
//!   сосед на Rust есть только у чистой формы, а под хендлером сравниваются
//!   между собой формы понижения. Цифра 1.5–2x требует эффектного соседа,
//!   которого писать не на чем.
//! - **Старт компилятора** мерен у драйвера (`adamas-cli/benches/startup.rs`).
//! - **Время release-сборки** §6 сознательно не ограничивает; она всё равно
//!   мерена ниже как `codegen/cc`, потому что без неё не прочитать, чего стоит
//!   весь путь.
//!
//! # Алгоритм и почему он
//!
//! Двоичное дерево глубины `d`: `grow` строит, `scaled` умножает каждый лист,
//! `total` складывает. Три прохода по 2^d листьям, рекурсия глубиной `d` —
//! стека не хватить не может ни у порождённого C, ни у соседа. Листья
//! **различны** (счётчик по битам пути), поэтому перепутанные поддеревья
//! меняют ответ, а не оставляют его тем же.
//!
//! Счётчик глубины — индуктивный `Nat` длиной `d` (единицы). **Построение**
//! его в замере не участвует: работа экспоненциальна по `d`, а счётчик линеен.
//! А вот **обход** его `grow` платит на каждом узле, тогда как сосед на Rust
//! вычитает единицу из машинного числа, и эта асимметрия в замере есть.
//! Измерена она 2026-09-13 на потолке (тот же алгоритм руками на C, счётчик
//! списком против счётчика числом): **0.47 мс из 17.0 на глубине 18, то есть
//! 2.8%**. Написать иначе язык не умеет — литеральных паттернов и сравнений
//! нет, см. первый пункт выше, — поэтому цена названа, а не снята.
//!
//! # Кто с кем сравнивается
//!
//! Все считают **одно и то же число**, и это проверяется до всякого
//! замера ([`checked`], [`same_answer`]):
//!
//! - `interp` — машина, то есть `adamas eval`;
//! - `native` — порождённый C, собранный строкой release ([`RELEASE`]) и
//!   запущенный процессом;
//! - `rust` — тот же алгоритм на Rust, теми же формами данных
//!   (`Box`-рекурсия), запущенный **тоже процессом**: стенд зовёт сам себя
//!   через `ADAMAS_BENCH_NEIGHBOUR` ([`as_child`]). Почему не в общем
//!   процессе — ниже;
//! - `floor` и `rust/floor` — те же два пути при `d = 0`: цена `fork`/`exec` и
//!   печати, которую каждая сторона платит сверх работы. Полов два, потому что
//!   двоичных файлов два: 0.20 мс у порождённого C против 0.48 мс у стенда,
//!   и вычитать надо свой.
//!
//! Сосед на Rust написан **эквивалентным кодом**, как того и требует §6
//! («Rustc на эквивалентном коде»), а не идиоматичным: те же конструкторы, та
//! же владеющая рекурсия, то же заворачивание арифметики. Идиоматичный сосед
//! (массив, цикл) мерил бы отсутствие цикла в языке, а не качество понижения.
//!
//! ## Почему сосед мерится процессом, а не в общем процессе со стендом
//!
//! Запись §13 от 2026-09-11 прочитала «понижение обгоняет Rust в полтора
//! раза» с числа, которое не повторялось: семь прогонов 2026-09-12 дали
//! `rust/18` либо 21–24 мс, либо 57–64. Мода устанавливалась до первой
//! выборки и держалась весь прогон, так что ни усреднить, ни отбросить её
//! было нельзя.
//!
//! **Двумодален был не сосед, а куча стенда** (измерено 2026-09-13). Пока
//! сосед считался в общем процессе с criterion, его цену задавала не машина и
//! не алгоритм, а то, сколько стенд успел выделить и освободить **до** замера.
//! Свидетель — одно и то же дерево, померенное дважды в одном прогоне:
//!
//! | где мерено | страниц под 524 286 узлов | размах | обход |
//! |---|---|---|---|
//! | до элаборации | 4 103 | 32 байт/узел | 9.7 мс |
//! | после элаборации и машины | 25 213 | 784 байт/узел | 30.4 мс |
//!
//! На нетронутой куче glibc кладёт узлы подряд — 128 штук на страницу, размах
//! равен размеру куска. После того как элаборация и машина взболтали
//! свободные списки, то же дерево растекается по шестикратно большему числу
//! страниц, обход перестаёт попадать в TLB и идёт втрое дольше. Тот же сдвиг
//! виден и позиционно: `rust/18`, померенный первым делом в том же прогоне,
//! давал 21.7 мс против 62.2 мс на своём прежнем месте.
//!
//! Порождённый C этого не платил никогда: он — свежий процесс на каждой
//! итерации. Асимметрия «C процессом, Rust в общем процессе» и была
//! двумодальностью, поэтому сосед переведён на тот же протокол: свежий
//! процесс, свежая куча, ответ печатью, свой пол.
//!
//! Проверено и отвергнуто замером, а не рассуждением: гибридные ядра машины
//! (P против E даёт 1.35 раза, а не 2.5, и свободное размещение все шесть раз
//! попало на P), ASLR, huge pages (режим `madvise` — их никто не просит).
//! Синтетическое взбалтывание кучи в чистом процессе воспроизводит 1.7 раза
//! из трёх и поднимает размах с 32 до сотен байт: механизм тот, величина у
//! настоящей элаборации больше.
//!
//! # Методика: что делает число повторяемым завтра
//!
//! Сравниваются два процесса, а цена процесса чувствительна к окружению
//! сильнее, чем цена функции. Что фиксируется:
//!
//! - **Не меньше пяти прогонов подряд.** Число — медиана прогонов, рядом
//!   обязан стоять размах. Один прогон — заявка, а не число: именно на нём
//!   сорвалась запись 2026-09-11.
//! - **Привязка к одному P-ядру:** `taskset -c <ядро>`. Машина гибридная,
//!   E-ядро идёт на треть медленнее, а дочерний процесс короткий, и
//!   планировщик размещает его заново на каждой итерации. Без привязки один
//!   прогон из пяти дал `native/pure/18` 70.6 мс при 44.8 у прочих; с
//!   привязкой размах между семью прогонами — 1.07.
//! - **`--noplot --discard-baseline`.** Отчёты и сравнение с прошлым прогоном
//!   идут между точками и меняют состояние процесса; прогоны обязаны
//!   начинаться одинаково.
//! - **Первый прогон после сборки — холодный:** страницы свежесобранных
//!   двоичных файлов ещё не в кэше, и `native/*` на нём завышен (10.5 → 13.5 мс
//!   на глубине 16). Медиана прогонов это переживает, среднее — нет.
//! - **Машина без другой нагрузки.** Нарушение видно в самом отчёте: разброс
//!   внутри выборки становится шире 10%.
//!
//! Число **недействительно**, если:
//!
//! - стороны собраны разными строками: у соседа профиль `release` этого
//!   репозитория, то есть `lto = "thin"`, и без [`RELEASE`] здесь сравнивалось
//!   бы собранное межмодульно с собранным по частям. Замер 2026-09-13: одна эта
//!   асимметрия стоила **99%** разрыва;
//! - сосед померен не отдельным процессом — тогда меряется куча стенда;
//! - свидетель `rust/N: размах` больше [`SPREAD_LIMIT`] — стенд падает сам и
//!   называет величину;
//! - разница точек меньше размаха между прогонами: померено окружение, а не
//!   программа. Размах называть **обязательно** — отношение двух медиан без
//!   него есть ровно та заявка, на которой сорвалась запись 2026-09-11.
//!
//! ## Чего методике недостаёт
//!
//! Остаточный разброс между прогонами — **около 2.8 мс, и он один и тот же у
//! обеих точек**: `rust/18` за семь прогонов лёг в 18.34–21.07 мс,
//! `native/pure/18` — в 42.24–45.20. Величина абсолютная, а не долевая: в
//! работе её, значит, нет, она постоянна на прогон. У соседа это 15% числа, у
//! понижения 7%, и у соседа разброс между прогонами поэтому впятеро шире
//! интервала внутри выборки. Причина, вероятно, в том, что ядро отдаёт
//! процессу 16 МБ свежих страниц, а машина при замере не пустая (нагрузка
//! 2–2.5 при привязке к одному ядру из двадцати). Чтобы снять и это, нужен
//! **изолированный процессор** (`isolcpus`/`cpuset`) или машина без сеанса
//! рабочего стола; ни того, ни другого здесь нет.
//!
//! **После [`RELEASE`] этого запаса больше нет, и это главное следствие
//! правки для методики.** Пока разница точек была 25 мс при разбросе 2.8, её
//! не трогало ничто; теперь она 3.4 мс при том же разбросе. Семь прогонов
//! 2026-09-13 дали `rust/18` 18.56–29.09 (первый холодный) и
//! `native/pure/18` 21.22–25.76, то есть размах 1.21–1.57. Отношение
//! 1.14–1.19 держится на медианах и **не держится на отдельной паре**: пятый
//! прогон того же дня дал `handled` быстрее `boxed` при заведомо большей
//! работе. Всё, что мельче полутора раз, на этой машине требует медианы по
//! пяти прогонам как минимум, а не одного числа.
//!
//! # Ответ на символьную строку §6, 2026-09-13 (вторая редакция)
//!
//! **Разрыв в 2.4 раза принадлежал строке сборки, а не понижению.** Семь
//! прогонов подряд, привязка к одному P-ядру, медианы за вычетом своего пола
//! (0.219 мс у `native`, 0.484 мс у соседа):
//!
//! | глубина | сосед на Rust | понижение | отношение | было утром |
//! |---|---|---|---|---|
//! | 14 | 1.01 мс | 1.20 мс | 1.19 | 2.6 |
//! | 16 | 4.27 мс | 4.88 мс | 1.14 | 2.5 |
//! | 18 | **18.22 мс** | **21.60 мс** | **1.19** | 2.4 |
//!
//! Первый из семи прогонов холодный, как и предупреждает «Методика»: у него
//! разброс внутри выборки шире 10% (`rust/18` — 23.1–38.0 мс), то есть по
//! собственному правилу стенда он недействителен. Медиана его переживает:
//! шесть остальных дают `rust/18` 18.56–19.90, `native/pure/18` 21.22–25.76.
//!
//! ## Из чего состояли 2.4 раза
//!
//! Разложено разностными сборками одного и того же порождённого C, с
//! пофазным замером **внутри** процесса (глубина 18, медиана 15 прогонов, мс):
//!
//! | точка | grow | scaled | total | сумма |
//! |---|---|---|---|---|
//! | сосед на Rust | 9.20 | 4.56 | 3.79 | 17.55 |
//! | тот же алгоритм руками на C | 10.04 | 3.89 | 3.04 | 16.97 |
//! | понижение, как собиралось утром | 16.20 | 12.08 | 14.06 | **42.34** |
//! | оно же с [`RELEASE`] | 9.40 | 2.90 | 5.35 | **17.65** |
//!
//! - **Невстроенные вызовы в рантайм — 24.7 мс из 24.8 мс разрыва.** Горячий
//!   путь состоит из `adamas_tag`, `adamas_field`, `adamas_dup`, `adamas_drop`;
//!   каждый — несколько инструкций в **чужой** единице трансляции. Проверено
//!   двумя независимыми способами, давшими одно: `-flto` и `static inline`
//!   тех же примитивов прямо в файле программы — 17.65 против 17.63.
//! - **`scaled` быстрее соседа на 1.7 мс** — reuse §5.1 работает: сосед на
//!   каждый узел роняет ячейку и берёт новую, понижение переписывает свою.
//! - **`total` медленнее соседа на 1.6 мс** — RC: разбор дупает поля, а дроп
//!   разобранного родителя обходит их и дропает обратно. Схлопывание этой пары
//!   при уникальном родителе проверено правкой порождённого C: 17.65 → 16.76,
//!   то есть 5%. Прохода, который её схлопывает, в [`perceus`] нет.
//! - **Заголовок объекта, косвенность `adamas_value`, аллокатор — ноль
//!   дифференциально.** Тот же алгоритм руками на C, теми же формами данных и
//!   тем же `malloc`, стоит 16.97 против 17.55 у соседа: пара gcc/glibc
//!   соседу не проигрывает, и весь разрыв принадлежал нам.
//! - **Индуктивный `Nat` вместо машинного счётчика — 0.47 мс (2.8%).** Тот же
//!   потолок со счётчиком-списком стоит 17.44 против 16.97. Гипотеза
//!   «счётчик дорог» отвергнута замером.
//!
//! ## Что осталось в 1.14–1.19
//!
//! Пофазно в процессе понижение и сосед сходятся (17.65 против 17.55), а
//! процессом расходятся на 3.4 мс. Разница названа: **2.5 мс из них —
//! консолидация свободных списков glibc**, и платит её первый `malloc`,
//! который не влезает в tcache, после того как программа освободила полмиллиона
//! ячеек. Таким первым выделением оказывается буфер `stdout`, который glibc
//! заводит на первом `printf` — то есть на печати ответа. Свидетель: `setvbuf`
//! статическим буфером до начала работы убирает хвост целиком (2.55 → 0.03 мс),
//! не трогая ни одной строки счёта. Сосед этого не платит потому, что его
//! первое послеосвобожденческое выделение мельче порога.
//!
//! Работа это или нет — зависит от программы, которая не кончается печатью;
//! стенд её не решает и потому и не прячет. Пол не помогает: он мерен на
//! глубине 0, где свободных списков ещё нет.
//!
//! Прежние чтения объяснены: «в полтора раза быстрее» (2026-09-11) — соседом
//! на взболтанной куче, «втрое медленнее» (2026-09-12) — соседом без цены
//! запуска процесса, «2.4 раза» (утро 2026-09-13) — соседом, собранным
//! межмодульно, против понижения, собранного по частям.
//!
//! # Чем проверено, что мерится не пустота
//!
//! Тремя вещами разом. Ответ **печатается** — обеими сторонами, соседом тоже,
//! — и сверен с машиной: выброси компилятор C вычисление, печатать станет
//! нечего. Точек по глубине три, и шаг глубины удваивает работу: линейному
//! исполнению отвечает удвоение времени. И полы показывают, сколько в
//! измеренном не работа, а запуск процесса.
//!
//! Защита проверена мутантом по времени после перевода соседа на процесс
//! (2026-09-13). `scaled (Node l r) = Node l r` **в исходнике Adamas**:
//! `assert_eq!` в цикле форм ловит его первым — 402644992 против 1207934976 у
//! соседа. Если сломать сразу обе стороны, сверка молчит, а время идёт следом
//! за ответом: 309237252096 → 103079084032, `rust/18` 18.6 → 14.3 мс,
//! `native/pure/18` 43.5 → 30.6 мс.
//!
//! Точка `native/handled` сверх того проверена двумя мутантами. Первый ловится
//! и сегодня; второй ловился до вопроса 74 и с тех пор молчит — см. ниже.
//!
//! - **Работа.** `scaled (Node l r) = Node l r` — свёртка перестаёт спускаться
//!   по дереву. Ответ меняется (309237252096 → 103079084032, ровно треть),
//!   время на глубине 16 падает 18.8 → 9.9 мс, блоки 1835025 → 524308.
//!   Заодно пойман соседом на Rust: `assert_eq!` у `rust/*` сработал раньше
//!   всех прочих.
//! - **Операция.** `scale ask x` → `scale Triple x` при сохранённых row,
//!   объявлении эффекта и хендлере. Ответ тот же, а разность точек **исчезала
//!   целиком**: `handled` садился на `boxed` и по времени (4.03 против 4.06 мс
//!   на глубине 14), и по блокам (49168 против 49165). Значит измеряемая
//!   разность есть операция, а не вторая форма вообще.
//!
//!   **Сегодня этот мутант не ловится, и виноват не он.** Прогон 2026-09-13:
//!   пять прогонов подряд с мутантом дали `handled/18` 23.95 мс против `boxed`
//!   25.47 — то есть «медленнее» вышло **быстрее**, при размахе между
//!   прогонами 1.55. Без мутанта отношение 1.04. Разница, которую свидетель
//!   обязан показать, стала меньше размаха, а это ровно тот случай, который
//!   «Методика» объявляет недействительным числом. Блоки не помогают вовсе:
//!   после первой ступени вопроса 74 операция не стоит ни одной ячейки, и
//!   49168 против 49165 читается одинаково с мутантом и без.
//!
//!   Стёрла свидетеля не правка стенда, а сам вопрос 74: он опустил цену
//!   хендлера с 1.43–1.50 до единиц процентов, а мутант различал именно её.
//!   Чтобы вернуть свидетеля, нужен либо счётный признак операции (её сегодня
//!   нет в блоках), либо программа, где операций на порядок больше работы.
//!   Записано как есть: свидетель, который молчит, хуже отсутствующего, если
//!   выдавать его за работающий.
//!
//! Второй мутант заодно показал, чего в решении 3 волны 4 не написано:
//! кадр ставится **не** на всякий вызов второй формы, а только там, откуда
//! приостановка достижима. У мутанта `scaled` осталась второй формой — берёт
//! `ev` и `kont`, — но `adamas_kont_push` в порождённом C не встречается ни
//! разу, и рекурсия идёт прямыми вызовами.
//!
//! Точка `native/handled-flat` держится на том же ответе и сверх того на двух
//! свидетелях вне стенда: `tests/boundary.rs` смотрит **представление** в
//! тексте C, а корпусная `eval/flat-across-a-suspension` — ширину перевода
//! через `Float64`. Стенд один их не заменяет: у него множитель целый, а на
//! целых подмена ширины сокращается — C приводит число обратно.
//!
//! # Цена хендлера: против чего она мерится
//!
//! Формы четыре, и ни одна не заведена для симметрии. Мерить `handled` против
//! `pure` было бы враньём: между ними **два** различия, а не одно.
//!
//! Различие первое — операция. Различие второе — представление множителя.
//! Отсюда [`Shape::Boxed`]: тот же алгоритм, множитель — **нульарный
//! конструктор** `Mult`, который применяет к листу чистая `scale`. Конструктор
//! без рантайм-полей объектом не становится (ABI 2026-09-08), то есть ячейки
//! кучи боксирование здесь не стоит; стоит оно вызова `scale` на лист, и
//! платят его `Boxed` и `TailResumptive` **одинаково**.
//!
//! Что мерит разность этих двух точек, зависит от среза. До первой ступени
//! вопроса 74 (2026-09-12) она мерила цену второй формы с дроблением: вектор
//! evidence скрытым аргументом, тело `scaled` кадрами по точкам приостановки,
//! диспетчер операции — 1.43–1.50 и ровно четыре блока на операцию, число
//! milestone 3. После ступени (2026-09-13) программа тиха — единственная
//! ветка хвостовая, — тело не дробится, и разность мерит **остаток**:
//! evidence-поиск и непрямой вызов ветки на лист. Измерено двумя прогонами:
//! **0.99–1.05** за вычетом пола, в блоках — **три на программу** (кадр
//! хендлера и два вектора evidence), ноль на операцию. Этим же числом закрыт
//! вопрос 74: заказчика у специализации по row среди записанных не осталось.
//!
//! [`RELEASE`] цену хендлера не сдвинул, и это проверено, а не предположено:
//! семь прогонов того же дня дают **1.01 / 1.03 / 1.04** на глубинах 14 / 16 /
//! 18 (медианы за вычетом пола: `boxed` 1.27 / 5.15 / 22.04, `handled` 1.28 /
//! 5.29 / 23.01). Ожидаемо: невстроенный вызов дорог всем четырём формам
//! одинаково, и в разности он сокращался.
//!
//! Точка `pure` при этом не сдвинулась ни на строку исходника: строка §6
//! «символьно-тяжёлый код» мерится ею и сравнивается с соседом на Rust, а
//! путь под хендлер лежит рядом, а не поверх.
//!
//! ## Четвёртая точка: эффект над плоскими данными
//!
//! [`Shape::FlatHandled`] — умножение стоит **после** операции
//! (`Leaf (mulInt64 x (factor ask))`), то есть плоское значение переживает
//! точку приостановки и пересекает границу куска дроблёного тела. До
//! 2026-09-12 такая программа не мерилась вовсе: понижение отвечало на неё
//! `Ok`, а печатало C, который не собирается (§10 вопрос 164). Стенд обходил
//! это, унося арифметику внутрь `scale`; обход снят, и точка мерится.
//!
//! Мерится она против `pure`, а не против `handled`: это и есть «цена эффекта
//! над плоскими данными» — то, ради чего §4.11 писался. До первой ступени
//! вопроса 74 разность блоков называла три различия числом — **семь блоков на
//! лист** (2026-09-12): четыре на операцию, два на лишние кадры дробления и
//! один на переиспользование ячейки листа, не проходящее через границу куска.
//! По времени — 1.68 / 1.56 / 1.62 раза. После ступени (2026-09-13) тело не
//! дробится, границы куска нет, reuse листа внутрифункционален и работает:
//! осталось **три блока на программу** и **1.07–1.12** по времени — операция
//! на месте (поиск, диспетчер, ветка) плюс вызов `factor` на каждый лист.
//! После [`RELEASE`] — **1.03 / 1.03 / 1.01** (семь прогонов, за вычетом пола).
//!
//! Множителей два (`Triple` и `Double`), хотя программе нужен один: с одним
//! конструктором ветка `ask -> resume Triple` не имела бы мутанта — вернуть
//! из хендлера **не то** было бы не из чего.

