//! Внешний вызов доходит до ответа обоими понижениями (§5.3, трек B волны 1
//! Фазы 8).
//!
//! Свидетель отвечает на один вопрос: **печатает ли эмиттер узел внешнего
//! вызова так, что собранная программа зовёт настоящую чужую функцию и
//! отвечает верно**. Трек A назвал границу своего доказанного прямо - его
//! уклады через эмиттеры не проходили, потому что узла IR не было вовсе, - и
//! эта граница закрывается здесь.
//!
//! Проверяется **прогоном до линковки и до ответа**, а не чтением `.ll`:
//! восемнадцатая версия принимает неизвестное имя молча как внешнюю функцию
//! (`tests/llvm.rs`,
//! `the_reader_of_the_minimum_llvm_is_blind_to_an_unknown_intrinsic`), и
//! «разобралось» не значит «работает». Для чужого символа этот жанр опаснее
//! обычного: **всякий** `declare` есть объявление внешней функции, и ошибиться
//! в нём разбор не может по построению - ошибиться может только линковка и
//! ABI.
//!
//! Программа - фикстура корпуса `tests/golden/programs/extern-c.adamas`, а не
//! строка здесь: вторая копия разъехалась бы с первой молча. Чужая сторона -
//! `tests/shim/probe.c`, и про Adamas она не знает ничего.
//!
//! Чего здесь нет: машины (§10 вопрос 182 - её отказ назван в
//! `adamas-interp`), `resource` над чужим объектом и линковки с настоящей
//! библиотекой - оба трека D.
//!
//! # Мутанты, которыми это мерено (2026-09-20)
//!
//! Таблица снята на каждой правке порознь, с возвратом между ними. Счёт -
//! упавших свидетелей **всего набора трека B**: этот файл, `running.rs`
//! машины, корпус `golden.rs` и круг печати `printing.rs`. Контроль на чистом
//! дереве - ноль. Полная таблица - `docs/phase8-trackB-notes.md`; здесь только
//! строки, относящиеся к печати узла.
//!
//! | Мутант | Красных |
//! |---|---|
//! | `emit_c::foreign`: у `void`-символа снять вызов, оставив единицу | 2 |
//! | `emit_llvm::foreign`: то же у `.ll` | 1 |
//! | `emit_c::foreign`: переставить аргументы местами | 1 |
//! | `emit_llvm::foreign`: приписать вызову `CONVENTION` | 1 |
//! | `lower::crossing`: пустить аргумент-единицу через границу | 1 |
//! | `emit_c::prototypes`: `(void)` в пустом списке аргументов на пусто | **0** |
//!
//! Один выживший, и он назван. **Пустые скобки C11 законны** - они объявляют
//! функцию с неизвестным списком аргументов, - и на этой платформе вызов через
//! такое объявление идёт тем же ABI. Различил бы их C23, где пустые скобки
//! значат `(void)`, либо цель с другим соглашением о переменном числе
//! аргументов; стенда на это волна не заводит, и правило держится доводом, а не
//! прогоном.
//!
//! Мутант «пустить единицу через границу» роняет **только C**: `.ll` принимает
//! лишний аргумент у объявленной без него функции молча, и прогон на этой
//! платформе доходит до верного ответа. Жанр тот же, что назвал трек A у
//! неизвестного интринсика, и относится он к `.ll` целиком, а не к этому
//! свидетелю: арность у границы ловит C, а не текстовый IR.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    reason = "заготовка теста: отказ здесь означает сломанное окружение, и падать он должен громко"
)]

mod harness;

use std::path::{Path, PathBuf};
use std::process::Command;

use adamas_codegen::llvm::Pipeline;

/// Ответ программы: `mix 14 2` даёт 44, ячейка отдаёт его обратно, походов к
/// шестому пять, и `mix 44 5` даёт 137.
///
/// Число записано здесь, а не взято у машины, и это не нарушение правила
/// «свидетель - интерпретатор»: машина эту программу считать не может вовсе
/// (§10 вопрос 182), и сверять её ответ не с чем. Зато оно **арифметика чужой
/// стороны**, а не вывод нашей: порядок вызовов свёрнут в него счётчиком
/// походов, поэтому потерянный или переставленный вызов меняет ответ.
const ANSWER: &str = "137";

/// Сколько раз программа ходит за границу: `mix` дважды, `alloc`, `read`,
/// `free` и `crossings`, который сам себя и считает шестым.
const CROSSINGS: usize = 6;

/// Программа корпуса, а не строка здесь.
fn source() -> String {
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/golden/programs/extern-c.adamas");
    std::fs::read_to_string(&path)
        .unwrap_or_else(|why| panic!("фикстуры {} нет: {why}", path.display()))
}

/// Чужая сторона: собирается **отдельной единицей трансляции**.
///
/// Отдельной намеренно: в одной с порождённым кодом компилятор увидел бы тело
/// и вправе был бы его развернуть, а свидетель обязан различать поход за
/// границу и посчитанное на месте.
fn probe_object() -> PathBuf {
    let dir = harness::scratch();
    let object = dir.join("foreign-probe.o");
    let source = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/shim/probe.c");
    let built = Command::new(env!("ADAMAS_CC"))
        .args(["-std=c11", "-O1", "-Wall", "-c"])
        .arg(&source)
        .arg("-o")
        .arg(&object)
        .output()
        .unwrap();
    assert!(
        built.status.success(),
        "чужая библиотека не собралась:\n{}",
        String::from_utf8_lossy(&built.stderr)
    );
    object
}

/// Понижение в C доходит до ответа.
#[test]
fn the_c_lowering_calls_the_foreign_symbol() {
    let text = harness::text(&source()).expect("понижение обязано взять чужой вызов");
    let object = probe_object();
    let (stdout, stderr) = harness::built_with(
        "foreign-call",
        &text,
        &[object.to_str().expect("путь объектника не UTF-8")],
    );
    assert_eq!(stdout.trim_end(), ANSWER, "C посчитал не то");
    let (_, live) = harness::blocks("foreign-call", &stderr);
    assert_eq!(live, 0, "прогон оставил блоки живыми");
}

/// Прототип чужого символа печатается **один раз на символ**, а не на вызов.
///
/// `adamas_probe_mix` зовётся дважды; объяви его дважды - и `-Werror` его не
/// поймает (повторное совместимое объявление законно), а свидетель формы
/// поймает.
#[test]
fn a_foreign_symbol_is_declared_once() {
    let text = harness::text(&source()).expect("понижение обязано взять чужой вызов");
    let declared = text
        .lines()
        .filter(|line| line.starts_with("extern ") && line.contains("adamas_probe_mix"))
        .count();
    assert_eq!(declared, 1, "прототип напечатан {declared} раз(а)");
    let mentioned = text.matches("adamas_probe_mix(").count();
    assert_eq!(
        mentioned, 3,
        "упоминаний ожидалось три: прототип и два места вызова"
    );
}

/// Понижение в текстовый `.ll` доходит до ответа - обеими цепочками.
///
/// Минимальная поддерживаемая версия проверяется наравне с текущей: правило
/// консервативного подмножества (`emit_llvm.rs`, шапка) держится прогоном, а
/// не грепом по формам.
#[test]
fn both_llvm_toolchains_call_the_foreign_symbol() {
    let Some((current, minimum)) = harness::llvm_toolchains() else {
        return;
    };
    let mut artefacts =
        harness::llvm_text("foreign-call", &source()).expect("понижение обязано взять чужой вызов");
    // Чужая сторона едет спутником: спутник - **своя** единица трансляции,
    // отдельная от объектника `.ll`, и вызов через неё настоящий.
    artefacts.support.push_str(&shim());
    for (tag, tools) in [("cur", &current), ("min", &minimum)] {
        let (stdout, stderr) = harness::llvm_built(
            &format!("foreign-call-{tag}"),
            &artefacts,
            tools,
            &Pipeline::optimised(),
        );
        assert_eq!(stdout.trim_end(), ANSWER, "{tag}: LLVM посчитал не то");
        let (_, live) = harness::blocks("foreign-call", &stderr);
        assert_eq!(live, 0, "{tag}: прогон оставил блоки живыми");
    }
}

/// Порождённый C ходит за границу ровно шесть раз.
///
/// Свидетели выше поймали бы лишний или потерянный поход **числом** - счёт
/// походов чужая сторона сворачивает в ответ, - но поймали бы его у обоих
/// понижений одинаково и не сказали бы, где он. Здесь число названо прямо и у
/// одной стороны; равенство сторон закрыто тем, что ответ у них один.
#[test]
fn the_generated_c_crosses_the_boundary_six_times() {
    let text = harness::text(&source()).expect("понижение обязано взять чужой вызов");
    let symbols = [
        "adamas_probe_mix(",
        "adamas_probe_alloc(",
        "adamas_probe_read(",
        "adamas_probe_free(",
        "adamas_probe_crossings(",
    ];
    let mentioned: usize = symbols
        .iter()
        .map(|symbol| text.matches(symbol).count())
        .sum();
    // Прототип на символ плюс место на поход: пять и шесть.
    assert_eq!(
        mentioned,
        symbols.len() + CROSSINGS,
        "упоминаний в порождённом C не столько, сколько прототипов и походов"
    );
}

/// Текст чужой стороны: он же собирается отдельным объектником для C-пути.
fn shim() -> String {
    let source = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/shim/probe.c");
    std::fs::read_to_string(&source).expect("исходник чужой библиотеки на месте")
}
