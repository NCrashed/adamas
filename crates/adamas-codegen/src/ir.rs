/// Исходник `.adamas`, к которому относятся позиции функций.
///
/// Пусто у всякой программы, понижённой без исходника, - а таких большинство:
/// корпус понижения зовёт [`lower`](crate::lower::lower), которому текста не
/// дают. Отсюда и `Option` на [`Program::source`]: отладочная информация есть
/// уточнение, а не часть программы.
///
/// Два поля, а не путь одной строкой, потому что DWARF просит их порознь:
/// `!DIFile(filename:, directory:)`. Склей их - и отладчик потерял бы каталог,
/// от которого разрешается относительное имя.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Source {
    /// Имя файла - то, что покажет отладчик.
    pub file: String,
    /// Каталог, относительно которого имя разрешается.
    pub directory: String,
}

