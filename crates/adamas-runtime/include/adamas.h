/* Объекты: аллокация, счётчик, переиспользование                      */
/* ------------------------------------------------------------------ */

/** Объект под `fields` полей. Поля не инициализируются. */
adamas_value adamas_alloc(uint16_t tag, size_t fields);

/** Освобождает объект, детей **не** дропая. */
void adamas_free(adamas_value value);

/** Номер конструктора: у непосредственного - его число, у объекта - тег. */
uint16_t adamas_tag(adamas_value value);

/** Счётчик лишних ссылок. У непосредственного - 0. */
uint32_t adamas_rc(adamas_value value);

/**
 * Переводит достижимое из `value` в разделяемый режим (§5.2): счётчики с этого
 * места считаются атомарно.
 *
 * Симметрично `adamas_drop`: рекурсию и пометку держит рантайм, а какие у
 * объекта дети, знает **тип**, поэтому обход приходит указателем `children`.
 * `NULL` значит «детей нет» - лист графа либо намеренный промоушен одного
 * объекта; `adamas_drop(value, NULL)` читается так же.
 *
 * *Уже разделённый останавливает обход*, и это не оптимизация, а то, чем
 * заканчивается рекурсия на общем подграфе и на цикле. Законна остановка
 * инвариантом «разделяемость транзитивна»: разделён объект - разделено и всё,
 * что из него достижимо. Держится он тем, что поля пишутся при постройке,
 * пока объект ещё локален, а `adamas_reuse` пометку с занятого блока
 * **снимает**. Названная граница - запись в **уже разделённый** объект:
 * ячейка указательного массива (`adamas_array_put`) пишется после постройки, и
 * положенное в разделяемый массив значение этот обход второй раз не увидит.
 * Свидетеля у границы нет: массив разделяемым сегодня не становится нигде.
 *
 * Глубина обхода - глубина графа, и класс этот **не новый**: тем же рискует
 * `adamas_drop`. Замерено, и замер оказался в пользу промоушена: оба вызова
 * здесь хвостовые, gcc их на `-O2` сводит, и список в 2 000 000 звеньев
 * проходится за 6.7 мс не тронув стека, - тогда как дроп того же списка стек
 * укладывает между 260 000 и 280 000 звеньями, потому что после детей ему ещё
 * освобождать блок. Без оптимизации хвостового вызова нет и у промоушена:
 * `-O0` обрывается на 200 000.
 *
 * Идемпотентно. Непосредственное значение игнорируется: счётчика у него нет.
 */
void adamas_share(adamas_value value, adamas_promote children);

/** Разделяемый ли объект. У непосредственного - ложь. */
int adamas_is_shared(adamas_value value);

/** Берёт лишнюю ссылку и возвращает то же значение. */
adamas_value adamas_dup(adamas_value value);

/**
 * Объект без лишних ссылок - блок, который вправе переписать FBIP (§5.1).
 * У непосредственного блока нет, поэтому ответ ложь: переиспользовать нечего.
 */
int adamas_is_unique(adamas_value value);

/** Отдаёт ссылку; на последней зовёт `release` и освобождает блок. */
void adamas_drop(adamas_value value, adamas_release release);

/**
 * Дроп, отдающий блок под переиспользование (§5.1). На последней ссылке зовёт
 * `release`, но блок **не** освобождает, а возвращает; иначе `NULL`.
 * Вставляет это Perceus; рантайм обязан предоставить точку входа.
 */
adamas_value adamas_drop_reuse(adamas_value value, adamas_release release);

/**
 * Занимает блок из `adamas_drop_reuse` под конструктор `tag`. `NULL` - значит
 * блока не досталось, и объект аллоцируется. Размер блока совпадает по
 * построению: reuse требует совпадения формы конструкторов (§5.1).
 */
adamas_value adamas_reuse(adamas_value block, uint16_t tag, size_t fields);

/** Поле объекта. */
adamas_value adamas_field(adamas_value value, size_t index);

/** Записывает поле объекта, владение переходит объекту. */
void adamas_set_field(adamas_value value, size_t index, adamas_value field);

