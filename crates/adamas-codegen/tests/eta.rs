//! Определение, свёрнутое по эте: арность берётся у типа (§10 вопрос 153).
//!
//! `instance Add Int64 where add = addInt64` и `1 + 2` - то, что §4.11 называет
//! обычным читаемым кодом, - до этого среза в C не шли вовсе. Причина не в
//! классах: определение приходит **свёрнутым по эте**, а понижение брало арность
//! у тела. Ноль ведущих лямбд значил нулевую C-арность, аргументы уходили
//! применением к значению - через границу замыкания, где плоскому места нет.
//!
//! Источников эта-свёртки **три**, и все измерены, а не предположены.
//!
//! - Мономорфизация: `add@_,Add#Int64` имеет тип `Int64 -> Int64 -> Int64` и
//!   тело `Const("Add#Int64.add")`.
//! - Написанное от руки целиком: `again = plus`.
//! - Написанное от руки частично: `half x = plus x` - лямбда одна, стрелок две.
//!
//! Отсюда и выбор: запретить эта-свёртку мономорфизации (вариант (в) вопроса
//! 153) закрыло бы один источник из трёх. Арность берётся у типа, недостающие
//! связывания достраиваются понижением и дописываются к спайну тела.
//!
//! Отказ `arithmetic_through_a_class_is_refused_by_name` переехал сюда из
//! `flat.rs` проходящим: [`a_class_method_written_by_eta_lowers_flat`]. Отказ на
//! этом месте остался, но на другой форме и по другой причине -
//! [`a_branch_that_answers_a_flat_function_is_refused_by_name`].

mod harness;

/// Сколько блоков выдал прогон. Ответ по дороге сверяется с `adamas eval`.
fn allocated(name: &str, source: &str) -> usize {
    let stderr = harness::agreed(name, source).unwrap_or_else(|error| panic!("{name}: {error}"));
    let (allocated, live) = harness::blocks(name, &stderr);
    assert_eq!(live, 0, "{name}: прогон оставил блоки живыми");
    allocated
}

/// Метод инстанса, написанный ровно так, как его пишет §4.11.
///
/// Два класса, а не один: производное определение заводится на каждый метод, и
/// одним классом не отличить «взяли свой» от «взяли первый попавшийся».
///
/// Инстансы написаны **по-разному** нарочно. `add = addInt64` - форма из §4.11,
/// и свёрнута она дважды: `add@_,Add#Int64` отдаёт `Add#Int64.add`, а тот -
/// сам примитив. Два слоя достроенных параметров у порядка сокращаются
/// (измерено мутантом «дописывать в обратном порядке»: на двух слоях он
/// выживает), поэтому порядок показывает `sub`, свёрнутый **однажды**: у
/// `Sub#Int64.sub` лямбды написаны, достраивается только производное имя.
/// Вычитание не коммутативно, и переставь достроенные, ответ станет `-14`
/// вместо `14`.
const BY_ETA: &str = "\
type Int = Int64

class Add a where
  add : a -> a -> a

class Sub a where
  sub : a -> a -> a

instance Add Int64 where
  add = addInt64

instance Sub Int64 where
  sub x y = subInt64 x y

main : Int
main = sub (add 20 3) (add 5 4)
";

/// Арифметика через класс идёт плоским путём: ноль ячеек кучи.
///
/// Ноль здесь говорит ровно то, ради чего вопрос 153 стоял: аргументы дошли до
/// операции **прямым вызовом**, а не через замыкание. Прошлое понижение на этой
/// программе не выдавало ячеек тоже - оно её отвергало; сегодня она считается, и
/// цена у неё та же, что у арифметики без класса (`flat.rs`,
/// `arithmetic_costs_no_cell`).
#[test]
fn a_class_method_written_by_eta_lowers_flat() {
    assert_eq!(
        allocated("метод-эта", BY_ETA),
        0,
        "арифметика через класс поехала через замыкание: у плоского значения \
         заголовка нет (§4.11)"
    );
}

/// Тот же класс над указательным типом: считает то же, а платит ячейками.
///
/// Без этого соседа ноль выше не говорил бы ничего: программа, ничего не
/// делающая, тоже выдаёт ноль. Форма у обоих одна - метод, свёрнутый по эте,
/// позванный дважды, - разошлись они представлением.
const BY_ETA_BOXED: &str = "\
data Nat where
  Zero : Nat
  Succ : Nat -> Nat

bump : Nat -> Nat
bump n = Succ n

class Wrap a where
  wrap : a -> a

instance Wrap Nat where
  wrap = bump

main : Nat
main = wrap (wrap (Succ Zero))
";

/// Указательный путь через тот же класс стоит ячейку на `Succ`.
///
/// Три, а не «больше нуля»: ответ есть `Succ (Succ (Succ Zero))`, `Zero`
/// непосредствен и блока не занимает, а каждый `Succ` - объект кучи.
#[test]
fn the_same_shape_over_a_boxed_type_pays_cells() {
    assert_eq!(
        allocated("метод-эта-указательный", BY_ETA_BOXED),
        3,
        "указательный метод обошёлся не в ячейку на `Succ`: счётчик считает не то"
    );
}

/// `1 + 2` через операторный класс, литерал - умолчанием по имени (§4.3).
///
/// Тип литерала здесь не написан нигде: `Int` есть прелюдный синоним, и решает
/// его умолчание по имени (лог 2026-09-09). Ответ различает значение, а не
/// только компиляцию: вычитание не коммутативно, и `(1 + 2) - 10` есть `-7`,
/// тогда как `10 - (1 + 2)` есть `7`.
const OPERATOR: &str = "\
type Int = Int64

class Ring a where
  plus : a -> a -> a
  minus : a -> a -> a

instance Ring Int64 where
  plus = addInt64
  minus = subInt64

infixl 6 +
(+) : {Ring a} => a -> a -> a
(+) x y = plus x y

infixl 6 -
(-) : {Ring a} => a -> a -> a
(-) x y = minus x y

main : Int
main = 1 + 2 - 10
";

/// Оператор поверх класса идёт тем же плоским путём.
#[test]
fn an_operator_over_a_class_lowers_flat() {
    assert_eq!(
        allocated("оператор-класса", OPERATOR),
        0,
        "`1 + 2` через класс поехало через замыкание (§4.11)"
    );
}

/// Эта-свёртка, написанная руками: целиком и частично.
///
/// Мономорфизация тут ни при чём - оба определения написаны как есть. `again`
/// свёрнуто целиком (ноль лямбд при двух стрелках), `half` частично (одна
/// лямбда при двух). Второе - тот самый случай, где эта-развёртка терма
/// потребовала бы сдвига де Брёйна; здесь сдвига нет, потому что снятая лямбда
/// остаётся в среде на своём месте, а достроенная в среду не попадает вовсе.
///
/// Вычитание снова не коммутативно: попади `x` не на своё место, ответ станет
/// `0` вместо `17`.
const BY_HAND: &str = "\
gap : Int64 -> Int64 -> Int64
gap x y = subInt64 x y

again : Int64 -> Int64 -> Int64
again = gap

half : Int64 -> Int64 -> Int64
half x = again x

main : Int64
main = half 20 3
";

/// Свёрнутое руками понижается наравне со свёрнутым мономорфизацией.
#[test]
fn an_eta_collapsed_definition_written_by_hand_lowers_flat() {
    assert_eq!(allocated("эта-руками", BY_HAND), 0);
}

/// Стёртое связывание среди достроенных.
///
/// Стёртый параметр в рантайме не существует (§3.3), и достроенный - тоже:
/// достраивается **факт** типа, а кратность у него оттуда же. Считай
/// достроенные наличными поголовно - и `again` позвала бы `pick` с лишним
/// аргументом на первой позиции.
const ERASED: &str = "\
data Nat where
  Zero : Nat
  Succ : Nat -> Nat

pick : (0 a : Type) -> a -> a -> a
pick a x y = x

again : (0 a : Type) -> a -> a -> a
again = pick

main : Nat
main = again Nat (Succ Zero) Zero
";

/// Достроенное стёртое связывание остаётся стёртым.
#[test]
fn an_erased_binder_among_the_supplied_stays_erased() {
    // Ответ `Succ Zero` стоит ячейку: `Zero` непосредствен, `Succ` - объект.
    assert_eq!(allocated("стёртый-достроенный", ERASED), 1);
}

/// Тело, спайном не являющееся: разбор, чья ветвь отдаёт функцию.
///
/// Дописать достроенный параметр можно спайну - у него голова имя, и лишний
/// аргумент делает вызов насыщенным. У разбора головы нет: параметры
/// применяются к его значению, то есть через границу замыкания, а плоскому там
/// места нет (§4.11). Граница та же, что у `flat.rs`
/// (`a_flat_value_does_not_cross_a_closure`), и снимет её дескриптор layout -
/// трек 3б, а не этот.
const BRANCHED: &str = "\
data Bool where
  True : Bool
  False : Bool

plus : Int64 -> Int64 -> Int64
plus x y = addInt64 x y

gap : Int64 -> Int64 -> Int64
gap x y = subInt64 x y

pick : Bool -> Int64 -> Int64 -> Int64
pick True = plus
pick False = gap

main : Int64
main = pick True 5 3
";

/// Ветвь, отдающая плоскую функцию, отвергается названной причиной.
#[test]
fn a_branch_that_answers_a_flat_function_is_refused_by_name() {
    let error = harness::compiled(BRANCHED).expect_err("плоское через ветвь не проходит");
    let text = error.to_string();
    assert!(
        text.contains("§4.11"),
        "отказ не назвал причину представлением: {text}"
    );
}

/// Ближайший проходящий сосед: та же ветвь над указательным типом.
///
/// Разошлись они одним - представлением поля. Значит отвергнуто представление, а
/// не форма «ветвь отдаёт функцию».
const BRANCHED_BOXED: &str = "\
data Bool where
  True : Bool
  False : Bool

data Nat where
  Zero : Nat
  Succ : Nat -> Nat

first : Nat -> Nat -> Nat
first x y = x

second : Nat -> Nat -> Nat
second x y = y

pick : Bool -> Nat -> Nat -> Nat
pick True = first
pick False = second

main : Nat
main = pick True (Succ Zero) Zero
";

/// Та же ветвь над указательным типом проходит.
#[test]
fn the_same_branch_over_a_boxed_type_passes() {
    // Ячейки: два `Succ Zero` в аргументах плюс замыкание, которым ветвь
    // отдаёт функцию, - у указательного пути она есть, и в этом всё различие.
    assert_eq!(allocated("ветвь-указательная", BRANCHED_BOXED), 3);
}
