/// сводится, и `simdLane` остаётся застрявшим спайном. Сходятся все трое в том,
/// что **ответа не даёт никто** - та же форма границы, что у выхода за длину
/// массива (§4.11).
pub const LANE_OUTSIDE: &str = "номер дорожки вне ширины вектора";

/// Текст обрыва по нулевому делителю (§4.3, трек A волны 4 Фазы 7).
///
/// Константа одна на два эмиттера по той же причине, что [`LANE_OUTSIDE`], и
/// с той же третьей стороной: машина обрыва не печатает - целое деление на
/// ноль у неё не сводится, - и сходятся все трое в том, что ответа не даёт
/// никто.
///
/// Плавающего это не касается: `1.0 / 0.0` есть `inf`, наблюдаемое значение
/// `Approximate` §4.3, и обрыва там нет ни у одного вычислителя.
///
/// C-сторона держит тот же текст в `flat.c`, потому что проверка стоит внутри
/// `adamas_div_*`; совпадение сверяется тестом
/// (`emit_c::tests::the_division_message_matches_the_helpers`), а не
/// обещанием.
pub const DIVISION_BY_ZERO: &str = "деление на ноль";

/// Ширина элемента плоского массива - шаг индексации `base + i * stride`.
///
/// Два случая - ровно те два, которые §4.11 называет режимами сборки.
/// Мономорфизованный код знает тип элемента и получает константу; обобщённый
/// над `{Flat a}` получает **дескриптор обычным имплиситом** и индексирует с
/// рантайм-шагом. Специализация (`adamas_elab::mono`) переводит второе в
/// первое, и оба обязаны давать один ответ.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Stride {
    /// Тип элемента известен: шаг - константа.
    Static(PrimTy),
    /// Элемент - плоский агрегат (§4.11): шаг - его размер, тоже константа.
    Packed(PackId),
    /// Шаг приходит дескриптором layout, лежащим в этом связывании.
    Dynamic(LocalId),
}

impl Stride {
    /// Представление прочитанного элемента.
    ///
    /// У константного шага тип элемента известен, у рантаймового - нет, и
    /// значение остаётся [`Repr::Opaque`]: байты есть, имени у них нет.
    #[must_use]
    pub const fn element(self) -> Repr {
        match self {
            Self::Static(ty) => Repr::Flat(ty),
            Self::Packed(pack) => Repr::Packed(pack),
            Self::Dynamic(_) => Repr::Opaque,
        }
    }
}

/// Как значение выглядит в рантайме (§4.11).
///
/// Различие это - **ABI, а не оптимизация** (§13, 2026-09-08): «`Flat`
/// заголовка не имеет, и это не исключение, а граница правила: заголовок
/// принадлежит объекту кучи Perceus, а плоское значение лежит по значению
/// внутри чужого объекта, массива или регистра».
///
/// Отсюда три следствия, и каждое наблюдаемо прогоном. Арифметика не выдаёт ни
/// одной ячейки кучи. RC по плоскому не идёт вовсе - счётчика у него нет, и
/// [`Expr::Dup`] с [`Expr::Drop`] по нему не эмитятся. А дроп и печать объекта
/// обязаны знать, какие его слоты плоские: слот с битами числа, принятый за
/// указатель, - это чтение по адресу `42`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Repr {
    /// Объект кучи Perceus с заголовком либо непосредственное значение.
    Boxed,
    /// Плоское значение примитивного типа: заголовка нет, счётчика нет.
    Flat(PrimTy),
    /// Вектор (§4.9): `lanes` дорожек типа `lane`, лежащих подряд.
    ///
    /// Плоское значение того же разряда, что [`Self::Flat`]: заголовка нет,
    /// счётчика нет, живёт в регистре. Отдельное имя ему нужно потому, что
    /// эмиттер обязан напечатать **векторный тип** - `<8 x float>` у LLVM,
    /// `__attribute__((vector_size))` у C, - а не восемь скаляров: ради этого
    /// §4.9 и писался, и поэлементный цикл под видом вектора дал бы тот же
    /// ответ, ничего не доказав.
    ///
    /// Ширина хранится числом, а не типом: у `Simd n a` она есть свойство
    /// написанного типа, приезжающее сюда **понижением**, и эмиттер ядра при
    /// этом не читает (шов, `tests/seam.rs`).
    Simd {
        /// Сколько дорожек.
        lanes: u32,
        /// Какого типа каждая.
        lane: PrimTy,
    },
    /// Плоский агрегат (§4.11): поля подряд по [`Packing`], заголовка нет.
    ///
    /// Живёт там же, где прочее плоское, - в регистре и внутри чужой укладки, -
    /// и наружу, за границу замыкания, не выходит по той же причине: слот
    /// замыкания единообразен, а агрегат занимает свои байты.
    Packed(PackId),
    /// Дескриптор укладки (§4.11): размер и выравнивание значением.
    ///
    /// Словарь `Flat a` в рантайме есть ровно это - у класса единственный
    /// метод, и метод этот `layout`. Поэтому связывание словарного типа
    /// получает своё представление, а не общий путь записей, которого у
    /// понижения нет вовсе.
    Layout,
    /// Плоский элемент, чей тип неизвестен: ширина приходит дескриптором.
    ///
    /// Живёт **внутри одного кадра** и наружу не выходит: вынести его значило
    /// бы боксировать (§5.1), а боксирование этим срезом не берётся. Понижение
    /// отвергает его в параметре, в ответе, в захвате и в поле конструктора.
    Opaque,
    /// Массив (§4.11): один объект кучи Perceus на весь массив.
    Array(Elems),
    /// Блок региона (§3.6): одна область на любое число значений в ней.
    ///
    /// Объект кучи Perceus, как массив, и по той же причине: заголовок нужен,
    /// чтобы дроп освободил область **разом** - «освобождение одно на всю
    /// область». Нагрузка внутри плоская по построению (`{Flat a}`), поэтому
    /// детей у блока нет вовсе, и release его пуст.
    Region,
    /// Запись (§4.2): объект кучи Perceus, слот на поле.
    ///
    /// Тег назван, потому что проекция обязана знать **номер слота**, а имени
    /// поля в рантайме нет: слоты раздаёт форма записи, и форма эта - тот же
    /// [`Constructor`], что у конструктора семейства, только с метками
    /// ([`Constructor::labels`]).
    ///
    /// Различаются формы по меткам и по представлениям полей, поэтому
    /// `{ x : Int64 }` и `{ x : Nat }` - разные теги: слот у первого несёт
    /// биты, у второго ссылку, и спутать их значило бы прочесть число
    /// указателем.
    Record(CtorId),
    /// Резумпция общей ветки: ручка приостановленного сегмента (§3.4).
    ///
    /// Объект кучи со своим заголовком, как всё прочее указательное, и потому
    /// живёт в слоте замыкания наравне с ними: `\s -> resume v s`
    /// параметризованного хендлера держит её средой (§10 вопрос 129). Отдельное
    /// имя ей нужно **дропу**: отдать резумпцию значит раскрутить её сегмент, а
    /// раскрутке нужна ручка стека, которой у `adamas_release` нет. Отсюда две
    /// точки дропа рантайма и одно различие здесь.
    Resumption,
}

impl Repr {
    /// Примитивный тип плоского значения. `None` - всё прочее.
    #[must_use]
    pub const fn primitive(self) -> Option<PrimTy> {
        match self {
            Self::Flat(ty) => Some(ty),
            Self::Boxed
            | Self::Simd { .. }
            | Self::Packed(_)
            | Self::Layout
            | Self::Opaque
            | Self::Array(_)
            | Self::Region
            | Self::Record(_)
            | Self::Resumption => None,
        }
    }

    /// Ширина и дорожка вектора (§4.9). `None` - всё прочее.
    #[must_use]
    pub const fn vector(self) -> Option<(u32, PrimTy)> {
        match self {
            Self::Simd { lanes, lane } => Some((lanes, lane)),
            _ => None,
        }
    }

    /// Указательное ли представление общего вида.
    ///
    /// Массив сюда **не** входит, хотя в рантайме он тоже указатель: позиция,
    /// объявленная `Boxed`, приходит от границы замыкания и от трамплина, а те
    /// не различают, что за объект за указателем. Сверка представлений на этих
    /// границах поэтому строгая.
    #[must_use]
    pub const fn boxed(self) -> bool {
        matches!(self, Self::Boxed)
    }

    /// Живёт ли значение указателем на объект Perceus.
    ///
    /// Шире [`Repr::boxed`] ровно на запись и резумпцию: у них тот же
    /// заголовок, тот же счётчик и тот же C-тип, и отличаются они только тем,
    /// что понижение помнит - форму у одной, способ дропа у другой. Поэтому обе
    /// годятся всюду, где объявлен указатель: слот замыкания и кадра; форма при
    /// этом теряется, и проекция после такой потери отвергается.
    #[must_use]
    pub const fn pointer(self) -> bool {
        matches!(self, Self::Boxed | Self::Record(_) | Self::Resumption)
    }

    /// Есть ли у значения заголовок со счётчиком - то есть считает ли его RC.
    ///
    /// Спрашивают это Perceus и таблица сортов слотов: массив считается
    /// наравне с объектом, потому что заголовок у него ровно один на весь
    /// массив (§5.1, «плоские массивы вне поэлементного RC»).
    #[must_use]
    pub const fn counted(self) -> bool {
        matches!(
            self,
            Self::Boxed | Self::Array(_) | Self::Region | Self::Record(_) | Self::Resumption
        )
    }
}

/// Что тайпчекер знает о связывании.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Fact {
    /// Кратность из ядра.
    pub mult: Mult,
    /// Уникальность производства (§10 вопрос 149) - см. [`Unique`].
    pub unique: Unique,
    /// Регион, которому принадлежит значение (§3.6). Всегда `None`.
    pub region: Option<RegionId>,
    /// Есть ли у связывания значение в рантайме.
    ///
    /// Стёртое (`0`) в C не эмитится вовсе, но в IR присутствует: это факт, и
    /// он нужен LLVM-эмиттеру наравне с прочими.
    pub present: bool,
    /// Плоское значение или указательное (§4.11).
    pub repr: Repr,
}

impl Fact {
    /// Факт о связывании объявленной кратности.
    ///
    /// Наличие берётся из неё же - так решает и машина, когда стирает аргумент
    /// глобального имени. [`Unique`] из кратности не заполняется вовсе (§10
    /// вопрос 149): прежнее `Certain` по `1` было ложью, которую никто не
    /// читал, но которую один раз уже прочитал план - как гарантию.
    #[must_use]
    pub fn declared(mult: Mult) -> Self {
        Self {
            mult,
            unique: Unique::Unknown,
            region: None,
            present: mult != Mult::Zero,
            repr: Repr::Boxed,
        }
    }

    /// Тот же факт с названным представлением (§4.11).
    #[must_use]
    pub const fn shaped(self, repr: Repr) -> Self {
        Self { repr, ..self }
    }

    /// Факт о связывании, значение которого в рантайме есть при любой кратности.
    ///
    /// Таковы связывания лямбды и `let`: машина их вычисляет, не спрашивая
    /// кратности, и кратность здесь - факт о **использовании**, а не о наличии.
    #[must_use]
    pub fn present(mult: Mult) -> Self {
        Self {
            present: true,
            ..Self::declared(mult)
        }
    }

    /// Факт о связывании, заведённом бэкендом.
    ///
    /// В ядре такого связывания нет вовсе - его завела вставка RC
    /// ([`crate::perceus`]), чтобы было что отдать после вызова, - поэтому
    /// кратности у него нет. Значение есть.
    #[must_use]
    pub fn opaque() -> Self {
        Self::present(Mult::Many)
    }
}

/// Связывание: имя для читаемости, номер для ссылок, факты для бэкенда.
#[derive(Clone, Debug)]
pub struct Binding {
    /// Имя из исходника. На семантику не влияет, идёт в комментарий.
    pub name: String,
    /// Номер, которым на связывание ссылается [`Expr::Local`].
    pub local: LocalId,
    /// Что о нём известно.
    pub fact: Fact,
}

/// Конструктор индуктивного типа - либо форма записи (§4.2).
///
/// Форма записи стоит здесь, а не отдельной таблицей, потому что в рантайме
/// это тот же объект: заголовок с тегом, слоты по полям. Дроп и печать читают
/// одну таблицу по тегу, и вторая означала бы второй такой обход.
#[derive(Clone, Debug)]
pub struct Constructor {
    /// Тег в заголовке объекта.
    pub tag: CtorId,
    /// Имя: его печатает ответ программы.
    pub name: String,
    /// Семейство, которому конструктор принадлежит.
    pub data: String,
    /// Факты о **всех** связываниях: сперва параметры семейства, потом поля.
    ///
    /// Стёртые здесь есть, и это то самое место, где IR богаче C: в объекте
    /// рантайма их нет, а в IR они лежат со своей кратностью.
    pub binders: Vec<Fact>,
    /// Сколько первых связываний - параметры семейства. Ветвь их не связывает.
    pub params: u32,
    /// Метки записи по связываниям. `None` - конструктор семейства.
    ///
    /// Порядок тот же, что у [`Self::binders`], и он же порядок печати:
    /// `adamas eval` печатает поля **как написаны** (§4.2), и разойдись здесь
    /// порядок - разошлись бы и две печати.
    pub labels: Option<Vec<String>>,
}

impl Constructor {
    /// Слот в объекте рантайма, если связывание до него доживает.
    #[must_use]
    pub fn slot(&self, binder: usize) -> Option<u32> {
        if !self.binders.get(binder)?.present {
            return None;
        }
        let live = self.binders[..binder]
            .iter()
            .filter(|fact| fact.present)
            .count();
        u32::try_from(live).ok()
    }

    /// Слот поля с такой меткой. `None` - метки нет либо поле стёрто.
    ///
    /// Параметров у формы записи нет вовсе, поэтому номер связывания и есть
    /// позиция метки.
    #[must_use]
    pub fn labelled(&self, label: &str) -> Option<u32> {
        let at = self.labels.as_ref()?.iter().position(|it| it == label)?;
        self.slot(at)
    }

    /// Сколько полей у объекта рантайма.
    #[must_use]
    pub fn slots(&self) -> usize {
        self.binders.iter().filter(|fact| fact.present).count()
    }

    /// Представление каждого слота в порядке слотов.
    ///
    /// Спрашивают его дроп и печать: слот с битами числа заголовка не имеет, и
    /// принять его за указатель значило бы читать по адресу этого числа.
    pub fn slot_reprs(&self) -> impl Iterator<Item = Repr> + '_ {
        self.binders
            .iter()
            .filter(|fact| fact.present)
            .map(|fact| fact.repr)
    }
}

/// Форма понижения (§13, записи 2026-09-08 про ABI).
///
/// Различает их **row написанного типа** (`lower::form`): меток нет - первая,
/// есть - вторая. Это не трёхзначный вердикт §3.4, у которого §5.1 насчитал
/// трёх потребителей, - вердикта нет по-прежнему, и `adamas-core/src/alloc.rs`
/// называет его отсутствие прямо. Row грубее: функция под заведомо
/// хвостово-резумптивной меткой получает вторую форму и платит за кадр, хотя
/// вердикт оставил бы её в первой. Цена названная, и снимет её §10 вопрос 74 -
/// тоньше row не различить, пока хендлер не виден в точке вызова.
///
/// Форма лежит **на функции**, а не угадывается эмиттером: от неё зависит
/// сигнатура, и угадывать её на месте вызова значило бы угадывать дважды.
///
/// Лямбда получает вторую форму **всегда**, и это не послабление правила, а
/// его единственное применение к случаю без написанного типа: у связывания
/// лямбды типа в ядре нет вовсе. Стоит это ноль - прямого вызова у лямбды не
/// бывает, зовут её через `adamas_apply`, а граница замыкания несёт оба
/// скрытых аргумента при любой форме (`adamas.h`, `adamas_code`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Form {
    /// Первая: обычная C-функция, кадр на C-стеке.
    ///
    /// Скрытых аргументов нет **вовсе** - написанное и есть всё. Отчуждать
    /// кадр она не умеет, хендлера не ищет и потому не платит ни за что.
    Stack,
    /// Вторая: кадр отчуждается в кучу.
    ///
    /// Скрытых аргумента два - вектор evidence и ручка стека продолжения рядом
    /// с ним: стек нужен, чтобы отчуждать кадр, резать сегмент и обрываться,
    /// вектор - чтобы находить хендлер. Сигнатуру им задаёт
    /// `adamas_lowered_second`, и порядок в ней тот же.
    ///
    /// Тело её **дроблено кадрами** по точкам приостановки (решение 3 волны
    /// 4): кадр стоит на вызове второй формы, на операции и на возобновлении,
    /// максимальный чистый отрезок между ними бежит обычным C. Отсюда договор
    /// возврата: такая функция возвращает не свой ответ, а значение, которое
    /// трамплин обязан отдать вершине стека.
    Detached,
}

/// Метка эффекта: имя для читаемости, операции - для номеров и отказов.
#[derive(Clone, Debug)]
pub struct Label {
    /// Имя метки из исходника.
    pub name: String,
    /// Операции в порядке объявления - он же порядок веток хендлера (§3.4).
    pub operations: Vec<String>,
}

/// Вердикт ветки: три значения §3.4, считанные по написанному телу.
///
/// Считает их понижение на месте `handle` (решение 2 волны 4), а не анализ по
/// графу: свойство это принадлежит написанной ветке.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Verdict {
    /// Хвостово-резумптивная: `resume` стоит в хвосте и снят.
    ///
    /// Ответ ветки и есть значение операции, сегмент цел, продолжение остаётся
    /// на стеке кадров нетронутым.
    Tail,
    /// Абортивная: `resume` не зовётся ни разу.
    ///
    /// Ответ ветки есть ответ **хендлера**: сегмент до его кадра срезается и
    /// раскручивается, деструкторы бегут LIFO.
    Abortive,
    /// Общая: `resume` зовётся, но не в хвосте.
    ///
    /// Сегмент режется в **значение** и уходит ветке лишним аргументом; она
    /// вправе возобновить его ([`Expr::Resume`]) либо дропнуть - тогда
    /// раскрутка идёт от дропа.
    General,
}

/// Ветка хендлера: своя функция, вердикт и сколько аргументов она связывает.
///
/// Связывает она **не всё**, что операция принимает: параметры метки ветке не
/// достаются, а синтезированный триггер приостановленного вычисления - тем
/// более (§3.4). Число это - у типа элиминатора, и оно же говорит ветке,
/// сколько пришедших аргументов дропнуть.
#[derive(Clone, Debug)]
pub struct Branch {
    /// Функция ветки.
    pub function: FuncId,
    /// Сколько аргументов операции она связывает.
    pub written: usize,
    /// Каким вышел вердикт (§3.4).
    ///
    /// У [`Verdict::General`] функция ветки принимает лишний параметр -
    /// резумпцию; у прочих двух его нет.
    pub verdict: Verdict,
}

/// Площадка `handle`: один кадр `HANDLER` в рантайме (§13, 2026-09-08).
///
/// Ветки - **статические функции со средой кадра** (решение 5 волны 4), а не
/// замыкания: формы их известны месту `handle`. Среда у всех одна - объединение
/// свободных переменных веток, - потому что лежит она в кадре, и второй кадр
/// ради экономии слота стоил бы дороже слота.
#[derive(Clone, Debug)]
pub struct Handler {
    /// Метка, которую площадка снимает.
    pub label: LabelId,
    /// Мультишотная ли: `#handleMulti.L` против `#handle.L` (§3.4).
    ///
    /// Различает она одно - судьбу сегмента при возобновлении: у мультишотной
    /// ручка помечается `ADAMAS_FLAG_MULTI`, и `resume` ставит **копию**, пока
    /// на ручку есть лишние ссылки. Вердикт всех её веток [`Verdict::General`]:
    /// сколько раз ω-резумпцию позовут, написанному телу не видно.
    pub multi: bool,
    /// Захваченная среда веток: её слоты лежат в кадре.
    pub captured: Vec<Binding>,
    /// Ветки в порядке операций метки.
    pub branches: Vec<Branch>,
    /// Ветка `return`: одноместная, ей идёт значение вычисления.
    pub returned: FuncId,
}

/// Функция программы.
#[derive(Clone, Debug)]
pub struct Function {
    /// Собственный номер.
    pub id: FuncId,
    /// Имя из исходника либо описание происхождения.
    pub name: String,
    /// Где определение написано - строка и колонка в `.adamas`.
    ///
    /// `None` у всего, за чем написанного определения нет: у функции,
    /// заведённой самим бэкендом (ветка хендлера, кусок дроблёного тела), и у
    /// всякой функции, когда понижение шло без исходника.
    ///
    /// Позиция стоит **на функции**, а не на связывании и не на узле, и это
    /// сегодняшний потолок цепочки, а не выбор: спанов в ядре нет вовсе, и
    /// самое мелкое, что доезжает сюда, - место определения целиком (§9 Фаза 7,
    /// трек E). Отсюда одна строка на всё тело: шаг отладчика идёт между
    /// функциями, а не между выражениями внутри.
    pub position: Option<Location>,
    /// Как понижается (§3.4, трёхзначный вердикт).
    pub form: Form,
    /// Захваченная среда. Пусто у определения верхнего уровня.
    pub captured: Vec<Binding>,
    /// Параметры.
    pub parameters: Vec<Binding>,
    /// Представление ответа: плоский ответ уходит в регистре, а не объектом.
    pub result: Repr,
    /// Тело.
    pub body: Expr,
}

impl Function {
    /// Параметры, доживающие до рантайма.
    pub fn live_parameters(&self) -> impl Iterator<Item = &Binding> {
        self.parameters.iter().filter(|it| it.fact.present)
    }

    /// Захваченное, доживающее до рантайма.
    pub fn live_captured(&self) -> impl Iterator<Item = &Binding> {
        self.captured.iter().filter(|it| it.fact.present)
    }
}

/// Ветвь разбора.
#[derive(Clone, Debug)]
pub struct Arm {
    /// Конструктор, который она разбирает.
    pub constructor: CtorId,
    /// Связывания полей - по одному на связывание конструктора после
    /// параметров, включая стёртые.
    pub fields: Vec<Binding>,
    /// Тело ветви.
    pub body: Expr,
}

/// Поля разобранного, чью судьбу берёт на себя дроп его самого (§5.1).
///
/// Пусто у всякого дропа, кроме одного места - дропа разобранного в ветви
/// ([`crate::perceus`]). Там `dup` поля и дроп родителя взаимно сокращаются на
/// **уникальном** родителе: дроп обходит поля и возвращает ровно те ссылки,
/// которые ветвь только что взяла. Схлопывание требует различить два случая, и
/// различаются они в рантайме (`rc == 0`) - той же уникальностью, на которой
/// стоит reuse, и по той же причине: из кратности она не следует (§10 вопрос
/// 149).
///
/// Отсюда два списка, и оба нужны. `taken` - поля, которые ветвь называет: на
/// уникальном родителе они достаются ей даром, на разделённом берутся `dup`'ом.
/// `spare` - поля, которые она не называет: на уникальном родителе их дропает
/// сам дроп, потому что освобождение блока детей не трогает, а на разделённом
/// их держит переживший родитель.
///
/// Узла под это не заведено намеренно, и цена узла тут считана обходами, а не
/// строками. Различить схлопнутый дроп от обычного обязана **одна** печать
/// ([`crate::emit_c`]); прочесть списки полей обязаны ещё два обхода - те, что
/// собирают названные связывания в [`crate::perceus`] и [`crate::split`].
/// Остальные полтора десятка ходят сквозь [`Expr::Drop`] по телу и о полях не
/// спрашивают вовсе. Своим узлом его пришлось бы назвать каждому.
#[derive(Clone, Debug, Default)]
pub struct Salvage {
    /// Поля, названные ветвью: ссылка на них берётся только у разделённого.
    pub taken: Vec<LocalId>,
    /// Поля, ветвью не названные: у уникального их дропает этот же дроп.
    pub spare: Vec<LocalId>,
}

impl Salvage {
    /// Схлопывается ли пара. Пустой `taken` значит «дроп обычный».
    #[must_use]
    pub fn collapses(&self) -> bool {
        !self.taken.is_empty()
    }

    /// Связывания, которые дроп называет сверх самого разобранного.
    pub fn locals(&self) -> impl Iterator<Item = LocalId> + '_ {
        self.taken.iter().chain(&self.spare).copied()
    }
}

/// Выражение IR.
///
/// Дерево, а не последовательность: `Bind` и `Match` задают порядок сами, а
/// линеаризация - работа эмиттера. Узлов ровно столько, сколько требует чистый
/// фрагмент, плюс пять эффектных - [`Expr::Handle`], [`Expr::Perform`],
/// [`Expr::Closing`], [`Expr::Resume`] и [`Expr::Mask`]. Хвостовая резумпция
/// среди них не значится: её снимает понижение на месте `handle`, и узла ей не
/// нужно.
#[derive(Clone, Debug)]
pub enum Expr {
    /// Значение локального связывания.
    Local(LocalId),
    /// Значения нет: позиция стёрта (§3.3).
    Erased,
    /// Плоский литерал: биты, обрезанные по ширине типа (§4.3).
    ///
    /// Биты, а не число: `Float32` и `Int64` тем самым доезжают до эмиттера
    /// побитово, и записать литерал в C нечем испортить - ни разбором текста, ни
    /// двойным округлением.
    Literal {
        /// Какого типа.
        ty: PrimTy,
        /// Его биты.
        bits: u64,
    },
    /// Дескриптор укладки значением (§4.11).
    ///
    /// Константа: словарь `Flat τ` порождает компилятор по представлению
    /// `τ`, и место вызова знает его целиком. Рантаймовым он становится
    /// **внутри** обобщённой функции, где приходит параметром.
    Layout {
        /// Сколько байт занимает значение.
        size: u32,
        /// По какой границе стоит.
        align: u32,
    },
    /// Плоский агрегат, собранный из полей (§4.11).
    ///
    /// Ячейки кучи не занимает: байты лежат на кадре, поле встаёт по своему
    /// смещению из [`Packing`]. У теговой укладки первым пишется тег - номером
    /// варианта, шириной [`Packing::tag`].
    Pack {
        /// По какой укладке.
        packing: PackId,
        /// Который вариант; он же значение тега.
        variant: u32,
        /// Значения полей в порядке [`Variant::labels`].
        fields: Vec<Expr>,
    },
    /// Поле плоского агрегата: чтение по смещению, а не по слоту.
    ///
    /// Вариант назван статически: читающий его знает - проекция читает
    /// запись, ветвь разбора стоит под своим конструктором, - а тег сверять
    /// здесь нечем и незачем.
    Unpack {
        /// По какой укладке.
        packing: PackId,
        /// Который вариант.
        variant: u32,
        /// Номер поля в [`Variant::slots`].
        field: u32,
        /// Откуда.
        value: Box<Expr>,
    },
    /// Число из дескриптора укладки: размер либо выравнивание (§4.11).
    ///
    /// Заводится проекцией метода `Flat`: словарь его живёт дескриптором, а не
    /// объектом кучи, поэтому `dict.layout` собирает запись из двух этих чисел,
    /// а не читает слот.
    LayoutField {
        /// Где лежит дескриптор.
        descriptor: LocalId,
        /// Выравнивание, а не размер.
        align: bool,
    },
    /// Новый массив: `count` ячеек, каждая занята `initial` (§4.11).
    ///
    /// Один объект кучи на весь массив, и это **одна** аллокация независимо от
    /// длины. `stride` - `None` у указательного массива: там ячейка есть слот.
    ArrayNew {
        /// Шаг индексации; `None` - элементы указательные.
        stride: Option<Stride>,
        /// Сколько ячеек.
        count: Box<Expr>,
        /// Чем они заняты.
        initial: Box<Expr>,
    },
    /// Тот же массив с переписанной ячейкой (§4.11).
    ///
    /// Переписывает **по месту**, когда блок уникален (`rc == 0`), и копирует
    /// иначе - тот же договор, что у [`Expr::Construct::reuse`], и спрашивается
    /// он у рантайма, а не у кратности (§10 вопрос 149).
    ArraySet {
        /// Шаг индексации; `None` - элементы указательные.
        stride: Option<Stride>,
        /// Какой массив.
        array: Box<Expr>,
        /// Какую ячейку.
        at: Box<Expr>,
        /// Чем занять.
        value: Box<Expr>,
    },
    /// Чтение ячейки: `base + i * stride` у плоского, слот у указательного.
    ArrayIndex {
        /// Шаг индексации; `None` - элементы указательные.
        stride: Option<Stride>,
        /// Приходит ли массив владением (§10 вопрос 171).
        ///
        /// Понижение ставит `true`; Perceus снимает у плоского чтения с
        /// локала-невладельца: наружу уходят биты без заголовка, массив
        /// потребит позже его владелец, и чтение **заимствует** - ни `dup`
        /// перед, ни дропа внутри. Пара записей счётчика на каждом чтении
        /// стоила вчетверо дороже самой работы и отнимала векторизацию.
        owned: bool,
        /// Какой массив.
        array: Box<Expr>,
        /// Какую ячейку.
        at: Box<Expr>,
    },
    /// Пустой регион (§3.6): одна область, один блок кучи Perceus.
    RegionNew,
    /// Тот же регион, в конце которого лежит ещё одно значение (§3.6).
    ///
    /// Ячейки кучи под само значение **не** выдаётся: нагрузка плоская
    /// (`{Flat a}`), и она ложится байтами внутрь области. Отсюда «один блок
    /// независимо от числа значений».
    RegionAlloc {
        /// Ширина и граница нагрузки: она же шаг подъёма курсора.
        stride: Stride,
        /// Куда.
        region: Box<Expr>,
        /// Что.
        value: Box<Expr>,
    },
    /// Хендл последней аллокации: смещение внутри области (§3.6, §4.11).
    RegionLast {
        /// У кого.
        region: Box<Expr>,
    },
    /// Значение, лежащее по хендлу (§3.6).
    RegionRead {
        /// Ширина и граница нагрузки.
        stride: Stride,
        /// Откуда.
        region: Box<Expr>,
        /// По какому хендлу.
        at: Box<Expr>,
    },
    /// Тот же регион с переписанным местом (§3.6).
    ///
    /// Курсор не двигает: `write` §3.6 - операция над уже размещённым местом,
    /// а не аллокация.
    RegionWrite {
        /// Ширина и граница нагрузки.
        stride: Stride,
        /// Где.
        region: Box<Expr>,
        /// По какому хендлу.
        at: Box<Expr>,
        /// Чем.
        value: Box<Expr>,
    },
    /// Ячейка по хендлу свободна: Pool (§3.6).
    ///
    /// Курсор не двигает и занятое не убавляет - правит только журнал области.
    /// Следующая аллокация **равного размера** займёт освобождённое место.
    RegionRecycle {
        /// Где.
        region: Box<Expr>,
        /// Какая ячейка.
        at: Box<Expr>,
    },
    /// Курсор опускается до хендла, если тот назвал последнюю аллокацию:
    /// `StackAlloc` (§3.6).
    ///
    /// Хендл, назвавший что-то другое, оставляет область как есть - LIFO и
    /// значит «только вершина».
    RegionPop {
        /// Где.
        region: Box<Expr>,
        /// До какого хендла.
        at: Box<Expr>,
    },
    /// Примитивная операция над двумя плоскими значениями (§4.3).
    ///
    /// Оба аргумента и ответ плоские по построению - другой типизации у неё
    /// нет. Ячейки кучи здесь не возникает вовсе, и это наблюдаемо счётчиком.
    Primitive {
        /// Какая.
        op: PrimOp,
        /// Над каким типом.
        ty: PrimTy,
        /// Левый аргумент.
        left: Box<Expr>,
        /// Правый аргумент.
        right: Box<Expr>,
    },
    /// Вектор, все дорожки которого заняты одним значением (§4.9).
    ///
    /// Ячейки кучи не занимает: вектор плоский, и лежит он в регистре. У LLVM
    /// это `insertelement` в нулевую дорожку плюс `shufflevector` нулевой
    /// маской - каноническая форма splat'а, которую распознаёт кодогенерация; у
    /// C - инициализация всех дорожек одним выражением.
    SimdSplat {
        /// Сколько дорожек.
        lanes: u32,
        /// Какого типа каждая.
        lane: PrimTy,
        /// Чем они заняты.
        value: Box<Expr>,
    },
    /// Тот же вектор с переписанной дорожкой (§4.9): `insertelement`.
    ///
    /// Номер приходит выражением, а не числом: §4.9 не обещает, что дорожка
    /// названа литералом, а обе инструкции - и LLVM'ная, и C'шный индекс -
    /// рантаймовый номер принимают. Литерал при этом остаётся обычным случаем,
    /// и на нём оптимизатор сводит операцию к перестановке.
    SimdSet {
        /// Сколько дорожек.
        lanes: u32,
        /// Какого типа каждая.
        lane: PrimTy,
        /// Какой вектор.
        vector: Box<Expr>,
        /// Какую дорожку.
        at: Box<Expr>,
        /// Чем занять.
        value: Box<Expr>,
    },
    /// Значение дорожки (§4.9): `extractelement`.
    ///
    /// Номер вне ширины обрывает прогон текстом [`LANE_OUTSIDE`] - у обоих
    /// бэкендов и дословно одним: сообщение об обрыве есть часть наблюдаемого
    /// поведения, и разъехаться в нём было бы тем же расхождением, что
    /// разъехаться в ответе.
    SimdLane {
        /// Сколько дорожек.
        lanes: u32,
        /// Какого типа каждая.
        lane: PrimTy,
        /// Какой вектор.
        vector: Box<Expr>,
        /// Какую дорожку.
        at: Box<Expr>,
    },
    /// Подорожечная арифметика (§4.9).
    ///
    /// Отдельный узел от [`Expr::Primitive`], а не флаг в нём, потому что
    /// различие проходит насквозь: у скаляра тип операнда - примитив, здесь -
    /// вектор, и печатается он у обоих эмиттеров другой формой. Операция при
    /// этом та же [`PrimOp`] нарочно: §4.9 обещает element-wise семантику, и
    /// второй счёт сложения разошёлся бы с первым молча.
    ///
    /// Флагов быстрой математики здесь нет ровно по той же причине, по какой их
    /// нет у скаляра (§4.3, трек F): `Float` кольца не образует, и
    /// переписывать компилятору нечем.
    SimdArith {
        /// Какая операция.
        op: PrimOp,
        /// Сколько дорожек.
        lanes: u32,
        /// Какого типа каждая.
        lane: PrimTy,
        /// Левый вектор.
        left: Box<Expr>,
        /// Правый вектор.
        right: Box<Expr>,
    },
    /// Векторная загрузка окна колонки (§4.9): `lanes` ячеек подряд с `at`.
    ///
    /// Пара к [`Expr::ArrayIndex`], и все её решения повторены: адрес окна
    /// берётся у рантайма (`adamas_array_window`), сами байты читаются
    /// **инструкцией**, а `owned` снимает Perceus там же и по тому же правилу
    /// (§10 вопрос 171). Отличается только проверка границы: у окна проверять
    /// надо хвост, и `adamas_array_at` этого не делает.
    ///
    /// Шаг здесь **не** `Option`: дорожкой бывает только `Primitive`, а он
    /// плоский по построению (§4.9, суперкласс `Flat`), так что указательной
    /// колонки на этом узле не бывает. Понижение отвергает её именем раньше.
    SimdLoad {
        /// Шаг индексации колонки: он же ширина дорожки.
        stride: Stride,
        /// Сколько дорожек.
        lanes: u32,
        /// Какого типа каждая.
        lane: PrimTy,
        /// Приходит ли колонка владением (§10 вопрос 171).
        owned: bool,
        /// Какая колонка.
        array: Box<Expr>,
        /// С какой ячейки.
        at: Box<Expr>,
    },
    /// Та же колонка с переписанным окном (§4.9).
    ///
    /// Пара к [`Expr::ArraySet`] и с тем же договором: функциональна по
    /// семантике, переписывает по исполнению - уникальность спрашивается у
    /// рантайма (`adamas_array_writable`) после того, как посчитаны все
    /// аргументы, ровно как у скалярной записи.
    SimdStore {
        /// Шаг индексации колонки: он же ширина дорожки.
        stride: Stride,
        /// Сколько дорожек.
        lanes: u32,
        /// Какого типа каждая.
        lane: PrimTy,
        /// Какая колонка.
        array: Box<Expr>,
        /// С какой ячейки.
        at: Box<Expr>,
        /// Чем занять окно.
        value: Box<Expr>,
    },
    /// Сравнение двух плоских значений (§4.3).
    ///
    /// Отдельный узел от [`Expr::Primitive`], потому что ответ у него другого
    /// сорта: аргументы плоские, а результат - конструктор `Bool`, то есть
    /// указательное представление. Ячейки кучи при этом не возникает и здесь -
    /// у `True` и `False` полей нет, и рантайм кладёт их непосредственным
    /// значением (`adamas_con0`).
    Compare {
        /// Какое.
        op: PrimCmp,
        /// Над каким типом.
        ty: PrimTy,
        /// Левый аргумент.
        left: Box<Expr>,
        /// Правый аргумент.
        right: Box<Expr>,
        /// Конструктор истины.
        yes: CtorId,
        /// Конструктор лжи.
        no: CtorId,
    },
    /// Конструктор со всеми аргументами: по одному на связывание, стёртые
    /// [`Expr::Erased`].
    Construct {
        /// Какой.
        constructor: CtorId,
        /// Блок, придержанный [`Expr::Reclaim`], если он этому месту достался.
        ///
        /// Ставит его вставка RC ([`crate::perceus`]) и только там, где формы
        /// совпали (§5.1). Достался блок или нет, решается в рантайме: `None` в
        /// придержавшем связывании значит «разобранное было разделено», и тогда
        /// объект аллоцируется обычным путём.
        reuse: Option<LocalId>,
        /// Аргументы по связываниям.
        arguments: Vec<Expr>,
    },
    /// Конструктор как значение: замыкание, собирающее его по аргументам.
    ConstructClosure {
        /// Какой.
        constructor: CtorId,
    },
    /// Прямой вызов функции: аргументов ровно столько, сколько параметров.
    Call {
        /// Кого.
        function: FuncId,
        /// Аргументы по параметрам, стёртые [`Expr::Erased`].
        arguments: Vec<Expr>,
    },
    /// Функция как значение: код плюс захваченная среда.
    Closure {
        /// Чей код.
        function: FuncId,
        /// Захваченное - по одному на связывание в [`Function::captured`].
        captured: Vec<Expr>,
    },
    /// Хендлер: кадр `HANDLER`, вычисление под ним, ответ - ветка `return`.
    ///
    /// Вычисление стоит **под расширенным вектором evidence**, и это не деталь
    /// печати: запись о хендлере видна только ему и тому, что он позовёт.
    /// Ветки же работают под вектором **места `handle`** - окружающая ветки
    /// есть окружающая применения хендлера (§3.4), - и берут его у кадра.
    Handle {
        /// Какая площадка.
        handler: HandlerId,
        /// Среда веток - по одному на связывание в [`Handler::captured`].
        captured: Vec<Expr>,
        /// Что под хендлером. Приостановка снята: `{ε} A` есть нульместная
        /// функция (§3.4), и понижение применяет её здесь же.
        computation: Box<Expr>,
    },
    /// Операция эффекта: хендлер ищется вектором evidence (§3.4).
    ///
    /// Вердикт трёхзначный, и сводить его к двум нельзя (`adamas.h`):
    /// `HANDLER` - ветка на месте, `SUPPRESSED` - обрыв своего деструктора,
    /// `MISSING` - операция без хендлера.
    Perform {
        /// Метка, чья операция.
        label: LabelId,
        /// Номер операции в метке - им ветка и выбирается.
        operation: u32,
        /// Аргументы операции без параметров метки.
        arguments: Vec<Expr>,
    },
    /// Маска: вычисление идёт мимо ближайшего одноимённого хендлера (§3.4).
    ///
    /// Кадра у неё нет вовсе, и в этом всё её понижение: маска строит вектор
    /// **без** ближайшей записи своей метки (`adamas_evidence_mask`) и считает
    /// вычисление под ним. Числом пропусков это не выражается: `skip` нужен
    /// месту операции, а операции лежат внутри маскируемого вычисления, то есть
    /// в чужой функции. Вложенные маски считаются по одной сами собой.
    ///
    /// Точкой приостановки маска не является - приостанавливается то, что под
    /// ней, - но вектор её живёт ровно до конца вычисления, и отдаёт его тот же
    /// узел.
    Mask {
        /// Чью запись снять.
        label: LabelId,
        /// Что под маской. Приостановка снята: `{ρ} A` есть нульместная
        /// функция (§3.4), и понижение применяет её здесь же.
        computation: Box<Expr>,
    },
    /// Питомник: круг файберов, корневым идёт написанное вычисление (§5.2).
    ///
    /// `withNursery` - постулат, чьё тело даёт рантайм: круг заводится, под
    /// свежим кадром `NURSERY` запускается корневой файбер, и ответом узла
    /// служит значение круга - то, чем ответил корневой, когда дожидаться
    /// стало некого. Модель повторена за машиной (`adamas-interp/src/fiber.rs`),
    /// а не придумана заново.
    Nursery {
        /// Тело корневого файбера: приостановленное вычисление **значением**.
        /// Приостановка здесь не снимается - её снимет круг, применив тело к
        /// единице под своим кадром.
        body: Box<Expr>,
    },
    /// Операция питомника: уступка, порождение, ожидание (§5.2).
    ///
    /// Узел свой, а не [`Expr::Perform`], потому что решение «кто обслуживает»
    /// принимается **в рантайме**: питомник берёт операцию, только если он
    /// ближе хендлера её метки, и написанный `handle` над той же меткой значит
    /// написанное. Статически это не решается - `eval/fibers.adamas` пишет те
    /// же имена без всякого питомника, - поэтому узел несёт **оба** пути.
    Fiber {
        /// Что делает операция под питомником.
        op: FiberOp,
        /// Метка, чью операцию написал автор.
        label: LabelId,
        /// Номер операции в метке - им ветка выбирается на пути к хендлеру.
        operation: u32,
        /// Аргументы операции без параметров метки - те же, что у
        /// [`Expr::Perform`]. Свой аргумент у порождения и ожидания
        /// **последний**: row стоит на последней стрелке.
        arguments: Vec<Expr>,
    },
    /// Отмена: разбор значения задачи потребил её мимо `await` (§5.2).
    ///
    /// Стоит вокруг разбираемого и отдаёт его же. Точка приостановки: раскрутка
    /// сегмента отменённого файбера кладётся кадром, и разбор продолжается,
    /// когда она договорит.
    Cancel {
        /// Слот, в котором у значения задачи стоит имя файбера.
        at: u32,
        /// Разбираемое.
        value: Box<Expr>,
    },
    /// Возобновление резумпции: сегмент встаёт обратно, значение идёт ему.
    ///
    /// Точка приостановки наравне с операцией: своё продолжение ветка кладёт
    /// кадром **под** возвращаемый сегмент, поэтому ответ возобновлённого
    /// вычисления доходит до неё трамплином.
    Resume {
        /// Резумпция. Потребляется: аффинна по §3.3, и второго вызова у неё
        /// не бывает.
        resumption: Box<Expr>,
        /// Чем возобновляют - значение операции.
        value: Box<Expr>,
    },
    /// Выход из scope, держащего ресурс: кадр `MARK_CLOSING` (§3.3).
    ///
    /// Только вторая форма: у первой ручки стека нет вовсе, обрываться в ней
    /// нечему, и понижение оставляет там прежнюю пару связываний - тело, потом
    /// деструктор. Кадр нужен **исключительному** выходу: раскрутка брошенного
    /// сегмента находит отложенное обходом цепочки, а не текстом.
    ///
    /// Деструктор поэтому и есть значение - замыкание: раскрутку ведёт рантайм,
    /// и позвать он умеет только значение. Это названная цена второй формы -
    /// ячейка кучи на scope с ресурсом.
    Closing {
        /// Код деструктора: своя функция, как у ветки хендлера.
        closer: FuncId,
        /// Среда деструктора - по одному на связывание в его `captured`.
        captured: Vec<Expr>,
        /// Тело scope. Его значение и есть ответ.
        body: Box<Expr>,
    },
    /// Применение значения-функции к одному аргументу.
    ///
    /// Стирания здесь не бывает: машина стирает аргумент по типу **глобального
    /// имени**, а к этому месту имени уже нет.
    Apply {
        /// Что применяется.
        callee: Box<Expr>,
        /// К чему.
        argument: Box<Expr>,
    },
    /// Связывание значения.
    Bind {
        /// Кого связывает.
        binding: Binding,
        /// Чем.
        value: Box<Expr>,
        /// Что под ним.
        body: Box<Expr>,
    },
    /// Разбор по конструктору. Пустой список ветвей - разбор пустого типа.
    ///
    /// После вставки RC разбираемое - всегда [`Expr::Local`]: отдать можно
    /// только связывание, а не выражение.
    Match {
        /// Что разбирается.
        scrutinee: Box<Expr>,
        /// Кратность, с которой разбор потребляет разбираемое (§3.3).
        consumed: Mult,
        /// Ветви.
        arms: Vec<Arm>,
    },
    /// Взять лишнюю ссылку на связывание, затем вычислить тело (§5.1).
    ///
    /// Ставит вставка RC там, где связывание употребляется не в последний раз.
    Dup {
        /// Кого.
        local: LocalId,
        /// Что под ним.
        body: Box<Expr>,
    },
    /// Отдать ссылку связывания, затем вычислить тело (§5.1).
    Drop {
        /// Кого.
        local: LocalId,
        /// Поля разобранного, чей `dup` схлопнут с этим дропом ([`Salvage`]).
        salvage: Salvage,
        /// Что под ним.
        body: Box<Expr>,
    },
    /// Отдать ссылку, придержав блок под переписывание (§5.1, FBIP).
    ///
    /// От [`Expr::Drop`] отличается только тем, что на последней ссылке блок не
    /// возвращается куче, а достаётся `token`; дети дропаются одинаково. Пустой
    /// `token` (разделённое значение) законен и означает «переписывать нечего».
    Reclaim {
        /// Кого отдаём.
        local: LocalId,
        /// Куда кладём блок.
        token: LocalId,
        /// Поля разобранного, чей `dup` схлопнут с этим дропом ([`Salvage`]).
        salvage: Salvage,
        /// Что под ним.
        body: Box<Expr>,
    },
    /// Вернуть куче придержанный блок, который этому пути занять нечем (§5.1).
    ///
    /// Парный узел к [`Expr::Reclaim`]: тот блок придерживает, этот отдаёт.
    /// Ставит его вставка RC там, где ячейку занимает **не всякий** путь через
    /// ветвь (§10 вопрос 173): занимающий путь переписывает её, незанимающий
    /// приходит сюда. Пустой `token` (разобранное было разделено) законен и
    /// означает «отдавать нечего» - `adamas_free` от `NULL` не делает ничего.
    ///
    /// От [`Expr::Drop`] отличается тем, что счётчика не трогает вовсе: блок
    /// пришёл из `adamas_drop_reuse`, то есть уже отдал последнюю ссылку, и
    /// поля его release обошёл. Дропнуть его заново значило бы обойти поля
    /// дважды.
    Discard {
        /// Что отдаём - связывание, заведённое [`Expr::Reclaim`].
        token: LocalId,
        /// Что под ним.
        body: Box<Expr>,
    },
}

impl Expr {
    /// Прямые подвыражения в порядке вычисления.
    ///
    /// Живёт здесь, а не у каждого читателя своя копия, потому что читателей
    /// пятеро - вставка RC тремя обходами, эмиттер и свидетели, - и обход,
    /// забывший узел, делает утверждение об **отсутствии** молча зелёным. Узел
    /// добавляется в одном месте.
    #[must_use]
    pub fn children(&self) -> Vec<&Self> {
        match self {
            Self::Local(_)
            | Self::Erased
            | Self::ConstructClosure { .. }
            | Self::Literal { .. }
            | Self::LayoutField { .. }
            | Self::RegionNew
            | Self::Layout { .. } => Vec::new(),
            Self::Unpack { value, .. }
            | Self::Cancel { value, .. }
            | Self::SimdSplat { value, .. } => vec![value],
            Self::RegionLast { region } => vec![region],
            Self::RegionAlloc { region, value, .. } => vec![region, value],
            Self::RegionRead { region, at, .. }
            | Self::RegionRecycle { region, at }
            | Self::RegionPop { region, at } => vec![region, at],
            Self::RegionWrite {
                region, at, value, ..
            }
            | Self::SimdSet {
                vector: region,
                at,
                value,
                ..
            } => vec![region, at, value],
            Self::Construct { arguments, .. }
            | Self::Call { arguments, .. }
            | Self::Perform { arguments, .. }
            | Self::Fiber { arguments, .. }
            | Self::Pack {
                fields: arguments, ..
            } => arguments.iter().collect(),
            Self::Nursery { body } => vec![body],
            Self::Handle {
                captured,
                computation,
                ..
            } => captured.iter().chain([&**computation]).collect(),
            Self::Closing { captured, body, .. } => captured.iter().chain([&**body]).collect(),
            Self::Mask { computation, .. } => vec![computation],
            Self::ArrayNew { count, initial, .. } => vec![count, initial],
            Self::ArraySet {
                array, at, value, ..
            }
            | Self::SimdStore {
                array, at, value, ..
            } => vec![array, at, value],
            Self::ArrayIndex { array, at, .. }
            | Self::SimdLoad { array, at, .. }
            | Self::SimdLane {
                vector: array, at, ..
            } => vec![array, at],
            Self::Resume { resumption, value } => vec![resumption, value],
            Self::Closure { captured, .. } => captured.iter().collect(),
            Self::Primitive { left, right, .. }
            | Self::Compare { left, right, .. }
            | Self::SimdArith { left, right, .. } => {
                vec![left, right]
            }
            Self::Apply { callee, argument } => vec![callee, argument],
            Self::Bind { value, body, .. } => vec![value, body],
            Self::Match {
                scrutinee, arms, ..
            } => [&**scrutinee]
                .into_iter()
                .chain(arms.iter().map(|arm| &arm.body))
                .collect(),
            Self::Dup { body, .. }
            | Self::Drop { body, .. }
            | Self::Reclaim { body, .. }
            | Self::Discard { body, .. } => {
                vec![body]
            }
        }
    }
}

/// Программа целиком.
#[derive(Clone, Debug)]
pub struct Program {
    /// Конструкторы по тегу: индекс совпадает с [`CtorId`].
    pub constructors: Vec<Constructor>,
    /// Плоские укладки по номеру: индекс совпадает с [`PackId`].
    pub packings: Vec<Packing>,
    /// Метки эффектов по номеру: индекс совпадает с [`LabelId`].
    pub labels: Vec<Label>,
    /// Площадки `handle` по номеру: индекс совпадает с [`HandlerId`].
    pub handlers: Vec<Handler>,
    /// Функции по номеру: индекс совпадает с [`FuncId`].
    pub functions: Vec<Function>,
    /// Точка входа: функция без параметров, чьё значение печатается.
    pub entry: FuncId,
    /// Исходник, к которому относятся [`Function::position`]. `None` - понижение
    /// шло без текста, и позиций нет ни у кого.
    pub source: Option<Source>,
}
