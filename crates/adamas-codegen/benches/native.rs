//! Отношение на цепочке из [`PASSES`] — **1.08** (2.436 мс на 29.60), что
//! сходится с прежними 1.01–1.12, мерившимися врозь. Как и у хендлера,
//! сравнимая величина — не отношение, а цена операции, и она у обеих точек
//! одна и та же с точностью до разброса: 2.3–3.0 нс. Это и есть содержание
