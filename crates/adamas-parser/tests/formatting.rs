//! `adamas fmt` на уровне библиотеки: где встаёт комментарий и что с ним не
//! случается (§7.1).
//!
//! Печать дерева проверяется рядом (`printing.rs`), и повторять её здесь
//! незачем: форматтер - это она же плюс комментарии. Проверяется поэтому ровно
//! добавленное.
//!
//! # Жанр подделки, от которого написан этот файл
//!
//! «Комментарии сохраняются» - утверждение, которое зелено у форматтера,
//! выводящего их все в конец файла. Поэтому места проверяются поимённо
//! ожидаемым текстом, а не счётом; счёт стоит отдельно и ловит другое -
//! потерю на формах, которых в таблице ниже нет.

use adamas_parser::{format, tokenize};
use proptest::prelude::*;

/// Форматирование, которое обязано удаться.
fn canonical(text: &str) -> String {
    match format(text) {
        Ok(out) => out,
        Err(error) => panic!("исходник не отформатировался: {error}\n{text}"),
    }
}

/// Сколько комментариев в тексте.
fn comments(text: &str) -> usize {
    match tokenize(text) {
        Ok(tokens) => tokens.comments.len(),
        Err(error) => panic!("исходник не разобрался: {error}\n{text}"),
    }
}

/// Пары «как написано - как печатается». Каждая проверяется и на второй
/// проход: правило, дающее канон только с первого раза, не правило.
fn placed(cases: &[(&str, &str)]) {
    for (source, expected) in cases {
        let once = canonical(source);
        assert_eq!(&once.as_str(), expected, "для {source:?}");
        assert_eq!(canonical(&once), once, "не идемпотентно: {source:?}");
        assert_eq!(
            comments(&once),
            comments(source),
            "комментарии потерялись: {source:?}"
        );
    }
}

#[test]
fn a_comment_stays_above_what_it_explains() {
    placed(&[
        ("-- шапка\nf = 1\n", "-- шапка\nf = 1\n"),
        // Пустая строка между комментарием и объявлением - единственный кусок
        // авторского форматирования, который печать сохраняет: без него шапка
        // файла приклеивалась бы к первому объявлению.
        ("-- шапка\n\nf = 1\n", "-- шапка\n\nf = 1\n"),
        // Комментарий делает объявление «высоким»: сосед сверху от него
        // отбивается пустой строкой, как от любого многострочного.
        (
            "f = 1\n-- про g\ng = 2\n",
            "f = 1\n\n-- про g\ng = 2\n",
        ),
        // Сигнатуру от её клауз пустая строка не отделяет и с комментарием.
        (
            "f : Nat\n-- первая\nf Zero = 1\nf n = 2\n",
            "f : Nat\n-- первая\nf Zero = 1\nf n = 2\n",
        ),
    ]);
}

#[test]
fn a_comment_on_a_line_of_code_stays_on_it() {
    placed(&[
        ("f = 1 -- хвост\n", "f = 1 -- хвост\n"),
        ("f = 1 {- a -} -- b\n", "f = 1 {- a -} -- b\n"),
        // Выравнивание хвоста не сохраняется: канон - один пробел.
        ("f = 1      -- хвост\n", "f = 1 -- хвост\n"),
    ]);
}

#[test]
fn a_comment_at_the_end_of_a_file_survives() {
    // Привязан он к `Eof`, и своей строки вывода у него нет: печатается хвостом
    // файла. Случай отдельный ровно потому, что «следующего члена» у него не
    // бывает.
    placed(&[
        ("f = 1\n-- хвост\n", "f = 1\n-- хвост\n"),
        ("f = 1\n-- один\n-- два\n", "f = 1\n-- один\n-- два\n"),
        // Файл из одних комментариев: объявлений ноль, терять нечего, и
        // печатать тоже.
        ("-- только это\n", "-- только это\n"),
        ("{- и это -}\n", "{- и это -}\n"),
    ]);
}

#[test]
fn a_nested_block_comment_survives_whole() {
    // Вложенность допускает лексер, и печать обязана отдать текст обратно
    // дословно: своего разбора у внутренности комментария нет.
    placed(&[
        ("{- {- x -} -}\nf = 1\n", "{- {- x -} -}\nf = 1\n"),
        (
            "{- внешний\n   {- внутренний -}\n   хвост -}\nf = 1\n",
            "{- внешний\n   {- внутренний -}\n   хвост -}\nf = 1\n",
        ),
    ]);
}

#[test]
fn a_comment_inside_a_block_keeps_its_member() {
    placed(&[
        (
            "data D where\n  -- нулевой\n  C : D\n  -- первый\n  K : D -> D\n",
            "data D where\n  -- нулевой\n  C : D\n  -- первый\n  K : D -> D\n",
        ),
        (
            "f x = case x of\n  -- пусто\n  Nil -> 1\n  Cons y ys -> 2\n",
            "f x = case x of\n  -- пусто\n  Nil -> 1\n  Cons y ys -> 2\n",
        ),
        (
            "f =\n  let\n    a = 1\n    -- второе\n    b = 2\n  add a b\n",
            "f =\n  let a = 1\n      -- второе\n      b = 2\n  add a b\n",
        ),
        (
            "f = y\n  where\n    -- местное\n    y = 1\n",
            "f = y\n  where\n    -- местное\n    y = 1\n",
        ),
        (
            "f = handle c with\n  -- ветка\n  get -> 1\n",
            "f = handle c with\n  -- ветка\n  get -> 1\n",
        ),
        (
            "effect E where\n  -- операция\n  op : Nat\n",
            "effect E where\n  -- операция\n  op : Nat\n",
        ),
        (
            "f =\n  -- первый оператор\n  put 1 -- и его хвост\n  get\n",
            "f =\n  -- первый оператор\n  put 1 -- и его хвост\n  get\n",
        ),
    ]);
}

#[test]
fn a_comment_without_a_line_of_its_own_moves_to_the_next_member() {
    // Названная цена. Внутри переносимого применения строки вывода нет, и
    // комментарий выносится к следующему члену - не теряется, но и не остаётся
    // там, где стоял. Свидетель нужен затем, чтобы это было решением, а не
    // сюрпризом.
    placed(&[(
        "f = g\n  -- посреди\n  h\ni = 2\n",
        "f = g h\n\n-- посреди\ni = 2\n",
    )]);
}

#[test]
fn an_unparsed_source_is_refused_and_not_guessed() {
    // Форматировать сломанное нечем: восстановления после ошибки у разбора
    // нет, и половина дерева стёрла бы вторую.
    let error = format("f = case\n").expect_err("сломанное не форматируется");
    assert!(
        error.to_string().contains("ожида"),
        "отказ обязан сказать, чего не хватило: {error}"
    );
    assert!(format("{- не закрыт\n").is_err(), "незакрытый комментарий");
}

#[test]
fn the_printer_alone_still_prints_no_comments() {
    // Договор round-trip'а не съехал: `print` комментариев не знает, и это не
    // regression, а разделение. Иначе снапшоты печати начали бы зависеть от
    // таблицы trivia.
    let module = adamas_parser::parse("-- шапка\nf = 1\n").expect("разбор удался");
    assert_eq!(adamas_parser::print(&module), "f = 1\n");
}

/// Лексика, на которой комментарии встречаются часто: минус и фигурная скобка
/// в наборе, поэтому `--`, `{-` и `-}` генератор порождает сам.
fn plausible() -> impl Strategy<Value = String> {
    r"[a-z0-9=(){}\[\],:\\ \n-]{0,160}".prop_map(String::from)
}

proptest! {
    /// Два свойства на одном входе: форматирование идемпотентно, и счёт
    /// комментариев оно не меняет. Текст случайный, поэтому разбирается редко -
    /// но каждый разобравшийся проверяется целиком.
    #[test]
    fn formatting_is_idempotent_and_keeps_every_comment(text in plausible()) {
        let Ok(once) = format(&text) else { return Ok(()) };
        let twice = format(&once);
        prop_assert!(
            twice.is_ok(),
            "отформатированное не разобралось: {:?}\n{once}",
            twice.err()
        );
        if let Ok(twice) = twice {
            prop_assert_eq!(&twice, &once, "не идемпотентно\nисходник:\n{}", text);
        }
        prop_assert_eq!(
            comments(&once),
            comments(&text),
            "комментарии потерялись\nисходник:\n{}\nпечать:\n{}",
            text,
            once
        );
    }
}
