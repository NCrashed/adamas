//! Первый бенчмарк понижения: во что обходится порождённая программа.
//!
//! У понижения замеров не было вовсе (§13, итог 2026-09-11: «native
//! performance не мерил никто»), и §6 оставался непроверенным целиком. Здесь
//! меряется одна его строка — **«символьно-тяжёлый код: паритет с Rust или
//! лучше»**. Взята она потому, что достижима сегодняшним срезом: §6 сам
//! называет символьный workload «цепочками функциональных преобразований над
//! деревьями и списками», а дерево, обход и свёртка — это чистый фрагмент,
//! который понижение берёт.
//!
//! Прочие строки §6 меряются не все, и вот чем.
//!
//! - **Горячие циклы с unboxed numerics** мерятся — но не здесь, а в
//!   `workloads.rs`, строкой `scalar`. **Прежняя запись этого пункта устарела
//!   и была неверна с 2026-09-14:** она говорила, что цикла в языке нет
//!   ([`PrimOp`](adamas_core::prim::PrimOp) знает только `Add`, `Sub`, `Mul`,
//!   литеральный паттерн элаборация отвергает), а счётчик поэтому обязан быть
//!   индуктивным. Трек A волны 5 дал шесть сравнений над десятью примитивными
//!   типами и литеральный паттерн в клаузе; счётчик остался плоским, и прогон
//!   печатает ноль выданных блоков.
//! - **Zero-alloc циклы с регионами** стали выразимы тем же треком — регионы
//!   понижение берёт с волны 3 — и **не меряются**: строка §6 сравнивает их с
//!   «C с manual arena management», то есть требует третьей программы, руками
//!   на C, а трек Z, ради которого таблица и снималась, называет четыре
//!   нагрузки, и этой среди них нет. Названо, чтобы не всплыло забытым.
//! - **`@noalloc`** — не число, а вердикт, и вердикт есть: §6 просит «ноль
//!   аллокаций в куче, проверено компилятором», а `adamas check` отвечает
//!   отказом на `tests/golden/errors/noalloc-boxing.adamas` (проверено
//!   прогоном 2026-09-15). Мерить здесь нечего по постановке самой строки.
//!   Прежняя запись числила его среди «механизмов в понижении нет»; механизм
//!   у него не в понижении, а в элаборации, и он был там уже 2026-09-10.
//! - **SIMD, mempool, FFI** — механизмов нет. `Simd` (§4.9) не объявлен вовсе:
//!   `adamas check` на `lane : Simd 4 Float32` отвечает «имя `Simd` не
//!   найдено», класса `Primitive` в крейтах нет ни одного упоминания. Трек H
//!   Фазы 7; в таблице разрыва это четвёртая строка, названная дырой.
//! - **Плоские контейнеры** есть (§4.11), но хеш-таблицы, против которых
//!   меряется строка, — библиотека, которой нет.
//! - **Бизнес-код с эффектами (1.5–2x Rust)** — мерится здесь же
//!   ([`Shape::TailResumptive`], [`Shape::FlatHandled`]), но не против Rust:
//!   сосед на Rust есть только у чистой формы, а под хендлером сравниваются
//!   между собой формы понижения. Цифра 1.5–2x требует эффектного соседа,
//!   которого писать не на чем.
//! - **Старт компилятора** мерен у драйвера (`adamas-cli/benches/startup.rs`).
//! - **Время release-сборки** §6 сознательно не ограничивает; она всё равно
//!   мерена ниже как `codegen/cc`, потому что без неё не прочитать, чего стоит
//!   весь путь.
//!
//! # Алгоритм и почему он
//!
//! Двоичное дерево глубины `d`: `grow` строит, `scaled` умножает каждый лист,
//! `total` складывает. Рекурсия глубиной `d` — стека не хватить не может ни у
//! порождённого C, ни у соседа. Листья **различны** (счётчик по битам пути),
//! поэтому перепутанные поддеревья меняют ответ, а не оставляют его тем же.
//!
//! `scaled` проходит дерево не один раз, а [`PASSES`]. Причина — не размер
//! работы, а её состав: хендлер живёт в `scaled` и больше нигде, а `scaled`
//! при одном проходе есть 16% измеряемого (пофазно на глубине 18: `grow`
//! 9.40, `scaled` 2.90, `total` 5.35). Спрашиваемое тонуло в неспрашиваемом.
//! Повтор прохода умножает **только** ту часть, где стоит операция, — `grow`
//! и `total` остаются по одному, — и §6 просит ровно этого: «цепочками
//! функциональных преобразований», во множественном числе. Что цена цепочки
//! у понижения и у соседа разная, само по себе результат: см. «Ответ на
//! символьную строку».
//!
//! Счётчик глубины — индуктивный `Nat` длиной `d` (единицы). **Построение**
//! его в замере не участвует: работа экспоненциальна по `d`, а счётчик линеен.
//! А вот **обход** его `grow` платит на каждом узле, тогда как сосед на Rust
//! вычитает единицу из машинного числа, и эта асимметрия в замере есть.
//! Измерена она 2026-09-13 на потолке (тот же алгоритм руками на C, счётчик
//! списком против счётчика числом): **0.47 мс из 17.0 на глубине 18, то есть
//! 2.8%**. Написать иначе язык не умеет — литеральных паттернов и сравнений
//! нет, см. первый пункт выше, — поэтому цена названа, а не снята.
//!
//! # Кто с кем сравнивается
//!
//! Все считают **одно и то же число**, и это проверяется до всякого
//! замера ([`checked`], [`same_answer`]):
//!
//! - `interp` — машина, то есть `adamas eval`;
//! - `native` — порождённый C, собранный строкой release ([`harness::RELEASE`]) и
//!   запущенный процессом;
//! - `rust` — тот же алгоритм на Rust, теми же формами данных
//!   (`Box`-рекурсия), запущенный **тоже процессом**: стенд зовёт сам себя
//!   через `ADAMAS_BENCH_NEIGHBOUR` ([`as_child`]). Почему не в общем
//!   процессе — ниже;
//! - `floor` и `rust/floor` — те же два пути при `d = 0`: цена `fork`/`exec` и
//!   печати, которую каждая сторона платит сверх работы. Полов два, потому что
//!   двоичных файлов два: 0.196 мс у порождённого C против 0.434 мс у стенда,
//!   и вычитать надо свой.
//!
//! Сосед на Rust написан **эквивалентным кодом**, как того и требует §6
//! («Rustc на эквивалентном коде»), а не идиоматичным: те же конструкторы, та
//! же владеющая рекурсия, то же заворачивание арифметики. Идиоматичный сосед
//! (массив, цикл) мерил бы отсутствие цикла в языке, а не качество понижения.
//!
//! ## Почему сосед мерится процессом, а не в общем процессе со стендом
//!
//! Запись §13 от 2026-09-11 прочитала «понижение обгоняет Rust в полтора
//! раза» с числа, которое не повторялось: семь прогонов 2026-09-12 дали
//! `rust/18` либо 21–24 мс, либо 57–64. Мода устанавливалась до первой
//! выборки и держалась весь прогон, так что ни усреднить, ни отбросить её
//! было нельзя.
//!
//! **Двумодален был не сосед, а куча стенда** (измерено 2026-09-13). Пока
//! сосед считался в общем процессе с criterion, его цену задавала не машина и
//! не алгоритм, а то, сколько стенд успел выделить и освободить **до** замера.
//! Свидетель — одно и то же дерево, померенное дважды в одном прогоне:
//!
//! | где мерено | страниц под 524 286 узлов | размах | обход |
//! |---|---|---|---|
//! | до элаборации | 4 103 | 32 байт/узел | 9.7 мс |
//! | после элаборации и машины | 25 213 | 784 байт/узел | 30.4 мс |
//!
//! На нетронутой куче glibc кладёт узлы подряд — 128 штук на страницу, размах
//! равен размеру куска. После того как элаборация и машина взболтали
//! свободные списки, то же дерево растекается по шестикратно большему числу
//! страниц, обход перестаёт попадать в TLB и идёт втрое дольше. Тот же сдвиг
//! виден и позиционно: `rust/18`, померенный первым делом в том же прогоне,
//! давал 21.7 мс против 62.2 мс на своём прежнем месте.
//!
//! Порождённый C этого не платил никогда: он — свежий процесс на каждой
//! итерации. Асимметрия «C процессом, Rust в общем процессе» и была
//! двумодальностью, поэтому сосед переведён на тот же протокол: свежий
//! процесс, свежая куча, ответ печатью, свой пол.
//!
//! Проверено и отвергнуто замером, а не рассуждением: гибридные ядра машины
//! (P против E даёт 1.35 раза, а не 2.5, и свободное размещение все шесть раз
//! попало на P), ASLR, huge pages (режим `madvise` — их никто не просит).
//! Синтетическое взбалтывание кучи в чистом процессе воспроизводит 1.7 раза
//! из трёх и поднимает размах с 32 до сотен байт: механизм тот, величина у
//! настоящей элаборации больше.
//!
//! # Методика: что делает число повторяемым завтра
//!
//! Сравниваются два процесса, а цена процесса чувствительна к окружению
//! сильнее, чем цена функции. Что фиксируется:
//!
//! - **Не меньше пяти прогонов подряд.** Число — медиана прогонов, рядом
//!   обязан стоять размах. Один прогон — заявка, а не число: именно на нём
//!   сорвалась запись 2026-09-11.
//! - **Разность двух точек читается не по их абсолютным числам, а по
//!   [`paired`].** Это главное правило после правки 2026-09-13, и оно
//!   измерено: пять прогонов того же дня дали `boxed/18` в размахе 3.74 мс
//!   при разности точек 3.51 — то есть врозь точки не разрешаются даже
//!   сейчас, когда разность выросла вшестеро. Чередование их разрешает:
//!   разность 3.10 мс при размахе между прогонами 0.58.
//! - **Оценка — пол выборки** ([`harness::least`]), а не среднее и не медиана. Помеха
//!   ко времени процесса только прибавляет.
//! - **Привязка к одному P-ядру:** `taskset -c <ядро>`. Машина гибридная,
//!   E-ядро идёт вдвое медленнее (`boxed/18`: 39.5 мс против 22.2 на P), а
//!   дочерний процесс короткий, и планировщик размещает его заново на каждой
//!   итерации. Без привязки один прогон из пяти дал `native/pure/18` 70.6 мс
//!   при 44.8 у прочих.
//!
//!   Привязка к **логическому** процессору половину дела не делает: сосед по
//!   гиперпотоку остаётся общим ресурсом, и его занимает кто угодно. Мерено
//!   2026-09-13: `boxed/18` при занятом сиблинге — 35.2 мс против 22.2, то
//!   есть 1.59 раза. Отключить SMT или снять сиблинг с планировщика без root
//!   нельзя, поэтому [`paired`] не устраняет эту помеху, а переживает её:
//!   помеха, накрывшая блок, поднимает пол обеих точек разом и уходит из
//!   разности, а блок, накрытый ею целиком, отбрасывается по свидетелю пола.
//! - **`--noplot --discard-baseline`.** Отчёты и сравнение с прошлым прогоном
//!   идут между точками и меняют состояние процесса; прогоны обязаны
//!   начинаться одинаково.
//! - **Первый прогон после сборки — холодный:** страницы свежесобранных
//!   двоичных файлов ещё не в кэше, и `native/*` на нём завышен (10.5 → 13.5 мс
//!   на глубине 16). Медиана прогонов это переживает, среднее — нет.
//! - **Машина без другой нагрузки.** Нарушение видно в самом отчёте: разброс
//!   внутри выборки становится шире 10%.
//!
//! Число **недействительно**, если:
//!
//! - стороны собраны разными строками: у соседа профиль `release` этого
//!   репозитория, то есть `lto = "thin"`, и без [`harness::RELEASE`] здесь сравнивалось
//!   бы собранное межмодульно с собранным по частям. Замер 2026-09-13: одна эта
//!   асимметрия стоила **99%** разрыва;
//! - сосед померен не отдельным процессом — тогда меряется куча стенда;
//! - свидетель `rust/N: размах` больше [`SPREAD_LIMIT`] — стенд падает сам и
//!   называет величину;
//! - разница точек меньше размаха: померено окружение, а не программа. Размах
//!   называть **обязательно** — отношение двух медиан без него есть ровно та
//!   заявка, на которой сорвалась запись 2026-09-11. Для парных точек стенд
//!   это правило не советует, а проверяет и падает по нему сам.
//!
//! ## Откуда берётся разброс: измерено 2026-09-13
//!
//! Правка сборки ([`harness::RELEASE`]) ускорила понижение втрое и тем **исчерпала
//! запас** методики: разность `boxed`/`handled` упала с 25 мс до 3.4 при
//! разбросе около 2.8. Пять прогонов подтвердили отказ — `boxed/18` лёг в
//! 21.41–23.97 при разности точек 0.5 мс, и в одном прогоне из пяти
//! `handled` вышел **быстрее** `boxed`, чего не может быть по построению.
//! Прежде чем чинить, разброс разложен:
//!
//! - **Не куча стенда.** Родитель с 800 МБ живой кучи даёт `boxed/18` 21.4 мс
//!   против 21.8 у чистого: `fork`/`exec` цену родителя не переносит. Тот
//!   механизм 2026-09-13 действительно был, но он касался соседа в общем
//!   процессе, и его уже сняли.
//! - **Не частота и не прогрев.** 120 с нагрузки на то же ядро не замедляют
//!   следующий замер (21.4 против 22.2 до неё). Калибровочный спин рядом с
//!   замером ходит с ним несогласованно: корреляция 0.14. Ядро действительно
//!   стартует свежий процесс на 1.25 гигагерца и доходит до 4.6, но эта прибавка
//!   одинакова у всех точек и в разности сокращается.
//! - **Не страницы.** Малых отказов страниц у `boxed/18` ровно 4177 в каждом
//!   из тридцати запусков — разброса там нет вовсе.
//! - **Не запуск процесса.** Стена и собственное CPU потомка (`wait4`)
//!   расходятся на 0.13 мс: разброс сидит внутри счёта, а не вокруг него.
//! - **Гиперпоток и вытеснение — да.** Занятый сиблинг стоит 1.59 раза
//!   (22.2 → 35.2 мс), что ровно та величина, которой различались прогоны
//!   владельца (23.7 / 24.0 / 24.6 / 30.6 / 40.5). Помеха приходит и уходит
//!   пятнами: она задевает часть запусков в окне, а не все.
//!
//! Отсюда обе правки. Раз помеха **прибавляет** и приходит пятнами, оценка —
//! пол выборки: двенадцать блоков по сорок запусков `boxed/18` дали минимумы
//! блоков в размахе 0.29 мс, медианы — 0.98, максимумы — 3.75. Раз помеха
//! длится десятки секунд, две точки нельзя мерить в разных окнах: [`paired`]
//! ставит их вплотную.
//!
//! ## Чего методике недостаёт
//!
//! Абсолютные числа точек по-прежнему гуляют, и это не лечится ничем из
//! доступного здесь: пять прогонов 2026-09-13 дали `native/pure/18`
//! 28.31–29.95 мс, `rust/18` 28.40–30.33, то есть 5–6%. Гуляют они **вместе**
//! — пятый прогон опустил все пять точек разом, — так что отношение переживает,
//! а разность двух точек, взятых из разных прогонов, нет. Чтобы снять и это,
//! нужен **изолированный процессор** (`isolcpus`/`cpuset`, отключённый SMT) или
//! машина без сеанса рабочего стола; ни того, ни другого здесь нет.
//!
//! Следствие для читателя: **всякое отношение мельче 1.2 берётся у [`paired`],
//! а не вычитанием двух строк отчёта criterion.** Строки отчёта годятся для
//! величин порядка самих чисел — например, для сравнения с соседом на Rust,
//! где разность и разброс одного порядка и обе стороны названы с размахом.
//!
//! Насколько это не теория, видно из одного прогона 2026-09-13, где обе схемы
//! отвечали разом. criterion: `boxed/18` 40.48 мс против `handled/18` 36.75 —
//! то есть программа **без** операции вышла на 4 мс медленнее той же
//! программы с операцией. [`paired`] в том же прогоне: разность 2.755 мс,
//! размах 0.483, запас 5.7x. Помеха, накрывшая окно одной точки, для
//! абсолютных чисел неотличима от работы; для чередования она общий
//! множитель, и он сокращается.
//!
//! # Ответ на символьную строку §6, 2026-09-13 (третья редакция)
//!
//! Мерено **до** схлопывания пары `dup`/`drop` (2026-09-14, ниже): понижение с
//! тех пор стало дешевле на 13%, сосед не менялся, и таблица его теперь
//! недооценивает.
//!
//! **Паритет: 0.99 (0.99–1.01).** Пять прогонов подряд, привязка к одному
//! P-ядру, оценка — пол ([`harness::least`]), медианы за вычетом своего пола (0.196 мс
//! у `native`, 0.434 мс у соседа), глубина 18:
//!
//! | прогон | сосед на Rust | понижение | отношение |
//! |---|---|---|---|
//! | 1 | 29.40 мс | 29.76 мс | 1.01 |
//! | 2 | 29.66 | 29.60 | 1.00 |
//! | 3 | 29.90 | 29.70 | 0.99 |
//! | 4 | 29.86 | 29.55 | 0.99 |
//! | 5 | 27.97 | 28.11 | 1.01 |
//!
//! **Читается это число иначе, чем прежние, потому что мерена другая
//! программа.** Прежние редакции мерили один проход `scaled` и дали 1.19;
//! эта мерит цепочку из [`PASSES`], и цепочку понижение проходит дешевле. У
//! соседа каждый проход стоит 2^19 пар «выделить/освободить» — он на каждый
//! узел роняет ячейку и берёт новую; у понижения проходы сверх первого не
//! стоят **ни одной** ячейки, и это видно в счётчике блоков: `native/pure/18`
//! печатает 524305 при одном проходе и 524305 при четырёх. Разрыв, который
//! при одном проходе составлял 1.19, цепочка съедает целиком.
//!
//! То есть §6 («паритет с Rust или лучше») достигнут не правкой понижения, а
//! тем, что стенд наконец меряет workload, который §6 и называет:
//! «цепочками функциональных преобразований». Строка §6 прямо говорит, что
//! опирается на FBIP, — вот на нём она и держится. Число за один проход
//! (1.14–1.19) остаётся верным для одного прохода и приведено ниже как
//! разложение.
//!
//! ## Из чего состояли 2.4 раза (замер за один проход, 2026-09-13)
//!
//! Разложено разностными сборками одного и того же порождённого C, с
//! пофазным замером **внутри** процесса (глубина 18, медиана 15 прогонов, мс):
//!
//! | точка | grow | scaled | total | сумма |
//! |---|---|---|---|---|
//! | сосед на Rust | 9.20 | 4.56 | 3.79 | 17.55 |
//! | тот же алгоритм руками на C | 10.04 | 3.89 | 3.04 | 16.97 |
//! | понижение, как собиралось утром | 16.20 | 12.08 | 14.06 | **42.34** |
//! | оно же с [`harness::RELEASE`] | 9.40 | 2.90 | 5.35 | **17.65** |
//!
//! - **Невстроенные вызовы в рантайм — 24.7 мс из 24.8 мс разрыва.** Горячий
//!   путь состоит из `adamas_tag`, `adamas_field`, `adamas_dup`, `adamas_drop`;
//!   каждый — несколько инструкций в **чужой** единице трансляции. Проверено
//!   двумя независимыми способами, давшими одно: `-flto` и `static inline`
//!   тех же примитивов прямо в файле программы — 17.65 против 17.63.
//! - **`scaled` быстрее соседа на 1.7 мс** — reuse §5.1 работает: сосед на
//!   каждый узел роняет ячейку и берёт новую, понижение переписывает свою.
//! - **`total` медленнее соседа на 1.6 мс** — RC: разбор дупает поля, а дроп
//!   разобранного родителя обходит их и дропает обратно. Пара **схлопнута**
//!   2026-09-14 ([`perceus`], `Salvage`): у уникального родителя поля переходят
//!   ветви даром, невзятые дропает сам дроп, блок освобождается без release.
//!   Взято это **больше 5%**, названных прежней оценкой, и вот чем: правка
//!   порождённого C, которой мерена оценка, трогала только `total`, а проход
//!   берёт заодно `scaled` — а её цепочка идёт [`PASSES`] раз — и `grow`.
//!   Замер — ниже.
//! - **Заголовок объекта, косвенность `adamas_value`, аллокатор — ноль
//!   дифференциально.** Тот же алгоритм руками на C, теми же формами данных и
//!   тем же `malloc`, стоит 16.97 против 17.55 у соседа: пара gcc/glibc
//!   соседу не проигрывает, и весь разрыв принадлежал нам.
//! - **Индуктивный `Nat` вместо машинного счётчика — 0.47 мс (2.8%).** Тот же
//!   потолок со счётчиком-списком стоит 17.44 против 16.97. Гипотеза
//!   «счётчик дорог» отвергнута замером.
//!
//! ## Схлопывание пары `dup`/`drop`: чего оно стоило (2026-09-14)
//!
//! **3.54 мс из 26.92, то есть 13%.** Мерено между двумя сборками самого
//! компилятора: тот же исходник Adamas (`pure`, глубина 18), тот же
//! [`harness::RELEASE`], тот же рантайм, — понижен до и после правки. Ответ у обеих
//! сторон 8349405806592, блоков выдано 524305 обеими: схлопывание трогает
//! счётчики, а не аллокации, и это условие годности замера, а не наблюдение.
//!
//! Протокол — [`paired`] дословно: чередование внутри блока, оценка стороны —
//! пол блока, в число идут четыре тишайших из семи, привязка к одному P-ядру.
//! Пять прогонов подряд:
//!
//! | прогон | 1 | 2 | 3 | 4 | 5 |
//! |---|---|---|---|---|---|
//! | разность, мс | 3.538 | 3.593 | 3.538 | 3.504 | 3.463 |
//!
//! Медиана 3.538, размах между прогонами 0.130, **запас 27x**. Пол базовой
//! стороны держался 26.84–27.02.
//!
//! Чередование здесь не роскошь, а то же требование, что и всюду: разность
//! мельче 1.2 от самих чисел, и врозь эти две точки не разрешаются.
//!
//! Строка §6 выше мерена **до** схлопывания, и её паритет 0.99 понижение
//! теперь недооценивает: сосед не менялся, а понижение стало на 13% дешевле.
//! Прямого чтения таблицы это не заменяет — оно требует тихой машины, а
//! величина, которую даёт неспокойная, недействительна по «Методике».
//!
//! ## Что осталось в 1.14–1.19
//!
//! Пофазно в процессе понижение и сосед сходятся (17.65 против 17.55), а
//! процессом расходятся на 3.4 мс. Разница названа: **2.5 мс из них —
//! консолидация свободных списков glibc**, и платит её первый `malloc`,
//! который не влезает в tcache, после того как программа освободила полмиллиона
//! ячеек. Таким первым выделением оказывается буфер `stdout`, который glibc
//! заводит на первом `printf` — то есть на печати ответа. Свидетель: `setvbuf`
//! статическим буфером до начала работы убирает хвост целиком (2.55 → 0.03 мс),
//! не трогая ни одной строки счёта. Сосед этого не платит потому, что его
//! первое послеосвобожденческое выделение мельче порога.
//!
//! Работа это или нет — зависит от программы, которая не кончается печатью;
//! стенд её не решает и потому и не прячет. Пол не помогает: он мерен на
//! глубине 0, где свободных списков ещё нет. На цепочке из [`PASSES`] эта
//! статья остаётся той же по величине — печать одна на программу, — а доля её
//! падает вчетверо; отсюда часть паритета.
//!
//! Прежние чтения объяснены: «в полтора раза быстрее» (2026-09-11) — соседом
//! на взболтанной куче, «втрое медленнее» (2026-09-12) — соседом без цены
//! запуска процесса, «2.4 раза» (утро 2026-09-13) — соседом, собранным
//! межмодульно, против понижения, собранного по частям, «1.19» (день
//! 2026-09-13) — цепочкой в один проход, где reuse нечего окупать.
//!
//! # Чем проверено, что мерится не пустота
//!
//! Тремя вещами разом. Ответ **печатается** — обеими сторонами, соседом тоже,
//! — и сверен с машиной: выброси компилятор C вычисление, печатать станет
//! нечего. Точек по глубине три, и шаг глубины удваивает работу: линейному
//! исполнению отвечает удвоение времени. И полы показывают, сколько в
//! измеренном не работа, а запуск процесса.
//!
//! Защита проверена мутантом по времени после перевода соседа на процесс
//! (2026-09-13). `scaled (Node l r) = Node l r` **в исходнике Adamas**:
//! `assert_eq!` в цикле форм ловит его первым — 402644992 против 1207934976 у
//! соседа. Если сломать сразу обе стороны, сверка молчит, а время идёт следом
//! за ответом: 309237252096 → 103079084032, `rust/18` 18.6 → 14.3 мс,
//! `native/pure/18` 43.5 → 30.6 мс.
//!
//! Точка `native/handled` сверх того проверена двумя мутантами, и оба ловятся.
//!
//! - **Работа.** `scaled (Node l r) = Node l r` — свёртка перестаёт спускаться
//!   по дереву. Ответ меняется (309237252096 → 103079084032, ровно треть),
//!   время на глубине 16 падает 18.8 → 9.9 мс, блоки 1835025 → 524308.
//!   Заодно пойман соседом на Rust: `assert_eq!` у `rust/*` сработал раньше
//!   всех прочих.
//! - **Операция.** `scale ask x` → `scale Triple x` при сохранённых row,
//!   объявлении эффекта и хендлере. Ответ тот же, а разность точек обязана
//!   исчезнуть: `handled` садится на `boxed`. Значит измеряемая разность есть
//!   операция, а не вторая форма вообще.
//!
//!   **Свидетель молчал между первой ступенью вопроса 74 и 2026-09-13.**
//!   Ступень опустила цену хендлера с 1.43–1.50 до единиц процентов, а мутант
//!   различал именно её: пять прогонов с мутантом дали `handled/18` 23.95 мс
//!   против `boxed` 25.47 — «медленнее» вышло быстрее, при размахе 1.55.
//!   Блоки не помогали вовсе: после ступени операция не стоит ни одной
//!   ячейки, и 49168 против 49165 читается одинаково с мутантом и без.
//!
//!   **Заговорил он от тех же двух правок, что и стенд**, — не от подпорки
//!   под мутанта. Цепочка [`PASSES`] подняла разность, [`paired`] убрала из
//!   неё увод окружения, и мутант ловится ими обеими, на любой глубине:
//!
//!   | глубина | без мутанта | с мутантом |
//!   |---|---|---|
//!   | 14 | +0.163 мс | −0.054 |
//!   | 18 | +3.096 | −0.117 |
//!
//!   Ловит его не сравнение с ожидаемым числом, а обязательство порядка:
//!   `handled` есть `boxed` плюс операция, значит медленнее. [`paired`] это
//!   проверяет и падает, называя обе величины. Мутант на глубине 14 —
//!   наименьшей и потому наихудшей — пойман первым же блоком.
//!
//! Второй мутант заодно показал, чего в решении 3 волны 4 не написано:
//! кадр ставится **не** на всякий вызов второй формы, а только там, откуда
//! приостановка достижима. У мутанта `scaled` осталась второй формой — берёт
//! `ev` и `kont`, — но `adamas_kont_push` в порождённом C не встречается ни
//! разу, и рекурсия идёт прямыми вызовами.
//!
//! Точка `native/handled-flat` держится на том же ответе и сверх того на двух
//! свидетелях вне стенда: `tests/boundary.rs` смотрит **представление** в
//! тексте C, а корпусная `eval/flat-across-a-suspension` — ширину перевода
//! через `Float64`. Стенд один их не заменяет: у него множитель целый, а на
//! целых подмена ширины сокращается — C приводит число обратно.
//!
//! # Цена хендлера: против чего она мерится
//!
//! Формы четыре, и ни одна не заведена для симметрии. Мерить `handled` против
//! `pure` было бы враньём: между ними **два** различия, а не одно.
//!
//! Различие первое — операция. Различие второе — представление множителя.
//! Отсюда [`Shape::Boxed`]: тот же алгоритм, множитель — **нульарный
//! конструктор** `Mult`, который применяет к листу чистая `scale`. Конструктор
//! без рантайм-полей объектом не становится (ABI 2026-09-08), то есть ячейки
//! кучи боксирование здесь не стоит; стоит оно вызова `scale` на лист, и
//! платят его `Boxed` и `TailResumptive` **одинаково**.
//!
//! Что мерит разность этих двух точек, зависит от среза. До первой ступени
//! вопроса 74 (2026-09-12) она мерила цену второй формы с дроблением: вектор
//! evidence скрытым аргументом, тело `scaled` кадрами по точкам приостановки,
//! диспетчер операции — 1.43–1.50 и ровно четыре блока на операцию, число
//! milestone 3. После ступени (2026-09-13) программа тиха — единственная
//! ветка хвостовая, — тело не дробится, и разность мерит **остаток**:
//! evidence-поиск и непрямой вызов ветки на лист. В блоках — **три на
//! программу** (кадр хендлера и два вектора evidence), ноль на операцию.
//! Этим числом закрыт вопрос 74: заказчика у специализации по row среди
//! записанных не осталось.
//!
//! ## Milestone 3, перемеренный парно (2026-09-13, третья редакция)
//!
//! Прежние отношения — 0.99–1.05, потом 1.01/1.03/1.04 — брались вычитанием
//! двух точек, померенных врозь, и держались только на медианах: разность
//! была меньше размаха. Теперь она берётся у [`paired`]. Пять прогонов,
//! медиана и размах **между** прогонами:
//!
//! | глубина | разность | размах | запас | на операцию |
//! |---|---|---|---|---|
//! | 14 | 0.163 мс | 0.039 | 4.2x | 2.49 нс |
//! | 16 | 0.739 | 0.184 | 4.0x | 2.82 нс |
//! | 18 | **3.096** | **0.579** | **5.3x** | **2.95 нс** |
//!
//! Число, которое сравнимо между срезами и глубинами, — **цена операции:
//! 2.5–3.0 нс**, то есть при 4.6 гигагерца около двенадцати тактов на
//! evidence-поиск плюс непрямой вызов ветки. Отношение из него выводится, но
//! отношению нужна ещё и программа: на цепочке из [`PASSES`] это **1.09**
//! (3.096 мс на 33.97).
//!
//! **С записанным 1.03–1.07 это сходится по нижнему краю**, и сходится
//! проверяемо: тот же стенд при `PASSES = 1` даёт разность 0.807 мс на
//! `boxed` 21.83, то есть **1.037**. Расхождения, которое стоило бы называть
//! находкой, нет. Находка обратная — **ширина 1.03–1.07 принадлежала стенду,
//! а не хендлеру**: цена операции держится в пределах 20% по трём глубинам и
//! пяти прогонам, тогда как отношение гуляло на 4%, потому что его знаменатель
//! мерился врозь.
//!
//! Тот же прогон при `PASSES = 1` показывает, зачем цепочка: запас на глубине
//! 18 падает до **1.0x** — разность 0.807 мс при размахе 0.788. Одного
//! чередования мало, одной цепочки тоже: разрешает пара.
//!
//! Точка `pure` при этом не сдвинулась ни на строку исходника, кроме длины
//! цепочки, общей всем четырём формам: строка §6 «символьно-тяжёлый код»
