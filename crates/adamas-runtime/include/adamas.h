/**
 * Код замыкания: сам себе `userdata`, оба скрытых аргумента, последний явный.
 *
 * Форм у понижения две, а граница замыкания **динамическая**: какая из них за
 * указателем, место вызова не знает. Поэтому здесь идёт объединение - и вектор,
 * и ручка стека, - а тело первой формы их просто не смотрит. Обещание «первая
 * форма не платит ничего» держится там, где вызываемый известен статически: его
 * понижение зовёт прямо, по `adamas_lowered_first`.
 */
typedef adamas_value (*adamas_code)(adamas_value self, const adamas_evidence *evidence,
                                    adamas_kont *kont, adamas_value argument);

/* Теги служебных объектов рантайма. Номера конструкторов раздаёт понижение
 * снизу, поэтому верх диапазона свободен. */

/** Тег замыкания в заголовке. */
#define ADAMAS_TAG_CLOSURE 0xFFFFu
/** Тег вектора evidence. */
#define ADAMAS_TAG_EVIDENCE 0xFFFEu
/** Тег сегмента продолжения. */
#define ADAMAS_TAG_SEGMENT 0xFFFDu
/** Тег невыразимого имени файбера (§5.2). */
#define ADAMAS_TAG_FIBER 0xFFF9u

/**
 * Замыкание на `arity` аргументов с `captured` слотами среды. Слоты среды
 * записываются `adamas_closure_set`; за ними рантайм держит место под
 * накопленные аргументы.
 */
adamas_value adamas_closure(adamas_code code, adamas_release release, uint32_t arity,
                            uint32_t captured);

/** Записывает слот среды, владение переходит замыканию. */
void adamas_closure_set(adamas_value closure, size_t index, adamas_value field);

/** Слот замыкания: среда, затем накопленные аргументы. */
adamas_value adamas_closure_get(adamas_value closure, size_t index);

/** Указатель на код - им же берётся голый C-указатель для §5.3. */
adamas_code adamas_closure_code(adamas_value closure);

/** Сколько аргументов замыкание ещё ждёт. */
uint32_t adamas_closure_missing(adamas_value closure);

/**
 * Сколько слотов **занято**: среда плюс накопленные аргументы.
 *
 * Спрашивает это release, порождённый понижением: `applied` меняется частичным
 * применением, а указатель на release остаётся тот же, поэтому число обязано
 * приходить от рантайма, а не быть вписано в порождённый код.
 */
size_t adamas_closure_taken(adamas_value closure);

/** Дроп замыкания как `adamas_release`: зовёт носимый им release. */
void adamas_closure_release(adamas_value closure);

/**
 * Применение. Замыкание, вектор и стек заимствуются, аргумент берётся
 * **владением**. Не хватает аргументов - ответ новое замыкание с дописанным, и
 * скрытые аргументы тогда не смотрятся вовсе: вызова не было.
 */
adamas_value adamas_apply(adamas_value closure, const adamas_evidence *evidence, adamas_kont *kont,
                          adamas_value argument);

