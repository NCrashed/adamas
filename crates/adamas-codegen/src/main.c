int main(void) {
    /* Вектор evidence пуст: хендлеров в чистом фрагменте нет. Пустой вектор -
     * `NULL`, и рантайм принимает его всюду, где вектор читается. */
    adamas_value answer = ADAMAS_ENTRY(NULL);
    adamas_print(answer, 0);
    printf("\n");
    /* Perceus (волна 3) ещё не вставлен: `dup` и `drop` не эмитятся ни одного,
     * поэтому программа не освобождает ничего. Счётчики говорят это числом -
     * затыкать течь разовыми `free` нельзя, вставку их пришлось бы потом
     * выковыривать из-под настоящей. */
    fprintf(stderr, "блоков выдано %zu, живо %zu\n", adamas_stat_allocated(),
            adamas_stat_live());
    return 0;
}
