/// Байты строки с завершающим нулём.
fn terminated(text: &str) -> Vec<u8> {
    let mut bytes = text.as_bytes().to_vec();
    bytes.push(0);
    bytes
}

/// Байты строковой константы в форме `.ll`.
///
/// Экранируется всё, кроме печатной латиницы и пробела: русский текст занимает
/// два байта на букву, и печатать их сырыми значило бы полагаться на кодировку
/// файла там, где `.ll` объявлен байтовым.
fn escaped(bytes: &[u8]) -> String {
    let mut out = String::new();
    for byte in bytes {
        if *byte == b' ' || (byte.is_ascii_graphic() && *byte != b'"' && *byte != b'\\') {
            out.push(char::from(*byte));
        } else {
            let _ = write!(out, "\\{byte:02X}");
        }
    }
    out
}

/// Тип регистра, в который представление ложится. `None` - не ложится.
///
/// Указательных три - [`Repr::Boxed`], [`Repr::Record`] и [`Repr::Resumption`]:
/// в рантайме это один и тот же объект с заголовком, а различие форм живёт в
/// понижении (`ir.rs`, [`Repr::pointer`]). Резумпция стояла здесь под запретом,
/// пока второй формы не было вовсе: дроп у неё свой - `adamas_resumption_drop`
/// с ручкой стека (§3.4), - и взять её типом значило бы дропнуть её как данные.
/// Запрет снят вместе с приходом дропа: различает их [`Builder::dropped`] по
/// представлению связывания, а тип у них и правда один.
fn slot(repr: Repr) -> Option<String> {
    match repr {
        // Массив (§4.11) стоит здесь наравне с прочим указательным: один блок
        // кучи на всю длину, заголовок один, счётчик один. Различие с
        // [`Repr::Boxed`] живёт в понижении ([`Repr::pointer`]) - оно помнит,
        // что за объект за указателем, - и в регистре не наблюдаемо.
        Repr::Boxed | Repr::Record(_) | Repr::Resumption | Repr::Array(_) => Some("ptr".to_owned()),
        // Вектор (§4.9) - единственное представление, чьё имя типа не
        // постоянно: ширина есть часть имени. Ради него все эти имена и стали
        // владеющими.
        Repr::Simd { lanes, lane } => Some(vector(lanes, lane)),
        other => other.primitive().map(|ty| machine(ty).to_owned()),
    }
}

/// Векторный тип LLVM: `<8 x float>` (§4.9).
///
/// Форма эта в LLVM с самого начала и между мажорами не двигалась - в отличие
/// от `llvm.vector.*`-интринсиков, которых этот срез не эмитит ни одного.
/// Проверяется правило треугольником версий (`tests/llvm.rs`), а не обещанием.
fn vector(lanes: u32, lane: PrimTy) -> String {
    format!("<{lanes} x {}>", machine(lane))
}

/// Он же с названным отказом.
fn slot_or(function: &Function, place: &str, repr: Repr) -> Result<String, LlvmError> {
    slot(repr).ok_or_else(|| LlvmError::Shape {
        function: function.name.clone(),
        place: place.to_owned(),
        shape: describe(repr),
    })
}

/// Состояние эмиссии одного тела.
struct Builder<'a> {
    program: &'a Program,
    function: &'a Function,
    /// Тип регистра, в котором функция отдаёт ответ.
    ///
    /// Нужен обходу хвостовой позиции: `ret` печатает он, а не вызывающий, и
    /// печатей этих у разбора столько, сколько ветвей.
    result: String,
    /// Что в каком связывании лежит: от этого тип регистра.
    reprs: HashMap<LocalId, Repr>,
    /// Связывания, чьё производство уникально ([`Unique::Certain`], трек B).
    ///
    /// Заполняет его [`crate::unique`] на IR, а не эмиттер по виду выражения:
    /// факт этот межпроцедурный - параметр уникален потому, что **каждое**
    /// место вызова кладёт в позицию свежий объект, - и увидеть его из одного
    /// тела нельзя.
    certain: HashSet<LocalId>,
    /// Чем связывание представлено в тексте.
    ///
    /// Подстановка, а не своё имя на связывание: `let` в IR - дерево, значение
    /// у него единственное, и лишний регистр пришлось бы заводить инструкцией,
    /// у которой для указателя нет формы (`add ptr` не бывает).
    operands: HashMap<LocalId, String>,
    /// Начало блока `entry`: только `alloca`.
    ///
    /// Отдельно от тела, потому что ячейка кадра обязана лежать в `entry`:
    /// `alloca` в блоке разбора была бы динамической, а по динамической
    /// `llvm.dbg.declare` не даёт постоянного смещения в кадре, и отладчик
    /// показал бы переменную не там. Запись в ячейку остаётся на месте, где
    /// значение посчитано, - так же делает всякий компилятор на `-O0`.
    head: String,
    /// Текст тела: блоки в порядке печати.
    body: String,
    /// Узлы метаданных модуля: сюда идут переменные и локации.
    metadata: &'a mut Metadata,
    /// Шапка DWARF, если исходник назван.
    dwarf: Option<&'a Dwarf>,
    /// Подпись этой функции. `None` - позиции у неё нет, и DWARF ей не пишется.
    scope: Option<Scope>,
    /// Счётчик ячеек кадра, заведённых ради отладчика.
    frames: u32,
    /// Счётчик временных имён.
    temps: u32,
    /// Счётчик разборов: им нумеруются блоки.
    matches: u32,
    /// Имя блока, в который печатается инструкция.
    ///
    /// Нужно `phi`: предшественник ветви - блок, которым она **закончилась**, а
    /// не тот, которым началась, и различаются они, как только внутри ветви
    /// встал ещё один разбор.
    block: String,
    /// Кто приостанавливается (§3.4, решение 3 волны 4).
    ///
    /// Читают это двое - [`crate::split`] и эмиттер, - и запись у них одна:
    /// проход выносит приостанавливающееся подвыражение в связывание, эмиттер
    /// ставит под него кадр. Разойдись они - кадр встал бы не там.
    suspending: &'a Suspension,
    /// Регистр, в котором лежит вектор evidence. `None` - взять его негде.
    ///
    /// Полем, а не именем: под `handle` действует **расширенный** вектор, и
    /// вычисление под ним идёт хвостом того же куска. В C это делает
    /// затенение имени внутри блока; в `.ll` блоков-областей нет вовсе.
    ///
    /// `None` у первой формы вне хендлера: скрытых аргументов у неё нет вовсе,
    /// и прямой вызов второй формы оттуда - названный отказ
    /// ([`LlvmError::Hidden`]), а не `null` в аргументе.
    ev: Option<String>,
    /// Он же для ручки стека продолжения.
    kont: Option<String>,
    /// Что обязан отдать всякий возврат из этого куска.
    ///
    /// Живёт здесь один жанр - расширенный вектор evidence места `handle`:
    /// вычисление под ним идёт хвостом того же куска, а дроп поставить после
    /// `ret` нечем. Кадры, положенные вычислением, свою ссылку берут сами.
    epilogue: Vec<String>,
    /// Готовые куски дроблёного тела: каждый - своя функция модуля.
    chunks: Vec<String>,
    /// Счётчик кусков: им нумеруются их имена.
    chunked: u32,
}

impl<'a> Builder<'a> {
    fn new(
        program: &'a Program,
        function: &'a Function,
        result: String,
        suspending: &'a Suspension,
        metadata: &'a mut Metadata,
        dwarf: Option<&'a Dwarf>,
        scope: Option<Scope>,
    ) -> Self {
        let hidden = function.form == Form::Detached;
        let mut reprs = HashMap::new();
        let mut operands = HashMap::new();
        let mut certain = HashSet::new();
        for binding in function.captured.iter().chain(&function.parameters) {
            reprs.insert(binding.local, binding.fact.repr);
            if binding.fact.unique == Unique::Certain {
                certain.insert(binding.local);
            }
        }
        // Значение получают только **дожившие** (§3.3): стёртого в рантайме нет
        // вовсе, и в сигнатуре его нет тоже. Упомяни его тело - и отказ придёт
        // названным, а не неопределённым именем в `.ll`.
        for binding in function.live_captured().chain(function.live_parameters()) {
            operands.insert(binding.local, format!("%v{}", binding.local.0));
        }
        collect(&function.body, &mut reprs, &mut certain);
        Self {
            program,
            function,
            result,
            reprs,
            certain,
            operands,
            head: String::new(),
            body: String::new(),
            metadata,
            dwarf,
            scope,
            frames: 0,
            temps: 0,
            matches: 0,
            block: "entry".to_owned(),
            suspending,
            ev: hidden.then(|| "%ev".to_owned()),
            kont: hidden.then(|| "%kont".to_owned()),
            epilogue: Vec::new(),
            chunks: Vec::new(),
            chunked: 0,
        }
    }

    /// Кладёт параметры в кадр, чтобы отладчик их видел.
    ///
    /// Ячейка **сверх** регистра, а не вместо него: вычисление по-прежнему идёт
    /// по `%vN`, а ячейка существует ровно ради `llvm.dbg.declare`. Переписывать
    /// тело на чтение из ячейки незачем - параметр в Adamas не переприсваивается,
    /// и записанное в прологе остаётся верным до конца.
    ///
    /// Цена названа: на `-O0` это лишняя запись в кадр на параметр. На `-O2`
    /// ячейка исчезает вместе с `mem2reg`, а вместе с ней и наблюдаемость - тот
    /// же размен, что у всякого компилятора.
    fn parameters_in_frame(&mut self, function: &Function) {
        if self.scope.is_none() {
            return;
        }
        for (at, binding) in function.live_parameters().enumerate() {
            let Some(ty) = slot(binding.fact.repr) else {
                continue;
            };
            let cell = self.frame_cell(&ty);
            let prologue = self.synthetic();
            self.instruction(
                &format!("store {ty} %v{}, ptr {cell}", binding.local.0),
                prologue.clone(),
            );
            let argument = u32::try_from(at + 1).unwrap_or(u32::MAX);
            self.declare(
                &binding.name,
                binding.fact.repr,
                Some(argument),
                &cell,
                prologue,
            );
        }
    }

    /// Заводит ячейку кадра и отдаёт её имя.
    fn frame_cell(&mut self, ty: &str) -> String {
        let cell = format!("%f{}", self.frames);
        self.frames += 1;
        let _ = writeln!(self.head, "  {cell} = alloca {ty}");
        cell
    }

    /// Объявляет отладчику переменную, лежащую в названной ячейке.
    ///
    /// `llvm.dbg.declare`, а не `llvm.dbg.value`: восемнадцатая версия печатает
    /// отладочные записи вызовами интринсиков, двадцать первая - записями
    /// `#dbg_declare`, и **общий** у них ровно вызов: новая читает старую форму
    /// и поднимает её, старая новую не читает вовсе. Проверено прогоном обеих
    /// цепочек, а не таблицей совместимости.
    fn declare(&mut self, name: &str, repr: Repr, argument: Option<u32>, cell: &str, notes: Notes) {
        let (Some(dwarf), Some(scope)) = (self.dwarf, self.scope.clone()) else {
            return;
        };
        let ty = Dwarf::ty(self.metadata, repr);
        let arg = argument.map_or_else(String::new, |at| format!("arg: {at}, "));
        let variable = self.metadata.node(&format!(
            "!DILocalVariable(name: \"{}\", {arg}scope: {}, file: {}, line: {}, type: {ty})",
            escaped_name(name),
            scope.subprogram,
            dwarf.file,
            scope.at.line
        ));
        self.instruction(
            &format!(
                "call void @llvm.dbg.declare(metadata ptr {cell}, \
                 metadata {variable}, metadata !DIExpression())"
            ),
            notes,
        );
    }

    /// Кладёт связывание `let` в кадр - ради отладчика, как и параметры.
    ///
    /// Ячейка в `entry`, запись здесь: до этой записи значения ещё нет, и
    /// отладчик, остановленный раньше, покажет мусор. Так же ведёт себя всякая
    /// неинициализированная переменная на `-O0`, и врать об этом нечем.
    fn in_frame(&mut self, binding: &Binding, value: &str) {
        if self.scope.is_none() || !binding.fact.present {
            return;
        }
        let Some(ty) = slot(binding.fact.repr) else {
            return;
        };
        let cell = self.frame_cell(&ty);
        self.instruction(&format!("store {ty} {value}, ptr {cell}"), self.here());
        self.declare(&binding.name, binding.fact.repr, None, &cell, self.here());
    }

    /// Локация ненаписанного кода: строка нуль. Пусто без отладочной
    /// информации.
    ///
    /// Не путать с `Builder::prologue` трека D: тот снимает узлы-приставки, а
    /// это - подпись инструкций, которых в исходнике нет.
    fn synthetic(&self) -> Notes {
        match &self.scope {
            Some(scope) => Notes::none().and("dbg", &scope.prologue),
            None => Notes::none(),
        }
    }

    /// Свежее временное имя.
    fn temp(&mut self) -> String {
        let name = format!("%t{}", self.temps);
        self.temps += 1;
        name
    }

    /// Единственная точка печати инструкции.
    ///
    /// Одна на весь эмиттер намеренно: форма суффикса метаданных живёт здесь, а
    /// не в двух десятках мест печати. Сами метаданные приходят **аргументом** -
    /// почему, сказано у [`Notes`].
    fn instruction(&mut self, text: &str, notes: Notes) {
        let _ = writeln!(self.body, "  {text}{}", notes.suffix());
    }

    /// Метаданные, которые несёт всякая инструкция тела.
    ///
    /// Сегодня это `!dbg` - строка определения. Своё дописывается поверх:
    /// `self.here().and("noalias", "!7")`.
    fn here(&self) -> Notes {
        match &self.scope {
            Some(scope) => Notes::none().and("dbg", &scope.here),
            None => Notes::none(),
        }
    }

    /// Начинает новый блок.
    fn start(&mut self, label: &str) {
        let _ = writeln!(self.body, "\n{label}:");
        label.clone_into(&mut self.block);
    }

    /// Отказ, названный этой функцией.
    fn node(&self, node: &'static str) -> LlvmError {
        LlvmError::Node {
            function: self.function.name.clone(),
            node,
        }
    }

    /// Текст, которым связывание попадает в инструкцию.
    fn operand(&self, local: LocalId) -> Result<String, LlvmError> {
        self.operands
            .get(&local)
            .cloned()
            .ok_or_else(|| self.node("связывание без значения"))
    }

    /// Представление значения выражения.
    fn shape(&self, expr: &Expr) -> Repr {
        match expr {
            Expr::Local(local) => self.reprs.get(local).copied().unwrap_or(Repr::Boxed),
            Expr::Literal { ty, .. } | Expr::Primitive { ty, .. } => Repr::Flat(*ty),
            Expr::Call { function, .. } => self.program.functions[function.0].result,
            Expr::Bind { body, .. }
            | Expr::Dup { body, .. }
            | Expr::Drop { body, .. }
            | Expr::Reclaim { body, .. } => self.shape(body),
            Expr::Match { arms, .. } => arms
                .first()
                .map_or(Repr::Boxed, |arm| self.shape(&arm.body)),
            // Массив (§4.11): постройка и запись отдают его же, чтение - ячейку.
            // Те же три строки, что у C-эмиттера, и это не совпадение: обход
            // один, и разъедься они - два бэкенда назвали бы одному узлу разные
            // представления.
            Expr::ArrayNew { stride, .. } | Expr::ArraySet { stride, .. } => {
                Repr::Array(elems(*stride))
            }
            Expr::ArrayIndex { stride, .. } => stride.map_or(Repr::Boxed, Stride::element),
            // Ответ сравнения - конструктор `Bool` (§4.3): аргументы плоские,
            // ответ указательный. Ответ конструктора указателен по построению -
            // и объект, и форма записи в рантайме одно и то же. Прочее срез
            // отвергает, и представление его здесь не спрашивается.
            _ => Repr::Boxed,
        }
    }

    /// Тип регистра, в котором лежит значение выражения.
    fn typed(&self, expr: &Expr) -> Result<String, LlvmError> {
        let repr = self.shape(expr);
        slot(repr).ok_or_else(|| LlvmError::Shape {
            function: self.function.name.clone(),
            place: "промежуточное значение".to_owned(),
            shape: describe(repr),
        })
    }

    /// Печатает узлы-приставки до упора и отдаёт то, что под ними.
    ///
    /// Приставка - `let`, `dup` и `drop`: узел печатает голову и передаёт
    /// позицию телу. Одна печать на **обе** позиции намеренно: разъедься они -
    /// хвостовой путь потерял бы счётчик молча, а расхождение вылезло бы
    /// течью, а не отказом.
    ///
    /// Отсюда же и то, что хвост считается контекстом, а не полем узла: дроп,
    /// вставленный Perceus **после** вызова, попадает в `value` и хвоста не
    /// получает; вставленный до - остаётся здесь, и хвост уезжает дальше в
    /// тело. Ни одного признака в представлении для этого не нужно.
    ///
    /// Цикл, а не рекурсия: цепочка `let` в понижении бывает длинной, и
    /// рекурсия по ней клала бы стек компилятора на ровном месте.
    fn prologue<'e>(&mut self, expr: &'e Expr) -> Result<&'e Expr, LlvmError> {
        let mut at = expr;
        loop {
            let next = self.bookkept(at)?;
            if std::ptr::eq(next, at) {
                return Ok(at);
            }
            at = next;
        }
    }

    /// Один шаг [`Self::prologue`]: печатает голову узла-приставки и отдаёт
    /// тело. Узел, приставкой не являющийся, отдаётся собой.
    ///
    /// Шагом, а не только циклом, потому что обход дроблёного тела
    /// ([`Self::flowing`]) обязан **прерваться** на связывании, чьё значение
    /// приостанавливается: продолжение такого связывания уезжает кадром, а не
    /// печатается следом.
    fn bookkept<'e>(&mut self, expr: &'e Expr) -> Result<&'e Expr, LlvmError> {
        match expr {
            Expr::Bind {
                binding,
                value,
                body,
            } => {
                let computed = self.value(value)?;
                let _ = writeln!(self.body, "  ; {computed} - {}", binding.name);
                self.in_frame(binding, &computed);
                self.operands.insert(binding.local, computed);
                Ok(body)
            }
            Expr::Dup { local, body } => {
                let value = self.operand(*local)?;
                let name = self.temp();
                self.instruction(
                    &format!("{name} = call ptr @adamas_dup(ptr {value})"),
                    self.here(),
                );
                Ok(body)
            }
            Expr::Drop {
                local,
                salvage,
                body,
            } => {
                self.dropped(*local, salvage, None)?;
                Ok(body)
            }
            Expr::Reclaim {
                local,
                token,
                salvage,
                body,
            } => {
                self.dropped(*local, salvage, Some(*token))?;
                Ok(body)
            }
            // Придержанный блок, которому постояльца не нашлось (§10 вопрос
            // 173). `adamas_free`, а не `adamas_drop`: счётчик он уже отдал, а
            // поля release обошёл на месте придержания. `null` - разделённое
            // разобранное, и отдавать нечего.
            Expr::Discard { token, body } => {
                let value = self.operand(*token)?;
                self.instruction(&format!("call void @adamas_free(ptr {value})"), self.here());
                Ok(body)
            }
            other => Ok(other),
        }
    }

    /// Эмитит выражение в **возвратной** позиции: блок кончается `ret`.
    ///
    /// Хвостовой вызов печатается `musttail` с `ret` следом - этого и требует
    /// LLVM, - а разбор раздаёт возвратную позицию своим ветвям, вместо того
    /// чтобы сводить их `phi` (трек D). `ret` печатает поэтому обход, а не
    /// вызывающий: у разбора их столько, сколько ветвей.
    fn tail(&mut self, expr: &Expr) -> Result<(), LlvmError> {
        let expr = self.prologue(expr)?;
        match expr {
            Expr::Match {
                scrutinee, arms, ..
            } => self.analysis_tail(scrutinee, arms),
            Expr::Call {
                function,
                arguments,
            } => {
                // `musttail` требует, чтобы `ret` вернул **значение вызова**, а
                // значит чтобы типы сошлись. У нашего понижения они сходятся по
                // построению - ответ функции и есть ответ хвостового вызова, -
                // но полагаться на это нечем: разойдись они, verifier отверг бы
                // модуль целиком. Обычный вызов в этом случае честнее отказа.
                let agreed = slot(self.program.functions[function.0].result)
                    .is_some_and(|it| it == self.result);
                let sort = if agreed { Tail::Must } else { Tail::Plain };
                let name = self.call(*function, arguments, sort)?;
                let result = self.result.clone();
                self.instruction(&format!("ret {result} {name}"), self.here());
                Ok(())
            }
            other => {
                let value = self.value(other)?;
                let result = self.result.clone();
                self.instruction(&format!("ret {result} {value}"), self.here());
                Ok(())
            }
        }
    }

    /// Эмитит выражение и отдаёт операнд, в котором лежит его значение.
    fn value(&mut self, expr: &Expr) -> Result<String, LlvmError> {
        let expr = self.prologue(expr)?;
        match expr {
            Expr::Local(local) => self.operand(*local),
            Expr::Literal { ty, bits } => Ok(constant(*ty, *bits)),
            Expr::Primitive {
                op,
                ty,
                left,
                right,
            } => self.arithmetic(*op, *ty, left, right),
            Expr::Compare {
                op,
                ty,
                left,
                right,
                yes,
                no,
            } => self.comparison(*op, *ty, left, right, (yes.0, no.0)),
            Expr::Call {
                function,
                arguments,
            } => self.call(*function, arguments, Tail::Plain),
            // Приставки сняты `prologue` выше, и досюда узел не
            // доезжает. Ветвь стоит ради исчерпывающего разбора: пропади она,
            // новый узел-приставка ушёл бы в тихий отказ вместо ошибки сборки.
            Expr::Bind { .. }
            | Expr::Dup { .. }
            | Expr::Drop { .. }
            | Expr::Reclaim { .. }
            | Expr::Discard { .. } => Err(self.node("узел-приставка после снятия приставок")),
            Expr::Match {
                scrutinee, arms, ..
            } => self.analysis(scrutinee, arms),
            // Стёртая позиция значением: то же `ADAMAS_ERASED`, что у
            // C-эмиттера. Встречается она в одном месте - аргументах операции:
            // раздача веток позиционна и типа операции не знает, поэтому
            // стёртый аргумент едет непосредственным значением, а ветка его
            // дропает наравне с лишними. Ячейки кучи за ним нет.
            Expr::Erased => {
                let name = self.temp();
                self.instruction(
                    &format!("{name} = call ptr @adamas_con0(i16 {ERASED_TAG})"),
                    self.here(),
                );
                Ok(name)
            }
            Expr::Construct {
                constructor,
                reuse,
                arguments,
            } => self.construct(*constructor, *reuse, arguments),
            Expr::ConstructClosure { constructor } => self.building(*constructor),
            Expr::Closure { function, captured } => self.closure(*function, captured),
            // Применение - точка приостановки всегда: какая из двух форм за
            // указателем, место вызова не знает (`crate::split`). В чистом
            // отрезке трамплин под неё заводится **свой**
            // ([`Self::applied`]); во второй форме её выносит дробление и
            // печатает [`Self::applying`].
            Expr::Apply { callee, argument } => self.applied(callee, argument),
            Expr::Pack { .. } | Expr::Unpack { .. } => Err(self.node("плотный агрегат")),
            Expr::Layout { .. } | Expr::LayoutField { .. } => Err(self.node("дескриптор укладки")),
            Expr::ArrayNew { .. } | Expr::ArraySet { .. } | Expr::ArrayIndex { .. } => {
                self.array(expr)
            }
            Expr::SimdSplat { lanes, lane, value } => self.splat(*lanes, *lane, value),
            Expr::SimdSet {
                lanes,
                lane,
                vector,
                at,
                value,
            } => self.insert(*lanes, *lane, vector, at, value),
            Expr::SimdLane {
                lanes,
                lane,
                vector,
                at,
            } => self.extract(*lanes, *lane, vector, at),
            Expr::SimdArith {
                op,
                lanes,
                lane,
                left,
                right,
            } => self.lanewise(*op, *lanes, *lane, left, right),
            Expr::RegionNew
            | Expr::RegionAlloc { .. }
            | Expr::RegionLast { .. }
            | Expr::RegionRead { .. }
            | Expr::RegionWrite { .. }
            | Expr::RegionRecycle { .. }
            | Expr::RegionPop { .. } => Err(self.node("регион")),
            Expr::Handle {
                handler,
                captured,
                computation,
            } => self.handling(*handler, captured, computation),
            Expr::Mask { label, computation } => self.masking(*label, computation),
            // Операция значением бывает только в тихой программе (вопрос 74):
            // там она не точка приостановки, и дробление её не выносит.
            Expr::Perform {
                label,
                operation,
                arguments,
            } => self.performing(*label, *operation, arguments),
            // Прочие точки приостановки значением не бывают: их снимает
            // дробление ([`crate::split`]), и в чистый отрезок они не попадают.
            Expr::Resume { .. } => Err(self.node("резумпция в чистом отрезке")),
            Expr::Closing { .. } => Err(self.node("выход из scope в чистом отрезке")),
            // Питомник в чистой функции - **корень своего стека**, тем же
            // правом, каким его заводит хендлер: row у `withNursery` пуста, и
            // наружу круга не уходит ни одной операции (§3.4, погашение
            // расширением справа).
            Expr::Nursery { body } => self.nursing(body),
            // Операция питомника и отмена значением не бывают: тишина их не
            // касается - уступка режет сегмент по построению, - и дробление
            // выносит их хвостом куска.
            Expr::Fiber { .. } | Expr::Cancel { .. } => {
                Err(self.node("операция питомника в чистом отрезке"))
            }
        }
    }

    /// Арифметика: `add`/`sub`/`mul` у целого, `fadd`/`fsub`/`fmul` у
    /// плавающего - и ни у тех, ни у других **ни одного флага**.
    ///
    /// У целых отсутствие флагов - не забывчивость: §4.3 требует
    /// **заворачивания**, то есть определённого поведения, а `nsw`/`nuw`
    /// объявили бы переполнение невозможным и отдали бы его оптимизатору как
    /// `poison`.
    ///
    /// У плавающих отсутствие флагов - и есть строгий режим §4.3, и это
    /// **измерение, разошедшееся с постановкой** (замер 2026-09-15, LLVM 18.1.8
    /// и 21.1.8). Постановка трека F говорила «флаги на инструкциях запрещают
    /// контракцию»; в LLVM всё наоборот - флаг `contract` её **разрешает**, а
    /// запрещает его отсутствие. Проверено прямо: `fmul`+`fadd` без флагов при
    /// `llc -mattr=+fma` дают `vmulsd`+`vaddsd`, те же с `contract` -
    /// `vfmadd213sd`. Быстрая математика (`fast`, `reassoc`, `nsz`, `ninf`,
    /// `nnan`, `afn`, `arcp`) не эмитится по той же причине, что `nsw`:
    /// §4.3 не даёт `Float` кольца, и переписывать компилятору нечем.
    ///
    /// **Граница обещания названа и закреплена прогоном** (`tests/float.rs`):
    /// `llc -fp-contract=fast` контрактит и IR без флагов, потому что ключ
    /// сильнее их отсутствия. Ключ этот подаёт конвейер, а конвейер наш
    /// ([`llvm::Pipeline`](crate::llvm::Pipeline)), - поэтому обещание держится
    /// на всяком ключе, который подаём мы, и перестаёт держаться у того, кто
    /// возьмёт промежуточный `.ll` и соберёт его сам.
    ///
    /// Второй вариант - `llvm.experimental.constrained.*` - **не отвергнут по
    /// цене, потому что цены у него на сегодняшнем срезе не нашлось.** Замер
    /// 2026-09-15 на том же свидетеле: обе версии LLVM его разбирают, `opt -O2`
    /// сворачивает константы и делает CSE и в нём тоже, инлайнинг и
    /// `tailrecurse` идут теми же, а `llc -O2 -mattr=+fma` печатает **те же 77
    /// инструкций**. Покупает он при этом больше: `-fp-contract=fast` его не
    /// берёт (ноль слитых против двух). Взят всё-таки простой вариант, и доводы
    /// у этого два, оба не про цену: имя `experimental` в самом IR против
    /// правила консервативного подмножества, и вектор - трек H, которому
    /// векторизация нужна, а через непрозрачный вызов она не идёт. Второе не
    /// измерено: векторизуемого плавающего цикла в срезе пока нет. Развилка
    /// живая, и решать её на данных трека H дешевле, чем сейчас.
    fn arithmetic(
        &mut self,
        op: PrimOp,
        ty: PrimTy,
        left: &Expr,
        right: &Expr,
    ) -> Result<String, LlvmError> {
        let opcode = match (op, ty.floating()) {
            (PrimOp::Add, false) => "add",
            (PrimOp::Sub, false) => "sub",
            (PrimOp::Mul, false) => "mul",
            (PrimOp::Add, true) => "fadd",
            (PrimOp::Sub, true) => "fsub",
            (PrimOp::Mul, true) => "fmul",
        };
        let left = self.value(left)?;
        let right = self.value(right)?;
        Ok(self.binary(opcode, "", machine(ty), &left, &right))
    }

    /// Вектор, все дорожки которого заняты одним значением (§4.9).
    ///
    /// Каноническая форма splat'а: `insertelement` в нулевую дорожку плюс
    /// `shufflevector` нулевой маской. Так её пишет сам LLVM, и так её узнаёт
    /// кодогенерация - `vbroadcastss` на x86, `dup` на ARM. Написать вместо
    /// этого `n` подряд идущих `insertelement` было бы законно и дало бы тот же
    /// ответ; узнавать splat при этом пришлось бы оптимизатору, а свидетель
    /// трека H обязан различать вектор и поэлементный код, а не надеяться.
    ///
    /// `poison` в качестве исходного вектора - тоже канон: дорожки его все до
    /// одной заменяются, и `zeroinitializer` дал бы лишнюю зависимость.
    /// Разбирают `poison` обе поддерживаемые версии (проверено треугольником,
    /// `tests/llvm.rs`): ключевое слово появилось в LLVM 12, минимум фазы - 18.
    fn splat(&mut self, lanes: u32, lane: PrimTy, value: &Expr) -> Result<String, LlvmError> {
        let value = self.value(value)?;
        let ty = vector(lanes, lane);
        let one = self.temp();
        self.instruction(
            &format!(
                "{one} = insertelement {ty} poison, {} {value}, i64 0",
                machine(lane)
            ),
            self.here(),
        );
        let name = self.temp();
        self.instruction(
            &format!(
                "{name} = shufflevector {ty} {one}, {ty} poison, <{lanes} x i32> zeroinitializer"
            ),
            self.here(),
        );
        Ok(name)
    }

    /// Обрыв, если номер дорожки вышел за ширину (§4.9).
    ///
    /// **Не украшение, а сведение двух бэкендов.** `extractelement` с номером
    /// вне ширины отдаёт `poison`, то есть молча неверный ответ; C-сторона в
    /// том же случае зовёт `adamas_fail`. Разойдись они - и договор трёх
    /// вычислителей держался бы только на программах, которые за ширину не
    /// выходят, а обещание «одна программа - одно значение» перестало бы быть
    /// про все программы. Машина третьей стороной не сводит такое чтение
    /// вовсе, и сходятся все трое в том, что ответа не даёт никто.
    ///
    /// Цена нулевая на обычном случае: номер там литерал, и `opt` сворачивает
    /// сравнение с константой вместе с веткой. Измерено на ядре свидетеля
    /// (`tests/simd.rs`, 2026-09-16, LLVM 21.1.8): **51 инструкция** в штатном
    /// выходе и до проверки, и после, пакетных те же четыре. На рантаймовом
    /// номере проверка остаётся и стоит сравнение с переходом - столько же,
    /// сколько стоит она же у массива (`adamas_array_at`).
    fn lane_in_range(&mut self, lanes: u32, at: &str) {
        let verdict = self.temp();
        self.instruction(
            &format!("{verdict} = icmp uge i64 {at}, {lanes}"),
            self.here(),
        );
        let bad = format!("lane{}.out", self.temps);
        let good = format!("lane{}.in", self.temps);
        self.instruction(
            &format!("br i1 {verdict}, label %{bad}, label %{good}"),
            self.here(),
        );
        self.start(&bad);
        self.instruction(
            &format!("call void @adamas_fail(ptr {LANE_MESSAGE})"),
            self.here(),
        );
        self.instruction("unreachable", self.here());
        self.start(&good);
    }

    /// Тот же вектор с переписанной дорожкой (§4.9): `insertelement`.
    fn insert(
        &mut self,
        lanes: u32,
        lane: PrimTy,
        vector_expr: &Expr,
        at: &Expr,
        value: &Expr,
    ) -> Result<String, LlvmError> {
        let source = self.value(vector_expr)?;
        let at = self.value(at)?;
        let value = self.value(value)?;
        self.lane_in_range(lanes, &at);
        let name = self.temp();
        self.instruction(
            &format!(
                "{name} = insertelement {} {source}, {} {value}, i64 {at}",
                vector(lanes, lane),
                machine(lane)
            ),
            self.here(),
        );
        Ok(name)
    }

    /// Значение дорожки (§4.9): `extractelement`.
    fn extract(
        &mut self,
        lanes: u32,
        lane: PrimTy,
        vector_expr: &Expr,
        at: &Expr,
    ) -> Result<String, LlvmError> {
        let source = self.value(vector_expr)?;
        let at = self.value(at)?;
        self.lane_in_range(lanes, &at);
        let name = self.temp();
        self.instruction(
            &format!(
                "{name} = extractelement {} {source}, i64 {at}",
                vector(lanes, lane)
            ),
            self.here(),
        );
        Ok(name)
    }

    /// Подорожечная арифметика (§4.9).
    ///
    /// Те же коды операций, что у скаляра, и с тем же отсутствием флагов -
    /// `add`/`sub`/`mul` у целого, `fadd`/`fsub`/`fmul` у плавающего. Отличает
    /// векторную форму только тип операнда, и в этом весь §4.9: `fadd
    /// <8 x float>` есть одна инструкция, а восемь `fadd float` - восемь.
    ///
    /// Про флаги см. [`Self::arithmetic`] - довод там один на обе формы, и
    /// разделять его было бы верным способом их разъехать. У целого вектора
    /// отсутствие `nsw`/`nuw` вдобавок несёт заворачивание §4.3, которое
    /// C-сторона держит счётом в беззнаковом спутнике.
    fn lanewise(
        &mut self,
        op: PrimOp,
        lanes: u32,
        lane: PrimTy,
        left: &Expr,
        right: &Expr,
    ) -> Result<String, LlvmError> {
        let opcode = match (op, lane.floating()) {
            (PrimOp::Add, false) => "add",
            (PrimOp::Sub, false) => "sub",
            (PrimOp::Mul, false) => "mul",
            (PrimOp::Add, true) => "fadd",
            (PrimOp::Sub, true) => "fsub",
            (PrimOp::Mul, true) => "fmul",
        };
        let left = self.value(left)?;
        let right = self.value(right)?;
        Ok(self.binary(opcode, "", &vector(lanes, lane), &left, &right))
    }

    /// Операция над массивом (§4.11): три формы одним разбором.
    ///
    /// Отдельным разбором, а не ветвями общего, по той же причине, по которой
    /// свой разбор у региона в C-эмиттере: у [`Self::value`] и без того сто
    /// строк, а формы эти разбираются только вместе.
    fn array(&mut self, expr: &Expr) -> Result<String, LlvmError> {
        match expr {
            Expr::ArrayNew {
                stride,
                count,
                initial,
            } => self.array_new(*stride, count, initial),
            Expr::ArraySet {
                stride,
                array,
                at,
                value,
            } => self.array_set(*stride, array, at, value),
            Expr::ArrayIndex {
                stride,
                owned,
                array,
                at,
            } => self.array_index(*stride, *owned, array, at),
            _ => Err(self.node("массив")),
        }
    }

    /// Ячейка плоского массива: ширина шага и тип значения в ней (§4.11).
    ///
    /// Отказ здесь **названный**, и оба его случая принадлежат чужим трекам:
    /// плотный агрегат ячейкой - трек C, дескриптор укладки - обобщённый код над
    /// `{Flat a}`. Молча положить в ячейку не тот тип было бы хуже: длина ячейки
    /// живёт в заголовке массива, и запись не той ширины уехала бы в соседнюю.
    fn cell(&self, stride: Stride) -> Result<(u64, PrimTy), LlvmError> {
        match stride {
            Stride::Static(ty) => Ok((u64::from(ty.size()), ty)),
            Stride::Packed(_) | Stride::Dynamic(_) => Err(LlvmError::Shape {
                function: self.function.name.clone(),
                place: "ячейка массива".to_owned(),
                shape: describe(stride.element()),
            }),
        }
    }

    /// Значение в целом слове: длина массива и номер ячейки - `size_t` (§4.11).
    ///
    /// Расширение беззнаковое, потому что таким его делает и C-сторона -
    /// `(size_t){at}`. Плавающее сюда не приходит вовсе, но отказ на него
    /// назван: `widen` перелил бы его биты и получил бы номер ячейки из мантиссы.
    fn word_operand(&mut self, expr: &Expr) -> Result<String, LlvmError> {
        let repr = self.shape(expr);
        let value = self.value(expr)?;
        match repr.primitive() {
            Some(ty) if !ty.floating() => Ok(self.widen(ty, &value)),
            _ => Err(LlvmError::Shape {
                function: self.function.name.clone(),
                place: "длина либо номер ячейки массива".to_owned(),
                shape: describe(repr),
            }),
        }
    }

    /// Новый массив: одна аллокация на всю длину (§4.11).
    ///
    /// Заполняет его **рантайм**, а не порождённый цикл, и это не уступка:
    /// ссылок на начальное значение нужно `count`, а длина есть величина
    /// рантайма - вставке RC (§5.1) её не видно. Та же точка входа, что зовёт
    /// C-бэкенд, и то же число выданных блоков.
    ///
    /// Плоское начальное значение уезжает в рантайм **байтами через ячейку
    /// кадра**: `adamas_array_fill_flat` берёт указатель, а не слово, потому что
    /// ширина ячейки бывает меньше слова. Ячейка стоит в `entry` наравне с
    /// прочими (см. [`Builder::frame_cell`]), и `alloca` внутри витка не растёт.
    fn array_new(
        &mut self,
        stride: Option<Stride>,
        count: &Expr,
        initial: &Expr,
    ) -> Result<String, LlvmError> {
        // Порядок тот же, что у C-бэкенда и у [`Self::construct`]: аргументы
        // считаются **до** аллокации, потому что аргумент вправе аллоцировать
        // сам, и переставь их - счётчик выданных блоков разошёлся бы между
        // бэкендами при том же ответе.
        let count = self.word_operand(count)?;
        let cell = stride.map(|it| self.cell(it)).transpose()?;
        let initial = self.value(initial)?;
        let step = cell.map_or(0, |(step, _)| step);
        let array = self.temp();
        self.instruction(
            &format!("{array} = call ptr @adamas_array_alloc(i64 {count}, i64 {step})"),
            self.here(),
        );
        match cell {
            Some((_, ty)) => {
                let bits = self.frame_cell(machine(ty));
                self.instruction(
                    &format!("store {} {initial}, ptr {bits}", machine(ty)),
                    self.here(),
                );
                self.instruction(
                    &format!("call void @adamas_array_fill_flat(ptr {array}, ptr {bits})"),
                    self.here(),
                );
            }
            None => self.instruction(
                &format!(
                    "call void @adamas_array_fill(ptr {array}, ptr {initial}, \
                     ptr @{RELEASE_SYMBOL})"
                ),
                self.here(),
            ),
        }
        Ok(array)
    }

    /// Тот же массив с переписанной ячейкой (§4.11).
    ///
    /// `adamas_array_writable` отдаёт тот же блок, когда он уникален, и копию
    /// иначе - переписывание по месту из §4.11, и решает его рантайм, а не
    /// кратность (§10 вопрос 149). Уникальность спрашивается **после** того, как
    /// посчитаны все аргументы: чтение из того же массива успевает отдать свою
    /// ссылку, и `arraySet xs i (arrayIndex xs j)` переписывает, а не копирует.
    /// Порядок этот тот же, что у C-эмиттера, и разъехаться ему нельзя - счётчик
    /// выданных блоков у двух бэкендов сверяется числом (`harness::same_work`).
    ///
    /// Плоская ячейка пишется **инструкцией**, а адрес её берётся у рантайма.
    /// Довод тот же, по которому слот объекта читает сам IR (см. шапку модуля):
    /// `store` прозрачен для `opt`, а вызов в чужую единицу трансляции нет.
    /// Проверку границы при этом делает `adamas_array_at` - одна на два бэкенда,
    /// потому что обрыв виден пользователю и входит в наблюдаемое поведение.
    fn array_set(
        &mut self,
        stride: Option<Stride>,
        array: &Expr,
        at: &Expr,
        value: &Expr,
    ) -> Result<String, LlvmError> {
        let source = self.value(array)?;
        let at = self.word_operand(at)?;
        let cell = stride.map(|it| self.cell(it)).transpose()?;
        let value = self.value(value)?;
        let writable = self.temp();
        self.instruction(
            &format!(
                "{writable} = call ptr @adamas_array_writable(ptr {source}, ptr @{RELEASE_SYMBOL})"
            ),
            self.here(),
        );
        match cell {
            Some((_, ty)) => {
                let address = self.array_cell(&writable, &at);
                self.instruction(
                    &format!("store {} {value}, ptr {address}", machine(ty)),
                    self.here(),
                );
            }
            None => self.instruction(
                &format!(
                    "call void @adamas_array_put(ptr {writable}, i64 {at}, ptr {value}, \
                     ptr @{RELEASE_SYMBOL})"
                ),
                self.here(),
            ),
        }
        Ok(writable)
    }

    /// Чтение ячейки (§4.11).
    ///
    /// Массив приходит владением и отдаётся здесь же - либо **заимствуется**
    /// (§10 вопрос 171): наружу уходят биты без заголовка, владелец потребит
    /// массив позже, и счётчик не трогается вовсе. Пара записей счётчика на
    /// каждом чтении стоила вчетверо дороже самой работы и отнимала
    /// векторизацию, поэтому различие это не украшение, а горячий путь строки 4а.
    ///
    /// Владеющее чтение печатается `load` плюс `adamas_drop`, а не вызовом
    /// `adamas_array_read`: тот делает ровно это - `memcpy` шагом и дроп, - а
    /// через буфер по указателю оно потребовало бы ячейки кадра и осталось бы
    /// непрозрачным для `opt` там, где рантайм не приложен битовым кодом.
    fn array_index(
        &mut self,
        stride: Option<Stride>,
        owned: bool,
        array: &Expr,
        at: &Expr,
    ) -> Result<String, LlvmError> {
        let source = self.value(array)?;
        let at = self.word_operand(at)?;
        let Some((_, ty)) = stride.map(|it| self.cell(it)).transpose()? else {
            // Указательная ячейка: `dup` взятой и дроп массива держит рантайм -
            // решением о владении это быть не должно.
            let name = self.temp();
            self.instruction(
                &format!(
                    "{name} = call ptr @adamas_array_take(ptr {source}, i64 {at}, \
                     ptr @{RELEASE_SYMBOL})"
                ),
                self.here(),
            );
            return Ok(name);
        };
        let address = self.array_cell(&source, &at);
        let name = self.temp();
        self.instruction(
            &format!("{name} = load {}, ptr {address}", machine(ty)),
            self.here(),
        );
        if owned {
            self.instruction(
                &format!("call void @adamas_drop(ptr {source}, ptr @{RELEASE_SYMBOL})"),
                self.here(),
            );
        }
        Ok(name)
    }

    /// Адрес плоской ячейки: `base + i * stride` с проверкой границы.
    ///
    /// Одной записью на чтение и запись, потому что у двух сторон адрес один:
    /// разъедься они - запись шла бы не туда, куда чтение, а сборка молчала бы.
    fn array_cell(&mut self, array: &str, at: &str) -> String {
        let name = self.temp();
        self.instruction(
            &format!("{name} = call ptr @adamas_array_at(ptr {array}, i64 {at})"),
            self.here(),
        );
        name
    }

    /// Двуместная инструкция.
    ///
    /// `flags` - поле между кодом операции и типом: предикат у `icmp`, флаги
    /// быстрой математики у плавающего. Пусто у всего, что эмитит этот срез,
    /// кроме предиката, - см. [`Self::arithmetic`].
    fn binary(&mut self, opcode: &str, flags: &str, ty: &str, left: &str, right: &str) -> String {
        let spaced = if flags.is_empty() {
            String::new()
        } else {
            format!("{flags} ")
        };
        let name = self.temp();
        self.instruction(
            &format!("{name} = {opcode} {spaced}{ty} {left}, {right}"),
            self.here(),
        );
        name
    }

    /// Сравнение: `icmp` по ключу порядка, затем нульарный конструктор `Bool`
    /// (§4.3).
    ///
    /// Тег выбирается `select`'ом, а значение строит **рантайм**
    /// (`adamas_con0`): непосредственное представление принадлежит ему, и
    /// вторая его запись здесь разъехалась бы с первой молча.
    ///
    /// **`fcmp` не эмитится ни в каком виде.** §4.3 наделяет `Eq`/`Ord` у
    /// `Float` семантикой IEEE-754 `totalOrder`, а не IEEE-сравнения, и
    /// расходятся они ровно в двух точках: `nan == nan` истинно, `0.0 /= -0.0`.
    /// Возьми эмиттер `fcmp olt` - и договор вычислителей разошёлся бы именно
    /// там, потому что C-сторона (`adamas_order_*` в `flat.c`) и машина
    /// (`PrimTy::key` в ядре) считают ключ. Знаковость у плавающих отсюда не
    /// спрашивается вовсе: ключ сравнивается **беззнаково** у всех десяти
    /// типов, а знаковый предикат берут только знаковые целые.
    fn comparison(
        &mut self,
        op: PrimCmp,
        ty: PrimTy,
        left: &Expr,
        right: &Expr,
        verdict: (u16, u16),
    ) -> Result<String, LlvmError> {
        let predicate = match (op, ty.signed()) {
            (PrimCmp::Eq, _) => "eq",
            (PrimCmp::Ne, _) => "ne",
            (PrimCmp::Lt, true) => "slt",
            (PrimCmp::Lt, false) => "ult",
            (PrimCmp::Le, true) => "sle",
            (PrimCmp::Le, false) => "ule",
            (PrimCmp::Gt, true) => "sgt",
            (PrimCmp::Gt, false) => "ugt",
            (PrimCmp::Ge, true) => "sge",
            (PrimCmp::Ge, false) => "uge",
        };
        let left = self.value(left)?;
        let right = self.value(right)?;
        let (left, right) = if ty.floating() {
            (self.key(ty, &left), self.key(ty, &right))
        } else {
            (left, right)
        };
        let verdicted = self.binary("icmp", predicate, word(ty), &left, &right);
        let (yes, no) = verdict;
        let tag = self.temp();
        self.instruction(
            &format!("{tag} = select i1 {verdicted}, i16 {yes}, i16 {no}"),
            self.here(),
        );
        let name = self.temp();
        self.instruction(
            &format!("{name} = call ptr @adamas_con0(i16 {tag})"),
            self.here(),
        );
        Ok(name)
    }

    /// Ключ `totalOrder` у плавающего (§4.3): беззнаковый порядок ключей и есть
    /// порядок значений.
    ///
    /// Шесть инструкций без ветвления, и они **дословно** то же преобразование,
    /// что `adamas_order_*` в `flat.c` и `PrimTy::key` в ядре: у отрицательного
    /// биты инвертируются целиком, у неотрицательного ставится старший разряд,
    /// а всякий NaN подменяется каноническим. Отсюда `-0.0 < 0.0`, `nan == nan`
    /// и `nan` выше всякого числа.
    ///
    /// Записано маской, а не `select`: `ashr` на ширину минус один даёт либо
    /// все единицы, либо ноль, `or` со старшим разрядом достраивает маску до
    /// нужной, и `xor` применяет её. Три те же значения при любом входе, без
    /// ветви и без обращения к памяти.
    ///
    /// # Канонизация NaN (вопрос 172)
    ///
    /// `totalOrder` различает NaN знаком и полезной нагрузкой, а их у NaN,
    /// **порождённого** недопустимой операцией, IEEE-754 не задаёт: железо x86
    /// отдаёт `0xFFF8000000000000`, свёртка констант LLVM -
    /// `0x7FF8000000000000`. Пока их различал ключ, ответ программы зависел от
    /// уровня оптимизации: `ltFloat64 nan 0.0` давало `1` на `-O0` и `0` на
    /// `-O1` и выше (замерено 2026-09-15). Отсюда три инструкции сверх трёх:
    /// модуль, сравнение с `+inf` и подмена ключа на канонический.
    ///
    /// Проверка идёт **в целом домене** - `fcmp` здесь по-прежнему не
    /// эмитится, - и `and` с `icmp` уходят параллельно самому ключу: на
    /// критическом пути прибавляется одна `select`. Цена измерена
    /// (`docs/measurements/nan-canon/`): на витке без плавающего сравнения
    /// ничего, на витке с независимым сравнением 1.02, на минимуме колонки -
    /// 1.36, потому что там ключ накопителя лежит на кольцевой зависимости.
    /// Канонизация на выходе каждой операции стоила бы 1.12 на скалярном
    /// плавающем проходе и 1.49 на векторизуемом.
    fn key(&mut self, ty: PrimTy, value: &str) -> String {
        let word = word(ty);
        let last = ty.size() * 8 - 1;
        let top = 1u64 << last;
        // Биты `+inf` и канонического тихого NaN: экспонента из одних единиц
        // при нулевой и при старшей мантиссе. Те же числа, что у `special()` в
        // ядре, - здесь они считаются, а не пишутся, потому что ширина типа
        // уже под рукой. Зовётся это только у плавающего: целому ключом служит
        // он сам, и ветка `else` принадлежит `Float64`, а не «всем прочим».
        let mantissa = if ty == PrimTy::Float32 { 23 } else { 52 };
        let infinity = top - (1u64 << mantissa);
        let canonical = infinity | (1u64 << (mantissa - 1)) | top;
        let bits = self.temp();
        self.instruction(
            &format!("{bits} = bitcast {} {value} to {word}", machine(ty)),
            self.here(),
        );
        let sign = self.binary("ashr", "", word, &bits, &last.to_string());
        let mask = self.binary("or", "", word, &sign, &top.to_string());
        let key = self.binary("xor", "", word, &bits, &mask);
        let magnitude = self.binary("and", "", word, &bits, &(top - 1).to_string());
        let unordered = self.binary("icmp", "ugt", word, &magnitude, &infinity.to_string());
        let name = self.temp();
        self.instruction(
            &format!("{name} = select i1 {unordered}, {word} {canonical}, {word} {key}"),
            self.here(),
        );
        name
    }

    /// Адрес слота: заголовок плюс номер слота на его ширину.
    ///
    /// `getelementptr i8` без `inbounds` и без `nuw` - правило консервативного
    /// подмножества. Разбор 18.1.8 ломает ровно `nuw` (перемерено 2026-09-15,
    /// см. шапку модуля); `inbounds` она читает, но причины ставить его,
    /// предъявимой числом, нет.
    ///
    /// Байтовый шаг, а не `getelementptr ptr`: слот носит и указатель, и биты
    /// числа в целом слове, а смещение у обоих одно (`flat.c`). Считать его
    /// типом элемента значило бы завести два разных GEP там, где адрес один.
    fn slot_pointer(&mut self, object: &str, slot: u32) -> String {
        let offset = HEADER_BYTES + slot * SLOT_BYTES;
        let name = self.temp();
        self.instruction(
            &format!("{name} = getelementptr i8, ptr {object}, i64 {offset}"),
            self.here(),
        );
        name
    }

    /// Пишет слот: плоское - битами в целое слово, ссылка - собой.
    ///
    /// Расширение беззнаковое, потому что таким его считает `adamas_word_*`
    /// (`flat.c`): биты типа берутся как есть и доливаются нулями. Читающая
    /// сторона - и здесь, и в печати - слово обрезает, поэтому верх не наблюдаем;
    /// но разойтись с C-бэкендом в **записанных байтах** незачем.
    fn store_slot(&mut self, object: &str, slot: u32, repr: Repr, value: &str) {
        let address = self.slot_pointer(object, slot);
        match repr.primitive() {
            Some(ty) => {
                let word = self.widen(ty, value);
                self.instruction(&format!("store i64 {word}, ptr {address}"), self.here());
            }
            None => {
                self.instruction(&format!("store ptr {value}, ptr {address}"), self.here());
            }
        }
    }

    /// Читает слот: обратная сторона [`Builder::store_slot`].
    fn load_slot(&mut self, object: &str, slot: u32, repr: Repr) -> String {
        let address = self.slot_pointer(object, slot);
        if let Some(ty) = repr.primitive() {
            let word = self.temp();
            self.instruction(&format!("{word} = load i64, ptr {address}"), self.here());
            return self.narrow(ty, &word);
        }
        let name = self.temp();
        self.instruction(&format!("{name} = load ptr, ptr {address}"), self.here());
        name
    }

    /// Плоское значение в слово слота.
    ///
    /// Плавающее сперва **переливается** в целое своей ширины ([`word`]), и это
    /// не украшение: `zext` от `float` LLVM отвергает разбором, а перелив через
    /// `bitcast` есть ровно то, что делает `adamas_word_Float32` в `flat.c` -
    /// `memcpy` в `uint32_t` и расширение. Расхождение здесь было бы не
    /// отказом, а другими байтами в слоте.
    fn widen(&mut self, ty: PrimTy, value: &str) -> String {
        let mut current = value.to_owned();
        if ty.floating() {
            let bits = self.temp();
            self.instruction(
                &format!("{bits} = bitcast {} {current} to {}", machine(ty), word(ty)),
                self.here(),
            );
            current = bits;
        }
        if ty.size() * 8 == 64 {
            return current;
        }
        let name = self.temp();
        self.instruction(
            &format!("{name} = zext {} {current} to i64", word(ty)),
            self.here(),
        );
        name
    }

    /// Слово слота обратно в плоское значение.
    fn narrow(&mut self, ty: PrimTy, slot: &str) -> String {
        let mut current = slot.to_owned();
        if ty.size() * 8 != 64 {
            let cut = self.temp();
            self.instruction(
                &format!("{cut} = trunc i64 {current} to {}", word(ty)),
                self.here(),
            );
            current = cut;
        }
        if !ty.floating() {
            return current;
        }
        let name = self.temp();
        self.instruction(
            &format!("{name} = bitcast {} {current} to {}", word(ty), machine(ty)),
            self.here(),
        );
        name
    }

    /// Объект конструктора: сперва аргументы, потом блок, потом слоты.
    ///
    /// Порядок тот же, что у C-бэкенда ([`crate::emit_c`]), и он не косметика:
    /// аргумент вправе сам аллоцировать, и посчитай его после `adamas_alloc` -
    /// счётчик выданных блоков разошёлся бы между двумя бэкендами при том же
    /// ответе.
    ///
    /// Придержанная ячейка (§5.1) занимает место `adamas_alloc`: `adamas_reuse`
    /// её переписывает, а на пустой аллоцирует сам - решается это в рантайме,
    /// потому что уникальность разобранного известна только там.
    fn construct(
        &mut self,
        constructor: CtorId,
        reuse: Option<LocalId>,
        arguments: &[Expr],
    ) -> Result<String, LlvmError> {
        let described = self.program.constructors[usize::from(constructor.0)].clone();
        let slots = described.slots();
        if slots == 0 {
            // Нульарный непосредствен: блока под него не выдаётся вовсе, и это
            // видно счётчиком (`main.c` печатает выданные и живые).
            let name = self.temp();
            self.instruction(
                &format!(
                    "{name} = call ptr @adamas_con0(i16 {}) ; {}",
                    constructor.0, described.name
                ),
                self.here(),
            );
            return Ok(name);
        }
        let given = self.given(&described, arguments)?;
        let object = self.temp();
        match reuse {
            Some(token) => {
                let block = self.operand(token)?;
                self.instruction(
                    &format!(
                        "{object} = call ptr @adamas_reuse(ptr {block}, i16 {}, i64 {slots}) ; {}",
                        constructor.0, described.name
                    ),
                    self.here(),
                );
            }
            None => {
                self.instruction(
                    &format!(
                        "{object} = call ptr @adamas_alloc(i16 {}, i64 {slots}) ; {}",
                        constructor.0, described.name
                    ),
                    self.here(),
                );
            }
        }
        for (slot, (argument, repr)) in given.into_iter().zip(described.slot_reprs()).enumerate() {
            let at = u32::try_from(slot).unwrap_or(u32::MAX);
            self.store_slot(&object, at, repr, &argument);
        }
        Ok(object)
    }

    /// Аргументы дожившим связываниям конструктора, в порядке слотов.
    fn given(
        &mut self,
        described: &Constructor,
        arguments: &[Expr],
    ) -> Result<Vec<String>, LlvmError> {
        let present: Vec<usize> = described
            .binders
            .iter()
            .enumerate()
            .filter(|(_, fact)| fact.present)
            .map(|(position, _)| position)
            .collect();
        let mut given = Vec::new();
        for position in present {
            let Some(argument) = arguments.get(position) else {
                continue;
            };
            given.push(self.value(argument)?);
        }
        Ok(given)
    }

    /// Отданная ссылка: [`Expr::Drop`] и [`Expr::Reclaim`] одной печатью.
    ///
    /// Различаются они одним - достаётся ли блок `token`, - и в схлопнутой
    /// форме тем же одним. Печатать их порознь значило бы завести четыре места,
    /// где стоит имя дропа детей.
    fn dropped(
        &mut self,
        local: LocalId,
        salvage: &Salvage,
        token: Option<LocalId>,
    ) -> Result<(), LlvmError> {
        if salvage.collapses() {
            return self.salvaged(local, salvage, token);
        }
        // Отдать резумпцию значит **раскрутить** её сегмент, а раскрутке нужна
        // ручка стека, которой у `adamas_release` нет (§3.4). Отсюда вторая
        // точка дропа и различение по представлению связывания.
        if self.reprs.get(&local) == Some(&Repr::Resumption) {
            let value = self.operand(local)?;
            let kont = self.kont()?;
            self.instruction(
                &format!("call void @adamas_resumption_drop(ptr {kont}, ptr {value})"),
                self.here(),
            );
            return Ok(());
        }
        let value = self.operand(local)?;
        match token {
            Some(token) => {
                let name = self.temp();
                self.instruction(
                    &format!(
                        "{name} = call ptr @adamas_drop_reuse(ptr {value}, ptr @{RELEASE_SYMBOL})"
                    ),
                    self.here(),
                );
                self.operands.insert(token, name);
            }
            None => self.instruction(
                &format!("call void @adamas_drop(ptr {value}, ptr @{RELEASE_SYMBOL})"),
                self.here(),
            ),
        }
        Ok(())
    }

    /// Дроп разобранного, схлопнутый с `dup` его полей (§5.1, [`Salvage`]).
    ///
    /// Форма та же, что у C-бэкенда, и различает ветви та же уникальность в
    /// рантайме (`adamas_is_unique`, §10 вопрос 149): у уникального взятые поля
    /// достаются ветви даром, невзятые дропаются здесь, блок либо освобождается,
    /// либо достаётся `token`; у разделённого берётся ссылка на каждое взятое,
    /// счётчик родителя идёт вниз, придержать нечего.
    ///
    /// Ветвление здесь, а не `select`: у ветвей разные **побочные действия**, и
    /// посчитать обе значило бы дропнуть невзятые поля разделённого родителя,
    /// который их держит.
    fn salvaged(
        &mut self,
        local: LocalId,
        salvage: &Salvage,
        token: Option<LocalId>,
    ) -> Result<(), LlvmError> {
        if self.certain.contains(&local) {
            return self.salvaged_unique(local, salvage, token);
        }
        let value = self.operand(local)?;
        let at = self.matches;
        self.matches += 1;
        let unique = format!("s{at}.unique");
        let shared = format!("s{at}.shared");
        let join = format!("s{at}.join");

        let answer = self.temp();
        self.instruction(
            &format!("{answer} = call i32 @adamas_is_unique(ptr {value})"),
            self.here(),
        );
        let verdict = self.temp();
        self.instruction(&format!("{verdict} = icmp ne i32 {answer}, 0"), self.here());
        self.instruction(
            &format!("br i1 {verdict}, label %{unique}, label %{shared}"),
            self.here(),
        );

        self.start(&unique);
        for field in &salvage.spare {
            let spare = self.operand(*field)?;
            self.instruction(
                &format!("call void @adamas_drop(ptr {spare}, ptr @{RELEASE_SYMBOL})"),
                self.here(),
            );
        }
        if token.is_none() {
            self.instruction(&format!("call void @adamas_free(ptr {value})"), self.here());
        }
        let from_unique = self.block.clone();
        self.instruction(&format!("br label %{join}"), self.here());

        self.start(&shared);
        for field in &salvage.taken {
            let named = self.operand(*field)?;
            let name = self.temp();
            self.instruction(
                &format!("{name} = call ptr @adamas_dup(ptr {named})"),
                self.here(),
            );
        }
        self.instruction(
            &format!("call void @adamas_drop(ptr {value}, ptr @{RELEASE_SYMBOL})"),
            self.here(),
        );
        let from_shared = self.block.clone();
        self.instruction(&format!("br label %{join}"), self.here());

        self.start(&join);
        if let Some(token) = token {
            let name = self.temp();
            self.instruction(
                &format!("{name} = phi ptr [ {value}, %{from_unique} ], [ null, %{from_shared} ]"),
                self.here(),
            );
            self.operands.insert(token, name);
        }
        Ok(())
    }

    /// Тот же дроп, когда уникальность известна статически ([`crate::unique`]).
    ///
    /// Печатается **одна** ветвь из двух - та, которую взял бы рантайм, - и
    /// вопроса `adamas_is_unique` не остаётся вовсе. Экономия не в одном вызове:
    /// уходят `dup` каждого взятого поля, `adamas_drop` родителя, два блока,
    /// ветвление и `phi` придержанной ячейки.
    ///
    /// Довод законности - у [`crate::unique`], и он проверяем: `rc` поднимает
    /// только `adamas_dup`, а его на это связывание в программе нет. Довод
    /// неверный виден **прогоном**: `tests/alias.rs` объявляет уникальным
    /// разделённое и получает другой ответ.
    fn salvaged_unique(
        &mut self,
        local: LocalId,
        salvage: &Salvage,
        token: Option<LocalId>,
    ) -> Result<(), LlvmError> {
        let value = self.operand(local)?;
        for field in &salvage.spare {
            let spare = self.operand(*field)?;
            self.instruction(
                &format!("call void @adamas_drop(ptr {spare}, ptr @{RELEASE_SYMBOL})"),
                self.here(),
            );
        }
        match token {
            // Блок достаётся придержавшему: `phi` не нужен, второго исхода нет.
            Some(token) => {
                self.operands.insert(token, value);
            }
            None => self.instruction(&format!("call void @adamas_free(ptr {value})"), self.here()),
        }
        Ok(())
    }

    /// Прямой вызов: стёртые позиции в вызов не идут.
    ///
    /// `sort` - шов трека D: [`Tail::Must`] печатает `musttail`, и следом за
    /// такой инструкцией обязан идти `ret` - его ставит [`Self::tail`].
    /// Соглашение [`CONVENTION`] печатается **всегда**, и не для красоты: оно
    /// объявлено у определения, и вызов, не назвавший его, звал бы по другому.
    fn call(
        &mut self,
        function: FuncId,
        arguments: &[Expr],
        sort: Tail,
    ) -> Result<String, LlvmError> {
        let called = &self.program.functions[function.0];
        // Ответ дроблёной функции - значение вершине стека, а не её собственный:
        // тип у границы один, и это слово.
        let result = if self.suspending.functions.contains(&function) {
            "ptr".to_owned()
        } else {
            slot(called.result).ok_or_else(|| LlvmError::Shape {
                function: self.function.name.clone(),
                place: format!("ответ `{}`", called.name),
                shape: describe(called.result),
            })?
        };
        // Скрытые аргументы идут ровно туда, где их ждут: второй форме - свои,
        // первой - никаких.
        let mut given = Vec::new();
        if called.form == Form::Detached {
            let (ev, kont) = self.forwarded(&called.name)?;
            given.push(format!("ptr {ev}"));
            given.push(format!("ptr {kont}"));
        }
        let present: Vec<usize> = called
            .parameters
            .iter()
            .enumerate()
            .filter(|(_, binding)| binding.fact.present)
            .map(|(position, _)| position)
            .collect();
        for position in present {
            let Some(argument) = arguments.get(position) else {
                continue;
            };
            let ty = self.typed(argument)?;
            let operand = self.value(argument)?;
            given.push(format!("{ty} {operand}"));
        }
        let name = self.temp();
        self.instruction(
            &format!(
                "{name} = {}call {CONVENTION} {result} @fn_{}({})",
                sort.prefix(),
                function.0,
                given.join(", ")
            ),
            self.here(),
        );
        Ok(name)
    }

    /// Голова разбора: тег, `switch` и блок обрыва.
    ///
    /// Разбираемое **заимствуется**: поля читаются по нему, а отдаёт его сама
    /// ветвь - [`Expr::Drop`] либо [`Expr::Reclaim`] внутри неё
    /// (`perceus::arm`). Владения поля не заводят: ссылку на нужное берёт
    /// `Dup`, поставленный тем же проходом, а ненужное не читается вовсе.
    /// Нульарный конструктор непосредствен, и тег у него - он сам.
    ///
    /// Одна на обе позиции намеренно: разъедься головы - хвостовой разбор
    /// поехал бы по другому тегу, и заметить это было бы нечем. Отдаёт
    /// разбираемое, номер разбора и метки ветвей; ветви печатает вызывающий,
    /// потому что позиция у них его. Разбираемое ему нужно затем же, зачем и
    /// голове: по нему читаются поля.
    fn dispatch(
        &mut self,
        scrutinee: &Expr,
        arms: &[Arm],
    ) -> Result<(String, u32, Vec<String>), LlvmError> {
        if arms.is_empty() {
            return Err(self.node("разбор пустого типа"));
        }

        let scrutinised = self.value(scrutinee)?;
        let at = self.matches;
        self.matches += 1;
        let tag = self.temp();
        self.instruction(
            &format!("{tag} = call i16 @adamas_tag(ptr {scrutinised})"),
            self.here(),
        );

        let labels: Vec<String> = (0..arms.len()).map(|it| format!("m{at}.a{it}")).collect();
        let fail = format!("m{at}.fail");
        let cases: Vec<String> = arms
            .iter()
            .zip(&labels)
            .map(|(arm, label)| format!("i16 {}, label %{label}", arm.constructor.0))
            .collect();
        self.instruction(
            &format!("switch i16 {tag}, label %{fail} [ {} ]", cases.join(" ")),
            self.here(),
        );

        self.start(&fail);
        self.instruction(
            &format!("call void @adamas_fail(ptr {TAG_MESSAGE})"),
            self.here(),
        );
        self.instruction("unreachable", self.here());
        Ok((scrutinised, at, labels))
    }

    /// Разбор значением: ветви сводятся `phi` в блоке стыковки.
    fn analysis(&mut self, scrutinee: &Expr, arms: &[Arm]) -> Result<String, LlvmError> {
        let (scrutinised, at, labels) = self.dispatch(scrutinee, arms)?;
        let answer = self.typed(&arms[0].body)?;
        let join = format!("m{at}.join");

        let mut incoming = Vec::new();
        for (arm, label) in arms.iter().zip(&labels) {
            self.start(label);
            self.bind_fields(&scrutinised, arm);
            let value = self.value(&arm.body)?;
            // Предшественник - блок, которым ветвь **закончилась**: вложенный
            // разбор внутри неё сменил бы его.
            incoming.push(format!("[ {value}, %{} ]", self.block));
            self.instruction(&format!("br label %{join}"), self.here());
        }

        self.start(&join);
        let name = self.temp();
        self.instruction(
            &format!("{name} = phi {answer} {}", incoming.join(", ")),
            self.here(),
        );
        Ok(name)
    }

    /// Разбор в хвостовой позиции: ветвь возвращает сама, `phi` не строится.
    ///
    /// Так и снимается препятствие трека D. `musttail` требует `ret` **в том же
    /// блоке**, а ветвь, кончающаяся `br label %join`, его не даёт; блока
    /// стыковки здесь нет вовсе, и хвост уезжает в каждую ветвь целым.
    fn analysis_tail(&mut self, scrutinee: &Expr, arms: &[Arm]) -> Result<(), LlvmError> {
        let (scrutinised, _, labels) = self.dispatch(scrutinee, arms)?;
        for (arm, label) in arms.iter().zip(&labels) {
            self.start(label);
            self.bind_fields(&scrutinised, arm);
            self.tail(&arm.body)?;
        }
        Ok(())
    }

    /// Поля ветви: слот у каждого свой, стёртое слота не занимает.
    ///
    /// Номер слота спрашивается у [`Constructor::slot`], а не считается здесь
    /// заново: стёртые связывания в объекте отсутствуют, и вторая арифметика
    /// нумерации разошлась бы с первой на первом же стёртом поле - молча и с
    /// перепутанными значениями, а не отказом.
    fn bind_fields(&mut self, object: &str, arm: &Arm) {
        let described = self.program.constructors[usize::from(arm.constructor.0)].clone();
        let params = described.params as usize;
        for (position, binding) in arm.fields.iter().enumerate() {
            let Some(slot) = described.slot(params + position) else {
                continue;
            };
            let taken = self.load_slot(object, slot, binding.fact.repr);
            let _ = writeln!(self.body, "  ; {taken} - {}", binding.name);
            self.operands.insert(binding.local, taken);
        }
    }

    // --- Вторая форма понижения (§3.4, волна 2, трек G) ------------------

    /// Вектор evidence, действующий здесь. Отказ - взять его негде.
    fn ev(&self) -> Result<String, LlvmError> {
        self.ev.clone().ok_or_else(|| LlvmError::Hidden {
            caller: self.function.name.clone(),
            callee: "вектор evidence".to_owned(),
        })
    }

    /// Ручка стека продолжения. Отказ - взять её негде.
    fn kont(&self) -> Result<String, LlvmError> {
        self.kont.clone().ok_or_else(|| LlvmError::Hidden {
            caller: self.function.name.clone(),
            callee: "ручка стека".to_owned(),
        })
    }

    /// Оба скрытых аргумента под прямой вызов названной второй формы.
    fn forwarded(&self, callee: &str) -> Result<(String, String), LlvmError> {
        match (self.ev.clone(), self.kont.clone()) {
            (Some(ev), Some(kont)) => Ok((ev, kont)),
            _ => Err(LlvmError::Hidden {
                caller: self.function.name.clone(),
                callee: callee.to_owned(),
            }),
        }
    }

    /// Точка ли приостановки: кадр ставится ровно на неё (решение 3 волны 4).
    fn stops(&self, expr: &Expr) -> bool {
        crate::split::halts(expr, self.suspending)
    }

    /// Значение словом: плоское - битами, указательное - собой.
    ///
    /// Граница куска носит слово, и других форм у неё нет: `adamas_frame_code`
    /// берёт `adamas_value` и им же отвечает. Половин у границы три - слот среды
    /// кадра, пришедшее в кусок и ответ куска трамплину, - и мера у всех трёх
    /// одна. Ячейки кучи это не стоит: биты примитива ложатся в слово целиком.
    #[expect(
        clippy::wrong_self_convention,
        reason = "перевод значения, а не самого билдера: инструкции печатает он"
    )]
    fn into_word(&mut self, repr: Repr, value: &str) -> Result<String, LlvmError> {
        if let Some(ty) = repr.primitive() {
            let bits = self.widen(ty, value);
            let name = self.temp();
            self.instruction(&format!("{name} = inttoptr i64 {bits} to ptr"), self.here());
            return Ok(name);
        }
        if slot(repr).as_deref() == Some("ptr") {
            return Ok(value.to_owned());
        }
        Err(LlvmError::Shape {
            function: self.function.name.clone(),
            place: "значение через границу кадра".to_owned(),
            shape: describe(repr),
        })
    }

    /// Обратно: слово границы в значение объявленного представления.
    #[expect(
        clippy::wrong_self_convention,
        reason = "перевод значения, а не самого билдера: инструкции печатает он"
    )]
    fn from_word(&mut self, repr: Repr, value: &str) -> Result<String, LlvmError> {
        if let Some(ty) = repr.primitive() {
            let bits = self.temp();
            self.instruction(
                &format!("{bits} = ptrtoint ptr {value} to i64"),
                self.here(),
            );
            return Ok(self.narrow(ty, &bits));
        }
        if slot(repr).as_deref() == Some("ptr") {
            return Ok(value.to_owned());
        }
        Err(LlvmError::Shape {
            function: self.function.name.clone(),
            place: "значение через границу кадра".to_owned(),
            shape: describe(repr),
        })
    }

    /// Возврат из куска: ответ уходит вершине стека, а до кадра его доводит
    /// трамплин.
    ///
    /// Эпилог печатается **после** вычисления ответа: в нём стоят дропы
    /// расширенных векторов, а ответ бывает вызовом, которому вектор и
    /// передаётся.
    fn finish(&mut self, answer: &str, repr: Repr) -> Result<(), LlvmError> {
        let word = self.into_word(repr, answer)?;
        for vector in self.epilogue.clone().iter().rev() {
            self.instruction(
                &format!("call void @adamas_evidence_drop(ptr {vector})"),
                self.here(),
            );
        }
        self.instruction(&format!("ret ptr {word}"), self.here());
        Ok(())
    }

    /// Хвост куска дроблёного тела: каждый путь отдаёт значение вершине стека.
    ///
    /// Отдельно от [`Self::tail`], и это не дубль: там позиция **возвратная** и
    /// хвостовой вызов печатается `musttail`, здесь позиция проточная, и
    /// возврат значит «отдай вершине». Свести их в одну печать нельзя - у них
    /// разный договор возврата.
    fn flowing(&mut self, expr: &Expr) -> Result<(), LlvmError> {
        match expr {
            // Связывание, чьё значение приостанавливается: продолжение уезжает
            // кадром, а само значение идёт хвостом.
            Expr::Bind {
                binding,
                value,
                body,
            } if self.stops(value) => {
                self.reified(binding, body)?;
                self.flowing(value)
            }
            Expr::Bind { .. }
            | Expr::Dup { .. }
            | Expr::Drop { .. }
            | Expr::Reclaim { .. }
            | Expr::Discard { .. } => {
                let body = self.bookkept(expr)?;
                self.flowing(body)
            }
            Expr::Match {
                scrutinee, arms, ..
            } if self.stops(expr) => self.branching(scrutinee, arms),
            Expr::Handle {
                handler,
                captured,
                computation,
            } => self.handling_tail(*handler, captured, computation),
            Expr::Closing {
                closer,
                captured,
                body,
            } => self.scoped_tail(*closer, captured, body),
            Expr::Mask { label, computation } => self.masking_tail(*label, computation),
            Expr::Perform {
                label,
                operation,
                arguments,
            } => self.performing_tail(*label, *operation, arguments),
            Expr::Resume { resumption, value } => self.resuming(resumption, value),
            Expr::Nursery { body } => self.nursery_tail(body),
            Expr::Fiber {
                op,
                label,
                operation,
                arguments,
            } => self.fibering_tail(*op, *label, *operation, arguments),
            Expr::Cancel { at, value } => self.cancelling(*at, value),
            Expr::Apply { callee, argument } => self.applying(callee, argument),
            other => {
                let repr = self.shape(other);
                let answer = self.value(other)?;
                self.finish(&answer, repr)
            }
        }
    }

    /// Разбор, у которого ветвь приостанавливается: каждая - свой хвост.
    ///
    /// Продолжение здесь уже лежит кадром - его поставило связывание, чьим
    /// значением стоит разбор, - поэтому ветвь просто отдаёт своё.
    fn branching(&mut self, scrutinee: &Expr, arms: &[Arm]) -> Result<(), LlvmError> {
        let (scrutinised, _, labels) = self.dispatch(scrutinee, arms)?;
        for (arm, label) in arms.iter().zip(&labels) {
            self.start(label);
            self.bind_fields(&scrutinised, arm);
            self.flowing(&arm.body)?;
        }
        Ok(())
    }

    /// Возобновление: звенья встают **над** уже положенным кадром продолжения.
    ///
    /// Ответ возобновлённого вычисления дойдёт до него трамплином. Ручка
    /// тратится возобновлением и дропается следом: мультишотная при этом
    /// потраченной не становится, и её последняя ссылка раскручивает нетронутый
    /// оригинал (`adamas.h`).
    fn resuming(&mut self, resumption: &Expr, value: &Expr) -> Result<(), LlvmError> {
        let kont = self.kont()?;
        let handle = self.value(resumption)?;
        let given = self.value(value)?;
        self.instruction(
            &format!("call void @adamas_kont_resume(ptr {kont}, ptr {handle})"),
            self.here(),
        );
        self.instruction(
            &format!("call void @adamas_resumption_drop(ptr {kont}, ptr {handle})"),
            self.here(),
        );
        // Аргумент резумпции указателен по договору понижения, и возобновлённое
        // вычисление ждёт от границы ровно его.
        self.finish(&given, Repr::Boxed)
    }

    /// Продолжение `λbinding. body` кадром, а его код - отдельной функцией.
    ///
    /// # Что уезжает в среду кадра
    ///
    /// То, что продолжение называет и не вводит само. Владение переходит кадру,
    /// и код куска забирает слоты **обратно**, зануляя их: кадр освобождается
    /// сразу после кода (`adamas.h`), и `dup` с последующим дропом стоил бы пары
    /// счётчику на каждый живой слот.
    ///
    /// # Плоское значение в слоте
    ///
    /// Слот кадра - слово, и плоское значение лежит в нём **битами**, ровно как
    /// в слоте объекта (§4.11). Счётчика у него нет, поэтому дроп среды его не
    /// трогает: какие слоты указательные, кусок знает по типам. Счётные слоты
    /// идут первыми - это соглашение с `adamas_kont_push`, и копия сегмента
    /// дупает ровно их.
    fn reified(&mut self, binding: &Binding, body: &Expr) -> Result<(), LlvmError> {
        let kont = self.kont()?;
        let ev = self.ev()?;
        let mut called = BTreeSet::new();
        crate::split::mentioned(body, &mut called);
        let mut inner = BTreeSet::new();
        crate::split::introduces(body, &mut inner);
        inner.insert(binding.local);
        let mut env: Vec<(LocalId, Repr)> = called
            .into_iter()
            .filter(|local| !inner.contains(local))
            .filter_map(|local| self.reprs.get(&local).map(|repr| (local, *repr)))
            .collect();
        env.sort_by_key(|(_, repr)| !repr.counted());
        let counted = env.iter().filter(|(_, repr)| repr.counted()).count();

        let at = self.chunked;
        self.chunked += 1;
        let code = format!("@fn_{}_k{at}", self.function.id.0);
        let release = if counted > 0 {
            format!("@release_{}_k{at}", self.function.id.0)
        } else {
            "null".to_owned()
        };

        let frame = self.temp();
        self.instruction(
            &format!(
                "{frame} = call ptr @adamas_kont_push(ptr {kont}, i16 0, i32 0, ptr {code}, \
                 ptr {release}, i64 {}, i64 {counted}, ptr {ev}) ; продолжение",
                env.len()
            ),
            self.here(),
        );
        if !env.is_empty() {
            let slots = self.temp();
            self.instruction(
                &format!("{slots} = call ptr @adamas_frame_env(ptr {frame})"),
                self.here(),
            );
            for (at, (local, repr)) in env.clone().iter().enumerate() {
                let value = self.operand(*local)?;
                let word = self.into_word(*repr, &value)?;
                let address = self.temp();
                self.instruction(
                    &format!(
                        "{address} = getelementptr i8, ptr {slots}, i64 {}",
                        offset(at)
                    ),
                    self.here(),
                );
                self.instruction(&format!("store ptr {word}, ptr {address}"), self.here());
            }
        }

        self.chunk(&code[1..], &env, binding, body)?;
        if counted > 0 {
            self.chunk_release(&release[1..], &env);
        }
        Ok(())
    }

    /// Код куска: слоты забираются, пришедшее становится связыванием.
    ///
    /// Своя функция модуля, а не блок: кусок зовёт трамплин рантайма по
    /// указателю, и соглашение о вызове у него C (`adamas_frame_code`), а не
    /// [`CONVENTION`]. Отладочной подписи у куска нет вовсе - написанного
    /// определения за ним не стоит, и `!DISubprogram` ему назвать нечем.
    fn chunk(
        &mut self,
        code: &str,
        env: &[(LocalId, Repr)],
        binding: &Binding,
        body: &Expr,
    ) -> Result<(), LlvmError> {
        let held_head = std::mem::take(&mut self.head);
        let held_body = std::mem::take(&mut self.body);
        let held_block = std::mem::replace(&mut self.block, "entry".to_owned());
        // Свой вектор кусок не держит: его отдаёт тот кусок, что его завёл, а
        // сюда он приходит от кадра - заимствованным.
        let held_epilogue = std::mem::take(&mut self.epilogue);
        let held_scope = self.scope.take();
        let held_ev = self.ev.take();
        let held_kont = self.kont.replace("%kont".to_owned());
        // Имена связываний куска - свои: регистры внешнего тела здесь не видны.
        let held_operands = std::mem::take(&mut self.operands);

        let vector = self.temp();
        self.instruction(
            &format!("{vector} = call ptr @adamas_frame_evidence(ptr %h)"),
            Notes::none(),
        );
        self.ev = Some(vector);
        if !env.is_empty() {
            let slots = self.temp();
            self.instruction(
                &format!("{slots} = call ptr @adamas_frame_env(ptr %h)"),
                Notes::none(),
            );
            for (at, (local, repr)) in env.iter().enumerate() {
                let address = self.temp();
                self.instruction(
                    &format!(
                        "{address} = getelementptr i8, ptr {slots}, i64 {}",
                        offset(at)
                    ),
                    Notes::none(),
                );
                let word = self.temp();
                self.instruction(&format!("{word} = load ptr, ptr {address}"), Notes::none());
                // Указательный слот **забирается**: значение уезжает в
                // связывание владением, и дроп среды его больше не увидит.
                // Плоский лежит битами, счётчика у него нет, забирать нечего.
                if repr.primitive().is_none() {
                    let erased = self.temp();
                    self.instruction(
                        &format!("{erased} = call ptr @adamas_con0(i16 {ERASED_TAG})"),
                        Notes::none(),
                    );
                    self.instruction(&format!("store ptr {erased}, ptr {address}"), Notes::none());
                }
                let taken = self.from_word(*repr, &word)?;
                self.operands.insert(*local, taken);
            }
        }
        // Пришедшее приходит словом: `adamas_frame_code` другого не носит.
        let incoming = self.from_word(binding.fact.repr, "%incoming")?;
        self.operands.insert(binding.local, incoming);
        self.flowing(body)?;

        let mut text = String::new();
        let _ = writeln!(text, "; продолжение точки приостановки");
        let _ = writeln!(
            text,
            "define internal ptr @{code}(ptr %h, ptr %kont, ptr %incoming) \
             {DEFINITION_ATTRIBUTES} {{"
        );
        text.push_str("entry:\n");
        text.push_str(&self.head);
        text.push_str(&self.body);
        text.push_str("}\n\n");
        self.chunks.push(text);

        self.head = held_head;
        self.body = held_body;
        self.block = held_block;
        self.epilogue = held_epilogue;
        self.scope = held_scope;
        self.ev = held_ev;
        self.kont = held_kont;
        self.operands = held_operands;
        Ok(())
    }

    /// Дроп среды куска: то, чего он не забрал, потому что не побежал.
    fn chunk_release(&mut self, release: &str, env: &[(LocalId, Repr)]) {
        let mut text = String::new();
        let _ = writeln!(text, "; среда продолжения");
        let _ = writeln!(
            text,
            "define internal void @{release}(ptr %h, ptr %kont) {DEFINITION_ATTRIBUTES} {{"
        );
        text.push_str("entry:\n");
        let _ = writeln!(text, "  %env = call ptr @adamas_frame_env(ptr %h)");
        let mut block = 0_u32;
        for (at, (_, repr)) in env.iter().enumerate() {
            if !repr.counted() {
                continue;
            }
            let _ = writeln!(
                text,
                "  %a{at} = getelementptr i8, ptr %env, i64 {}",
                offset(at)
            );
            let _ = writeln!(text, "  %s{at} = load ptr, ptr %a{at}");
            if *repr == Repr::Resumption {
                // Забранный слот занят непосредственным значением, а резумпцией
                // оно не бывает: ручка сегмента - объект кучи. Сравнение поэтому
                // и есть «слот ещё не забрали».
                let _ = writeln!(text, "  %i{at} = call i32 @adamas_is_imm(ptr %s{at})");
                let _ = writeln!(text, "  %c{at} = icmp eq i32 %i{at}, 0");
                let _ = writeln!(
                    text,
                    "  br i1 %c{at}, label %live{block}, label %skip{block}"
                );
                let _ = writeln!(text, "\nlive{block}:");
                let _ = writeln!(
                    text,
                    "  call void @adamas_resumption_drop(ptr %kont, ptr %s{at})"
                );
                let _ = writeln!(text, "  br label %skip{block}");
                let _ = writeln!(text, "\nskip{block}:");
                block += 1;
            } else {
                let _ = writeln!(
                    text,
                    "  call void @adamas_drop(ptr %s{at}, ptr @{RELEASE_SYMBOL})"
                );
            }
        }
        text.push_str("  ret void\n}\n\n");
        self.chunks.push(text);
    }

    /// Кадр `HANDLER` со средой веток и расширенный вектор под вычисление.
    ///
    /// Общее у обеих форм: у первой кадр стоит на своём корне, у второй - на
    /// ручке, пришедшей аргументом, а сама постановка одна и та же.
    fn installed(
        &mut self,
        handler: HandlerId,
        taken: &[String],
    ) -> Result<(String, String), LlvmError> {
        let kont = self.kont()?;
        let ev = self.ev()?;
        let label = self.program.handlers[handler.0 as usize].label;
        let slots = taken.len();
        let release = if slots == 0 {
            "null".to_owned()
        } else {
            format!("@relh_{}", handler.0)
        };
        let frame = self.temp();
        self.instruction(
            &format!(
                "{frame} = call ptr @adamas_kont_handler(ptr {kont}, i32 {}, ptr @handler_{}, \
                 ptr {release}, i64 {slots}, ptr {ev})",
                label.0, handler.0
            ),
            self.here(),
        );
        if slots > 0 {
            let env = self.temp();
            self.instruction(
                &format!("{env} = call ptr @adamas_frame_env(ptr {frame})"),
                self.here(),
            );
            for (at, capture) in taken.iter().enumerate() {
                let address = self.temp();
                self.instruction(
                    &format!(
                        "{address} = getelementptr i8, ptr {env}, i64 {}",
                        offset(at)
                    ),
                    self.here(),
                );
                self.instruction(&format!("store ptr {capture}, ptr {address}"), self.here());
            }
        }
        let vector = self.temp();
        self.instruction(
            &format!(
                "{vector} = call ptr @adamas_evidence_extend(ptr {ev}, i32 {}, ptr {frame})",
                label.0
            ),
            self.here(),
        );
        Ok((frame, vector))
    }

    /// Среда веток по слотам кадра: живые захваты в порядке объявления.
    fn environment(
        &mut self,
        handler: HandlerId,
        captured: &[Expr],
    ) -> Result<Vec<String>, LlvmError> {
        let present: Vec<usize> = self.program.handlers[handler.0 as usize]
            .captured
            .iter()
            .enumerate()
            .filter(|(_, binding)| binding.fact.present)
            .map(|(position, _)| position)
            .collect();
        let mut taken = Vec::new();
        for position in present {
            let Some(capture) = captured.get(position) else {
                continue;
            };
            taken.push(self.value(capture)?);
        }
        Ok(taken)
    }

    /// Хендлер во **второй** форме: кадр под уже стоящим продолжением.
    ///
    /// Вычисление идёт хвостом того же куска и под своим вектором; ответ его
    /// доходит до кадра `HANDLER` трамплином, и ветку `return` зовёт он же.
    /// Своей ссылки на расширенный вектор кусок не переживает - её отдаёт
    /// эпилог, - а кадры, положенные вычислением, берут свою.
    fn handling_tail(
        &mut self,
        handler: HandlerId,
        captured: &[Expr],
        computation: &Expr,
    ) -> Result<(), LlvmError> {
        let taken = self.environment(handler, captured)?;
        let (_, vector) = self.installed(handler, &taken)?;
        let held = self.ev.replace(vector.clone());
        self.epilogue.push(vector);
        let outcome = self.flowing(computation);
        self.epilogue.pop();
        self.ev = held;
        outcome
    }

    /// Маска, под которой вычисление приостанавливается.
    ///
    /// Вектор её переживает кусок не своей ссылкой, а ссылками кадров: каждый
    /// кадр, положенный вычислением, дупает вектор себе, и продолжение читает
    /// его у кадра. Своя ссылка уходит эпилогом на возврате.
    fn masking_tail(&mut self, label: LabelId, computation: &Expr) -> Result<(), LlvmError> {
        let vector = self.masked(label)?;
        let held = self.ev.replace(vector.clone());
        self.epilogue.push(vector);
        let outcome = self.flowing(computation);
        self.epilogue.pop();
        self.ev = held;
        outcome
    }

    /// Вектор без ближайшей записи метки: `#mask.L` (§3.4).
    fn masked(&mut self, label: LabelId) -> Result<String, LlvmError> {
        let ev = self.ev()?;
        let title = &self.program.labels[label.0 as usize].name;
        let vector = self.temp();
        let text = format!(
            "{vector} = call ptr @adamas_evidence_mask(ptr {ev}, i32 {}) ; mask {title}",
            label.0
        );
        self.instruction(&text, self.here());
        Ok(vector)
    }

    /// Выход из scope с ресурсом во второй форме: кадр `CLOSING` (§3.3).
    ///
    /// Тело идёт хвостом, а деструктор зовёт трамплин, дойдя до кадра, - и
    /// нормальный выход, и раскрутка идут одним путём. LIFO выходит
    /// вложенностью кадров: внутренний scope лежит выше, раскрутка идёт сверху.
    fn scoped_tail(
        &mut self,
        closer: FuncId,
        captured: &[Expr],
        body: &Expr,
    ) -> Result<(), LlvmError> {
        let kont = self.kont()?;
        let ev = self.ev()?;
        // Замыкание деструктора строится **забирающим** трамплином: кадр его
        // единственный владелец, зовут его раз, и слоты уходят в деструктор
        // владением. Общий трамплин отдал бы ресурс разделённым.
        let value = self.holding(closer, captured)?;
        let frame = self.temp();
        self.instruction(
            &format!(
                "{frame} = call ptr @adamas_kont_closing(ptr {kont}, ptr {ev}, \
                 ptr @release_closing, ptr {value})"
            ),
            self.here(),
        );
        self.flowing(body)
    }

    /// Замыкание значением: код общего трамплина плюс среда по слотам.
    fn closure(&mut self, function: FuncId, captured: &[Expr]) -> Result<String, LlvmError> {
        self.captured(function, captured, "box")
    }

    /// Применение значения-функции: форму за указателем решает рантайм.
    ///
    /// Точка приостановки по построению - вызываемое может оказаться второй
    /// формы, - поэтому только в хвосте куска. Замыкание заимствуется,
    /// аргумент уходит владением (`adamas.h`).
    fn applying(&mut self, callee: &Expr, argument: &Expr) -> Result<(), LlvmError> {
        let kont = self.kont()?;
        let ev = self.ev()?;
        let callee = self.value(callee)?;
        let given = self.value(argument)?;
        let answer = self.temp();
        self.instruction(
            &format!(
                "{answer} = call ptr @adamas_apply(ptr {callee}, ptr {ev}, ptr {kont}, \
                 ptr {given})"
            ),
            self.here(),
        );
        self.finish(&answer, Repr::Boxed)
    }

    /// Конструктор значением: замыкание над его сборщиком ([`Module::maker`]).
    ///
    /// Арность - **все** связывания ядра, стёртые в том числе: применение
    /// позиционно и о стёртых полях не знает. Накопленных аргументов ноль -
    /// частичного применения понижение здесь не порождает, а доберёт их
    /// `adamas_apply`.
    ///
    /// Два вида поля отвергаются названно, и оба - расхождение с C-эмиттером,
    /// сделанное намеренно. Его сборщик кладёт всякое поле `adamas_set_field`,
    /// то есть указателем, и на **плоском** поле это записало бы в слот адрес
    /// вместо битов: читающая сторона берёт слот как биты (§4.11), и ответ
    /// разошёлся бы молча. **Стёртые все** дают объект о нуле слотов, а прямая
    /// постройка отдаёт на нуле `adamas_con0`, то есть непосредственное
    /// значение, - два разных представления одного конструктора в одной
    /// программе. Ни того, ни другого корпус не порождает; отказ здесь -
    /// страховка, а не граница языка.
    fn building(&mut self, constructor: CtorId) -> Result<String, LlvmError> {
        let described = &self.program.constructors[usize::from(constructor.0)];
        let arity = described.binders.len();
        let slots = described.slots();
        if described
            .slot_reprs()
            .any(|repr| repr.primitive().is_some())
        {
            return Err(self.node("конструктор с плоским полем значением"));
        }
        if arity > 0 && slots == 0 {
            return Err(self.node("конструктор со стёртыми полями значением"));
        }
        let name = self.temp();
        self.instruction(
            &format!(
                "{name} = call ptr @adamas_closure(ptr @make_{}, ptr @{RELEASE_SYMBOL}, \
                 i32 {arity}, i32 0) ; {}",
                constructor.0, described.name
            ),
            self.here(),
        );
        Ok(name)
    }

    /// Применение значения-функции в **чистом** отрезке: корень трамплина свой.
    ///
    /// Тем же правом, каким его заводят [`Self::handling`] и [`Self::nursing`]:
    /// ручки стека у первой формы нет, а применению она нужна - за указателем
    /// может оказаться вторая форма, и кадр ей положить некуда. Корень стоит на
    /// C-стеке (`alloca ptr`, `adamas_kont` есть одна вершина), трамплин
    /// докручивает [`adamas_kont_run`], и до кучи это не доходит: первая форма
    /// за указателем отвечает сразу, кадров не положив ни одного.
    ///
    /// Вектор evidence берётся свой, если он есть: под [`Self::masking`] в
    /// чистом отрезке он ненулевой, и `null` там потерял бы маску молча.
    /// Снаружи маски его нет вовсе, и `null` - то же, что печатает
    /// C-эмиттер: у первой формы вектора не бывает по записи ABI.
    fn applied(&mut self, callee: &Expr, argument: &Expr) -> Result<String, LlvmError> {
        if self.kont.is_some() {
            // Внутри второй формы применение значением не бывает: дробление
            // выносит его хвостом куска ([`Self::applying`]). Отказ, а не
            // свой корень: чужую ручку докрутил бы не тот, кто её завёл.
            return Err(self.node("применение значением во второй форме"));
        }
        let callee = self.value(callee)?;
        let given = self.value(argument)?;
        let root = format!("%k{}", self.frames);
        self.frames += 1;
        let _ = writeln!(self.head, "  {root} = alloca ptr");
        self.instruction(
            &format!("call void @adamas_kont_init(ptr {root})"),
            self.here(),
        );
        let vector = self.ev.clone().unwrap_or_else(|| "null".to_owned());
        let answer = self.temp();
        self.instruction(
            &format!(
                "{answer} = call ptr @adamas_apply(ptr {callee}, ptr {vector}, ptr {root}, \
                 ptr {given})"
            ),
            self.here(),
        );
        let driven = self.temp();
        self.instruction(
            &format!("{driven} = call ptr @adamas_kont_run(ptr {root}, ptr {answer})"),
            self.here(),
        );
        Ok(driven)
    }

    /// Замыкание деструктора: код забирающего трамплина плюс среда по слотам.
    fn holding(&mut self, function: FuncId, captured: &[Expr]) -> Result<String, LlvmError> {
        self.captured(function, captured, "take")
    }

    /// Замыкание с названным трамплином: общим (`box`) либо забирающим (`take`).
    fn captured(
        &mut self,
        function: FuncId,
        captured: &[Expr],
        code: &str,
    ) -> Result<String, LlvmError> {
        let described = &self.program.functions[function.0];
        // Арность замыкания - **все** связывания ядра, стёртые в том числе:
        // применение к значению позиционно и типа вызываемого не знает.
        let arity = described.parameters.len();
        let present: Vec<usize> = described
            .captured
            .iter()
            .enumerate()
            .filter(|(_, binding)| binding.fact.present)
            .map(|(position, _)| position)
            .collect();
        let mut taken = Vec::new();
        for position in present {
            let Some(capture) = captured.get(position) else {
                continue;
            };
            taken.push(self.value(capture)?);
        }
        let name = self.temp();
        self.instruction(
            &format!(
                "{name} = call ptr @adamas_closure(ptr @{code}_{}, ptr @{RELEASE_SYMBOL}, \
                 i32 {arity}, i32 {})",
                function.0,
                taken.len()
            ),
            self.here(),
        );
        for (at, capture) in taken.iter().enumerate() {
            self.instruction(
                &format!("call void @adamas_closure_set(ptr {name}, i64 {at}, ptr {capture})"),
                self.here(),
            );
        }
        Ok(name)
    }

    /// Аргументы операции массивом: одно соглашение о вызове на оба пути.
    ///
    /// Массивом, а не именами по одному, потому что владельца у них в IR нет:
    /// это соглашение о вызове ветки, а не узел. Отсюда и дроп на путях, где
    /// ветка не побежит, идёт по слоту массива.
    fn operands(&mut self, arguments: &[Expr]) -> Result<(String, usize), LlvmError> {
        let mut given = Vec::new();
        for argument in arguments {
            given.push(self.value(argument)?);
        }
        if given.is_empty() {
            return Ok(("null".to_owned(), 0));
        }
        let cell = format!("%o{}", self.frames);
        self.frames += 1;
        let _ = writeln!(self.head, "  {cell} = alloca ptr, i64 {}", given.len());
        for (at, value) in given.iter().enumerate() {
            let address = self.temp();
            self.instruction(
                &format!("{address} = getelementptr ptr, ptr {cell}, i64 {at}"),
                self.here(),
            );
            self.instruction(&format!("store ptr {value}, ptr {address}"), self.here());
        }
        Ok((cell, given.len()))
    }

    /// Операция в хвосте куска: вердикт вектора трёхзначен, и все три написаны.
    ///
    /// `HANDLER` - ветка зовётся на месте; чем она ответит, решает её вердикт, а
    /// сюда ответ приходит одинаково - возвратом вершине стека. `SUPPRESSED` -
    /// хендлер ответ уже дал, деться второму некуда: `adamas_kont_abort` и
    /// немедленный возврат. `MISSING` - операция без хендлера.
    ///
    /// Сводить вердикт к двум нельзя: операция деструктора ушла бы к
    /// одноимённому хендлеру снаружи - ровно тот дефект, который ревью
    /// 2026-09-05 нашло у машины.
    fn performing_tail(
        &mut self,
        label: LabelId,
        operation: u32,
        arguments: &[Expr],
    ) -> Result<(), LlvmError> {
        let (operands, count) = self.operands(arguments)?;
        self.performed_tail(label, operation, &operands, count)
    }

    /// Он же с уже посчитанными аргументами.
    ///
    /// Отдельно от [`Self::performing_tail`] ради операции питомника: у неё
    /// аргументы считаются **однажды** и годятся обоим путям - и кругу, и
    /// хендлеру. Второй счёт был бы вторым вычислением аргументов.
    fn performed_tail(
        &mut self,
        label: LabelId,
        operation: u32,
        operands: &str,
        count: usize,
    ) -> Result<(), LlvmError> {
        let kont = self.kont()?;
        let (verdict, frame) = self.looked(label)?;
        let at = self.matches;
        self.matches += 1;
        let handled = format!("p{at}.handler");
        let other = format!("p{at}.other");
        let suppressed = format!("p{at}.suppressed");
        let missing = format!("p{at}.missing");

        let is_handler = self.temp();
        self.instruction(
            &format!("{is_handler} = icmp eq i32 {verdict}, 1"),
            self.here(),
        );
        self.instruction(
            &format!("br i1 {is_handler}, label %{handled}, label %{other}"),
            self.here(),
        );

        self.start(&handled);
        let found = self.temp();
        self.instruction(&format!("{found} = load ptr, ptr {frame}"), self.here());
        let answer = self.temp();
        self.instruction(
            &format!(
                "{answer} = call ptr @adamas_frame_perform(ptr {found}, ptr {kont}, \
                 i32 {operation}, ptr {operands}, i64 {count})"
            ),
            self.here(),
        );
        self.finish(&answer, Repr::Boxed)?;

        self.start(&other);
        let is_suppressed = self.temp();
        self.instruction(
            &format!("{is_suppressed} = icmp eq i32 {verdict}, 2"),
            self.here(),
        );
        self.instruction(
            &format!("br i1 {is_suppressed}, label %{suppressed}, label %{missing}"),
            self.here(),
        );

        self.start(&suppressed);
        for slot in 0..count {
            let address = self.temp();
            self.instruction(
                &format!("{address} = getelementptr ptr, ptr {operands}, i64 {slot}"),
                self.here(),
            );
            let dead = self.temp();
            self.instruction(&format!("{dead} = load ptr, ptr {address}"), self.here());
            self.instruction(
                &format!("call void @adamas_drop(ptr {dead}, ptr @{RELEASE_SYMBOL})"),
                self.here(),
            );
        }
        // Кадры, ради которых код бы продолжался, снимает сам обрыв - и кадр
        // продолжения этой операции в их числе. Прибирать здесь нечего: владение
        // уехало в среду кадра, а её отдаёт его дроп.
        let aborted = self.temp();
        self.instruction(
            &format!("{aborted} = call ptr @adamas_kont_abort(ptr {kont})"),
            self.here(),
        );
        self.finish(&aborted, Repr::Boxed)?;

        self.start(&missing);
        self.instruction(
            &format!("call void @adamas_fail(ptr {MISSING_MESSAGE})"),
            self.here(),
        );
        self.instruction("unreachable", self.here());
        Ok(())
    }

    /// Операция значением: ветка бежит на месте, ответ - значение операции.
    ///
    /// Позиция не хвостовая, и это не пропуск дробления, а **тихая программа**
    /// (§3.4, вопрос 74): все ветки всех площадок хвостовые, и обрыв невозможен
    /// по построению - `SUPPRESSED` требует разрезанного сегмента, а резать его
    /// в тихой программе некому. Подавление здесь поэтому - нарушение инварианта
    /// тишины, и отвечает ему немедленный `adamas_fail`.
    fn performing(
        &mut self,
        label: LabelId,
        operation: u32,
        arguments: &[Expr],
    ) -> Result<String, LlvmError> {
        if !self.suspending.quiet {
            return Err(self.node("операция значением в нетихой программе"));
        }
        let kont = self.kont()?;
        let (operands, count) = self.operands(arguments)?;
        let (verdict, frame) = self.looked(label)?;
        let at = self.matches;
        self.matches += 1;
        let ready = format!("q{at}.handler");
        let broken = format!("q{at}.broken");

        let is_handler = self.temp();
        self.instruction(
            &format!("{is_handler} = icmp eq i32 {verdict}, 1"),
            self.here(),
        );
        self.instruction(
            &format!("br i1 {is_handler}, label %{ready}, label %{broken}"),
            self.here(),
        );
        self.start(&broken);
        self.instruction(
            &format!("call void @adamas_fail(ptr {MISSING_MESSAGE})"),
            self.here(),
        );
        self.instruction("unreachable", self.here());

        self.start(&ready);
        let found = self.temp();
        self.instruction(&format!("{found} = load ptr, ptr {frame}"), self.here());
        let answer = self.temp();
        self.instruction(
            &format!(
                "{answer} = call ptr @adamas_frame_perform(ptr {found}, ptr {kont}, \
                 i32 {operation}, ptr {operands}, i64 {count})"
            ),
            self.here(),
        );
        Ok(answer)
    }

    /// Питомник в **чистой** функции: корень своего стека, круг, трамплин до дна.
    ///
    /// Тот же приём, что у хендлера первой формы ([`Self::handling`]), и то же
    /// основание: row у `withNursery` пуста, значит наружу круга не уходит ни
    /// одной операции, и стек этот один на всё, что друг друга видит.
    ///
    /// Тело считается **внутри** корня: под ним уже есть и вектор, и ручка, а
    /// снаружи первой формы их нет вовсе.
    fn nursing(&mut self, body: &Expr) -> Result<String, LlvmError> {
        if self.kont.is_some() {
            // Внутри второй формы питомник значением не бывает: дробление
            // выносит его хвостом куска ([`Self::nursery_tail`]).
            return Err(self.node("питомник значением во второй форме"));
        }
        let root = format!("%k{}", self.frames);
        self.frames += 1;
        let _ = writeln!(self.head, "  {root} = alloca ptr");
        self.instruction(
            &format!("call void @adamas_kont_init(ptr {root})"),
            self.here(),
        );
        let empty = self.temp();
        self.instruction(
            &format!("{empty} = call ptr @adamas_evidence_empty()"),
            self.here(),
        );
        let held_kont = self.kont.replace(root.clone());
        let held_ev = self.ev.replace(empty.clone());

        let outcome = (|builder: &mut Self| {
            let body = builder.value(body)?;
            let seed = builder.temp();
            builder.instruction(
                &format!(
                    "{seed} = call ptr @adamas_nursery_begin(ptr {root}, ptr {empty}, \
                     ptr {body}, ptr @{RELEASE_SYMBOL})"
                ),
                builder.here(),
            );
            let answer = builder.temp();
            builder.instruction(
                &format!("{answer} = call ptr @adamas_kont_run(ptr {root}, ptr {seed})"),
                builder.here(),
            );
            Ok(answer)
        })(self);

        self.kont = held_kont;
        self.ev = held_ev;
        let answer = outcome?;
        self.instruction(
            &format!("call void @adamas_evidence_drop(ptr {empty})"),
            self.here(),
        );
        Ok(answer)
    }

    /// Питомник во **второй** форме: круг заводится на пришедшей ручке.
    ///
    /// Своего корня здесь нет и быть не может - кадр `NURSERY` встаёт над уже
    /// стоящим продолжением, - а трамплин крутит тот, кто позвал кусок.
    fn nursery_tail(&mut self, body: &Expr) -> Result<(), LlvmError> {
        let kont = self.kont()?;
        let ev = self.ev()?;
        let body = self.value(body)?;
        let seed = self.temp();
        self.instruction(
            &format!(
                "{seed} = call ptr @adamas_nursery_begin(ptr {kont}, ptr {ev}, ptr {body}, \
                 ptr @{RELEASE_SYMBOL})"
            ),
            self.here(),
        );
        self.finish(&seed, Repr::Boxed)
    }

    /// Отмена: разбор значения задачи потребил её мимо `await` (§5.2).
    ///
    /// Точка приостановки - раскрутка сегмента отменённого кладётся кадром, -
    /// поэтому только в хвосте куска. Отдаёт она то же разбираемое.
    fn cancelling(&mut self, at: u32, value: &Expr) -> Result<(), LlvmError> {
        let kont = self.kont()?;
        let value = self.value(value)?;
        let answer = self.temp();
        self.instruction(
            &format!(
                "{answer} = call ptr @adamas_nursery_cancel(ptr {kont}, ptr {value}, i32 {at})"
            ),
            self.here(),
        );
        self.finish(&answer, Repr::Boxed)
    }

    /// Операция питомника: круг берёт её, только если он ближе хендлера (§5.2).
    ///
    /// Оба пути стоят рядом, и это не дублирование, а само правило: решает
    /// между ними **рантайм**, потому что `eval/fibers.adamas` пишет те же имена
    /// без всякого питомника, а написанный `handle` над той же меткой значит
    /// написанное. Обычный путь идёт следом тем же кодом, что у всякой операции:
    /// аргументы посчитаны однажды и годятся обоим.
    ///
    /// Свой аргумент у порождения и ожидания - **последний**: row стоит на
    /// последней стрелке. Прочие (синтезированный триггер приостановленного
    /// вычисления) на этом пути дропаются здесь: ветки, которая дропнула бы их
    /// сама, у круга нет.
    fn fibering_tail(
        &mut self,
        op: FiberOp,
        label: LabelId,
        operation: u32,
        arguments: &[Expr],
    ) -> Result<(), LlvmError> {
        let kont = self.kont()?;
        let ev = self.ev()?;
        let (operands, count) = self.operands(arguments)?;
        let at = self.matches;
        self.matches += 1;
        let circle = format!("n{at}.nursery");
        let elsewhere = format!("n{at}.elsewhere");

        let title = &self.program.labels[label.0 as usize].name;
        let serves = self.temp();
        let text = format!(
            "{serves} = call i32 @adamas_nursery_serves(ptr {ev}, i32 {}) ; питомник: {title}",
            label.0
        );
        self.instruction(&text, self.here());
        let nearest = self.temp();
        self.instruction(&format!("{nearest} = icmp ne i32 {serves}, 0"), self.here());
        self.instruction(
            &format!("br i1 {nearest}, label %{circle}, label %{elsewhere}"),
            self.here(),
        );

        self.start(&circle);
        let taken = match op {
            FiberOp::Suspend => None,
            _ => count.checked_sub(1),
        };
        for slot in 0..count {
            if taken == Some(slot) {
                continue;
            }
            let dead = self.slot_of(&operands, slot);
            self.instruction(
                &format!("call void @adamas_drop(ptr {dead}, ptr @{RELEASE_SYMBOL})"),
                self.here(),
            );
        }
        let own = taken.map(|slot| self.slot_of(&operands, slot));
        let call = match (op, own) {
            (FiberOp::Suspend, _) => Some(format!(
                "call ptr @adamas_nursery_suspend(ptr {kont}, ptr {ev})"
            )),
            (FiberOp::Detached, Some(own)) => Some(format!(
                "call ptr @adamas_nursery_spawn(ptr {kont}, ptr {ev}, ptr {own}, \
                 i32 {NO_TASK}, i32 0, i32 0)"
            )),
            (FiberOp::Spawn(Some(task)), Some(own)) => Some(format!(
                "call ptr @adamas_nursery_spawn(ptr {kont}, ptr {ev}, ptr {own}, i32 {}, \
                 i32 {}, i32 {})",
                task.constructor.0, task.slots, task.at
            )),
            (FiberOp::Await(Some(slot)), Some(own)) => Some(format!(
                "call ptr @adamas_nursery_await(ptr {kont}, ptr {ev}, ptr {own}, i32 {slot})"
            )),
            // Форма задачи не сошлась - либо своего аргумента у операции нет
            // вовсе: у машины это тот же отказ на месте, а не молча собранное не
            // то (`Machine::handle_value`).
            _ => None,
        };
        if let Some(call) = call {
            let answer = self.temp();
            self.instruction(&format!("{answer} = {call}"), self.here());
            self.finish(&answer, Repr::Boxed)?;
        } else {
            self.instruction(
                &format!("call void @adamas_fail(ptr {SHAPELESS_MESSAGE})"),
                self.here(),
            );
            self.instruction("unreachable", self.here());
        }

        self.start(&elsewhere);
        self.performed_tail(label, operation, &operands, count)
    }

    /// Значение в слоте массива аргументов операции.
    fn slot_of(&mut self, operands: &str, slot: usize) -> String {
        let address = self.temp();
        self.instruction(
            &format!("{address} = getelementptr ptr, ptr {operands}, i64 {slot}"),
            self.here(),
        );
        let value = self.temp();
        self.instruction(&format!("{value} = load ptr, ptr {address}"), self.here());
        value
    }

    /// Поиск метки в векторе: вердикт числом и ячейка под найденный кадр.
    fn looked(&mut self, label: LabelId) -> Result<(String, String), LlvmError> {
        let ev = self.ev()?;
        let title = self.program.labels[label.0 as usize].name.clone();
        let cell = format!("%h{}", self.frames);
        self.frames += 1;
        let _ = writeln!(self.head, "  {cell} = alloca ptr");
        self.instruction(&format!("store ptr null, ptr {cell}"), self.here());
        let verdict = self.temp();
        self.instruction(
            &format!(
                "{verdict} = call i32 @adamas_evidence_lookup(ptr {ev}, i32 {}, ptr {cell}) ; {title}",
                label.0
            ),
            self.here(),
        );
        Ok((verdict, cell))
    }

    /// Хендлер в **первой** форме: корень стека, кадр, трамплин до дна.
    ///
    /// Ставить кадр нужно и той функции, чья собственная row пуста: `runIO`
    /// гасит `IO` внутри себя и наружу его не отдаёт. Скрытых аргументов у неё
    /// нет, и брать их неоткуда - значит она **корень**: заводит свой стек и
    /// пустой вектор. Законно это ровно потому, что row её пуста: операции
    /// наружу не уходит ни одной (§3.4, погашение расширением справа).
    fn handling(
        &mut self,
        handler: HandlerId,
        captured: &[Expr],
        computation: &Expr,
    ) -> Result<String, LlvmError> {
        if self.kont.is_some() {
            // Внутри второй формы `handle` значением не бывает: дробление
            // выносит его хвостом куска.
            return Err(self.node("хендлер значением во второй форме"));
        }
        let taken = self.environment(handler, captured)?;
        let root = format!("%k{}", self.frames);
        self.frames += 1;
        let _ = writeln!(self.head, "  {root} = alloca ptr");
        self.instruction(
            &format!("call void @adamas_kont_init(ptr {root})"),
            self.here(),
        );
        let empty = self.temp();
        self.instruction(
            &format!("{empty} = call ptr @adamas_evidence_empty()"),
            self.here(),
        );
        let held_kont = self.kont.replace(root.clone());
        let held_ev = self.ev.replace(empty.clone());

        let outcome = (|builder: &mut Self| {
            let (_, vector) = builder.installed(handler, &taken)?;
            let inner = builder.ev.replace(vector.clone());
            let seed = builder.value(computation);
            builder.ev = inner;
            let seed = seed?;
            builder.instruction(
                &format!("call void @adamas_evidence_drop(ptr {vector})"),
                builder.here(),
            );
            let answer = builder.temp();
            builder.instruction(
                &format!("{answer} = call ptr @adamas_kont_run(ptr {root}, ptr {seed})"),
                builder.here(),
            );
            Ok(answer)
        })(self);

        self.kont = held_kont;
        self.ev = held_ev;
        let answer = outcome?;
        self.instruction(
            &format!("call void @adamas_evidence_drop(ptr {empty})"),
            self.here(),
        );
        Ok(answer)
    }

    /// Маска в чистом отрезке: вектор без записи, вычисление под ним.
    ///
    /// Кадра здесь нет и быть не может - маска ничего не откладывает. Своя
    /// ссылка на вектор живёт до конца вычисления: кадры, которые вычисление
    /// положит, берут свою.
    fn masking(&mut self, label: LabelId, computation: &Expr) -> Result<String, LlvmError> {
        let vector = self.masked(label)?;
        let held = self.ev.replace(vector.clone());
        let answer = self.value(computation);
        self.ev = held;
        let answer = answer?;
        self.instruction(
            &format!("call void @adamas_evidence_drop(ptr {vector})"),
            self.here(),
        );
        Ok(answer)
    }
}

/// Представления связываний, заведённых телом, и уникальность их производства.
///
/// Оба сразу, а не двумя обходами: собираются они из одного и того же
/// [`Fact`], и второй обход разошёлся бы с первым молча - ровно тот жанр
/// дефекта, ради которого [`Expr::children`] живёт одной штукой.
fn collect(expr: &Expr, found: &mut HashMap<LocalId, Repr>, certain: &mut HashSet<LocalId>) {
    let mut note = |binding: &Binding| {
        found.insert(binding.local, binding.fact.repr);
        if binding.fact.unique == Unique::Certain {
            certain.insert(binding.local);
        }
    };
    match expr {
        Expr::Bind { binding, .. } => note(binding),
        Expr::Match { arms, .. } => {
            for arm in arms {
                for field in &arm.fields {
                    note(field);
                }
            }
        }
        Expr::Reclaim { token, .. } => {
            // Придержанный блок - сырая ячейка, представление у неё одно.
            found.insert(*token, Repr::Boxed);
        }
        _ => {}
    }
    for child in expr.children() {
        collect(child, found, certain);
    }
}

/// Спутник на C: таблица конструкторов, печать, дроп детей и точка входа.
///
/// `flat.c`, `print.c`, `release.c` и `main.c` берутся **дословно** теми же
/// `include_str!`, какими их берёт C-бэкенд, и над той же таблицей: печать и
/// дроп у двух бэкендов обязаны быть одними, иначе «печатает то же» держалось
/// бы на совпадении двух печатей, а не на их тождестве.
fn support(program: &Program, answer: Answer) -> String {
    let mut out = String::new();
    out.push_str(concat!(
        "/* Порождено понижением Adamas: спутник `.ll`.\n",
        " *\n",
        " * Программу считает `.ll` целиком; здесь только таблица конструкторов,\n",
        " * печать ответа, дроп его детей и точка входа. `flat.c`, `print.c`,\n",
        " * `release.c` и `main.c` - те же файлы, что собирает C-бэкенд, взятые\n",
        " * дословно.\n",
        " */\n",
        "\n",
        "#include \"adamas.h\"\n",
        "\n",
        "#include <stdio.h>\n",
        "\n",
    ));
    out.push_str(crate::emit_c::FLAT);
    out.push('\n');
    crate::emit_c::table(&mut out, program);
    out.push_str(crate::emit_c::RELEASE);
    out.push('\n');
    out.push_str(crate::emit_c::PRINTER);
    out.push('\n');

    // Раскладка объекта записана дважды - здесь и в `emit_llvm.rs`, - потому
    // что слот `.ll` читает инструкцией. Расхождение обязано ронять **сборку**,
    // а не ответ: числа подставлены отсюда, а не написаны в файле руками.
    out.push_str(concat!(
        "/* Раскладка объекта: те же числа, по которым `.ll` считает адрес\n",
        " * слота. Разъедься они с рантаймом - не соберётся спутник. */\n"
    ));
    let _ = writeln!(
        out,
        "_Static_assert(offsetof(adamas_object, fields) == {HEADER_BYTES}u, \
         \"заголовок объекта разошёлся с `emit_llvm.rs`\");"
    );
    let _ = writeln!(
        out,
        "_Static_assert(sizeof(adamas_value) == {SLOT_BYTES}u, \
         \"слот объекта разошёлся с `emit_llvm.rs`\");\n"
    );

    out.push_str(concat!(
        "/* Дроп детей, видимый из `.ll`: тот же `adamas_release_value`, только\n",
        " * не `static` - порождённый IR лежит в другой единице трансляции. */\n"
    ));
    let _ = writeln!(
        out,
        "void {RELEASE_SYMBOL}(adamas_value value) {{ adamas_release_value(value); }}\n"
    );

    out.push_str("/* Ответ считает `.ll`, печатает `main.c` ниже. */\n");
    match answer {
        Answer::Flat(ty) => {
            let ctype = crate::emit_c::scalar(Repr::Flat(ty));
            let _ = writeln!(out, "{ctype} {ENTRY_SYMBOL}(void);");
            let _ = writeln!(out, "#define ADAMAS_ENTRY {ENTRY_SYMBOL}");
            let _ = writeln!(out, "#define ADAMAS_ANSWER_FLAT adamas_word_{}", ty.name());
            let _ = writeln!(out, "#define ADAMAS_ANSWER_TYPE {ctype}");
            let _ = writeln!(
                out,
                "#define ADAMAS_ANSWER_KIND {}u",
                crate::emit_c::kind(ty)
            );
        }
        // Без `ADAMAS_ANSWER_FLAT`: `main.c` разводит две формы ответа
        // препроцессором, и объектная - его же вторая ветка, с печатью по
        // таблице и дропом после.
        Answer::Boxed => {
            let _ = writeln!(out, "adamas_value {ENTRY_SYMBOL}(void);");
            let _ = writeln!(out, "#define ADAMAS_ENTRY {ENTRY_SYMBOL}");
        }
    }
    out.push('\n');
    out.push_str(crate::emit_c::ENTRY);
    out
}

#[cfg(test)]
mod tests {
    use adamas_core::prim::PrimTy;

    use super::{constant, widened};

    /// Сколько младших бит расширения обязаны быть нулевыми.
    ///
    /// Двадцать девять - разница ширин мантисс, и на неё смотрит сам `llvm-as`:
    /// шестнадцатеричная константа типа `float` принимается только тогда, когда
    /// сужение обратно точно.
    const TAIL: u64 = (1 << 29) - 1;

    #[test]
    fn a_double_is_written_by_its_bits() {
        assert_eq!(
            constant(PrimTy::Float64, 1.0f64.to_bits()),
            "0x3FF0000000000000"
        );
        assert_eq!(
            constant(PrimTy::Float64, (-0.0f64).to_bits()),
            "0x8000000000000000"
        );
        assert_eq!(
            constant(PrimTy::Float32, u64::from(1.0f32.to_bits())),
            "0x3FF0000000000000"
        );
    }

    /// Расширение любого `float` оставляет хвост нулевым.
    ///
    /// Перебор идёт умножением на нечётное: оно биекция на `u32`, поэтому
    /// шестьдесят пять тысяч шагов раскладываются по всему диапазону, а не
    /// толпятся у нуля, где живут одни субнормали.
    #[test]
    fn widening_a_single_leaves_the_tail_clear() {
        for step in 0..=0xffffu32 {
            let bits = step.wrapping_mul(65_537);
            assert_eq!(
                widened(u64::from(bits)) & TAIL,
                0,
                "хвост не нулевой у {bits:#010x}"
            );
        }
    }

    /// NaN переносится вместе со знаком и полезной нагрузкой.
    ///
    /// Ветвь эта программой не достигается - литерала NaN в языке нет, - и
    /// стоит она потому, что приведение железом квитирует сигнальный NaN, то
    /// есть меняет биты константы при записи её в текст `.ll`. Порядок этих
    /// битов больше не читает (вопрос 172), но константа обязана доезжать до
    /// `llvm-as` той же, какой её написало понижение.
    #[test]
    fn a_single_nan_keeps_its_sign_and_payload() {
        assert_eq!(widened(0x7fc0_0001), 0x7ff8_0000_2000_0000);
        let signalling = (1u64 << 63) | (0x7ffu64 << 52) | (0x0020_0003u64 << 29);
        assert_eq!(widened(0xffa0_0003), signalling);
        assert_eq!(widened(0xffa0_0003) & TAIL, 0);
    }
}
