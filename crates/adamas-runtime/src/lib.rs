//! Минимальный рантайм Adamas (§9 Фаза 6, волна 2, трек G).
//!
//! **Основной текст здесь на C**, и документ ABI живёт в `include/adamas.h`:
//! форма значения, договор о владении, кадры и вектор evidence. Спецификация -
//! запись decision log `adamas-design.md` §13 от 2026-09-08 «ABI: где живут
//! кадры и как выглядит значение в C».
//!
//! Rust-стороне достаётся три роли и ни одной больше:
//!
//! - собрать библиотеку (`build.rs`) и отдать потребителю путь к заголовку
//!   через `DEP_ADAMAS_RUNTIME_INCLUDE` - им воспользуется понижение (трек H);
//! - объявить ABI для тестов ([`ffi`]);
//! - быть местом, где рантайм гоняется: поведение показано прогоном, а не
//!   наличием кода, и `cargo test` эти прогоны запускает.
//!
//! Безопасных обёрток здесь нет намеренно. Потребитель рантайма - генератор
//! C-кода, и обёртка, которой он не пользуется, разъезжается с заголовком
//! молча.
//!
//! # Что рантайм умеет
//!
//! Заголовок объекта и аллокацию; `dup`/`drop` с уникальностью как `rc == 0`;
//! `drop` с переиспользованием блока (`reuse`) - точку входа, которую позже
//! вставит Perceus; непосредственные значения тегом указателя; конструкторы с
//! полями, замыкания и частичное применение; кадры, сегменты продолжения с
//! копированием под мультишот и раскруткой с деструкторами; вектор evidence;
//! регионы и плоские массивы; питомник с файберами (§5.2) - круг, уступка
//! разрезом сегмента, ожидание, отмена задачи.
//!
//! Атомарных счётчиков здесь нет - они приходят Фазой 7: машина однопоточна, и
//! файберы этой стадии тоже.

