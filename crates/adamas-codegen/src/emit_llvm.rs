/// Указательный массив или плоский: различает их наличие шага (§4.11).
///
/// Та же запись, что у C-эмиттера, и она там же однострочная: шаг есть
/// **единственное**, чем два представления массива различаются, - ровно как в
/// рантайме, где их различает `stride == 0`.
const fn elems(stride: Option<Stride>) -> Elems {
    match stride {
        Some(_) => Elems::Flat,
        None => Elems::Boxed,
    }
}

/// Почему эмиссия в LLVM отказала.
///
/// Отказ **названный**, как у понижения: молча посчитать не то хуже, чем не
/// посчитать. Мера среза читается прогоном по корпусу (`tests/llvm.rs`), а не
/// оценкой, и каждая причина здесь - строка этой меры.
#[derive(Debug, thiserror::Error)]
pub enum LlvmError {
    /// Узел представления, которого скалярный фрагмент не знает.
    #[error("`{function}`: {node} - узел вне скалярного фрагмента")]
    Node {
        /// Чья функция.
        function: String,
        /// Какой узел.
        node: &'static str,
    },

    /// Представление, которое в регистр не ложится.
    #[error("`{function}`: {place} - {shape}, а срез берёт только плоское значение")]
    Shape {
        /// Чья функция.
        function: String,
        /// Что именно: параметр, ответ, промежуточное значение.
        place: String,
        /// Как оно представлено.
        shape: String,
    },

    /// Вторая форма позвана оттуда, где скрытых аргументов взять неоткуда.
    ///
    /// Не предположение, а проверка: расхождение здесь молчаливо - `null`
    /// вместо вектора собирается и падает в рантайме. То же утверждение и тем
    /// же местом делает C-эмиттер (`emit_c::forms_agree`).
    #[error("`{caller}`: `{callee}` второй формы позван без скрытых аргументов")]
    Hidden {
        /// Кто зовёт.
        caller: String,
        /// Кого.
        callee: String,
    },
}

