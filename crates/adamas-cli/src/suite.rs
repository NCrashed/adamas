//! `adamas test`: что считается тестом и как он краснеет (§7.1).
//!
//! # Развилка, которой у языка не было
//!
//! §7.1 называет команду и не даёт ей предмета: ни атрибута теста, ни
//! соглашения об именах в языке нет. Рассмотрено четыре варианта.
//!
//! - **Атрибут `@test`.** Ближе всего к Rust. Стоит новой синтаксической формы
//!   в поверхностном языке ради инструмента, то есть записи в §4 и §10; а
//!   §4.6 отводит атрибутам роль обязательств перед проверкой (`@fbip`,
//!   `@noalloc`, `total`), и тест среди них - чужой.
//! - **Отдельный каталог с записанным ответом.** Так устроен корпус
//!   (`tests/golden/`), и для компилятора это правильно: сверяется текст.
//!   Пользовательскому проекту он навязывает второй файл на каждый тест и
//!   ответ, записанный в синтаксисе печати ядра, а не языка.
//! - **Сверка ответа `main` с записанным.** Один тест на программу - и всё.
//! - **Соглашение об имени и типе.** Тест - определение, названное `test…` и
//!   объявленное `Bool`; проходит, когда считается в `True`.
//!
//! Взято последнее, и довод - **прецедент в самом ядре**. `Bool` уже есть
//! соглашение по имени, а не занятое ядром имя: тип объявляет программа, а
//! компилятор знает, как он называется, и на этом стоят три вещи - тип
//! сравнения, свёртка `if` и разбор литерального паттерна
//! ([`adamas_core::prim::BOOL`], §4.3). Тест по имени и типу - тот же жанр
//! соглашения, и языку он не стоит ни строки: ни нового ключевого слова, ни
//! новой формы, ни записи в §4.
//!
//! Цена названа. Определение, названное `testFoo` без умысла, становится
//! тестом; свойство «тест обязан завершаться» не проверяется - его проверяет
//! `total` (§4.7), и требовать его от теста значило бы запретить тесты на
//! незавершимость; а тест - определение **без параметров**, потому что
//! вычислять функцию не над чем.
//!
//! # Где тесты живут
//!
//! В отдельном модуле - `[package] test`, по умолчанию `Test`. Программа и её
//! тесты - две **разные** программы: у теста свой вход, он подключает
//! написанное как обычный модуль (§4.8), и в собранный `adamas build` бинарь
//! тестовое определение не попадает по построению.
//!
//! Тестами считаются определения **входного файла** сюиты, а не всей её
//! программы. Иначе `adamas test` гонял бы тесты подключённых пакетов, то есть
//! отвечал бы за чужой код.
//!
//! # Чем он краснеет
//!
//! Тремя способами, и все три - настоящие. Тест посчитался в `False` - отказ с
//! именем. Тест не посчитался (непогашенная операция, обрыв машины) - отказ с
//! причиной. Тестов не нашлось ни одного - **тоже отказ**: команда, которая
//! ничего не нашла и ушла с нулём, зелена ровно так же, как та, что всё
//! прогнала.

use std::path::Path;

use adamas_core::sig::Signature;
use adamas_core::term::Term;

use crate::project;

/// С чего начинается имя теста.
const PREFIX: &str = "test";

/// Прогоняет тесты проекта. Отдаёт `true`, если все зелены.
///
/// # Errors
///
/// Тестового модуля нет, он не проверяется, либо тестов в нём ни одного.
pub(crate) fn run(path: &Path) -> anyhow::Result<bool> {
    let opened = project::opened(path)?;
    let Some(entry) = opened.tests else {
        anyhow::bail!(
            "{}: это не проект, а тесты живут в модуле проекта (`[package] test`)",
            opened.entry.display()
        );
    };
    if !entry.is_file() {
        anyhow::bail!(
            "тестового модуля нет: ожидался {}; имя модуля задаёт `[package] test`",
            entry.display()
        );
    }
    let checked = project::checked(&entry, opened.sources.as_ref())?;
    let named = collected(&checked.signature)?;
    // Тесты ходят наружу теми же библиотеками, что и программа (§5.3).
    let linkage = adamas_interp::Linkage::new(&opened.link.libraries, &opened.link.paths);

    let mut failed = 0_usize;
    for name in &named {
        match verdict(&checked.signature, name, &linkage) {
            Ok(()) => println!("{name}: ok"),
            Err(why) => {
                failed += 1;
                println!("{name}: ОТКАЗ - {why}");
            }
        }
    }
    println!("{}: тестов {}, отказов {failed}", checked.name, named.len());
    Ok(failed == 0)
}

/// Имена тестов входного файла сюиты в порядке объявления.
///
/// Определение входного файла - то, чьё имя не квалифицировано: подключённый
/// модуль поднимает свои члены под путём (`Std.Prelude.insert`), входной - нет
/// (§4.8, `adamas_elab::program`).
///
/// # Errors
///
/// Тестов нет ни одного либо тест объявлен не `Bool`.
fn collected(signature: &Signature) -> anyhow::Result<Vec<String>> {
    let mut named = Vec::new();
    for name in signature.names() {
        if !name.starts_with(PREFIX) || name.contains('.') {
            continue;
        }
        let Some(definition) = signature.lookup(&name) else {
            continue;
        };
        // Не `Bool` - отказ, а не пропуск. Пропущенный тест не отличается от
        // прошедшего ничем, кроме отсутствия строки в выводе, а это ровно тот
        // способ, которым команда бывает зелена, ничего не сделав.
        if !boolean(&definition.ty) {
            anyhow::bail!(
                "`{name}` назван тестом, но объявлен не `Bool`; тест - определение \
                 с именем на `{PREFIX}` и типом `Bool`"
            );
        }
        named.push(name.to_string());
    }
    named.sort();
    if named.is_empty() {
        anyhow::bail!(
            "тестов нет ни одного; тест - определение с именем на `{PREFIX}` и типом `Bool`"
        );
    }
    Ok(named)
}

/// Объявлен ли тип истинности (§4.3).
///
/// Сверяется **последний сегмент** имени: `Bool`, объявленный во входном файле
/// сюиты, лежит под коротким именем, а пришедший из модуля - под путём
/// (`Std.Base.Bool`). Ядро в том же соглашении смотрит только короткое имя
/// ([`adamas_core::prim::BOOL`]), и чужой `Bool` оно принимает тем же образом.
fn boolean(ty: &Term) -> bool {
    matches!(ty, Term::Const(name, _, _) if short(name) == adamas_core::prim::BOOL)
}

/// Последний сегмент квалифицированного имени.
fn short(name: &str) -> &str {
    name.rsplit('.').next().unwrap_or(name)
}

/// Считает тест и говорит, чем он не прошёл.
fn verdict(
    signature: &Signature,
    name: &str,
    linkage: &adamas_interp::Linkage,
) -> Result<(), String> {
    let body = project::body(signature, name).map_err(|why| why.to_string())?;
    let answer = adamas_interp::run_linked(signature, &body, linkage.clone())
        .map_err(|why| why.to_string())?;
    match &answer {
        Term::Const(constructor, _, _) if short(constructor) == adamas_core::prim::TRUE => Ok(()),
        other => Err(format!(
            "ожидался `{}`, получено `{}`",
            adamas_core::prim::TRUE,
            other.printed(Some(adamas_core::term::PRINT_DEPTH))
        )),
    }
}
