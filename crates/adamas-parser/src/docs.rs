//! Документирующий блок и то, к чему он относится (§7.1).
//!
//! # Разновидность отвечает за начало, положение - за принадлежность
//!
//! [`CommentKind::Doc`] говорит, что блок здесь **начинается**: так написано
//! `-- |`. Кому блок принадлежит, написанием не выражается вовсе, и правило
//! тут одно: **между блоком и объявлением стоит только пробел, и пустой строки
//! в нём нет**.
//!
//! Пустая строка - разделитель, и снимать её `doc` не станет. Довод не
//! эстетический. Шапка файла отделена от первого объявления пустой строкой
//! ровно затем, чтобы к нему не относиться, и форматтер (волна 3, трек B)
//! сохраняет **одну авторскую пустую строку** именно в этом месте. Читай `doc`
//! блок поверх пустой строки, и шапка `Std/Prelude.adamas` - двадцать одна
//! строка про закрытые вопросы - стала бы документацией `data Unit`.
//!
//! Из двух способов ошибиться выбран тот, который автор видит. Проглоченная
//! пустая строка даёт **ложную** документацию: читатель получает текст не о
//! том, что перед ним, и узнать об этом ему неоткуда. Уважённая пустая строка
//! даёт **отсутствующую**: автор пишет `-- |`, не видит записи в выводе `doc` и
//! убирает пустую строку. Второе громче, и ошибается оно в сторону молчания.
//!
//! # Продолжение блока
//!
//! Первая строка написана `-- |`, следующие - обычными `--`. Блоком их делает
//! смежность: пустая строка внутри блока кончает его так же, как кончает перед
//! объявлением.
//!
//! Начало ищется **сверху**: блок открывает первый `-- |` смежной группы, а не
//! ближайший к объявлению. Иначе заметка, приписанная над готовым `-- |`,
//! молча отменяла бы документацию целиком.

use adamas_core::source::Span;

use crate::token::{Comment, CommentKind};

/// Документация объявления, начинающегося в `span`. `None` - её нет.
///
/// Текст отдаётся без маркеров и без отступа, строки разделены переводом.
/// Голая строка `--` даёт пустую строку **текста** - ею и разделяются абзацы;
/// пустая строка **исходника** блок кончает, и внутрь его не попадает.
#[must_use]
pub fn attached(text: &str, comments: &[Comment], span: Span) -> Option<String> {
    let run = adjacent(text, comments, span);
    // Открывает блок первый `-- |` сверху: заметка над готовой документацией не
    // отменяет её, а входит в неё.
    let opens = run.iter().position(|it| it.kind == CommentKind::Doc)?;
    let said: Vec<&str> = run[opens..]
        .iter()
        .map(|it| stripped(&text[it.span.start()..it.span.end()]))
        .collect();
    let block = said.join("\n");
    let block = block.trim();
    (!block.is_empty()).then(|| block.to_owned())
}

/// Смежная группа строчных комментариев прямо над `span`, сверху вниз.
///
/// Смежность - пробел без пустой строки. Всё прочее между комментарием и
/// объявлением (хотя бы хвост предыдущего определения) группу кончает: иначе
/// документация `f` доставалась бы `g`, написанному следом без пустой строки.
fn adjacent<'a>(text: &str, comments: &'a [Comment], span: Span) -> Vec<&'a Comment> {
    let mut run: Vec<&Comment> = Vec::new();
    let mut next = span.start();
    for comment in comments.iter().rev() {
        if comment.span.end() > next {
            continue;
        }
        // Блочный комментарий документацией не бывает и группу кончает: у
        // `{- … -}` нет разновидности `Doc`, а поглотить его строчным блоком
        // значило бы печатать в документации то, чего автор в неё не писал.
        if comment.kind == CommentKind::Block || !glued(text, comment.span.end(), next) {
            break;
        }
        run.push(comment);
        next = comment.span.start();
    }
    run.reverse();
    run
}

/// Между `from` и `to` только пробел, и пустой строки в нём нет.
///
/// Пустая строка считается переводами, а не поиском `"\n\n"`: пробелы на
/// пустой строке её пустой быть не перестают, а строчный комментарий кончается
/// **до** своего перевода, поэтому смежность - это ровно один перевод.
fn glued(text: &str, from: usize, to: usize) -> bool {
    let between = &text[from..to];
    between.chars().all(char::is_whitespace)
        && between.bytes().filter(|it| *it == b'\n').count() < 2
}

/// Строка комментария без маркера.
///
/// Снимается ровно один пробел за маркером: он разделитель, а не отступ, и
/// отступ внутри документации - авторский.
fn stripped(line: &str) -> &str {
    let rest = line
        .strip_prefix("-- |")
        .or_else(|| line.strip_prefix("--"))
        .unwrap_or(line);
    rest.strip_prefix(' ').unwrap_or(rest)
}
